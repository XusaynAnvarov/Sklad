// ========================================================================
//  ГЛАВНОЕ ФОТО ТОВАРА И ПОРЯДОК СНИМКОВ.
//
//  Две РАЗНЫЕ вещи, которые раньше были одной:
//
//    photos    — порядок снимков. В каком порядке их листает клиент.
//    photo_url — ГЛАВНОЕ фото (аватар). Его показывают там, где места на
//                один снимок: список товаров, склад, поиск, заказы,
//                приход, карточка поставщика, накладная, каталог.
//
//  Раньше аватаром было просто первое фото: карточка товара сохраняла
//  photo_url = photos[0]. Поэтому поменять порядок снимков было нельзя,
//  не поменяв заодно аватар, — а это два разных желания. Теперь владелец
//  двигает снимки как ему удобно и отдельно отмечает, какой из них
//  главный.
//
//  СТАРЫЕ ТОВАРЫ. У них photo_url и так равен первому снимку, поэтому
//  правило «главное = photo_url, если он есть среди снимков» ничего им не
//  меняет: выглядят они точно так же, как до этой правки. Если же
//  photo_url ведёт на снимок, которого в photos нет (товары, заведённые
//  до появления галереи, и пересжатые старые адреса), берём первый из
//  списка — то есть опять то же самое, что показывалось раньше.
//
//  Модуль НАРОЧНО без импортов и без обращений к странице: его читает и
//  браузер, и сервер (PDF, каталог, накладные клиента), и тест.
// ========================================================================

// Все снимки товара в том порядке, в котором их показывают.
// Новые товары держат список в photos, самые старые — один в photo_url.
export function снимки(p) {
  if (!p) return [];
  const список = Array.isArray(p.photos) ? p.photos.filter(Boolean).map(String) : [];
  if (список.length) return список;
  return p.photo_url ? [String(p.photo_url)] : [];
}

// Главное фото (аватар) — одной строкой. Нет фото вовсе → пустая строка.
export function главноеФото(p) {
  if (!p) return "";
  const список = снимки(p);
  const выбран = p.photo_url ? String(p.photo_url) : "";
  // Выбранный аватар должен быть среди снимков — иначе это остаток от
  // прежних времён, и показывать надо то же, что показывалось раньше.
  if (выбран && список.includes(выбран)) return выбран;
  return список[0] || выбран || "";
}

// То же самое, когда на руках не товар, а два поля (внутри редактора).
export function главноеИз(photos, photo_url) {
  return главноеФото({ photos, photo_url });
}

// Место главного фото в списке. Нужно, чтобы просмотр во весь экран
// открывался на том снимке, который человек видел в списке, а не на первом.
export function индексГлавного(p) {
  const список = снимки(p);
  const главное = главноеФото(p);
  const i = список.indexOf(главное);
  return i < 0 ? 0 : i;
}

// Это фото — главное?
export function этоГлавное(p, url) {
  return !!url && главноеФото(p) === String(url);
}

// ------------------------------------------------------------------
//  Правки списка. Ничего не меняют на месте — отдают новые значения,
//  поэтому их можно проверить тестом и безопасно вызывать из отрисовки.
// ------------------------------------------------------------------

// Переставить снимок с места «из» на место «куда».
export function переставить(photos, из, куда) {
  const список = (photos || []).slice();
  const i = Number(из);
  if (!(i >= 0) || i >= список.length) return список;
  const [снимок] = список.splice(i, 1);
  const место = Math.max(0, Math.min(Number(куда) || 0, список.length));
  список.splice(место, 0, снимок);
  return список;
}

// Убрать снимок.
//
// Если убрали ГЛАВНЫЙ — аватаром становится первый из оставшихся. Молча
// оставить photo_url на удалённый снимок нельзя: в списках товар станет
// битой картинкой, причём заметят это не сразу, а у клиента в каталоге.
// Вернуть «потеряноГлавное» нужно, чтобы редактор сказал об этом вслух.
export function убрать(photos, главное, индекс) {
  const было = (photos || []).slice();
  const i = Number(индекс);
  if (!(i >= 0) || i >= было.length) {
    return { photos: было, главное: главное || "", потеряноГлавное: false };
  }
  const убираем = было[i];
  const стало = было.filter((_, k) => k !== i);
  // Снимок мог стоять в списке дважды — тогда главный никуда не делся.
  const потеряноГлавное = !!главное && убираем === главное && !стало.includes(главное);
  return {
    photos: стало,
    главное: потеряноГлавное ? (стало[0] || "") : (главное || ""),
    потеряноГлавное,
  };
}

// Сделать главным снимок под номером «индекс». Порядок НЕ трогаем:
// выбор аватара и порядок показа — две независимые вещи.
export function сделатьГлавным(photos, индекс) {
  const список = (photos || []);
  const i = Number(индекс);
  if (!(i >= 0) || i >= список.length) return главноеИз(список, "");
  return String(список[i]);
}

// Добавить снимок в конец. Один и тот же адрес дважды не кладём: в
// галерее это выглядело бы как два одинаковых фото, а выбор главного стал
// бы неоднозначным.
export function добавить(photos, url) {
  const список = (photos || []).slice();
  const адрес = String(url || "").trim();
  if (!адрес || список.includes(адрес)) return список;
  список.push(адрес);
  return список;
}

// Что записать в товар.
export function поляТовара(photos, главное) {
  const список = (photos || []).filter(Boolean).map(String);
  return { photos: список, photo_url: главноеИз(список, главное) };
}

// Адреса снимков поменялись (пересжатие фото), порядок тот же.
// Главный снимок должен остаться ТЕМ ЖЕ снимком, просто по новому адресу.
export function переназначить(былиАдреса, сталиАдреса, главное) {
  const было = (былиАдреса || []).map(String);
  const стало = (сталиАдреса || []).map(String);
  const i = было.indexOf(String(главное || ""));
  return i >= 0 && i < стало.length ? стало[i] : главноеИз(стало, главное);
}
