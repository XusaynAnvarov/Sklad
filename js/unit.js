// ========================================================================
//  ЕДИНИЦА ИЗМЕРЕНИЯ ТОВАРА.
//
//  Часть товара продаётся штуками, часть — пачками, коробками, наборами.
//  Считать всё «в штуках» неудобно: на полке лежат пачки, клиент в
//  накладной видит пачки, и остаток должен быть в пачках.
//
//  Храним два поля:
//    unit      — в чём считаем и продаём: «шт», «пачка», «коробка», …
//    pack_size — сколько штук внутри одной такой единицы (у «шт» это 1)
//
//  ПЕРЕВОД. Когда владелец меняет единицу, пересчитать нужно и остаток, и
//  себестоимость, и все партии — иначе склад покажет 4800 пачек вместо 400,
//  а прибыль посчитается от цены штуки. Поводом стал реальный случай:
//  4800 шт по ¥0,75 перевели в 400 пачек по 12 штук — пачка стоит ¥9.
// ========================================================================

export const ЕДИНИЦЫ = [
  { value: "шт", label: "Штука", вПачке: false },
  { value: "пачка", label: "Пачка", вПачке: true },
  { value: "коробка", label: "Коробка", вПачке: true },
  { value: "набор", label: "Набор", вПачке: true },
  { value: "комплект", label: "Комплект", вПачке: true },
  { value: "метр", label: "Метр", вПачке: false },
  { value: "кг", label: "Килограмм", вПачке: false },
];

const ПО_ЗНАЧЕНИЮ = Object.fromEntries(ЕДИНИЦЫ.map(e => [e.value, e]));

const ч = (n) => Math.round((Number(n) || 0) * 100) / 100;
// Количество считаем точнее денег: при делении на размер пачки остаток в
// сотых заметно двигает итог — цена пачки во столько же раз больше.
const ч3 = (n) => Math.round((Number(n) || 0) * 1000) / 1000;

// Единица товара. У старых товаров поля нет — значит штуки.
export function единица(p) {
  const u = String((p && p.unit) || "").trim();
  return ПО_ЗНАЧЕНИЮ[u] ? u : "шт";
}

// Сколько штук внутри одной единицы. Для штук — всегда 1.
export function вЕдинице(p) {
  if (единица(p) === "шт") return 1;
  const n = Number(p && p.pack_size);
  return isFinite(n) && n > 0 ? n : 1;
}

// Спрашивать ли у этой единицы «сколько штук внутри».
export const считаетсяПачками = (unit) => !!(ПО_ЗНАЧЕНИЮ[unit] || {}).вПачке;

// Русское склонение: 1 пачка, 2 пачки, 5 пачек, 21 пачка, 11 пачек.
function склонение(n, одна, две, пять) {
  const ц = Math.abs(Math.trunc(Number(n) || 0));
  const сотня = ц % 100, десяток = ц % 10;
  if (сотня >= 11 && сотня <= 14) return пять;
  if (десяток === 1) return одна;
  if (десяток >= 2 && десяток <= 4) return две;
  return пять;
}

// Подпись к количеству: «400 пачек», «885 шт».
export function подпись(кол, p) {
  const u = единица(p);
  if (u === "шт") return кол + " шт";
  if (u === "пачка") return кол + " " + склонение(кол, "пачка", "пачки", "пачек");
  if (u === "коробка") return кол + " " + склонение(кол, "коробка", "коробки", "коробок");
  if (u === "набор") return кол + " " + склонение(кол, "набор", "набора", "наборов");
  if (u === "комплект") return кол + " " + склонение(кол, "комплект", "комплекта", "комплектов");
  if (u === "метр") return кол + " " + склонение(кол, "метр", "метра", "метров");
  return кол + " " + u;
}

// Короткая подпись для тесных мест: «400 пач.», «885 шт».
export function коротко(кол, p) {
  const u = единица(p);
  if (u === "шт") return кол + " шт";
  if (u === "пачка") return кол + " пач.";
  if (u === "коробка") return кол + " кор.";
  if (u === "комплект") return кол + " компл.";
  return кол + " " + u;
}

// ------------------------------------------------------------------
//  Пересчёт при смене единицы.
//  множитель = сколько штук в НОВОЙ единице ÷ сколько было в СТАРОЙ.
//  Количество делим на него, цену умножаем: товара столько же и денег
//  столько же, меняется только то, чем мы это меряем.
// ------------------------------------------------------------------
export function множитель(былоВЕдинице, сталоВЕдинице) {
  const было = Number(былоВЕдинице) > 0 ? Number(былоВЕдинице) : 1;
  const стало = Number(сталоВЕдинице) > 0 ? Number(сталоВЕдинице) : 1;
  return стало / было;
}

// Пересчитать товар целиком. Ничего не меняет на месте — отдаёт новые значения.
export function перевести(p, { unit, pack_size }) {
  const былоВ = вЕдинице(p);
  const сталоВ = String(unit) === "шт" ? 1 : (Number(pack_size) > 0 ? Number(pack_size) : 1);
  const k = множитель(былоВ, сталоВ);

  const партии = (Array.isArray(p.batches) ? p.batches : []).map(b => ({
    ...b,
    qty: ч3((Number(b.qty) || 0) / k),
    cost_yuan: ч((Number(b.cost_yuan) || 0) * k),
    cost_usd: ч((Number(b.cost_usd) || 0) * k),
  }));

  // Делится ли остаток нацело. Если нет — выйдут дробные пачки, и владельцу
  // об этом надо сказать прямо, а не показывать «1,55 пачки» как ни в чём
  // не бывало: скорее всего он ошибся в том, сколько штук внутри.
  const остаток = Number(p.stock_qty) || 0;
  const делитсяРовно = Math.abs(остаток / k - Math.round(остаток / k)) < 0.0005;

  return {
    множитель: k,
    делитсяРовно,
    unit: String(unit) === "шт" ? "шт" : String(unit),
    pack_size: сталоВ,
    stock_qty: ч3(остаток / k),
    cost_yuan: ч((Number(p.cost_yuan) || 0) * k),
    cost_usd: ч((Number(p.cost_usd) || 0) * k),
    batches: партии,
  };
}

// Что именно изменится — показываем до того, как применить.
export function объяснение(p, новое) {
  const было = { кол: Number(p.stock_qty) || 0, цена: Number(p.cost_yuan) || 0, ед: единица(p) };
  const стало = { кол: новое.stock_qty, цена: новое.cost_yuan, ед: новое.unit };

  const строки = [
    "Остаток: " + подпись(было.кол, { unit: было.ед }) + " → " + подпись(стало.кол, { unit: стало.ед }),
    "Себестоимость: ¥" + ч(было.цена) + " → ¥" + ч(стало.цена)
      + " за " + (стало.ед === "шт" ? "штуку" : стало.ед),
    "Товара и денег на складе столько же — меняется только то, чем считаем.",
  ];
  if (новое.делитсяРовно === false) {
    строки.push("");
    строки.push("ВНИМАНИЕ: остаток не делится нацело, выйдет дробное количество. "
      + "Проверьте, сколько штук в одной единице.");
  }
  return строки.join("\n");
}
