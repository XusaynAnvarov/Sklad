// ========================================================================
//  НОМЕРА КОРОБОК (МЕСТ) В НАКЛАДНОЙ — общий модуль для склада и сервера.
//
//  Одна позиция может лежать в одной коробке («2») или в нескольких
//  подряд: гилдирак 960 штук по 120 в мешке — это 8 мешков, «4-11».
//  Нумерация мест общая: коробки и мешки считаются вместе, как их
//  и грузят. Можно и через запятую: «1, 3».
//
//  Подпись буквами («А», «верх») остаётся подписью. «А-3» — тоже
//  подпись, а не промежуток: промежуток только из двух чисел.
//
//  Порядок в накладной — по коробкам: сначала всё из первой, потом из
//  второй и так далее; подписи буквами после чисел; без коробки — в конце.
//  Внутри одной коробки сохраняется порядок, в котором позиции вносили.
// ========================================================================

const ЧИСЛО = /^\d{1,4}$/;
const ПРОМЕЖУТОК = /^(\d{1,4})\s*[-–—]\s*(\d{1,4})$/;
const БОЛЬШЕ_НЕ_БЫВАЕТ = 500;           // «1-9999» — опечатка, а не 9999 мешков

export function разобратьКоробку(сырое) {
  const текст = String(сырое ?? "").trim();
  const номера = [], метки = [], куски = [];
  if (!текст) return { пусто: true, номера, метки, вид: "" };

  for (const часть of текст.split(/\s*[,;]\s*/).filter(Boolean)) {
    const п = часть.match(ПРОМЕЖУТОК);
    if (ЧИСЛО.test(часть)) {
      номера.push(Number(часть)); куски.push(String(Number(часть)));
    } else if (п && Number(п[1]) <= Number(п[2]) && Number(п[2]) - Number(п[1]) < БОЛЬШЕ_НЕ_БЫВАЕТ) {
      const а = Number(п[1]), б = Number(п[2]);
      for (let н = а; н <= б; н++) номера.push(н);
      куски.push(а === б ? String(а) : `${а}–${б}`);
    } else {
      метки.push(часть); куски.push(часть);
    }
  }
  return { пусто: false, номера, метки, вид: куски.join(", ") };
}

// Как показать номер в накладной: «1-8» → «1–8», «1 ,3» → «1, 3».
export const видКоробки = (сырое) => разобратьКоробку(сырое).вид;

// Сколько мест в заказе: разные номера плюс разные подписи.
// «1», «2», «4-11» → 10 мест; «1» у двух позиций — одно место.
export function местВсего(позиции, взять = (п) => п.box) {
  const номера = new Set(), метки = new Set();
  for (const п of позиции || []) {
    const к = разобратьКоробку(взять(п));
    к.номера.forEach((н) => номера.add(н));
    к.метки.forEach((м) => метки.add(м.toLowerCase()));
  }
  return номера.size + метки.size;
}

// Ключ сортировки: [разряд, первый номер, подпись].
function ключ(сырое) {
  const к = разобратьКоробку(сырое);
  if (к.пусто) return [2, 0, ""];
  if (к.номера.length) return [0, Math.min(...к.номера), ""];
  return [1, 0, к.метки[0].toLowerCase()];
}

// Позиции по порядку коробок. Возвращает НОВЫЙ массив, исходный не трогает:
// в базе позиции лежат так, как их вносили, и это менять незачем.
export function поКоробкам(позиции, взять = (п) => п.box) {
  return (позиции || [])
    .map((п, i) => ({ п, i, к: ключ(взять(п)) }))
    .sort((а, б) => (а.к[0] - б.к[0]) || (а.к[1] - б.к[1]) || а.к[2].localeCompare(б.к[2], "ru") || (а.i - б.i))
    .map((x) => x.п);
}

// Сменилась ли коробка между соседними строками — для черты в накладной.
export const таЖеКоробка = (а, б) => {
  const ка = ключ(а), кб = ключ(б);
  return ка[0] === кб[0] && ка[1] === кб[1] && ка[2] === кб[2];
};
