// ========================================================================
//  ВОЗВРАТ ОТ КЛИЕНТА.
//
//  Как устроено. Возврат — это НАКЛАДНАЯ С МИНУСОМ: та же запись в
//  «Накладных», но количества отрицательные и помечена source="refund".
//  Из этого само собой выходит всё, что нужно владельцу:
//    • оборот уменьшается → долг клиента падает;
//    • если вернули больше, чем он должен, долг уходит в минус и склад
//      показывает «Аванс (мы должны клиенту)» — это и есть «мы ему
//      должны». Следующая покупка этот аванс съедает сама;
//    • прибыль честная: из дохода вычитается цена продажи, а из
//      себестоимости — себестоимость возвращённого;
//    • товар возвращается на склад теми же партиями (js/inventory.js).
//
//  Отдельная таблица «возвраты» была бы лишней: пришлось бы учить считать
//  долг, оборот, прибыль и акт сверки ещё одному источнику — а это четыре
//  места, где цифры могут разойтись.
//
//  Здесь только расчёт, без записи, — поэтому проверяется тестом
//  _tools/tests/t-refund.mjs.
// ========================================================================
import { ensureBatches, returnToStock, sumQty, costAfter } from "./inventory.js?v=20261030j";
import { isIssued } from "./debt.js?v=20261030j";

const r2 = (n) => Math.round((Number(n) || 0) * 100) / 100;

export const ВОЗВРАТ = "refund";
export const этоВозврат = (s) => String((s && s.source) || "") === ВОЗВРАТ;

// ------------------------------------------------------------------
//  ЧТО КЛИЕНТ ПОКУПАЛ И ЧТО ЕЩЁ МОЖНО ВЕРНУТЬ.
//  Считаем по выданным накладным: заказы, которые ещё не оформлены, —
//  это не покупка, возвращать по ним нечего. Прошлые возвраты вычитаем,
//  иначе один и тот же товар можно вернуть дважды.
// ------------------------------------------------------------------
export function покупки(sales, customerId, товары = []) {
  const имена = Object.fromEntries((товары || []).map(p => [String(p.id), p]));
  const карта = new Map();

  (sales || [])
    .filter(s => String(s.customer_id || "") === String(customerId || "") && isIssued(s))
    .sort((a, b) => new Date(a.date) - new Date(b.date))
    .forEach(s => {
      (s.items || []).forEach(it => {
        const id = String(it.product_id || "");
        if (!id) return;
        const кол = Number(it.qty) || 0;
        if (!кол) return;
        const вал = it.currency || s.currency || "som";
        const запись = карта.get(id) || {
          product_id: id,
          name: (имена[id] && имена[id].name) || it.name || "товар удалён",
          товар: имена[id] || null,
          куплено: 0, возвращено: 0,
          цена: 0, валюта: вал,
          cogs_yuan: 0, cogs_usd: 0,        // себестоимость за штуку из последней продажи
          когда: s.date,
        };
        if (кол > 0) {
          запись.куплено += кол;
          запись.цена = Number(it.unit_price) || запись.цена;   // цена последней продажи
          запись.валюта = вал;
          запись.когда = s.date;
          const шт = кол || 1;
          if (it.cogs_yuan !== undefined) запись.cogs_yuan = r2((Number(it.cogs_yuan) || 0) / шт);
          if (it.cogs_usd !== undefined) запись.cogs_usd = r2((Number(it.cogs_usd) || 0) / шт);
        } else {
          запись.возвращено += -кол;
        }
        карта.set(id, запись);
      });
    });

  return [...карта.values()]
    .map(з => ({ ...з, осталось: r2(з.куплено - з.возвращено) }))
    .filter(з => з.куплено > 0)
    .sort((a, b) => new Date(b.когда) - new Date(a.когда));
}

// ------------------------------------------------------------------
//  СОБРАТЬ ВОЗВРАТ.
//  позиции: [{ product_id, qty, unit_price, currency, cogs_yuan, cogs_usd, name }]
//           qty — ПОЛОЖИТЕЛЬНОЕ число: сколько вернули.
//  Возвращает { накладная, строки, сумма, ошибки }:
//    накладная — что записать в «Накладные» (количества уже с минусом);
//    строки    — что записать в товары (склад пополнен);
//    сумма     — на сколько уменьшится долг, по валютам.
// ------------------------------------------------------------------
export function составить({ customer_id, позиции, товары = [], дата, причина = "" }) {
  const карта = Object.fromEntries((товары || []).map(p => [String(p.id), p]));
  const когда = дата || new Date().toISOString();
  const ошибки = [];
  const items = [];
  const сумма = { som: 0, usd: 0, yuan: 0 };
  const рабочие = new Map();

  for (const поз of (позиции || [])) {
    const кол = Number(поз.qty) || 0;
    if (кол <= 0) { ошибки.push("Количество должно быть больше нуля"); continue; }

    const цена = Number(поз.unit_price) || 0;
    const вал = поз.currency || "som";
    if (сумма[вал] === undefined) { ошибки.push("Неизвестная валюта: " + вал); continue; }
    сумма[вал] = r2(сумма[вал] + кол * цена);

    // Позиция накладной: минус и количество, и себестоимость — чтобы
    // прибыль пересчиталась сама, а не осталась от проданного.
    const зашт = { y: Number(поз.cogs_yuan) || 0, u: Number(поз.cogs_usd) || 0 };
    items.push({
      product_id: поз.product_id || null,
      name: поз.name || (карта[String(поз.product_id)] || {}).name || "",
      qty: -кол,
      unit_price: цена,
      currency: вал,
      applied: true,                                   // склад по этой строке уже подвинут
      cogs_yuan: -r2(зашт.y * кол),
      cogs_usd: -r2(зашт.u * кол),
    });

    // Склад: товар возвращается теми же партиями. Если товара в складе
    // нет (карточку удалили) — деньги вернём, но складу сказать нечего.
    const p = карта[String(поз.product_id || "")];
    if (!p) { if (поз.product_id) ошибки.push("Товар не найден в складе: " + (поз.name || поз.product_id)); continue; }

    const текущий = рабочие.get(p.id) || { ...p, batches: ensureBatches(p) };
    текущий.batches = returnToStock(текущий.batches, кол, зашт.y || Number(p.cost_yuan) || 0, зашт.u || Number(p.cost_usd) || 0, когда);
    текущий.stock_qty = sumQty(текущий.batches);
    рабочие.set(p.id, текущий);
  }

  const строки = [...рабочие.values()].map(p => {
    const cc = costAfter(p.batches, p);
    return { id: p.id, stock_qty: sumQty(p.batches), cost_yuan: cc.cost_yuan, cost_usd: cc.cost_usd, batches: p.batches };
  });

  const накладная = {
    customer_id: customer_id || null,
    date: когда,
    currency: items[0] ? items[0].currency : "som",
    status: "final",            // возврат — свершившийся факт, как и выдача
    source: ВОЗВРАТ,
    items,
    order_from: причина ? { причина } : null,
  };

  return { накладная, строки, сумма, ошибки };
}

// ------------------------------------------------------------------
//  ВЕРНУЛИ ДЕНЬГАМИ.
//  Если клиент за товар уже заплатил и забирает деньги, одного возврата
//  мало: без этой записи он остался бы «авансом» — как будто мы ему
//  должны, хотя деньги уже отдали. Выплата — это оплата с МИНУСОМ:
//      долг = оборот + старый долг − оплаты
//  возврат убавил оборот, выплата убавляет оплаты, и расчёты сходятся
//  обратно в ноль. В списке оплат и в акте сверки она видна отдельной
//  строкой «Возврат денег».
// ------------------------------------------------------------------
export const ВЫПЛАТА = "refund_cash";

export function выплаты({ customer_id, сумма, дата, комментарий = "" }) {
  const когда = дата || new Date().toISOString();
  return ["som", "yuan", "usd"]
    .filter(c => Math.abs(Number((сумма || {})[c]) || 0) > 0.0001)
    .map(c => ({
      customer_id,
      amount: -r2(Number(сумма[c]) || 0),      // минус: деньги ушли от нас
      currency: c,
      date: когда,
      method: ВЫПЛАТА,
      note: ("Возврат денег клиенту" + (комментарий ? ": " + комментарий : "")).slice(0, 200),
    }));
}

// Это выплата по возврату, а не приход денег?
export const этоВыплата = (p) => String((p && p.method) || "") === ВЫПЛАТА || (Number(p && p.amount) || 0) < 0;

// Короткая подпись для списка: «Возврат: 3 поз. · 450 000 сум»
export function подписьВозврата(накладная, сумма) {
  const части = [];
  if (сумма) {
    if (сумма.som) части.push(Math.round(сумма.som).toLocaleString("ru-RU") + " сум");
    if (сумма.yuan) части.push("¥" + r2(сумма.yuan));
    if (сумма.usd) части.push("$" + r2(сумма.usd));
  }
  const поз = ((накладная && накладная.items) || []).length;
  return "Возврат: " + поз + " поз." + (части.length ? " · " + части.join(" + ") : "");
}
