// ========================================================================
//  УПАКОВКА ТОВАРА: в чём покупаем, в чём храним, в чём продаём.
//
//  Поставщик продаёт шпульки поштучно, а на полке они лежат пачками по 10
//  и пачками же уходят клиенту. Раньше это приходилось считать в уме при
//  каждом приходе: 100 штук по 2000 сум — это 10 пачек по 20 000 сум.
//  Ошибиться тут легко, а замечают через месяц, когда прибыль посчиталась
//  от цены штуки.
//
//  ТРИ РАЗНЫЕ ЕДИНИЦЫ:
//    buy_unit   — в чём берём у поставщика (единица в накладной прихода)
//    unit       — в чём лежит на складе и считается остаток   (уже было)
//    sell_unit  — в чём продаём
//
//  ДВА РАЗМЕРА:
//    pack_size  — сколько ШТУК внутри одной складской единицы (уже было)
//    box_size   — сколько СКЛАДСКИХ единиц в одной коробке
//
//  Отсюда получается коэффициент: сколько складских единиц приносит одна
//  закупочная. Всё остальное — количество и себестоимость — считается из
//  него, и считается одинаково в браузере, на сервере и в тесте.
//
//  ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он НЕ трогает остаток. Настройка упаковки
//  — это правило для БУДУЩИХ приходов, а не движение товара. Перевод уже
//  лежащего на складе остатка из штук в пачки — отдельное действие с
//  отдельным подтверждением, оно живёт в js/unit.js (перевести).
//  Путать их нельзя: тогда простая настройка «в пачке 10 штук» молча
//  поделила бы остаток на десять.
//
//  Модуль без обращений к странице: его читает и браузер, и сервер, и тест.
// ========================================================================
import { ЕДИНИЦЫ, единица, вЕдинице, считаетсяПачками, подпись } from "./unit.js?v=20261109j";

// Деньги — до копейки. Количество точнее: при делении на размер пачки
// остаток в сотых заметно двигает итог, а цена пачки во столько же раз
// больше. Шесть знаков — чтобы 105 штук по 10 в пачке не «усохли».
const д2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
const к6 = (n) => Math.round((Number(n) || 0) * 1e6) / 1e6;

const ЗНАЧЕНИЯ = new Set(ЕДИНИЦЫ.map(e => e.value));
const ед = (v) => (ЗНАЧЕНИЯ.has(String(v || "").trim()) ? String(v).trim() : "");

// Что делать с неполной упаковкой: 105 штук при пачке по 10 — это
// 10 пачек и 5 штук. Превращать их в 11 пачек нельзя, терять 5 штук тоже.
export const ПРАВИЛА_ОСТАТКА = [
  { value: "keep",   label: "Оставить как есть — 10 пачек и 5 шт" },
  { value: "pieces", label: "Разрешить продажу поштучно" },
  { value: "wait",   label: "Отложить остаток до следующего прихода" },
  { value: "ask",    label: "Спрашивать подтверждение" },
];
const ПРАВИЛА = new Set(ПРАВИЛА_ОСТАТКА.map(п => п.value));

export const СТАТУС = { НЕТ: "none", ЕСТЬ: "set", ПРОВЕРИТЬ: "check" };

// Есть ли в базе колонки упаковки (db/packing-migration.sql). До миграции
// их нет, и сохранять настройки некуда — об этом надо сказать прямо, а не
// молча не сохранить.
export const естьКолонки = (товары) =>
  (товары || []).some(p => p && Object.prototype.hasOwnProperty.call(p, "packing_ver"));

// ------------------------------------------------------------------
//  Настройки товара, приведённые к одному виду.
//  У товаров, которых ещё не касались, новых колонок нет — тогда всё
//  берётся из того, что было: единица склада и штук внутри.
// ------------------------------------------------------------------
export function настройки(p) {
  const склад = единица(p);
  const вСкладской = вЕдинице(p);
  const закуп = ед(p && p.buy_unit) || склад;
  const продажа = ед(p && p.sell_unit) || склад;
  const вКоробке = Number(p && p.box_size) > 0 ? Number(p.box_size) : 0;
  const список = Array.isArray(p && p.sell_units) ? p.sell_units.map(ед).filter(Boolean) : [];
  const разрешено = список.length ? [...new Set(список)] : [продажа];
  return {
    склад, вСкладской, закуп, продажа, вКоробке, разрешено,
    авто: (p && p.auto_convert) === true,
    правило: ПРАВИЛА.has(p && p.odd_rule) ? p.odd_rule : "keep",
    версия: Math.max(0, Math.trunc(Number(p && p.packing_ver) || 0)),
  };
}

// Сколько ШТУК в одной единице «е». 0 — посчитать нельзя.
// Порядок проверок важен: если на складе считают коробками, то «коробка»
// — это и есть складская единица, а не коробка пачек.
export function штукВ(н, е) {
  if (е === н.склад) return н.вСкладской;
  if (е === "шт") return 1;
  if (е === "коробка") return н.вКоробке > 0 ? н.вКоробке * н.вСкладской : 0;
  return 0;
}

// Сколько СКЛАДСКИХ единиц приносит одна ЗАКУПОЧНАЯ. 0 — не знаем.
//   шпулька: берём штуками, храним пачками по 10 → 0,1
//   коробка из 20 пачек                          → 20
export function коэффициент(p) {
  const н = настройки(p);
  const ш = штукВ(н, н.закуп);
  return ш > 0 && н.вСкладской > 0 ? к6(ш / н.вСкладской) : 0;
}

// ------------------------------------------------------------------
//  Противоречия в настройках. Это НЕ ошибки ввода — это места, где
//  система честно не может посчитать и спрашивать надо у владельца.
// ------------------------------------------------------------------
export function проверки(p) {
  const н = настройки(p);
  const беды = [];
  if (считаетсяПачками(н.склад) && !(н.вСкладской > 1)) {
    беды.push(`Складская единица — «${н.склад}», а сколько штук внутри, не указано.`);
  }
  if (н.закуп === "коробка" && н.склад !== "коробка" && !(н.вКоробке > 0)) {
    беды.push("Закупка коробками, а сколько складских единиц в коробке, не указано.");
  }
  if (p && p.buy_unit && !ед(p.buy_unit)) {
    беды.push(`Единица закупки «${p.buy_unit}» неизвестна.`);
  }
  if (н.вСкладской > 0 && Math.abs(н.вСкладской - Math.round(н.вСкладской)) > 1e-9) {
    беды.push("Штук в упаковке — дробное число. Так не бывает: проверьте.");
  }
  if (н.вКоробке > 0 && Math.abs(н.вКоробке - Math.round(н.вКоробке)) > 1e-9) {
    беды.push("Упаковок в коробке — дробное число. Так не бывает: проверьте.");
  }
  if (!н.разрешено.includes(н.продажа)) {
    беды.push(`Продаём в «${н.продажа}», но этой единицы нет среди разрешённых.`);
  }
  if (н.авто && !коэффициент(p)) {
    беды.push("Автопреобразование включено, но пересчитать приход не из чего.");
  }
  return беды;
}

// Три состояния из задания: не настроено / настроено / требует проверки.
//
// «Не настроено» — у товара ещё не сохраняли упаковку (packing_ver = 0).
// Такие товары приходуются по старому, безопасному пути, без всякого
// пересчёта. Противоречия у них НЕ считаем: иначе каждый из восьмисот
// товаров, заведённых до этой работы, сразу бы потребовал проверки, и
// список стал бы бесполезным.
export function статус(p) {
  const н = настройки(p);
  if (н.версия < 1) return { код: СТАТУС.НЕТ, подпись: "Не настроено", причины: [] };
  const беды = проверки(p);
  if (беды.length) return { код: СТАТУС.ПРОВЕРИТЬ, подпись: "Требует проверки", причины: беды };
  return { код: СТАТУС.ЕСТЬ, подпись: "Настроено", причины: [] };
}

// Применяется ли автопреобразование к приходу этого товара.
export const автоВключено = (p) => статус(p).код === СТАТУС.ЕСТЬ && настройки(p).авто && коэффициент(p) > 0;

// ------------------------------------------------------------------
//  ПЕРЕСЧЁТ ПРИХОДА. Ничего не пишет — только считает, поэтому
//  проверяется тестом без базы и показывается как предпросмотр.
//
//    qty  — сколько закупили, в ЗАКУПОЧНЫХ единицах
//    цена — за одну ЗАКУПОЧНУЮ единицу
// ------------------------------------------------------------------
export function пересчитатьПриход(p, { qty, цена = 0 } = {}) {
  const н = настройки(p);
  const k = коэффициент(p);
  const кол = Number(qty) || 0;
  const ц = Number(цена) || 0;
  const штукВЗакуп = штукВ(н, н.закуп);

  const итог = {
    можно: k > 0,
    коэффициент: k,
    исходно: { кол, ед: н.закуп, цена: д2(ц) },
    сумма: д2(кол * ц),
    правило: н.правило,
  };
  if (!итог.можно) return { ...итог, складских: 0, штук: 0, полных: 0, остатокШтук: 0, ровно: true, себестоимость: 0 };

  // Количество считаем ЧЕРЕЗ ШТУКИ — это целые числа, и на них ничего не
  // теряется. Складские единицы получаются делением, и только здесь
  // появляется дробь: 105 штук по 10 в пачке — это ровно 10,5 пачки.
  const штук = к6(кол * штукВЗакуп);
  const складских = к6(штук / н.вСкладской);
  const полных = Math.floor(к6(складских + 1e-9));
  const остатокШтук = к6(штук - полных * н.вСкладской);

  return {
    ...итог,
    штук,
    складских,
    полных,
    остатокШтук,
    ровно: остатокШтук < 1e-6,
    // Себестоимость ОДНОЙ СКЛАДСКОЙ единицы. Делим цену закупочной на
    // коэффициент: цена штуки 2000 при 10 штуках в пачке — пачка 20 000.
    себестоимость: д2(ц / k),
  };
}

// ------------------------------------------------------------------
//  Человеческие объяснения — их показывают в карточке и в предпросмотре
//  прихода. Держим рядом с расчётом, чтобы подпись не разошлась с числом.
// ------------------------------------------------------------------

// «1 коробка = 20 пачек = 200 шт»
export function цепочка(p) {
  const н = настройки(p);
  const части = [];
  if (н.вСкладской > 1) части.push(`1 ${н.склад} = ${н.вСкладской} шт`);
  if (н.вКоробке > 0 && н.склад !== "коробка") {
    части.push(`1 коробка = ${подпись(н.вКоробке, { unit: н.склад })}`
      + (н.вСкладской > 1 ? ` = ${к6(н.вКоробке * н.вСкладской)} шт` : ""));
  }
  return части.join(" · ");
}

// «Закупаем штуками, на склад кладём пачками: 10 шт = 1 пачка»
//
// Равенство пишем так, чтобы с обеих сторон стояли целые числа. «1 шт =
// 0,1 пачка» формально верно, но читается как ошибка и не склоняется;
// «10 шт = 1 пачка» — ровно то, что человек держит в руках.
export function описаниеЗакупки(p) {
  const н = настройки(p);
  const k = коэффициент(p);
  if (н.закуп === н.склад) return `Закупаем и храним одинаково — в «${н.склад}». Пересчёт не нужен.`;
  if (!k) return "Пересчитать приход не из чего — не хватает размера упаковки.";
  const слева = k < 1 ? подпись(к6(1 / k), { unit: н.закуп }) : подпись(1, { unit: н.закуп });
  const справа = k < 1 ? подпись(1, { unit: н.склад }) : подпись(к6(k), { unit: н.склад });
  return `Закупаем в «${н.закуп}», на склад кладём в «${н.склад}»: ${слева} = ${справа}.`;
}

// Предпросмотр прихода словами. Ровно то, что увидит владелец до того,
// как нажмёт «Оприходовать».
export function объяснитьПриход(p, расчёт) {
  const н = настройки(p);
  if (!расчёт.можно) return "Упаковка не настроена — приход зачислится как раньше, без пересчёта.";
  const строки = [
    `Закуплено: ${подпись(расчёт.исходно.кол, { unit: н.закуп })}`
      + (расчёт.исходно.цена ? ` по ${расчёт.исходно.цена} за ${н.закуп}` : ""),
    `На склад: ${подпись(расчёт.полных, { unit: н.склад })}`
      + (расчёт.ровно ? "" : ` и ${расчёт.остатокШтук} шт отдельно`),
  ];
  if (расчёт.исходно.цена) {
    строки.push(`Себестоимость: ${расчёт.себестоимость} за ${н.склад}`);
    строки.push(`Всего на сумму: ${расчёт.сумма}`);
  }
  if (!расчёт.ровно) {
    строки.push(`Неполная упаковка: ${(ПРАВИЛА_ОСТАТКА.find(п => п.value === н.правило) || {}).label}`);
  }
  return строки.join("\n");
}

// ------------------------------------------------------------------
//  Что записать в товар при сохранении настроек упаковки.
//
//  packing_ver растёт на единицу при каждом сохранении. По нему видно,
//  что упаковку настраивали, и по нему же приход запоминает, ПО КАКИМ
//  правилам он пересчитан: поменяли коэффициент потом — старые документы
//  остаются посчитанными по-старому, как и должно быть.
// ------------------------------------------------------------------
export function поляНастроек(p, значения) {
  const было = настройки(p);
  const склад = ед(значения.unit) || было.склад;
  const вСкладской = склад === "шт" ? 1 : Math.max(1, Number(значения.pack_size) || 1);
  const закуп = ед(значения.buy_unit) || склад;
  const продажа = ед(значения.sell_unit) || склад;
  const вКоробке = Number(значения.box_size) > 0 ? Number(значения.box_size) : null;
  const разрешено = Array.isArray(значения.sell_units)
    ? [...new Set(значения.sell_units.map(ед).filter(Boolean))]
    : было.разрешено;
  return {
    unit: склад,
    pack_size: вСкладской,
    buy_unit: закуп,
    sell_unit: продажа,
    box_size: вКоробке,
    sell_units: разрешено.length ? разрешено : [продажа],
    auto_convert: значения.auto_convert === true,
    odd_rule: ПРАВИЛА.has(значения.odd_rule) ? значения.odd_rule : "keep",
    packing_ver: было.версия + 1,
  };
}

// Меняется ли от этих настроек то, ЧЕМ МЕРЯЮТ остаток. Только в этом
// случае нужен перевод склада (js/unit.js, перевести) и подтверждение
// владельца. Смена единицы закупки или правила остатка остаток не трогает.
export function нуженПереводОстатка(p, значения) {
  const было = настройки(p);
  const склад = ед(значения.unit) || было.склад;
  const вСкладской = склад === "шт" ? 1 : Math.max(1, Number(значения.pack_size) || 1);
  return склад !== было.склад || вСкладской !== было.вСкладской;
}
