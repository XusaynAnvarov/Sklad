//  «У МЕНЯ СТАРАЯ ВЕРСИЯ» — ловим сами.
//
//  Страницы отдаёт nginx, браузер их кэширует, и внутри страницы прописаны
//  адреса кода с версией — значит грузится вчерашний код, хотя на сервере
//  уже новый. Спросить у сервера саму страницу нельзя: её и кэширует
//  браузер. Зато sw.js крошечный и запрашивается в обход кэша — туда
//  _tools/bump.mjs при каждой выкладке пишет версию сборки.
//
//  ОТКУДА БЕРЁМ СВОЮ ВЕРСИЮ. Только из метки в самой странице:
//      <meta name="gm-build" content="20260822c">
//  Из адреса модуля брать НЕЛЬЗЯ. Служебный работник (sw.js) подменяет
//  адреса js и css на "?v=<имя кэша>", а браузер берёт import.meta.url из
//  ОТВЕТА, а не из запроса — и вместо версии сборки оттуда приходит
//  "sklad-v142". Из-за этого проверка сравнивала разное и на каждой
//  загрузке кричала, что версия устарела, хотя всё было свежее.
// ========================================================================

const ВИД = /^\d{8}[a-z]\d*$/;               // как выглядит версия сборки
const ФЛАГ = "gm_reloaded_for";              // чтобы не зациклиться

// Версия страницы, которая сейчас открыта.
export function мояВерсия() {
  try {
    const m = document.querySelector('meta[name="gm-build"]');
    const v = m && m.getAttribute("content");
    return ВИД.test(v || "") ? v : "";
  } catch { return ""; }
}

// Версия, выложенная на сервере. Пустая строка — узнать не удалось.
export async function версияНаСервере() {
  try {
    const r = await fetch("/sw.js?nocache=" + Date.now(), { cache: "no-store" });
    if (!r.ok) return "";
    const текст = await r.text();
    const от = текст.indexOf('const BUILD = "');
    if (от < 0) return "";
    const начало = от + 'const BUILD = "'.length;
    const до = текст.indexOf('"', начало);
    const v = до > начало ? текст.slice(начало, до) : "";
    return ВИД.test(v) ? v : "";
  } catch { return ""; }
}

// Перезагрузиться, если открыто устаревшее. true — решили перезагружаться.
//
// Молчим при любой неясности: не смогли прочитать свою версию или
// серверную — просто работаем дальше. Ложная тревога здесь хуже, чем
// пропущенная: человек увидит красное предупреждение на рабочем экране и
