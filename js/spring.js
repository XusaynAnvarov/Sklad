// ========================================================================
//  ПРУЖИНА И ВЕДЕНИЕ ПАЛЬЦЕМ.
//
//  Зачем своё, а не библиотека. Всё, что нам нужно, — полсотни строк
//  честной физики; тянуть ради этого 30 КБ со стороннего адреса значит
//  добавить ещё одну точку отказа там, где сейчас её нет.
//
//  Чем пружина лучше обычной анимации. У анимации с фиксированной
//  длительностью есть начало и конец, и перебить её нельзя: пока не
//  доиграет, элемент чужой. Пружина же в каждый момент знает, где она и
//  с какой скоростью идёт, — поэтому цель можно поменять на лету, и
//  движение останется непрерывным. Отпустил палец — пружина подхватывает
//  его скорость и доносит элемент сама, без шва между «я тащу» и «оно
//  летит».
//
//  Параметры взяты как у Apple, в понятном виде:
//    затухание 1.0 — доходит и останавливается, без отскока (обычное дело);
//    затухание 0.8 — лёгкий отскок, уместен только после броска;
//    отклик — за сколько секунд доходит до цели (меньше = резче).
//
//  Здесь только расчёт и события указателя, без разметки, — поэтому
//  проверяется тестом _tools/tests/t-spring.mjs.
// ========================================================================

const меньшеДвижения = () => {
  try { return matchMedia("(prefers-reduced-motion: reduce)").matches; } catch { return false; }
};

// ------------------------------------------------------------------
//  ПРУЖИНА.
//  пустить({ от, к, скорость, затухание, отклик, наКадр, наКонец })
//  Возвращает ручку: .кЦели(новая) — поменять цель на ходу, не теряя
//  скорости; .стоп() — бросить; .где() — текущее значение.
// ------------------------------------------------------------------
export function пустить({ от = 0, к = 0, скорость = 0, затухание = 1, отклик = 0.4,
                          наКадр, наКонец, шагВремени }) {
  let x = Number(от) || 0;
  let v = Number(скорость) || 0;
  let цель = Number(к) || 0;
  let живо = true;

  // Перевод «отклик + затухание» в обычные жёсткость и трение.
  const частота = (2 * Math.PI) / Math.max(0.05, отклик);
  const жёсткость = частота * частота;
  const трение = 2 * затухание * частота;

  const близко = () => Math.abs(цель - x) < 0.5 && Math.abs(v) < 2;

  const шаг = (дт) => {
    // Считаем мелкими шагами: один большой шаг при провисшем кадре
    // разносит пружину вразнос.
    const мелкий = Math.min(дт, 0.064);
    const шагов = Math.max(1, Math.ceil(мелкий / 0.004));
    const h = мелкий / шагов;
    for (let i = 0; i < шагов; i++) {
      const ускорение = жёсткость * (цель - x) - трение * v;
      v += ускорение * h;
      x += v * h;
    }
  };

  // Для теста: можно прокрутить пружину без браузера.
  if (шагВремени) {
    return {
      шаг: (дт) => { шаг(дт); return x; },
      где: () => x,
      скорость: () => v,
      кЦели: (н) => { цель = Number(н) || 0; },
      готово: () => близко(),
    };
  }

  if (меньшеДвижения()) {
    x = цель;
    if (наКадр) наКадр(x, 0);
    if (наКонец) наКонец(x);
    return { кЦели: (н) => { цель = Number(н) || 0; x = цель; if (наКадр) наКадр(x, 0); }, стоп() {}, где: () => x };
  }

  let прошлое = performance.now();
  const кадр = (теперь) => {
    if (!живо) return;
    const дт = Math.max(0, (теперь - прошлое) / 1000);
    прошлое = теперь;
    шаг(дт);
    if (близко()) {
      x = цель; v = 0; живо = false;
      if (наКадр) наКадр(x, 0);
      if (наКонец) наКонец(x);
      return;
    }
    if (наКадр) наКадр(x, v);
    requestAnimationFrame(кадр);
  };
  requestAnimationFrame(кадр);

  return {
    // Цель меняется на ходу: положение и скорость остаются прежними —
    // именно это и даёт перехват без рывка.
    кЦели(новая) {
      цель = Number(новая) || 0;
      if (!живо) { живо = true; прошлое = performance.now(); requestAnimationFrame(кадр); }
    },
    стоп() { живо = false; },
    где: () => x,
    скорость: () => v,
  };
}

// ------------------------------------------------------------------
//  КУДА ДОЛЕТИТ.
//  Бросок надо доводить не до ближайшей точки от места отпускания, а до
//  той, куда он сам летит. Формула Apple из примеров к «Designing Fluid
//  Interfaces»: экспоненциальное затухание, а не школьное v²/2a.
// ------------------------------------------------------------------
export function проекция(скорость, замедление = 0.998) {
  const v = Number(скорость) || 0;
  return (v / 1000) * замедление / (1 - замедление);
}

// ------------------------------------------------------------------
//  СОПРОТИВЛЕНИЕ НА КРАЮ.
//  За границей элемент идёт за пальцем всё хуже — как резинка. Жёсткий
//  упор читается как «зависло», мягкий — как «дальше ничего нет».
// ------------------------------------------------------------------
export function резинка(перелёт, размер, постоянная = 0.55) {
  const п = Number(перелёт) || 0;
  const д = Math.max(1, Number(размер) || 1);
  return (п * д * постоянная) / (д + постоянная * Math.abs(п));
}

// ------------------------------------------------------------------
//  ВЕДЕНИЕ ПАЛЬЦЕМ.
//  вести(элемент, { наНачало, наДвижение, наОтпускание, порог, ось })
//    • захват указателя — палец можно увести за край, ведение не рвётся;
//    • помним, откуда взяли (смещение), иначе элемент прыгает под палец;
//    • помним последние точки — из них считается скорость на отпускании;
//    • порог в 10 px: пока не сдвинулись, это нажатие, а не перетаскивание.
// ------------------------------------------------------------------
export function вести(элемент, { наНачало, наДвижение, наОтпускание, порог = 10, ось = "x" } = {}) {
  if (!элемент) return () => {};
  let след = [];          // последние точки: { t, x, y }
  let начат = false, решено = false, id = null, нач = null;

  const точка = (e) => ({ t: performance.now(), x: e.clientX, y: e.clientY });

  const скорость = () => {
    // Берём отрезок последних ~80 мс: по одному кадру скорость скачет.
    const теперь = performance.now();
    const свежие = след.filter(п => теперь - п.t < 80);
    if (свежие.length < 2) return { x: 0, y: 0 };
    const а = свежие[0], б = свежие[свежие.length - 1];
    const дт = Math.max(0.001, (б.t - а.t) / 1000);
    return { x: (б.x - а.x) / дт, y: (б.y - а.y) / дт };
  };

  const вниз = (e) => {
    if (e.button != null && e.button !== 0) return;
    начат = true; решено = false; id = e.pointerId;
    нач = точка(e);
    след = [нач];
    if (наНачало) наНачало(нач);
  };

  const движение = (e) => {
    if (!начат || e.pointerId !== id) return;
    const т = точка(e);
    след.push(т);
    if (след.length > 12) след.shift();
    const дх = т.x - нач.x, ду = т.y - нач.y;
    if (!решено) {
      const путь = ось === "y" ? Math.abs(ду) : Math.abs(дх);
      const поперёк = ось === "y" ? Math.abs(дх) : Math.abs(ду);
      if (путь < порог) return;             // ещё не ясно, нажатие это или ведение
      if (поперёк > путь) { начат = false; return; }   // ведут поперёк — не наше
      решено = true;
      try { элемент.setPointerCapture(id); } catch {}
    }
    if (наДвижение) наДвижение({ дх, ду, точка: т, начало: нач });
  };

  const вверх = (e) => {
    if (!начат || (id != null && e.pointerId !== id)) return;
    const было = решено;
    начат = false; решено = false;
    try { элемент.releasePointerCapture(id); } catch {}
    const т = точка(e);
    const v = скорость();
    id = null;
    if (было && наОтпускание) наОтпускание({ дх: т.x - нач.x, ду: т.y - нач.y, скорость: v });
  };

  элемент.addEventListener("pointerdown", вниз, { passive: true });
  элемент.addEventListener("pointermove", движение, { passive: true });
  элемент.addEventListener("pointerup", вверх, { passive: true });
  элемент.addEventListener("pointercancel", вверх, { passive: true });

  return () => {
    элемент.removeEventListener("pointerdown", вниз);
    элемент.removeEventListener("pointermove", движение);
    элемент.removeEventListener("pointerup", вверх);
    элемент.removeEventListener("pointercancel", вверх);
  };
}
