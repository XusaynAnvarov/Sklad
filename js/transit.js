// ========================================================================
//  ТОВАР В ДОРОГЕ.
//
//  «В дороге» — это позиции приходов, которые ещё не оприходованы
//  (purchases.status ≠ "arrived"). Склад их пока не видит: остаток не
//  изменился, себестоимость прежняя. Но владельцу это знать надо:
//    • сколько едет и от кого — видно на карточке товара, даже если
//      товар сейчас есть в наличии;
//    • если едущая партия ДОРОЖЕ той, что продаётся сейчас, — надо
//      заранее поднять цену, иначе после прихода пойдёт убыток;
//    • товар, которого нет на складе, но он едет, — это не «нет в
//      наличии», а «в дороге», и в списках закончившихся ему не место.
//
//  Здесь только расчёт, без разметки — поэтому проверяется тестом
//  (_tools/tests/t-transit.mjs) и годится и для сайта, и для телефона.
// ========================================================================
import { convert } from "./fx.js?v=20261010e";
import { ensureBatches, currentCost } from "./inventory.js?v=20261010e";

const r2 = (n) => Math.round((Number(n) || 0) * 100) / 100;

// Карта «что едет»: { id товара: { qty, поставщики: [], cost_yuan, cost_usd } }
// Цену берём САМУЮ ВЫСОКУЮ из едущих партий: предупредить надо по худшей.
export function картаДороги(purchases) {
  const карта = {};
  (purchases || []).forEach(приход => {
    if (!приход || приход.status === "arrived") return;
    const валютаПрихода = приход.currency;
    (приход.items || []).forEach(it => {
      const id = String(it.product_id || "");
      if (!id) return;
      const кол = Number(it.qty) || 0;
      if (кол <= 0) return;
      const запись = карта[id] || (карта[id] = { qty: 0, поставщики: [], cost_yuan: 0, cost_usd: 0 });
      запись.qty += кол;
      const кто = String(приход.supplier || "").trim();
      if (кто && !запись.поставщики.includes(кто)) запись.поставщики.push(кто);
      const вал = it.currency || валютаПрихода;
      const цена = Number(it.unit_cost) || 0;
      if (цена > 0) {
        запись.cost_yuan = Math.max(запись.cost_yuan, r2(convert(цена, вал, "yuan")));
        запись.cost_usd = Math.max(запись.cost_usd, r2(convert(цена, вал, "usd")));
      }
    });
  });
  return карта;
}

// Запись о дороге для товара (или null).
export function вДороге(карта, p) {
  if (!карта || !p) return null;
  const з = карта[String(p.id)];
  return з && з.qty > 0 ? з : null;
}

// Едущая партия дороже той, что продаётся сейчас?
// Сравниваем с ценой ТЕКУЩЕЙ партии, а если склад пуст — с последней
// известной ценой из карточки: именно по ней считалась прибыль.
// Сравниваем в той валюте, где цена известна с обеих сторон (обычно юань,
// в нём ведётся закуп), а отдаём обе — показывать надо в валюте товара.
// Возвращает { валюта, было:{yuan,usd}, станет:{yuan,usd}, разница, процент } или null.
export function дорожеСейчас(запись, p) {
  if (!запись || !p) return null;
  const едетY = Number(запись.cost_yuan) || 0, едетU = Number(запись.cost_usd) || 0;
  const своя = currentCost(ensureBatches(p));
  const сейчасY = Number(своя.cost_yuan) || Number(p.cost_yuan) || 0;
  const сейчасU = Number(своя.cost_usd) || Number(p.cost_usd) || 0;

  const пара = (едетY > 0 && сейчасY > 0) ? ["yuan", сейчасY, едетY]
    : (едетU > 0 && сейчасU > 0) ? ["usd", сейчасU, едетU] : null;
  if (!пара) return null;                       // не с чем сравнивать
  const [валюта, было, стало] = пара;
  const мелочь = валюта === "yuan" ? 0.004 : 0.0009;   // копейки округления не считаем
  if (стало <= было + мелочь) return null;
  return {
    валюта,
    было: { yuan: сейчасY, usd: сейчасU },
    станет: { yuan: едетY, usd: едетU },
    разница: r2(стало - было),
    процент: Math.round((стало - было) / было * 100),
  };
}

// Товар закончился, но едет — это не «нет в наличии».
export function едетВместоНет(карта, p) {
  return (Number(p.stock_qty) || 0) <= 0 && !!вДороге(карта, p);
}

// Короткая подпись для карточки: «В дороге: 300 шт · JACK»
export function подписьДороги(запись) {
  if (!запись) return "";
  return "В дороге: " + (Math.round(запись.qty * 100) / 100) + " шт"
    + (запись.поставщики.length ? " · " + запись.поставщики.join(", ") : "");
}
