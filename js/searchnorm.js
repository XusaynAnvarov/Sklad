// Запрос → список «слов», каждое — набор вариантов (любой подходит).
export function разобратьЗапрос(q) {
  const слова = String(q || "").toLowerCase().split(/[\s,;/]+/).filter(Boolean);
  const итог = [];
  for (const w of слова) {
    let варианты = [w];
    for (const [re, на] of СИНОНИМЫ) {
      if (re.test(w)) { варианты = на ? на.split("|") : []; break; }
    }
    if (варианты.length) итог.push(варианты);
  }
  return итог;
}

// Подходит ли товар под запрос (все значимые слова должны найтись)
export function подходитЗапрос(p, q) {
  const слова = разобратьЗапрос(q);
  if (!слова.length) return true;     // запрос из одних общих слов («запчасти для швейных машин»)
  const текст = [p.name, p.category, p.sku, p.code].join(" ").toLowerCase();
  const ключ = компакт(текст);
  return слова.every(варианты => варианты.some(v => {
    if (текст.includes(v)) return true;
    const k = компакт(v);
    return k.length >= 2 && ключ.includes(k);
  }));
}
