//  (браузер импортирует напрямую, сервер — из api/seo/text.js).
//
//  Латиница и кириллица сводятся к одному ключу, артикулы сравниваются
//  без дефисов и скобок, частые опечатки («напчасти», «мошина»), узбекские
//  и английские слова («nina», «needle») понимаются как основная форма.
// ========================================================================

const РУ = {
  а: "a", б: "b", в: "v", г: "g", д: "d", е: "e", ё: "yo", ж: "zh", з: "z", и: "i",
  й: "y", к: "k", л: "l", м: "m", н: "n", о: "o", п: "p", р: "r", с: "s", т: "t",
  у: "u", ф: "f", х: "h", ц: "ts", ч: "ch", ш: "sh", щ: "sch", ъ: "", ы: "y", ь: "",
  э: "e", ю: "yu", я: "ya",
  // узбекская кириллица
  ў: "o", қ: "q", ғ: "g", ҳ: "h",
};

export function translit(s) {
  let out = "";
  for (const ch of String(s || "").toLowerCase()) out += (ch in РУ) ? РУ[ch] : ch;
  return out;
}

// «Мокки вышивка (Арзони)» → «mokki-vyshivka-arzoni»

// ------------------------------------------------------------------
//  ПОИСК: один ключ сравнения для «LP-017», «lp017», «лп 017»,
//  «P36LN-NF» и «p36lnnf». Латиница/кириллица сводятся к латинице.
// ------------------------------------------------------------------
export function компакт(s) {
  return translit(s).replace(/[^a-z0-9]/g, "");
}

