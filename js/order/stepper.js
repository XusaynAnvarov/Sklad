// ========================================================================
//  СЧЁТЧИК КОЛИЧЕСТВА — минус, поле, плюс.
//
//  Поле именно ВВОДИТСЯ с клавиатуры: заказывают не по три штуки, а по
//  двести, и набирать это плюсиком — мучение. Кнопки остаются для мелкой
//  правки «на одну больше».
//
//  Один счётчик на все три экрана: каталог, корзина и позиции заказа.
//  Иначе в одном месте вводить можно, а в другом опять только тыкать.
// ========================================================================
import { el } from "../el.js?v=20260901b";

const ПОТОЛОК = 100000;
const число = (v) => {
  const n = Math.floor(Number(String(v).replace(/[^\d]/g, "")) || 0);
  return n > 0 ? Math.min(n, ПОТОЛОК) : 0;
};

// значение   — сколько показывать сейчас
// изменить   — вызывается ТОЛЬКО когда число окончательно выбрано
//              (нажали кнопку, ушли из поля, нажали Enter). Возвращённое
//              им число становится показанным: так экран правки заказа
//              может отказать в изменении, и поле вернётся к прежнему.
// минимум    — 0 в корзине (ноль = убрать), 1 в каталоге
export function счётчик(значение, изменить, { минимум = 0 } = {}) {
  let текущее = число(значение);

  const поле = el("input.n", {
    // не type=number: он рисует стрелки, а на телефоне пускает в поле
    // минусы и точки. Нужны только цифры.
    type: "text", inputmode: "numeric", pattern: "[0-9]*",
    autocomplete: "off", enterkeyhint: "done",
    "aria-label": "Количество",
    value: String(текущее),
  });

  const показать = (n) => { текущее = n; поле.value = String(n); };

  // Отдать новое число наружу и показать то, что оттуда вернулось.
  const применить = (n) => {
    const хочу = Math.max(минимум, число(n));
    if (хочу === текущее) { поле.value = String(текущее); return; }
    const стало = изменить(хочу);
    показать(стало == null ? хочу : число(стало));
  };

  // Ввод: в поле оставляем только цифры, но наружу пока не отдаём —
  // иначе «200» по дороге успело бы стать «2», потом «20».
  поле.addEventListener("input", () => {
    const чисто = поле.value.replace(/[^\d]/g, "").slice(0, 6);
    if (поле.value !== чисто) поле.value = чисто;
  });
  // Всё выделяем при заходе: обычно вводят новое число, а не дописывают.
  поле.addEventListener("focus", () => { try { поле.select(); } catch { } });
  поле.addEventListener("blur", () => применить(поле.value));
  поле.addEventListener("keydown", (e) => {
    if (e.key !== "Enter") return;
    e.preventDefault();
    применить(поле.value);       // применяем сразу, а не через потерю фокуса
    поле.blur();                 // и прячем клавиатуру (применить повторно — не страшно)
  });

  const кнопка = (знак, шаг) => {
    const b = el("button.q", { type: "button", text: знак, "aria-label": шаг > 0 ? "Больше" : "Меньше" });
    b.addEventListener("click", () => применить(текущее + шаг));
    return b;
  };

  const рамка = el("div.ord-qty", {}, [кнопка("−", -1), поле, кнопка("+", 1)]);
  // Экран может обновить число снаружи (например, перечитал заказ).
  рамка.поставить = показать;
  // Досчитать прямо сейчас и отдать число. Нужно кнопке «В корзину»:
  // клиент мог набрать «200» и нажать её, не уводя палец из поля.
  рамка.значение = () => { применить(поле.value); return текущее; };
  return рамка;
}
