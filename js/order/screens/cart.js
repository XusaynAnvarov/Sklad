// ========================================================================
//  КОРЗИНА — что уйдёт в заказ.
//  Здесь же честно сказано, что произойдёт при отправке: если заказ уже
//  отправлен и ещё не оценён, товары допишутся в него, а количества
//  сложатся. Раньше клиент об этом узнавал постфактум — и решал, что
//  первый заказ пропал.
// ========================================================================
import { el } from "../../el.js?v=20260902c";
import { icon } from "../../icons.js?v=20260902c";
import { toast, confirmDialog } from "../../ui.js?v=20260902c";
import { идти } from "../app.js?v=20260902c";
import { отправитьКорзину } from "../api.js?v=20260902c";
import { снимки, картинка } from "../photo.js?v=20260902c";
import { счётчик } from "../stepper.js?v=20260902c";

const дата = (d) => { const t = new Date(d); return isFinite(t) ? t.toLocaleDateString("ru-RU") : "—"; };

export default function render(box, ctx) {
  const { корзина } = ctx;
  // Заказ, в который допишутся товары. Годится и тот, которому цены уже
  // выставили: клиент, увидев цены, часто добавляет ещё. Тогда заказ
  // вернётся владельцу на расчёт — предупреждаем об этом заранее.
  const открытый = ctx.заказы.find(o => o.status === "order")
    || ctx.заказы.find(o => o.status === "pending_confirm") || null;
  const сЦенами = открытый && открытый.status === "pending_confirm";

  const список = el("div.mini-list");
  const низ = el("div.mini-cta");
  // Итог считается отдельно: при вводе количества незачем перерисовывать
  // весь список — под пальцем пропало бы поле, в которое только что вводили.
  const сводка = el("div.ord-sum");
  const обновитьСводку = () => {
    const { позиций, штук } = корзина.итого();
    сводка.textContent = позиций + " поз. · " + штук + " шт.";
  };
  box.append(список, низ);

  function рисовать() {
    список.innerHTML = "";
    низ.innerHTML = "";

    const позиции = корзина.позиции();
    if (!позиции.length) {
      список.append(el("div.mini-empty", { text: "Корзина пуста. Выберите товары в каталоге." }));
      const кн = el("button.btn.btn-outline", {
        style: { width: "100%", justifyContent: "center", minHeight: "46px", marginTop: "4px" },
        text: "Открыть каталог", onclick: () => идти("catalog"),
      });
      список.append(кн);
      return;
    }

    if (открытый) {
      список.append(el("div.ord-note", {}, [
        icon("alert", { size: 16 }),
        el("span", { text: сЦенами
          ? `По заказу от ${дата(открытый.date)} цена уже готова. Эти товары допишем в него — `
            + "на новое посчитаем цену и пришлём заказ на подтверждение заново."
          : `У вас уже есть заказ от ${дата(открытый.date)}, мы его ещё считаем. `
            + "Эти товары допишем в него — одинаковые сложатся по количеству." }),
      ]));
    }

    позиции.forEach(({ id, qty }) => {
      const p = ctx.поИд.get(String(id));
      const имя = p ? p.name : "товар недоступен";
      const фото = p ? снимки(p) : [];

      // Ноль убирает товар из корзины — тогда список перерисовывается целиком.
      const поле = счётчик(qty, (n) => {
        const стало = корзина.поставить(id, n);
        if (стало <= 0) { рисовать(); return 0; }
        обновитьСводку();
        return стало;
      });

      список.append(el("div.mini-row", {}, [
        картинка(фото[0], { size: 96, имя, className: "ph" }),
        el("div.info", {}, [
          el("div.nm", { text: имя }),
          p && p.sku ? el("div.sku", { text: p.sku }) : null,
        ].filter(Boolean)),
        поле,
        el("button.ord-del", { title: "Убрать", onclick: () => { корзина.поставить(id, 0); рисовать(); } }, [icon("trash", { size: 16 })]),
      ]));
    });

    список.append(сводка, el("div.hint", { style: { marginTop: "6px" },
      text: "Цену мы посчитаем и пришлём вам на подтверждение." }));
    обновитьСводку();

    const отправить = el("button.btn.btn-primary", {}, [
      icon("send", { size: 17 }),
      открытый ? "Добавить к заказу" : "Отправить заказ",
    ]);
    отправить.addEventListener("click", () => подтвердить(отправить));
    низ.append(отправить);
  }

  function подтвердить(кнопка) {
    const { позиций, штук } = корзина.итого();
    const вопрос = открытый
      ? `Дописать ${позиций} поз. (${штук} шт.) к заказу от ${дата(открытый.date)}?`
      : `Отправить заказ: ${позиций} поз., ${штук} шт.?`;
    confirmDialog(вопрос, async () => {
      кнопка.disabled = true;
      const прежний = кнопка.innerHTML;
      кнопка.textContent = "Отправляем…";
      try {
        const ответ = await отправитьКорзину(корзина.позиции().map(({ id, qty }) => ({ id, qty })));
        корзина.очистить();
        if (ответ.skipped && ответ.skipped.length) {
          toast("Не попали в заказ (разобрали): " + ответ.skipped.join(", "), "err");
        }
        try { await ctx.обновитьЗаказы(); } catch {}
        toast(ответ.repriced ? "Добавили. Посчитаем цену на новое и пришлём заказ заново"
          : ответ.merged ? "Товары добавлены в ваш заказ"
            : "Заказ отправлен", "ok");
        идти("orders");
      } catch (e) {
        кнопка.disabled = false;
        кнопка.innerHTML = прежний;
        toast("Не удалось отправить: " + (e.message || e), "err");
      }
    });
  }

  рисовать();
}
