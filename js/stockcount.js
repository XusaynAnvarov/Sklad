// ========================================================================
//  ПЕРЕСЧЁТ СКЛАДА ПО ЛИСТУ EXCEL.
//
//  Владелец ходит по полкам с листом (или с телефоном), вписывает в колонку
//  «Факт на полке» то, что реально лежит, и загружает файл назад. Здесь —
//  только расчёт: кого с кем сопоставили, где расхождение и что записать.
//  Записью занимается экран (js/pages/stock_count.js), поэтому всё, что
//  ниже, проверяется тестом t-stockcount.mjs.
//
//  Два правила, из-за которых всё это и написано отдельным модулем:
//  1. ПУСТАЯ клетка — это «не считал», а НЕ ноль. Склад на 941 товар за
//     один раз не обходят; незаполненные строки нельзя обнулять.
//  2. Сопоставляем сначала по коду, потом по артикулу и только потом по
//     названию. Названия у нас похожие («Кайчи (10) KDP» и «Кайчи (11) KDP»),
//     и по имени легко попасть не в тот товар.
// ========================================================================
import { ensureBatches, sumQty, consumeFIFO, returnToStock, currentCost, costAfter } from "./inventory.js?v=20261007c";

const чисто = (s) => String(s == null ? "" : s).trim();
const ключКода = (s) => чисто(s).toUpperCase().replace(/[^A-Z0-9]/g, "");
// Ведущий апостроф отрезаем: в выгруженный лист он попадает нарочно, чтобы
// Excel не принял название вроде «=СУММА…» за формулу (js/xlsx-export.js).
const ключИмени = (s) => чисто(s).replace(/^'+/, "").toLowerCase().replace(/\s+/g, " ");

// Число из клетки: «1 200», «12,5», «  » → null, если считать нечего.
export function число(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).trim().replace(/\s/g, "").replace(",", ".");
  if (s === "") return null;
  if (!/^-?\d+(\.\d+)?$/.test(s)) return null;
  const n = parseFloat(s);
  return isFinite(n) ? n : null;
}

// Сопоставить строки листа с товарами склада.
// строки: [{ code, sku, name, факт }]
// Возвращает:
//   расхождения — [{ p, было, факт, разница }] (только где факт ≠ остаток)
//   совпало     — сколько посчитали и остаток сошёлся
//   пустые      — строк без числа (не считали)
//   ненайденные — названия, которых нет на складе
//   повторы     — товары, встреченные в листе дважды (берём первое число)
export function сверитьЛист(строки, товары) {
  const поКоду = new Map(), поАртикулу = new Map(), поИмени = new Map();
  for (const p of (товары || [])) {
    if (p.code) поКоду.set(ключКода(p.code), p);
    if (p.sku) поАртикулу.set(ключКода(p.sku), p);
    const k = ключИмени(p.name);
    if (k && !поИмени.has(k)) поИмени.set(k, p);     // первый с таким именем
  }
  const найти = (r) =>
    (r.code && поКоду.get(ключКода(r.code))) ||
    (r.sku && поАртикулу.get(ключКода(r.sku))) ||
    (r.name && поИмени.get(ключИмени(r.name))) || null;

  const расхождения = [], ненайденные = [], повторы = [];
  const видели = new Set();
  let совпало = 0, пустые = 0;

  for (const r of (строки || [])) {
    const факт = число(r.факт);
    if (факт === null) { пустые++; continue; }
    const p = найти(r);
    if (!p) { ненайденные.push(чисто(r.name) || чисто(r.code) || "—"); continue; }
    if (видели.has(p.id)) { повторы.push(p.name); continue; }
    видели.add(p.id);
    const было = Number(p.stock_qty) || 0;
    if (Math.abs(факт - было) < 0.0001) { совпало++; continue; }
    расхождения.push({ p, было, факт, разница: Math.round((факт - было) * 100) / 100 });
  }
  расхождения.sort((a, b) => Math.abs(b.разница) - Math.abs(a.разница));
  return { расхождения, совпало, пустые, ненайденные, повторы, посчитано: видели.size };
}

// Что записать по одному товару, чтобы остаток стал равен факту.
// Это та же арифметика, что в setStock (js/sklad/stock.js), но без обращения
// к базе: пересчёт правит сотни товаров и пишется пачкой.
// Вниз — списываем по FIFO (уходит самое старое). Вверх — дописываем по цене
// той партии, что продаётся сейчас: вводить цену при пересчёте никто не будет,
// а себестоимость трогать нельзя.
export function строкаПересчёта(p, факт) {
  const цель = Number(факт);
  if (!isFinite(цель)) return null;
  const партии = ensureBatches(p);
  const сейчас = sumQty(партии);
  if (Math.abs(цель - сейчас) < 0.0001) return null;

  let next;
  if (цель < сейчас) {
    next = consumeFIFO(партии, сейчас - цель).batches;
  } else {
    const своя = currentCost(партии);
    const cy = своя.cost_yuan || Number(p.cost_yuan) || 0;
    const cu = своя.cost_usd || Number(p.cost_usd) || 0;
    // Долг (минус внутри партий) закрываем: остаток вписан «как на полке»,
    // значит никому ничего не должны. Иначе минус всплыл бы при продаже.
    const живые = партии.filter(b => (Number(b.qty) || 0) > 0);
    const есть = sumQty(живые);
    // Живого товара может оказаться БОЛЬШЕ факта (остаток 0, а внутри
    // «+20 и −20»): тогда лишнее надо списать, а не оставить как есть.
    next = цель > есть ? returnToStock(живые, цель - есть, cy, cu) : consumeFIFO(живые, есть - цель).batches;
  }
  const cc = costAfter(next, p);
  return { id: p.id, stock_qty: sumQty(next), cost_yuan: cc.cost_yuan, cost_usd: cc.cost_usd, batches: next };
}
