// ========================================================================
//  ПОИСК ТОВАРА — одно правило на весь склад.
//
//  Раньше условие «название, категория или артикул» было написано заново в
//  девяти местах, и они разошлись: где-то искали по категории, где-то нет.
//  Теперь ищет одна функция — и по постоянному коду тоже.
//
//  Код клиенты пишут как придётся: «LP-017», «lp17», «LP 017». Всё это
//  находит один и тот же товар.
// ========================================================================
import { компактныйКод } from "./catalogcode.js?v=20260926a";

const низ = (s) => String(s || "").toLowerCase();

export function подходит(p, запрос) {
  const q = низ(запрос).trim();
  if (!q) return true;
  if (!p) return false;
  if (низ(p.name).includes(q)) return true;
  if (низ(p.category).includes(q)) return true;
  if (низ(p.sku).includes(q)) return true;
  if (низ(p.code).includes(q)) return true;
  // «lp17» и «LP-017» — один код
  const искомый = компактныйКод(q);
  return !!искомый && !!p.code && компактныйКод(p.code) === искомый;
}
