// ========================================================================
//  ЦЕНЫ: ЗА ШТУКУ, ЗА ПАЧКУ, ЗА КОРОБКУ — И ЧТО К НИМ ДОБАВЛЯЕТСЯ.
//
//  Поставщик называет цену в своих единицах: «2000 за штуку» или «400 000
//  за коробку». На полке лежит пачка, и прибыль считается от пачки. Пока
//  это пересчитывают в уме, ошибка видна не сразу: продаёшь месяц, а потом
//  выясняется, что считал от цены штуки.
//
//  Здесь три разные вещи, и путать их нельзя:
//
//    1. УРОВНИ ЦЕН — одна и та же цена, показанная за штуку, за складскую
//       единицу и за коробку. Ничего не решает, просто переводит.
//
//    2. ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ закупки (доставка, растаможка, комиссия).
//       Они ложатся в себестоимость товара, и разложить их надо так, чтобы
//       сумма долей ДО КОПЕЙКИ совпала с расходом. Поэтому делим в
//       копейках целыми числами, а нераспределённые копейки отдаём тем
//       позициям, у которых остаток от деления больше. Ни одна копейка не
//       пропадает и ни одна не появляется из ниоткуда.
//
//    3. МАРЖА — разница между ценой продажи и себестоимостью. Считается,
//       но НИЧЕГО не меняет: цена продажи от себестоимости сама не едет.
//       Это требование владельца, и оно здесь выполняется тем, что модуль
//       не умеет записывать цену — только показывать прибыль от неё.
//
//  Модуль без обращений к странице: его читает и браузер, и сервер, и
//  тест. Денег не пишет, остатков не трогает — только считает.
// ========================================================================
import { настройки, штукВ } from "./packing.js?v=20261109d";
import { isShop } from "./purchase.js?v=20261109d";

// Деньги — до копейки. Количество точнее: доля расхода на одну закупочную
// единицу может быть дробной, и округлять её до копейки рано — иначе на
// 105 штуках копейка расхода пропадёт, а итог перестанет сходиться.
const д2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
const к6 = (n) => Math.round((Number(n) || 0) * 1e6) / 1e6;
const вКопейки = (n) => Math.round((Number(n) || 0) * 100);

// ------------------------------------------------------------------
//  1. УРОВНИ ЦЕН
//
//  Одна цена, названная в какой-то единице, — во всех остальных.
//  Отдаёт числа, а не подписи: форматирование валюты знает страница.
// ------------------------------------------------------------------
export function уровниЦен(p, { цена = 0, ед = "" } = {}) {
  const н = настройки(p);
  const за = ед || н.склад;
  const штукВИсходной = штукВ(н, за);
  if (!(штукВИсходной > 0)) return [];

  const цена1шт = Number(цена) / штукВИсходной;
  const уровни = [];
  for (const единица of ["шт", н.склад, н.закуп, "коробка"]) {
    if (уровни.some(у => у.ед === единица)) continue;
    const ш = штукВ(н, единица);
    if (!(ш > 0)) continue;
    уровни.push({ ед: единица, штук: ш, цена: д2(цена1шт * ш), исходный: единица === за });
  }
  return уровни.sort((a, b) => a.штук - b.штук);
}

// ------------------------------------------------------------------
//  2. ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ ЗАКУПКИ
// ------------------------------------------------------------------

// Правило учёта: пропорционально чему делить расход между позициями.
// «По стоимости» — обычный способ для доставки и растаможки: дорогой
// товар забирает большую часть. «По штукам» — когда платят за объём.
export const ПРАВИЛА_РАСХОДОВ = [
  { value: "value", label: "По стоимости позиций" },
  { value: "pieces", label: "По количеству штук" },
  { value: "items", label: "Поровну между позициями" },
];
const ПРАВИЛА = new Set(ПРАВИЛА_РАСХОДОВ.map(п => п.value));
export const правилоРасходов = (v) => (ПРАВИЛА.has(v) ? v : "value");

// Расходы документа, приведённые к одному виду. У приходов, заведённых до
// этой работы, поля extra нет — значит расходов нет, и ничего не меняется.
export function расходы(purchase) {
  const e = (purchase && purchase.extra) || null;
  const сумма = д2(Math.max(0, Number(e && e.сумма) || 0));
  return {
    сумма,
    есть: сумма > 0,
    валюта: String((e && e.валюта) || (purchase && purchase.currency) || ""),
    правило: правилоРасходов(e && e.правило),
    примечание: String((e && e.примечание) || ""),
  };
}

// Что записать в документ. Ноль — значит расходов нет: пишем null, чтобы
// в приходе не оставалась пустая запись.
export function поляРасходов({ сумма, валюта, правило, примечание } = {}) {
  const с = д2(Math.max(0, Number(сумма) || 0));
  if (!(с > 0)) return null;
  return {
    сумма: с,
    валюта: String(валюта || ""),
    правило: правилоРасходов(правило),
    ...(примечание ? { примечание: String(примечание) } : {}),
  };
}

// Вес позиции — то, пропорционально чему делим. Только целые числа:
// на дробных «деление без потерь» не докажешь.
function веса(items, products, правило) {
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  return (items || []).map(it => {
    const кол = Number(it && it.qty) || 0;
    if (кол <= 0) return 0;
    if (правило === "items") return 1;
    if (правило === "pieces") {
      // Сколько штук приносит эта позиция. У ненастроенного товара
      // закупочная единица и складская совпадают, и выходит само
      // количество — ровно то, что и имелось в виду.
      const н = настройки(pmap[it.product_id] || {});
      const ш = штукВ(н, н.закуп);
      return Math.max(0, Math.round(кол * (ш > 0 ? ш : 1)));
    }
    return Math.max(0, вКопейки(кол * (Number(it.unit_cost) || 0)));
  });
}

// РАСПРЕДЕЛЕНИЕ БЕЗ ПОТЕРЬ. Отдаёт по доле на каждую позицию документа,
// в валюте расхода, в том же порядке, что items.
//
// Делим целыми копейками (BigInt), поэтому результат не зависит от того,
// как лёг двоичный дробный знак: сумма долей РАВНА сумме расхода.
export function доплаты(purchase, products) {
  const items = (purchase && purchase.items) || [];
  const ноль = items.map(() => 0);
  const р = расходы(purchase);
  if (!р.есть) return ноль;
  // Из магазина товар приходуется по НАШЕЙ складской цене — чужие расходы
  // к ней добавлять нельзя, иначе себестоимость поедет вверх без причины.
  if (isShop(purchase)) return ноль;

  let вес = веса(items, products, р.правило).map(x => BigInt(x));
  let всегоВеса = вес.reduce((a, b) => a + b, 0n);
  // Веса не посчитались (нулевые цены или нулевые количества) — делим
  // поровну: это честнее, чем молча не разделить вовсе.
  if (всегоВеса === 0n) { вес = items.map(() => 1n); всегоВеса = BigInt(items.length); }
  if (всегоВеса === 0n) return ноль;

  const всего = BigInt(вКопейки(р.сумма));
  const доли = вес.map(w => (всего * w) / всегоВеса);
  const остатки = вес.map(w => (всего * w) % всегоВеса);
  let нераздано = всего - доли.reduce((a, b) => a + b, 0n);

  // Нераспределённые копейки — тем, у кого остаток от деления больше.
  // При равных остатках порядок решает номер позиции, чтобы один и тот
  // же документ всегда делился одинаково.
  const порядок = остатки
    .map((o, i) => ({ o, i }))
    .sort((a, b) => (a.o === b.o ? a.i - b.i : (b.o > a.o ? 1 : -1)));
  for (const { i } of порядок) {
    if (нераздано <= 0n) break;
    доли[i] += 1n;
    нераздано -= 1n;
  }
  return доли.map(d => Number(d) / 100);
}

// Цена одной ЗАКУПОЧНОЙ единицы вместе с долей расходов.
// Округляем только в шестом знаке: копейка расхода, поделённая на 105
// штук, в копейках не умещается, а в итоге обязана сойтись.
export function ценаСРасходами(кол, цена, доп) {
  const к = Number(кол) || 0;
  const ц = Number(цена) || 0;
  const д = Number(доп) || 0;
  if (!(к > 0) || !д) return к6(ц);
  return к6(ц + д / к);
}

// ------------------------------------------------------------------
//  3. МАРЖА И ПРИБЫЛЬ
//
//  Считается от цены продажи, которая УЖЕ задана владельцем. Обратного
//  хода нет: себестоимость выросла — здесь просто станет видно, что
//  прибыль упала, а цену владелец поменяет сам, если захочет.
// ------------------------------------------------------------------
export function маржа({ себестоимость = 0, цена = 0 } = {}) {
  const с = д2(себестоимость);
  const ц = д2(цена);
  const прибыль = д2(ц - с);
  return {
    себестоимость: с,
    цена: ц,
    прибыль,
    // Доля прибыли в цене продажи — то, что обычно и называют маржой.
    маржа: ц > 0 ? д2((прибыль / ц) * 100) : 0,
    // Насколько цена дороже себестоимости — наценка. Это другое число, и
    // путать их нельзя: наценка 100% — это маржа 50%.
    наценка: с > 0 ? д2((прибыль / с) * 100) : 0,
    есть: ц > 0,
    вМинус: ц > 0 && прибыль < 0,
  };
}
