// ========================================================================
//  ТЕКСТ ПОСТА: РАЗМЕТКА TELEGRAM ↔ ОБЫЧНЫЙ ТЕКСТ.
//  Общий модуль — им пользуются и редактор в складе, и сервер.
//
//  Пост для Telegram хранится с разметкой (<b>, <code>). Владелец её
//  видеть не должен: он правит обычный текст, а разметку ставим мы сами
//  по двум правилам:
//    1. первая строка — заголовок, жирным;
//    2. строка «Артикул: …» — код артикула моноширинным.
//  Всё, что владелец написал, экранируется. Значит, никакой символ «<»
//  в тексте не сломает разметку поста и ничего лишнего в него не вставит.
// ========================================================================

export const ДЛИНА_МАКС = 3500;   // у текстового сообщения Telegram предел 4096

const экран = (s) => String(s ?? "")
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Разметка → обычный текст (для правки).
export function вТекст(html) {
  return String(html ?? "")
    .replace(/<\/?(b|strong|i|em|u|s|code|pre)>/gi, "")
    .replace(/<a\b[^>]*>|<\/a>/gi, "")
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, "\"")
    .replace(/&amp;/g, "&");
}

// Обычный текст → разметка Telegram. Пустые строки по краям убираются,
// подряд идущих пустых строк остаётся не больше одной.
export function вРазметку(текст) {
  const строки = String(текст ?? "")
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((с) => с.replace(/\s+$/, ""));
  while (строки.length && !строки[0].trim()) строки.shift();
  while (строки.length && !строки[строки.length - 1].trim()) строки.pop();
  const сжатые = строки.filter((с, i) => с.trim() || строки[i - 1]?.trim());
  return сжатые.map((с, i) => {
    if (i === 0) return `<b>${экран(с.trim())}</b>`;
    const а = с.match(/^(Артикул:\s*)(\S.*)$/);
    if (а) return `${экран(а[1])}<code>${экран(а[2])}</code>`;
    return экран(с);
  }).join("\n");
}

// Что видно человеку: длина без разметки (так считает и Telegram).
export const видимаяДлина = (html) => вТекст(html).length;
