// ========================================================================
//  СМЕНА ТЕМЫ КРУГОВОЙ ВОЛНОЙ
//
//  Новая тема не подменяет старую разом, а раскрывается кругом из той
//  кнопки, которую нажали, — как в ролике, присланном владельцем
//  (IMG_3214: переключатель в правом верхнем углу, и светлая тема
//  выезжает кругом поверх тёмной).
//
//  Работает это на View Transitions: браузер сам снимает кадр «до» и
//  кадр «после» и даёт анимировать переход между ними. Нам остаётся
//  задать круг растущего радиуса.
//
//  Где такого нет (Firefox до 129, Safari до 18) — тема меняется как
//  раньше, мгновенно. Ради красоты ничего не ломаем: смена темы обязана
//  срабатывать всегда.
//
//  Используется и сайтом (js/site/app.js), и складом (js/effects.js) —
//  потому и вынесено в отдельный файл.
// ========================================================================

const меньшеДвижения = () => {
  try { return matchMedia("(prefers-reduced-motion: reduce)").matches; } catch { return false; }
};

export const умеетВолну = () =>
  typeof document !== "undefined" && typeof document.startViewTransition === "function";

// ========================================================================
//  ГДЕ ВОЛНА СТОИТ ДОРОЖЕ, ЧЕМ КРАСИВА.
//
//  Волна — это не просто анимация. Чтобы её показать, браузер снимает
//  кадр ВСЕЙ страницы до и после, а пока круг растёт, страница заморожена:
//  ни нажать, ни прокрутить. На дашборде этого не видно. На складском
//  списке в несколько сотен строк снимок сам по себе стоит сотни
//  миллисекунд, и получается то, на что жаловался владелец: нажал
//  «Тёмная» — и секунду ничего.
//
//  Замерено на стенде (admin-demo, демо-данные размножены):
//    258 карточек товара  — с волной: тема встала через 64 мс, худший
//                           кадр 117 мс; без волны: 0.1 мс и 50 мс.
//    1500 строк таблицы   — с волной: тема встала через 3.8 с, худший
//                           кадр 5.5 с; без волны: 0.2 мс и 2.0 с.
//
//  Отсюда два ограничителя. Первый — по размеру страницы: считаем узлы
//  перед снимком, это одна дешёвая операция. Второй — по факту: если
//  снимок всё-таки вышел дорогим (слабый телефон, страница потяжелела
//  после догрузки), волну выключаем до конца сеанса. Второй раз человек
//  за ту же красоту платить не должен.
//
//  Смена темы при этом не ломается никогда: не вышла волна — тема
//  меняется мгновенно, как и было задумано изначально.
// ========================================================================

const ПОРОГ_УЗЛОВ = 1800;        // страница крупнее — меняем тему сразу
const ПОРОГ_СНИМКА = 150;        // мс: снимок вышел дорогим, волну больше не зовём
const КЛЮЧ_ОТКАЗА = "gm_volna_off";

// ------------------------------------------------------------------------
//  ГЛУШИЛКА CSS-ПЕРЕХОДОВ НА МОМЕНТ СМЕНЫ ТЕМЫ.
//
//  Без неё сотни элементов разом начинают анимировать цвет: на списке в
//  1200 строк это 849 мс потерянных кадров против 433 мс с глушилкой.
//
//  Класс снимаем В ПРОСТОЕ, а не через два кадра, как было. Селектор
//  `html.no-theme-anim *` (css/theme.css, css/site.css) универсальный —
//  браузер и на появление, и на исчезновение класса пересчитывает стили
//  всего документа. Два кадра ставили второй пересчёт ровно за отрисовкой
//  новой темы, и он добавлял к той же задержке ещё 133 мс: 566 мс против
//  433 мс на том же списке. В простое он никому не мешает, а переходы к
//  тому времени всё равно уже не нужны.
//
//  Снять класс обязаны в любом случае — иначе на странице навсегда
//  останутся выключенные переходы. Поэтому и простой, и запасной таймер.
// ------------------------------------------------------------------------
export function безПереходов(применить) {
  const root = document.documentElement;
  root.classList.add("no-theme-anim");
  применить();
  let снято = false;
  const снять = () => {
    if (снято) return;
    снято = true;
    root.classList.remove("no-theme-anim");
  };
  try {
    if (typeof requestIdleCallback === "function") requestIdleCallback(снять, { timeout: 400 });
  } catch {}
  setTimeout(снять, 450);
}

const тяжёлаяСтраница = () => {
  try { return document.getElementsByTagName("*").length > ПОРОГ_УЗЛОВ; } catch { return false; }
};
const волнаВыключена = () => {
  try { return sessionStorage.getItem(КЛЮЧ_ОТКАЗА) === "1"; } catch { return false; }
};
const выключитьВолну = () => { try { sessionStorage.setItem(КЛЮЧ_ОТКАЗА, "1"); } catch {} };

// откуда — нажатая кнопка (из неё пойдёт круг); применить — смена темы.
export function сменитьТемуВолной(откуда, применить) {
  if (!умеетВолну() || меньшеДвижения() || волнаВыключена() || тяжёлаяСтраница()) {
    применить(); return;
  }

  // Центр волны — середина нажатой кнопки. Если кнопки нет (смена из
  // кода), берём правый верхний угол: переключатель стоит там.
  const к = откуда && откуда.getBoundingClientRect ? откуда.getBoundingClientRect() : null;
  const x = к ? к.left + к.width / 2 : window.innerWidth - 40;
  const y = к ? к.top + к.height / 2 : 40;

  // Радиус — до самого дальнего угла экрана. Считать по ширине экрана
  // мало: если кнопка в углу, круг не накроет противоположный край, и
  // в нём останется лоскут старой темы.
  const радиус = Math.hypot(
    Math.max(x, window.innerWidth - x),
    Math.max(y, window.innerHeight - y),
  );

  let переход;
  const начало = performance.now();
  try { переход = document.startViewTransition(() => применить()); }
  catch { применить(); return; }

  переход.ready
    .then(() => {
      // Снимок обошёлся дорого — больше в этом сеансе не повторяем.
      if (performance.now() - начало > ПОРОГ_СНИМКА) выключитьВолну();
      document.documentElement.animate(
        {
          clipPath: [
            `circle(0px at ${x}px ${y}px)`,
            `circle(${радиус}px at ${x}px ${y}px)`,
          ],
        },
        {
          // 420, а не 520: всё это время страница заморожена, и каждые
          // лишние сто миллисекунд читаются как тормоз. Круг по-прежнему
          // видно, что он круг.
          duration: 420,
          easing: "cubic-bezier(.2,.8,.25,1)",
          // Растёт именно НОВЫЙ кадр — старый остаётся на месте и
          // открывается из-под него. Наоборот было бы «стирание».
          pseudoElement: "::view-transition-new(root)",
        },
      );
    })
    // Отказ перехода (вкладка скрыта, снимок не вышел) не должен ничего
    // ронять: тема к этому моменту уже сменилась.
    .catch(() => {});
}
