// ========================================================================
//  СМЕНА ТЕМЫ КРУГОВОЙ ВОЛНОЙ
//
//  Новая тема не подменяет старую разом, а раскрывается кругом из той
//  кнопки, которую нажали, — как в ролике, присланном владельцем
//  (IMG_3214: переключатель в правом верхнем углу, и светлая тема
//  выезжает кругом поверх тёмной).
//
//  Работает это на View Transitions: браузер сам снимает кадр «до» и
//  кадр «после» и даёт анимировать переход между ними. Нам остаётся
//  задать круг растущего радиуса.
//
//  Где такого нет (Firefox до 129, Safari до 18) — тема меняется как
//  раньше, мгновенно. Ради красоты ничего не ломаем: смена темы обязана
//  срабатывать всегда.
//
//  Используется и сайтом (js/site/app.js), и складом (js/effects.js) —
//  потому и вынесено в отдельный файл.
// ========================================================================

const меньшеДвижения = () => {
  try { return matchMedia("(prefers-reduced-motion: reduce)").matches; } catch { return false; }
};

export const умеетВолну = () =>
  typeof document !== "undefined" && typeof document.startViewTransition === "function";

// откуда — нажатая кнопка (из неё пойдёт круг); применить — смена темы.
export function сменитьТемуВолной(откуда, применить) {
  if (!умеетВолну() || меньшеДвижения()) { применить(); return; }

  // Центр волны — середина нажатой кнопки. Если кнопки нет (смена из
  // кода), берём правый верхний угол: переключатель стоит там.
  const к = откуда && откуда.getBoundingClientRect ? откуда.getBoundingClientRect() : null;
  const x = к ? к.left + к.width / 2 : window.innerWidth - 40;
  const y = к ? к.top + к.height / 2 : 40;

  // Радиус — до самого дальнего угла экрана. Считать по ширине экрана
  // мало: если кнопка в углу, круг не накроет противоположный край, и
  // в нём останется лоскут старой темы.
  const радиус = Math.hypot(
    Math.max(x, window.innerWidth - x),
    Math.max(y, window.innerHeight - y),
  );

  let переход;
  try { переход = document.startViewTransition(() => применить()); }
  catch { применить(); return; }

  переход.ready
    .then(() => {
      document.documentElement.animate(
        {
          clipPath: [
            `circle(0px at ${x}px ${y}px)`,
            `circle(${радиус}px at ${x}px ${y}px)`,
          ],
        },
        {
          duration: 520,
          easing: "cubic-bezier(.2,.8,.25,1)",
          // Растёт именно НОВЫЙ кадр — старый остаётся на месте и
          // открывается из-под него. Наоборот было бы «стирание».
          pseudoElement: "::view-transition-new(root)",
        },
      );
    })
    // Отказ перехода (вкладка скрыта, снимок не вышел) не должен ничего
    // ронять: тема к этому моменту уже сменилась.
    .catch(() => {});
}
