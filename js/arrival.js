// ========================================================================
//  ОПРИХОДОВАНИЕ — товар с поступления попадает на склад.
//  Один расчёт для склада на сайте и для склада в телефоне.
//
//  Главное правило: себестоимость НЕ перескакивает на цену нового прихода.
//  Пока на полке лежит старая партия, продаётся именно она — значит и цена
//  показывается её. Новая цена вступит в силу сама, когда FIFO доест
//  старую партию. Иначе прибыль по старому товару считалась бы по новой
//  цене и врала.
// ========================================================================
import { ensureBatches, sumQty, costAfter, currentCost } from "./inventory.js?v=20261109d";
import { convert } from "./fx.js?v=20261109d";
import { isShop } from "./purchase.js?v=20261109d";
// Упаковка: поставщик продаёт штуками, у нас лежит пачками. Расчёт общий
// с карточкой товара и с предпросмотром — см. js/packing.js.
import { автоВключено, настройки, пересчитатьПриход } from "./packing.js?v=20261109d";
// Доставка и растаможка ложатся в себестоимость. Делёж — в js/pricing.js:
// там он идёт целыми копейками, чтобы сумма долей сошлась с расходом.
import { доплаты, ценаСРасходами } from "./pricing.js?v=20261109d";

const r2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
const к6 = (n) => Math.round((Number(n) || 0) * 1e6) / 1e6;

// ========================================================================
//  ЧТО СТАНЕТ С ОДНОЙ ПОЗИЦИЕЙ ПРИХОДА.
//
//  Ничего не пишет и не меняет — только считает. Поэтому одно и то же
//  решение показывается в предпросмотре и применяется при оприходовании:
//  владелец видит ровно те числа, которые лягут на склад.
//
//  ИСТОРИЯ ЗАМОРОЖЕНА. Если позиция уже оприходована, у неё есть запись
//  it.приход — и мы берём её КАК ЕСТЬ, не пересчитывая. Иначе смена
//  коэффициента упаковки задним числом переписала бы старые документы:
//  поставили «в пачке 12 вместо 10» — и прошлогодний приход вдруг стал
//  другим. Этого быть не должно.
//
//  доп — доля дополнительных расходов документа (доставка, растаможка),
//  уже посчитанная на ВСЮ эту позицию, в валюте прихода. Она ложится в
//  себестоимость, но цену из накладной не подменяет: в документе остаётся
//  и то, что назвал поставщик, и то, во что товар обошёлся на самом деле.
// ========================================================================
export function позицияПрихода(it, p, доп = 0) {
  if (it && it.приход && typeof it.приход === "object") return { ...it.приход, изЗаписи: true };

  const кол = Number(it && it.qty) || 0;
  const цена = Number(it && it.unit_cost) || 0;
  const валюта = (it && it.currency) || "";
  const доля = Number(доп) || 0;
  // Цена закупочной единицы вместе с долей расходов. Без расходов это
  // ровно цена из накладной — тогда всё считается как раньше.
  const ценаПолная = ценаСРасходами(кол, цена, доля);
  const расход = доля ? { доп: Math.round(доля * 100) / 100, ценаСДоп: ценаПолная } : {};

  // Упаковка не настроена или пересчёт выключен — старый, безопасный путь:
  // сколько вписали, столько и кладём. Расходы при этом всё равно
  // учитываются: они к упаковке отношения не имеют.
  if (!p || !автоВключено(p)) {
    return {
      пересчитано: false, изЗаписи: false,
      ед: настройки(p || {}).склад, кол, цена, валюта,
      складскаяЕд: настройки(p || {}).склад,
      коэффициент: 1, версия: настройки(p || {}).версия,
      складских: кол, себестоимость: r2(ценаПолная),
      полных: кол, остатокШтук: 0, ровно: true,
      правило: "keep", отложеноШтук: 0,
      ...расход,
    };
  }

  const н = настройки(p);
  const р = пересчитатьПриход(p, { qty: кол, цена: ценаПолная });

  // Правило «отложить»: на полку кладём только ПОЛНЫЕ упаковки, а
  // отдельные штуки остаются записанными в документе. Терять их нельзя —
  // поэтому они не исчезают, а числятся отложенными и видны в приходе.
  const откладываем = н.правило === "wait" && !р.ровно;

  return {
    пересчитано: true, изЗаписи: false,
    ед: н.закуп, кол, цена, валюта,
    складскаяЕд: н.склад,
    коэффициент: р.коэффициент, версия: н.версия,
    складских: откладываем ? р.полных : р.складских,
    себестоимость: р.себестоимость,
    полных: р.полных, остатокШтук: р.остатокШтук, ровно: р.ровно,
    правило: н.правило,
    отложеноШтук: откладываем ? р.остатокШтук : 0,
    ...расход,
  };
}

// Решения по всем позициям сразу — для предпросмотра и для оприходования.
// Доли расходов считаются по ВСЕМУ документу сразу: иначе их сумма не
// сошлась бы с расходом, который вписал владелец.
export function пересчётПрихода(purchase, products) {
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  const доли = доплаты(purchase, products);
  return (purchase.items || []).map((it, i) => ({
    it, p: pmap[it.product_id] || null, доп: доли[i] || 0,
    решение: позицияПрихода(it, pmap[it.product_id], доли[i] || 0),
  }));
}

// ------------------------------------------------------------------
//  ПРАВКА ПОЗИЦИИ. Замороженная запись описывает КОНКРЕТНЫЕ числа: эти
//  100 штук по 2 000. Поменяли количество или цену — запись описывает
//  уже не эту позицию, и держать её нельзя.
//
//  Иначе исправление молча пропадало: владелец оприходовал 100 штук,
//  заметил ошибку, списал приход со склада, исправил на 90 и оприходовал
//  заново — а на склад опять ложились 10 пачек по прежней цене, потому
//  что позицияПрихода() честно брала записанное. Деньги при этом
//  расходились на целую пачку.
//
//  Поля, которые запись описывает: товар, количество, цена, валюта.
//  Всё остальное (например, примечание) её не касается.
// ------------------------------------------------------------------
const ЧИСЛА_ПОЗИЦИИ = ["product_id", "qty", "unit_cost", "currency"];

export function правкаПозиции(it, изменения = {}) {
  const было = it || {};
  const стало = { ...было, ...изменения };
  const поехало = ЧИСЛА_ПОЗИЦИИ.some(к => (к in изменения)
    && String(было[к] ?? "") !== String(изменения[к] ?? ""));
  if (!поехало) return стало;
  const { приход, ...без } = стало;
  return без;
}

// То же для объекта, который правят НА МЕСТЕ: так устроен редактор
// прихода — поля ввода держат ту же позицию в руках.
export function применитьПравку(it, изменения = {}) {
  const стало = правкаПозиции(it, изменения);
  Object.assign(it, изменения);
  if (!стало.приход) delete it.приход;
  return it;
}

// Этот документ уже оприходован? Видно по метке src на партиях.
// Нужно, чтобы сказать владельцу: исправления дойдут до склада только
// после того, как приход будет списан со склада.
export function ужеОприходован(purchase, products) {
  if (!purchase || !purchase.id) return false;
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  return (purchase.items || []).some(it => {
    const p = pmap[it && it.product_id];
    return !!p && ensureBatches(p).some(b => b && b.src === purchase.id);
  });
}

// Что записать в документ, чтобы приход навсегда помнил, как он посчитан.
export function записьПрихода(решение, когда, кто) {
  const { изЗаписи, ...чисто } = решение;
  return изЗаписи ? решение : { ...чисто, когда: когда || new Date().toISOString(), ...(кто ? { кто } : {}) };
}

// Зачислить пришедшее на склад.
// Порядок важен: сперва закрываем «долговые» партии (отрицательные — это
// товар, который продали, когда его уже не было), и лишь остаток кладём
// новой партией В КОНЕЦ очереди, чтобы старые запасы продавались первыми.
export function зачислить(batches, qty, cost_yuan, cost_usd, when, откуда) {
  const список = (batches || []).map(b => ({ ...b }));
  let осталось = Number(qty) || 0;

  for (const b of список) {
    if (осталось <= 0) break;
    const q = Number(b.qty) || 0;
    if (q >= 0) continue;                       // долги идут первыми
    const покрыть = Math.min(осталось, -q);
    b.qty = q + покрыть;
    осталось -= покрыть;
  }

  const оставить = список.filter(b => Math.abs(Number(b.qty) || 0) > 0.0001);
  if (осталось > 0.0001) {
    // откуда — номер поступления. По нему видно, что этот приход уже
    // зачислен, и повторное нажатие не задваивает остаток.
    оставить.push({ qty: осталось, cost_yuan, cost_usd, date: when || new Date().toISOString(), ...(откуда ? { src: откуда } : {}) });
  }
  return оставить;
}

// Что записать по каждому товару поступления. Ничего не пишет — только считает,
// поэтому проверяется тестом без базы.
export function arrivalRows(purchase, products) {
  const shop = isShop(purchase);
  const when = purchase.date || new Date().toISOString();
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  const доли = доплаты(purchase, products);
  const rows = [];

  for (const [i, it] of (purchase.items || []).entries()) {
    const p = pmap[it.product_id];
    if (!p) continue;
    const cur = it.currency || purchase.currency;
    // Сколько единиц ляжет на склад и почём одна — с учётом упаковки и
    // доли дополнительных расходов документа.
    // У ненастроенных товаров решение один к одному, как было всегда.
    const реш = позицияПрихода(it, p, доли[i] || 0);
    const наСклад = Number(реш.складских) || 0;
    const ценаЗаСкладскую = Number(реш.себестоимость) || 0;
    const batches = ensureBatches(p);
    // Этот товар из этого же поступления уже зачислен — второй раз не кладём.
    // Оприходование сорвалось на середине (закрыли вкладку, оборвалась связь)
    // — жмём «Оприходовать» снова, и допишется только то, чего не хватает.
    if (purchase.id && batches.some(b => b && b.src === purchase.id)) continue;
    const own = currentCost(batches);

    // Из магазина берём НАШУ складскую цену: сколько отдали в магазине —
    // наше дело, но если записать ту цену, себестоимость и прибыль поедут.
    //
    // ВАЖНО про запасной путь. Когда товар КОНЧИЛСЯ, партий не остаётся, и
    // currentCost честно отвечает нулём — брать цену неоткуда. Раньше этот
    // ноль и записывался: приход из магазина обнулял себестоимость товара.
    // А из магазина докупают ровно то, что кончилось, — поэтому попадало
    // почти каждый раз. Берём последнюю известную цену из карточки товара.
    const своя = {
      cost_yuan: own.cost_yuan || Number(p.cost_yuan) || 0,
      cost_usd: own.cost_usd || Number(p.cost_usd) || 0,
    };
    // Цена из накладной — уже пересчитанная в СКЛАДСКУЮ единицу: если
    // поставщик продал 100 штук по 2000, а у нас пачки по 10, то на склад
    // ложится 10 пачек по 20 000. Если цену не вписали, ноль записывать
    // нельзя — оставляем то, что знали о товаре раньше.
    const отПоставщика = {
      cost_yuan: r2(convert(ценаЗаСкладскую, cur, "yuan")) || Number(p.cost_yuan) || 0,
      cost_usd: r2(convert(ценаЗаСкладскую, cur, "usd")) || Number(p.cost_usd) || 0,
    };
    const cy = shop ? своя.cost_yuan : отПоставщика.cost_yuan;
    const cu = shop ? своя.cost_usd : отПоставщика.cost_usd;
    // Приход СНАЧАЛА ГАСИТ ДОЛГ, и только остаток становится новой партией.
    // Раньше долг оставался висеть отдельной строкой рядом с приходом:
    // общее количество сходилось, но себестоимость система брала с первой
    // ПОЛОЖИТЕЛЬНОЙ партии, и на складе с долгом −60 и старыми 900 шт по
    // ¥12,5 она показывала цену мелкой новой партии, а не настоящую.
    const next = зачислить(batches, наСклад, cy, cu, when, purchase.id);
    const cc = costAfter(next, { cost_yuan: cy, cost_usd: cu });

    const row = { id: p.id, stock_qty: sumQty(next), cost_yuan: cc.cost_yuan, cost_usd: cc.cost_usd, batches: next };
    // last_arrival_at поднимает товар в начало каталога и метит новинкой.
    // Приход из магазина — пополнение, а не новинка: давно продающийся товар
    // не должен всплывать наверх после каждой добавки.
    if (!shop) row.last_arrival_at = new Date().toISOString();
    rows.push(row);
    // держим объект товара в списке в согласии с тем, что записали
    p.batches = next; p.cost_yuan = cc.cost_yuan; p.cost_usd = cc.cost_usd; p.stock_qty = row.stock_qty;
  }
  return rows;
}

// Записать пакетом, одним запросом. Поштучно 43 позиции пишутся полминуты:
// выглядит как «зависло», владелец закрывает вкладку или жмёт ещё раз — и
// половина прихода остаётся незачисленной, а половина попадает дважды.
// Если пакет не прошёл — пробуем без партий и лишь потом по одному,
// и обязательно сообщаем об ошибке наверх.
export async function записатьПачкой(db, rows, наПрогресс) {
  if (!rows.length) return 0;
  const безПартий = () => rows.map(({ batches, ...rest }) => rest);
  if (typeof db.products.upsertMany === "function") {
    try { await db.products.upsertMany(rows); if (наПрогресс) наПрогресс(rows.length, rows.length); return rows.length; } catch { }
    try { await db.products.upsertMany(безПартий()); if (наПрогресс) наПрогресс(rows.length, rows.length); return rows.length; } catch { }
  }
  let n = 0;
  for (const row of rows) {
    try { await db.products.upsert(row); }
    catch { const { batches, ...noBatches } = row; await db.products.upsert(noBatches); }
    if (наПрогресс) наПрогресс(++n, rows.length);
  }
  return rows.length;
}

// Оприходовать: записать остатки И заморозить в документе, как он посчитан.
//
// История нужна, чтобы потом можно было ответить на вопрос «откуда взялись
// эти 10 пачек»: в документе остаются исходная единица, исходное
// количество, исходная цена, коэффициент и версия настроек упаковки,
// действовавшая В ТОТ МОМЕНТ. Поменяли упаковку позже — документ не
// меняется, потому что позицияПрихода() берёт записанное как есть.
//
// Запись документа НЕ должна рушить оприходование: остатки уже на складе,
// и если не удалось дописать историю, об этом лучше сказать, чем
// откатывать склад. Повторное нажатие «Оприходовать» допишет её.
export async function applyArrival(db, purchase, products, наПрогресс, { кто = "" } = {}) {
  const rows = arrivalRows(purchase, products);
  const записано = await записатьПачкой(db, rows, наПрогресс);
  await записатьИсторию(db, purchase, products, кто).catch(() => {});
  return записано;
}

// Дописать в документ, как посчитана каждая позиция.
export async function записатьИсторию(db, purchase, products, кто = "") {
  if (!purchase || !purchase.id || !Array.isArray(purchase.items)) return false;
  const когда = new Date().toISOString();
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  const доли = доплаты(purchase, products);
  let новое = false;
  const items = purchase.items.map((it, i) => {
    if (it && it.приход) return it;                   // уже записано — не трогаем
    новое = true;
    return { ...it, приход: записьПрихода(позицияПрихода(it, pmap[it.product_id], доли[i] || 0), когда, кто) };
  });
  if (!новое) return false;
  await db.purchases.upsert({ id: purchase.id, items });
  purchase.items = items;                             // документ в руках — в согласии с базой
  return true;
}

// Снять зачисление этого поступления: убираем ровно те партии, которые он
// положил (по метке src). Старые приходы метки не имеют — для них, как и
// раньше, списываем количество позиции по очереди (FIFO).
export function откатитьПриход(purchase, products, consumeFIFO) {
  const pmap = Object.fromEntries((products || []).map(p => [p.id, p]));
  const rows = [];
  for (const it of (purchase.items || [])) {
    const p = pmap[it.product_id];
    if (!p) continue;
    const batches = ensureBatches(p);
    const свои = purchase.id ? batches.filter(b => b && b.src === purchase.id) : [];
    let next;
    if (свои.length) {
      // убираем одну партию этого прихода — последнюю из положенных
      const лишняя = свои[свои.length - 1];
      let убрали = false;
      next = batches.filter(b => (b === лишняя && !убрали ? (убрали = true, false) : true));
    } else {
      // Сколько клали, столько и снимаем: у настроенной упаковки это НЕ
      // число из накладной, а пересчитанное количество складских единиц.
      next = consumeFIFO(batches, Number(позицияПрихода(it, p).складских) || 0).batches;
    }
    const cc = costAfter(next, p);
    rows.push({ id: p.id, stock_qty: sumQty(next), cost_yuan: cc.cost_yuan, cost_usd: cc.cost_usd, batches: next });
    p.batches = next; p.stock_qty = sumQty(next);
  }
  return rows;
}
