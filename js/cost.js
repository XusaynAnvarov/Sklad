// ========================================================================
//  СЕБЕСТОИМОСТЬ — в той валюте, в которой её ввели.
//
//  Товар может прийти из Китая за юани, из магазина за сумы, от поставщика
//  за доллары. Мы храним сумму сразу в двух валютах (cost_yuan и cost_usd)
//  плюс помним, какая была ИСХОДНОЙ — cost_cur. Показываем в исходной:
//  владелец помнит цену той бумажкой, которой платил, и пересчёт в другую
//  валюту читается как чужая цифра.
//
//  Раньше это правило знал только склад на сайте. Склад в телефоне всегда
//  писал «¥» и показывал пересчёт: один и тот же товар выглядел как
//  «$33.87» на компьютере и «241,94 ¥» в телефоне. Цифра верная, но
//  доверия к ней никакого. Теперь правило общее.
// ========================================================================
import { fmt, convert } from "./fx.js?v=20260826a";

export const ВАЛЮТЫ = [
  { value: "yuan", label: "Юань ¥", знак: "¥" },
  { value: "usd", label: "Доллар $", знак: "$" },
  { value: "som", label: "Сум", знак: "сум" },
];

// В какой валюте вводили. У старых товаров поля нет — угадываем по тому,
// что заполнено: если есть только доллары, значит вводили доллары.
export function костВалюта(p) {
  if (p && p.cost_cur) return p.cost_cur;
  const cy = Number(p && p.cost_yuan) || 0;
  const cu = Number(p && p.cost_usd) || 0;
  return (cu > 0 && !(cy > 0)) ? "usd" : "yuan";
}

// Сумма для показа — числом, в исходной валюте.
export function костЧисло(cy, cu, ccur) {
  cy = Number(cy) || 0;
  cu = Number(cu) || 0;
  if (ccur === "usd") return cu;
  if (ccur === "som") return convert(cu > 0 ? cu : convert(cy, "yuan", "usd"), "usd", "som");
  return cy;
}

// Сумма для показа — строкой со знаком валюты.
export function костСтрока(cy, cu, ccur) {
  const v = костЧисло(cy, cu, ccur);
  return fmt(v, ccur === "som" ? "som" : ccur === "usd" ? "usd" : "yuan");
}

// Что записать в товар, когда сумму ввели в валюте cur.
// Храним обе валюты: отчёты считают в долларах, наклейки и заказы — в юанях.
export function костПоля(amount, cur) {
  const amt = Number(amount) || 0;
  const r2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
  return {
    cost_yuan: cur === "yuan" ? amt : r2(convert(amt, cur, "yuan")),
    cost_usd: cur === "usd" ? amt : r2(convert(amt, cur, "usd")),
    cost_cur: cur,
  };
}
