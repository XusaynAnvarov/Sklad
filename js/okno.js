// ========================================================================
//  ОКНО СТРОК: в разметке живёт только то, что видно.
//
//  Зачем. Смена темы, поворот экрана, да и просто первая отрисовка стоят
//  ровно столько, сколько узлов в странице. Замерено на стенде, таблица
//  продаж с настоящей разметкой строки (8 ячеек, четыре кнопки со
//  значками — 43 узла на строку):
//
//      строк   узлов   пересчёт стилей при смене темы
//        100    4 600    18 мс
//        300   13 200    55 мс
//        600   26 100   119 мс
//       1200   51 900   216 мс
//
//  Зависимость прямая, и больше половины веса — значки в кнопках. Пока
//  все накладные за год лежат в разметке разом, любое изменение темы
//  пересчитывает их все, хотя человек видит пятнадцать строк.
//
//  Что делаем. Строки страница по-прежнему строит все и сразу — так
//  работают все четырнадцать разделов, и переписывать их мы не будем.
//  Мы лишь держим в таблице окно вокруг видимого места, а остальные
//  строки лежат рядом, отсоединённые. Сверху и снизу — распорки нужной
//  высоты, поэтому полоса прокрутки и её положение остаются прежними.
//
//  Строки — те же самые узлы, не копии: обработчики на кнопках, подписи
//  ячеек (data-label для телефона) и переводы ставятся один раз и при
//  возврате строки в таблицу никуда не деваются.
//
//  Чего это стоит. Поиск самого браузера (Ctrl+F) находит только то, что
//  сейчас в окне. В складе есть свой поиск по разделам и строка поиска
//  над таблицами — им это не мешает.
//
//  Ниже порога не трогаем ничего: на короткой таблице выигрыша нет, а
//  лишний слушатель прокрутки есть.
// ========================================================================

const ПОРОГ = 120;          // строк меньше — таблицу оставляем как есть
const ЭКРАНОВ_ЗАПАС = 1;    // столько высот экрана держим сверху и снизу
const МИН_ОКНО = 60;        // но не меньше этого числа строк

// Ближайший предок, который действительно прокручивается. В складе это
// #view внутри .main, но полагаться на имя нельзя: на телефоне каркас
// другой, а на странице заказа таблица лежит прямо в документе.
function прокрутчик(узел) {
  let э = узел.parentElement;
  while (э && э !== document.body) {
    const o = getComputedStyle(э).overflowY;
    if ((o === "auto" || o === "scroll") && э.scrollHeight > э.clientHeight + 4) return э;
    э = э.parentElement;
  }
  return document.scrollingElement || document.documentElement;
}

function распорка(колонок) {
  const tr = document.createElement("tr");
  tr.className = "gm-okno-sp";
  tr.setAttribute("aria-hidden", "true");
  const td = document.createElement("td");
  td.colSpan = колонок;
  tr.append(td);
  return tr;
}

function окноОднойТаблицы(табл) {
  const тело = табл.tBodies[0];
  if (!тело) return;
  const все = [...тело.rows];
  if (все.length <= ПОРОГ) return;
  if (табл.dataset.gmOkno === "1") return;      // уже под окном
  табл.dataset.gmOkno = "1";

  const колонок = Math.max(1, табл.tHead ? табл.tHead.rows[0].cells.length : все[0].cells.length);
  const верх = распорка(колонок);
  const низ = распорка(колонок);

  // Высоту строки узнаём по тем, что сейчас нарисованы. До первого замера
  // берём прикидку: без неё первая распорка была бы нулевой и страница
  // прыгнула бы сразу после открытия.
  let высота = 52;
  let первая = -1, последняя = -1;

  const контейнер = прокрутчик(табл);
  const высотаЭкрана = () =>
    (контейнер === document.scrollingElement || контейнер === document.documentElement)
      ? window.innerHeight : контейнер.clientHeight;

  // Высоту строки берём не из offsetHeight (он целый, и на сотне строк
  // потерянные доли пикселя складываются в экраны пустоты), а по
  // расстоянию между верхом первой и верхом последней настоящей строки
  // окна. Так в неё сами собой входят и схлопнутые рамки, и дробные доли.
  function замерить() {
    const в = тело.rows;
    if (в.length < 4) return;
    const первый = в[1].getBoundingClientRect().top;
    const последний = в[в.length - 2].getBoundingClientRect().top;
    const промежутков = в.length - 3;
    if (промежутков > 0 && последний > первый) {
      высота = Math.max(18, (последний - первый) / промежутков);
    }
  }

  // Сколько строк таблицы ушло выше верхнего края окна прокрутки.
  // Считаем от ТЕЛА таблицы, а не от неё самой: между ними шапка со
  // своей высотой, и без этого окно уезжало бы на строку-другую.
  function сколькоУшло() {
    const кТелу = тело.getBoundingClientRect();
    const верхОкна = (контейнер === document.scrollingElement || контейнер === document.documentElement)
      ? 0 : контейнер.getBoundingClientRect().top;
    return Math.max(0, верхОкна - кТелу.top);
  }

  // Один проход сдвигает окно, но сам же двигает содержимое: распорка
  // сверху меняет высоту, и то, что было под курсором, съезжает. После
  // большого прыжка (перетащили ползунок с начала в конец) одного
  // прохода мало — нужно пересчитать по новому положению. Поэтому цикл:
  // он останавливается сам, как только окно перестаёт меняться, а
  // четырёх проходов хватает с запасом на любой прыжок.
  function нарисовать() {
    if (!табл.isConnected) { отписаться(); return; }
    for (let проход = 0; проход < 4; проход++) {
      const запас = Math.max(МИН_ОКНО, Math.ceil(высотаЭкрана() * ЭКРАНОВ_ЗАПАС / высота));
      const видно = Math.ceil(высотаЭкрана() / высота);
      let от = Math.max(0, Math.floor(сколькоУшло() / высота) - запас);
      let до = Math.min(все.length, от + видно + запас * 2);
      if (до - от < МИН_ОКНО) от = Math.max(0, до - МИН_ОКНО);

      const тоЖеОкно = (от === первая && до === последняя);
      if (!тоЖеОкно) {
        // Докладываем и убираем только то, что сменилось. Перестраивать
        // всё окно целиком на каждый сдвиг — это сто с лишним строк, и
        // при прокрутке колесом получались рывки: каждый кадр, где окно
        // ехало, стоил впятеро дороже обычного. При прыжке ползунком
        // старое и новое окно не пересекаются — тогда проще заменить всё.
        if (от < последняя && до > первая) {
          for (let i = первая; i < от; i++) все[i].remove();
          for (let i = до; i < последняя; i++) все[i].remove();
          for (let i = первая - 1; i >= от; i--) верх.after(все[i]);
          for (let i = последняя; i < до; i++) низ.before(все[i]);
        } else {
          тело.replaceChildren(верх, ...все.slice(от, до), низ);
        }
        первая = от; последняя = до;
      }

      // Сначала меряем по тому, что сейчас нарисовано, и только потом
      // ставим распорки: иначе проход оставил бы их посчитанными по
      // прикидке, и внизу таблицы выросла бы пустота.
      замерить();
      верх.firstElementChild.style.height = Math.round(от * высота) + "px";
      низ.firstElementChild.style.height = Math.round((все.length - до) * высота) + "px";

      if (тоЖеОкно) break;
    }
  }

  // КУДА ВЕШАТЬ СЛУШАТЕЛЬ.
  //
  // Когда прокручивается обычный блок (в складе на широком экране это
  // #view) — события приходят на него. Но когда прокручивается страница
  // целиком, а так устроен телефон, событие прокрутки приходит НЕ на
  // <html>, а на документ. Слушатель, повешенный на document­Element, в
  // этом случае не срабатывает вовсе: на телефоне окно строк оставалось
  // на месте, сколько ни прокручивай.
  const источник =
    (контейнер === document.scrollingElement || контейнер === document.documentElement)
      ? window : контейнер;

  // Рисуем прямо в обработчике прокрутки, а не через requestAnimationFrame.
  // Браузер и так зовёт обработчик не чаще раза в кадр, а лишний кадр
  // отсрочки означал, что окно приезжает на событие позже ползунка: при
  // быстром перетаскивании в разметке оказывались строки с прошлого
  // места. Пересчёт стоит доли миллисекунды — в кадр укладывается.
  function отписаться() {
    источник.removeEventListener("scroll", нарисовать);
    window.removeEventListener("resize", нарисовать);
  }

  источник.addEventListener("scroll", нарисовать, { passive: true });
  window.addEventListener("resize", нарисовать, { passive: true });
  нарисовать();

  // Страница сменилась — таблица ушла из документа, слушатели не нужны.
  табл.__gmОкноСнять = отписаться;
}

/**
 * Включает окно строк для всех длинных таблиц внутри корня.
 * Зовётся последней в отрисовке раздела: подписи ячеек, переводы и
 * оживление чисел должны успеть пройтись по полному набору строк.
 */
export function окноДлинныхТаблиц(корень) {
  try {
    (корень || document).querySelectorAll("table.tbl").forEach(окноОднойТаблицы);
  } catch (e) {
    // Окно — ускорение, а не обязанность. Сломалось — таблица просто
    // остаётся целиком в разметке, как было до этой правки.
    console.warn("окно строк не включилось:", e);
  }
}
