// ========================================================================
//  ПОСТОЯННЫЙ КОД ТОВАРА — LP-017.
//
//  Две латинские буквы раздела и номер. Клиент листает печатный каталог и
//  пишет «LP-017» — владелец набирает это в поиске и сразу видит товар.
//  Латиница, а не кириллица: код набирают и русские, и узбекские клиенты,
//  а латинские буквы есть на любой клавиатуре.
//
//  Главное правило: выданный код НЕ МЕНЯЕТСЯ НИКОГДА. Товар перенесли в
//  другой раздел — код остался прежним. Иначе старый каталог у клиента на
//  руках стал бы указывать не на тот товар.
//
//  Модуль чистый: без базы и без страницы. Им пользуются и сервер (раздача
//  кодов, печатный каталог), и склад в браузере (код новому товару, поиск).
// ========================================================================

