// Колонка code появляется после db/catalog-migration.sql. До этого писать
// код нельзя: база отвергнет сохранение товара целиком. Если колонка есть,
// в каждом товаре из списка есть поле code (пусть и пустое).
export const естьКолонкаКода = (товары) =>
  (товары || []).some(p => p && Object.prototype.hasOwnProperty.call(p, "code"));

// «lp17», «LP 017» → «LP-017». Не код — пустая строка.
export function привестиКод(s) {
  const k = компактныйКод(s);
  if (!k) return "";
  return k.slice(0, 2) + "-" + сНулями(Number(k.slice(2)));
}

// Буквы раздела с учётом уже розданных кодов: если раздела нет в таблице,
// но его товары уже получили коды (раздача на сервере завела новые буквы),
// берём те же буквы — иначе у раздела появились бы вторые.
export function таблицаПоТоварам(товары) {
  const таблица = { ...БУКВЫ };
  for (const p of товары || []) {
    const r = p && разобратьКод(p.code);
    if (!r) continue;
    const имя = раздел(p.category);
    if (!найтиВТаблице(таблица, имя)) таблица[имя] = r.буквы;
  }
  return таблица;
}

export function кодДляНового(категория, товары) {
  const буквы = буквыРаздела(категория, таблицаПоТоварам(товары));
  return следующийКод(буквы, (товары || []).map(p => p && p.code));
}

// Подпись под названием товара: код из каталога и артикул поставщика.
// Код первым — клиент видит его в каталоге и пишет именно его.
//   { code: "LP-017", sku: "KDP-10" } → «LP-017 · Арт.: KDP-10»
export function подписьКода(p) {
  const части = [];
  if (p && p.code) части.push(p.code);
  if (p && p.sku) части.push("Арт.: " + p.sku);
  return части.join(" · ");
}

// Так база отвечает, если код уже у другого товара (уникальный индекс
// из db/catalog-migration.sql).
export const КОД_ЗАНЯТ = /products_code_unique|duplicate key/i;

// Следующий номер тех же букв — если база ответила, что код уже занят
// (два телефона завели товар одновременно).
export function следующийПосле(code) {
  const r = разобратьКод(code);
  return r ? r.буквы + "-" + сНулями(r.номер + 1) : "";
}

// Какой код записать при сохранении.
//   товар   — что сохраняем ({ id, code? }); у нового id может не быть
//   вписано — что владелец ввёл в поле «Код» (может быть пусто)
//   категория, товары — раздел и весь список товаров
// Возвращает { code } (null — код пока не выдаём) или { ошибка }.
export function кодПриСохранении({ товар, вписано, категория, товары }) {
  const свой = (товар && товар.code) || null;
  const текст = String(вписано || "").trim();

  if (текст) {
    const code = привестиКод(текст);
    if (!code) return { ошибка: "Код должен быть вида LP-017" };
    const занят = (товары || []).find(p => p && p.code && p.id !== (товар && товар.id)
      && компактныйКод(p.code) === компактныйКод(code));
    if (занят) return { ошибка: `Код ${code} уже у товара «${занят.name || "без названия"}»` };
    return { code };
  }

  // Поле очистили — код не стираем: он мог уже уйти в напечатанный каталог.
  if (свой) return { code: свой };

  // Новый товар получает код сразу. Старый товар без кода — только когда
  // коды уже розданы: до раздачи номер ему даст общая раздача по дате
  // заведения, иначе порядок номеров перепутается.
  const новый = !(товар && товар.id && (товары || []).some(p => p && p.id === товар.id));
  const розданы = (товары || []).some(p => p && p.code);
  if (новый || розданы) return { code: кодДляНового(категория, товары) };
  return { code: null };
}
