export const БЕЗ_РАЗДЕЛА = "Без категории";
export const раздел = (category) => (category && String(category).trim()) || БЕЗ_РАЗДЕЛА;

// Кириллица (русская и узбекская) → латиница. Только для того, чтобы
// подобрать буквы новому разделу, которого нет в таблице.
const ЛАТИНИЦА = {
  а: "A", б: "B", в: "V", г: "G", д: "D", е: "E", ё: "E", ж: "J", з: "Z", и: "I",
  й: "Y", к: "K", л: "L", м: "M", н: "N", о: "O", п: "P", р: "R", с: "S", т: "T",
  у: "U", ф: "F", х: "H", ц: "C", ч: "C", ш: "S", щ: "S", ъ: "", ы: "Y", ь: "",
  э: "E", ю: "U", я: "Y", ў: "O", қ: "Q", ғ: "G", ҳ: "H",
};
export function латиницей(s) {
  let out = "";
  for (const ch of String(s || "").toLowerCase()) {
    if (ch >= "a" && ch <= "z") out += ch.toUpperCase();
    else if (ЛАТИНИЦА[ch] !== undefined) out += ЛАТИНИЦА[ch];
    else out += " ";
  }
  return out;
}

// Ищем раздел в таблице без учёта регистра и лишних пробелов: «лапки » и
// «Лапки» — один раздел.
function найтиВТаблице(таблица, имя) {
  if (таблица[имя]) return таблица[имя];
  const ключ = имя.toLowerCase().replace(/\s+/g, " ");
  for (const [k, v] of Object.entries(таблица)) {
    if (k.toLowerCase().replace(/\s+/g, " ") === ключ) return v;
  }
  return null;
}

// Буквы раздела. Новому разделу подбираем две буквы из его названия так,
// чтобы они не совпали ни с одним уже занятым разделом, и дописываем в
// таблицу — дальше этот раздел всегда получает те же буквы.
export function буквыРаздела(category, таблица) {
  const имя = раздел(category);
  const есть = найтиВТаблице(таблица, имя);
  if (есть) return есть;

  const занято = new Set(Object.values(таблица));
  const слова = латиницей(имя).split(" ").filter(Boolean);
  const все = слова.join("");
  const кандидаты = [];
  if (слова.length >= 2) кандидаты.push(слова[0][0] + слова[1][0]);
  if (все.length >= 2) {
    for (let i = 1; i < все.length; i++) кандидаты.push(все[0] + все[i]);
  }
  // запасной путь: первая буква с любой другой, затем любые две
  const АБВ = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  if (все) for (const b of АБВ) кандидаты.push(все[0] + b);
  for (const a of АБВ) for (const b of АБВ) кандидаты.push(a + b);

  const выбрано = кандидаты.find(c => /^[A-Z]{2}$/.test(c) && !занято.has(c));
  таблица[имя] = выбрано;
  return выбрано;
}

// «LP-017» → { буквы: "LP", номер: 17 }. Чужой формат — null.
export function разобратьКод(code) {
  const m = /^([A-Z]{2})-(\d{3,})$/.exec(String(code || "").trim().toUpperCase());
  return m ? { буквы: m[1], номер: Number(m[2]) } : null;
}

// Без дефиса, пробелов и нулей впереди: «lp 017», «LP17», «lp-0017» —
// всё это один и тот же код. Клиенты пишут как придётся.
export function компактныйКод(s) {
  const m = /^([A-Za-z]{2})[\s\-_.]*0*(\d+)$/.exec(String(s || "").trim());
  return m ? m[1].toUpperCase() + String(Number(m[2])) : "";
}

const сНулями = (n) => String(n).padStart(3, "0");

// Следующий свободный код раздела: наибольший номер + 1.
// Дыры после удалённых товаров не занимаем: номер, однажды напечатанный в
// каталоге, не должен достаться другому товару.
export function следующийКод(буквы, занятыеКоды) {
  let макс = 0;
  for (const c of занятыеКоды || []) {
    const r = разобратьКод(c);
    if (r && r.буквы === буквы && r.номер > макс) макс = r.номер;
  }
  return буквы + "-" + сНулями(макс + 1);
}

// Раздать коды тем товарам, у которых их нет.
// Порядок — по дате заведения: старые товары получают меньшие номера, и
// новые встают в конец раздела. Уже выданные коды не трогаем.
// Возвращает { выдать: [{ id, name, category, code }], таблица }.
export function раздатьКоды(товары, таблица = БУКВЫ) {
  const карта = { ...таблица };
  const занятые = new Set((товары || []).map(p => p && p.code).filter(Boolean));

  // наибольший номер по каждым буквам — считаем один раз, а не на каждый товар
  const макс = new Map();
  for (const c of занятые) {
    const r = разобратьКод(c);
    if (r) макс.set(r.буквы, Math.max(макс.get(r.буквы) || 0, r.номер));
  }

  const безКода = (товары || [])
    .filter(p => p && p.id && !p.code)
    .slice()
    .sort((a, b) => {
      const da = new Date(a.created_at || 0) - new Date(b.created_at || 0);
      return da !== 0 ? da : String(a.name || "").localeCompare(String(b.name || ""), "ru");
    });

  const выдать = [];
  for (const p of безКода) {
    const буквы = буквыРаздела(p.category, карта);
    const номер = (макс.get(буквы) || 0) + 1;
    макс.set(буквы, номер);
    const code = буквы + "-" + сНулями(номер);
    занятые.add(code);
    выдать.push({ id: p.id, name: p.name, category: раздел(p.category), code });
  }
  return { выдать, таблица: карта };
}

