// ========================================================================
//  МАССОВАЯ НАСТРОЙКА УПАКОВОК.
//
//  Товаров восемьсот, и у каждого надо сказать, в чём его берут, в чём он
//  лежит и сколько штук в упаковке. По одному это неделя работы, поэтому
//  нужен экран, где отмечают сразу десятки и правят одним действием.
//
//  И ровно поэтому здесь главное — НЕ скорость, а осторожность:
//
//    1. ПУСТОЕ ПОЛЕ ЗНАЧИТ «НЕ МЕНЯТЬ». У каждого товара своя упаковка;
//       если владелец заполнил только «автопересчёт», всё остальное у
//       каждого обязано остаться своим. Иначе одна правка на пятьдесят
//       товаров стёрла бы пятьдесят разных настроек.
//
//    2. ТОВАРЫ БЕЗ ИЗМЕНЕНИЙ НЕ ЗАПИСЫВАЮТСЯ ВОВСЕ. Не из экономии: любая
//       запись поднимает версию настроек упаковки, а версия — это то, по
//       чему приход потом объясняет, как он посчитан. Трогать её без
//       причины значит врать в истории.
//
//    3. СМЕНА СКЛАДСКОЙ ЕДИНИЦЫ ИЛИ РАЗМЕРА УПАКОВКИ ДВИГАЕТ ОСТАТОК.
//       Это уже не настройка, а пересчёт всего склада: 4800 штук
//       превращаются в 400 пачек, и цена обязана поехать вместе с ними.
//       План такие товары помечает отдельно, и записываются они ТОЛЬКО с
//       отдельного разрешения — по умолчанию пропускаются.
//
//  Модуль ничего не пишет и ничего не меняет на месте: он отдаёт ПЛАН —
//  что станет с каждым товаром и что при этом двинется. План показывают
//  владельцу как предпросмотр, и тот же план потом записывают. Поэтому
//  предпросмотр не может разойтись с тем, что произойдёт.
// ========================================================================
import { настройки, статус, поляНастроек, нуженПереводОстатка, СТАТУС } from "./packing.js?v=20261103f";
import { перевести, подпись } from "./unit.js?v=20261103f";

// Пустое значение в форме массовой правки — «не менять».
const неТронуто = (v) => v === "" || v === null || v === undefined;

// Слить то, что заполнил владелец, с тем, что у товара уже есть.
export function слитьЗначения(p, значения = {}) {
  const н = настройки(p);
  const взять = (v, своё) => (неТронуто(v) ? своё : v);
  const склад = взять(значения.unit, н.склад);
  const продажа = взять(значения.sell_unit, н.продажа);
  return {
    unit: склад,
    pack_size: склад === "шт" ? 1 : Math.max(1, Number(взять(значения.pack_size, н.вСкладской)) || 1),
    buy_unit: взять(значения.buy_unit, н.закуп),
    sell_unit: продажа,
    box_size: Number(взять(значения.box_size, н.вКоробке)) > 0 ? Number(взять(значения.box_size, н.вКоробке)) : null,
    // Разрешённые единицы продажи копим, а не затираем: товар могли
    // продавать и пачками, и поштучно.
    sell_units: [...new Set([продажа, ...н.разрешено])],
    odd_rule: взять(значения.odd_rule, н.правило),
    auto_convert: неТронуто(значения.auto_convert) ? н.авто : значения.auto_convert === true || значения.auto_convert === "on",
  };
}

// Что именно изменится у этого товара — человеческими словами, чтобы
// предпросмотр и подпись не разошлись с расчётом.
function различия(было, станет) {
  const список = [];
  const сверить = (подписьПоля, a, b) => { if (String(a) !== String(b)) список.push({ поле: подписьПоля, было: a, стало: b }); };
  сверить("Покупаем в", было.закуп, станет.закуп);
  сверить("На складе", было.склад, станет.склад);
  сверить("Продаём в", было.продажа, станет.продажа);
  сверить("Штук в упаковке", было.вСкладской, станет.вСкладской);
  сверить("Упаковок в коробке", было.вКоробке || "—", станет.вКоробке || "—");
  сверить("Неполная упаковка", было.правило, станет.правило);
  сверить("Автопересчёт", было.авто ? "включён" : "выключен", станет.авто ? "включён" : "выключен");
  return список;
}

// ------------------------------------------------------------------
//  ПЛАН: что станет с каждым товаром.
//
//  значения.подтвердить — «отметить упаковку настроенной, даже если
//  ничего не меняется». Нужно для товаров, у которых всё и так верно:
//  штуки есть штуки, и владелец хочет сказать об этом вслух, чтобы они
//  ушли из списка «не настроено».
// ------------------------------------------------------------------
export function планПравки(товары, значения = {}) {
  return (товары || []).map(p => {
    const слито = слитьЗначения(p, значения);
    const поля = поляНастроек(p, слито);
    const было = настройки(p);
    const станет = настройки({ ...p, ...поля });
    const diff = различия(было, станет);
    // Подтверждение имеет смысл только там, где упаковку ещё не настраивали.
    const подтвердить = значения.подтвердить === true && было.версия < 1;
    const двигает = нуженПереводОстатка(p, слито);
    return {
      p, поля, было, станет,
      различия: diff,
      меняется: diff.length > 0 || подтвердить,
      толькоПодтверждение: diff.length === 0 && подтвердить,
      двигает,
      // Пересчёт остатка считаем заранее — чтобы владелец увидел ровно те
      // числа, которые лягут на склад, если он разрешит перевод.
      перевод: двигает ? перевести(p, { unit: слито.unit, pack_size: слито.pack_size }) : null,
      остаток: Number(p.stock_qty) || 0,
      статус: статус({ ...p, ...поля }),
    };
  });
}

// Короткая сводка для предпросмотра: по ней владелец решает, жать ли.
export function сводка(план) {
  const меняется = план.filter(x => x.меняется);
  const переводы = меняется.filter(x => x.двигает);
  return {
    всего: план.length,
    меняется: меняется.length,
    безИзменений: план.length - меняется.length,
    переводов: переводы.length,
    переводовСОстатком: переводы.filter(x => Math.abs(x.остаток) > 0.0001).length,
    дробных: переводы.filter(x => x.перевод && x.перевод.делитсяРовно === false).length,
    требуютПроверки: меняется.filter(x => x.статус.код === СТАТУС.ПРОВЕРИТЬ).length,
    включитсяАвто: меняется.filter(x => x.станет.авто && !x.было.авто).length,
  };
}

// Строки для записи в базу.
//
// Товары без изменений сюда не попадают вовсе. Товары, у которых меняется
// мера остатка, попадают ТОЛЬКО с разрешением переводить — и тогда вместе
// с пересчитанным остатком, себестоимостью и всеми партиями: товара и
// денег на складе остаётся столько же, меняется лишь то, чем их меряют.
export function строкиДляЗаписи(план, { переводить = false } = {}) {
  const строки = [];
  for (const x of план) {
    if (!x.меняется) continue;
    if (x.двигает && !переводить) continue;
    const строка = { id: x.p.id, ...x.поля };
    if (x.двигает && x.перевод) {
      строка.stock_qty = x.перевод.stock_qty;
      строка.cost_yuan = x.перевод.cost_yuan;
      строка.cost_usd = x.перевод.cost_usd;
      строка.batches = x.перевод.batches;
    }
    строки.push(строка);
  }
  return строки;
}

// Объяснение перевода одной строкой: «4800 шт → 400 пачек · ¥0,75 → ¥9».
export function объяснитьПеревод(x) {
  if (!x || !x.двигает || !x.перевод) return "";
  const части = [
    подпись(x.остаток, { unit: x.было.склад }) + " → " + подпись(x.перевод.stock_qty, { unit: x.станет.склад }),
  ];
  const ц1 = Number(x.p.cost_yuan) || 0, ц2 = Number(x.перевод.cost_yuan) || 0;
  if (ц1 || ц2) части.push("¥" + ц1 + " → ¥" + ц2);
  if (x.перевод.делитсяРовно === false) части.push("не делится нацело");
  return части.join("  ·  ");
}

// ------------------------------------------------------------------
//  ОДНОФАМИЛЬЦЫ.
//
//  Два разных товара могут называться одинаково — и это НЕ повод считать
//  их одним. Объединять товары по совпадению названия нельзя: у них свои
//  остатки, своя себестоимость и своя история. Но показать владельцу, что
//  название повторяется, стоит: именно здесь он правит упаковки и легко
//  настроит не тот товар.
// ------------------------------------------------------------------
export function однофамильцы(товары) {
  const счёт = new Map();
  for (const p of (товары || [])) {
    const имя = String((p && p.name) || "").trim().toLowerCase();
    if (!имя) continue;
    счёт.set(имя, (счёт.get(имя) || 0) + 1);
  }
  const двойные = new Map();
  for (const [имя, n] of счёт) if (n > 1) двойные.set(имя, n);
  return двойные;
}
