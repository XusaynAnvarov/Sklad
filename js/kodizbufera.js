// ========================================================================
//  КОД ИЗ БУФЕРА — САМОПОДСТАНОВКА ПОСЛЕ TELEGRAM.
//
//  Чего ждал владелец: «пришёл код из бота — и сразу вставился».
//
//  Честно о пределах: страница НЕ МОЖЕТ читать сообщения Telegram.
//  Встроенная автоподстановка браузера (autocomplete="one-time-code",
//  WebOTP) работает только с SMS — Telegram ей недоступен. Поэтому
//  делаем ближайшее к задуманному и единственное, что вообще возможно:
//
//    1) в боте код отправлен моноширинным — одно касание копирует его
//       (api/client/login-start.js, api/admin-auth.js);
//    2) человек возвращается на вкладку — и мы сами заглядываем в буфер
//       обмена. Нашли шесть цифр — раскладываем по ячейкам и проверяем.
//
//  Почему не всегда срабатывает само. Chrome на Android читает буфер без
//  спроса, если вкладка в фокусе. Safari на iPhone — нет: там чтение
//  буфера разрешено только прямо по касанию человека. Поэтому молчаливую
//  попытку оборачиваем в try и, если она не прошла, показываем кнопку
//  «Вставить код» — по нажатию буфер читается уже законно.
//
//  Буфер не трогаем, если в ячейках что-то уже набрано: человек может
//  печатать руками, и перетирать набранное нельзя.
// ========================================================================

// Вынуть код из того, что лежит в буфере.
//
// Считать все цифры подряд нельзя — на этом ловились чужие строки:
// «841 772 сум» давало ровно шесть цифр и подставлялось как код, а
// сообщение бота «481294 … действует 5 минут» давало семь и не
// подставлялось вовсе. Поэтому ищем ОТДЕЛЬНО СТОЯЩУЮ группу нужной
// длины: слева и справа от неё цифр быть не должно.
//
// И требуем, чтобы такая группа была ровно одна. Две — значит мы не
// знаем, какая из них код, а гадать в поле ввода нельзя.
//
// Ссылки отбрасываем сразу: в адресе товара (/p/123456/…) попадается
// отдельная шестизначная группа, и это не код.
const ПОХОЖЕ_НА_ССЫЛКУ = /:\/\/|www\./i;

export function кодИзТекста(текст, длина) {
  const s = String(текст || "");
  if (!s || ПОХОЖЕ_НА_ССЫЛКУ.test(s)) return "";
  const найдено = s.match(new RegExp(`(?<!\\d)\\d{${длина}}(?!\\d)`, "g"));
  return найдено && найдено.length === 1 ? найдено[0] : "";
}

// Следить за буфером, пока открыт экран кода.
//
//   длина     — сколько цифр ждём;
//   занято    — () => true, если в ячейках уже что-то есть (не перетираем);
//   вставить  — (код) => void, сюда отдаём найденное;
//   неВышло   — () => void, зовётся, если прочитать молча не удалось
//               (экран покажет кнопку «Вставить код»).
//
// Возвращает { стоп, попробовать } — попробовать() зовут по нажатию кнопки.
export function следитьЗаБуфером({ длина, занято, вставить, неВышло }) {
  let живо = true;
  let прошлое = "";          // не вставляем один и тот же код дважды подряд

  async function прочитать(поЖесту) {
    if (!живо || занято()) return false;
    try {
      if (!navigator.clipboard || !navigator.clipboard.readText) throw new Error("нет буфера");
      const текст = await navigator.clipboard.readText();
      const код = кодИзТекста(текст, длина);
      if (!код || код === прошлое) return false;
      прошлое = код;
      вставить(код);
      return true;
    } catch {
      // Safari и любой отказ в доступе приходят сюда. По жесту человека
      // это уже настоящая неудача, без жеста — обычное дело.
      if (!поЖесту && неВышло) неВышло();
      return false;
    }
  }

  // Вернулись на вкладку из Telegram — самый частый случай.
  const наВидимость = () => { if (document.visibilityState === "visible") прочитать(false); };
  document.addEventListener("visibilitychange", наВидимость);
  window.addEventListener("focus", наВидимость);
  // И одна попытка сразу: код могли скопировать до того, как открыли экран.
  прочитать(false);

  return {
    стоп() {
      живо = false;
      document.removeEventListener("visibilitychange", наВидимость);
      window.removeEventListener("focus", наВидимость);
    },
    попробовать: () => прочитать(true),
  };
}
