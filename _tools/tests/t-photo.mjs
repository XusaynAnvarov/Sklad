// ========================================================================
//  ГЛАВНОЕ ФОТО И ПОРЯДОК СНИМКОВ.  node _tools/tests/t-photo.mjs
//
//  Проверяем то, что ломается молча и замечается у клиента в каталоге:
//  порядок снимков, выбор аватара, удаление аватара и — главное —
//  что старые товары после правки выглядят ТОЧНО ТАК ЖЕ, как раньше.
//
//  До этой правки аватаром было просто первое фото: карточка товара
//  сохраняла photo_url = photos[0]. Поэтому поменять порядок снимков без
//  смены аватара было нельзя. Теперь это две независимые вещи, и ровно
//  их независимость тут и проверяется.
// ========================================================================
import {
  снимки, главноеФото, главноеИз, индексГлавного, этоГлавное,
  переставить, убрать, сделатьГлавным, добавить, поляТовара, переназначить,
} from "../../js/photo.js";

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const одно = (a, b) => JSON.stringify(a) === JSON.stringify(b);

const А = "https://x/a.jpg", Б = "https://x/b.jpg", В = "https://x/c.jpg";

// ---------- что считается снимками ----------
{
  ok("нет фото — пустой список", одно(снимки({}), []));
  ok("нет товара — пустой список", одно(снимки(null), []));
  ok("список из photos", одно(снимки({ photos: [А, Б] }), [А, Б]));
  ok("пустые адреса выбрасываются", одно(снимки({ photos: [А, "", null, Б] }), [А, Б]));
  ok("самый старый товар: один photo_url", одно(снимки({ photo_url: А }), [А]));
  ok("нет фото вовсе — главное пустое", главноеФото({}) === "");
}

// ---------- старые товары не должны измениться ----------
{
  // Так выглядит товар, сохранённый прежней карточкой: photo_url = photos[0].
  const старый = { photos: [А, Б, В], photo_url: А };
  ok("старый товар: главное — то же, что показывалось раньше", главноеФото(старый) === А);
  ok("старый товар: главное стоит первым", индексГлавного(старый) === 0);

  // А так — товар, заведённый до появления галереи: photo_url ведёт на
  // снимок, которого в photos нет (например, после переезда хранилища).
  const древний = { photos: [А, Б], photo_url: "https://x/старый.jpg" };
  ok("photo_url не из списка — берём первый снимок, как и раньше", главноеФото(древний) === А);
  ok("…и его же место", индексГлавного(древний) === 0);
}

// ---------- выбор главного ----------
{
  const p = { photos: [А, Б, В], photo_url: А };
  const выбрано = сделатьГлавным(снимки(p), 2);
  ok("выбрали третий снимок главным", выбрано === В);
  const стало = { ...p, ...поляТовара(снимки(p), выбрано) };
  ok("главным стал третий", главноеФото(стало) === В);
  ok("порядок снимков НЕ изменился", одно(снимки(стало), [А, Б, В]));
  ok("место главного — третье", индексГлавного(стало) === 2);
  ok("этоГлавное узнаёт выбранный", этоГлавное(стало, В) === true);
  ok("этоГлавное не путает остальные", этоГлавное(стало, А) === false);
  ok("мимо списка — выбор не меняется наугад", сделатьГлавным([А, Б], 9) === А);
}

// ---------- порядок ----------
{
  ok("третий на первое место", одно(переставить([А, Б, В], 2, 0), [В, А, Б]));
  ok("первый на последнее место", одно(переставить([А, Б, В], 0, 2), [Б, В, А]));
  ok("на месте — ничего не меняется", одно(переставить([А, Б, В], 1, 1), [А, Б, В]));
  ok("за конец — встаёт последним", одно(переставить([А, Б, В], 0, 99), [Б, В, А]));
  ok("мимо списка — список цел", одно(переставить([А, Б], 5, 0), [А, Б]));
  ok("исходный список не портится", (() => {
    const было = [А, Б, В];
    переставить(было, 0, 2);
    return одно(было, [А, Б, В]);
  })());
}

// ---------- порядок и аватар независимы ----------
{
  // Главным выбран Б. Двигаем снимки — аватар обязан остаться Б.
  let список = [А, Б, В];
  let аватар = Б;
  список = переставить(список, 0, 2);                 // [Б, В, А]
  const стало = поляТовара(список, аватар);
  ok("после смены порядка главным остался тот же снимок", главноеФото(стало) === Б);
  ok("порядок применился", одно(стало.photos, [Б, В, А]));
  ok("место главного пересчиталось", индексГлавного(стало) === 0);
}

// ---------- удаление ----------
{
  const р = убрать([А, Б, В], Б, 1);
  ok("удалили главный — он ушёл из списка", одно(р.photos, [А, В]));
  ok("удалили главный — главным стал первый доступный", р.главное === А);
  ok("…и об этом сказано вслух", р.потеряноГлавное === true);

  const р2 = убрать([А, Б, В], Б, 0);
  ok("удалили НЕ главный — главное не трогаем", р2.главное === Б);
  ok("…и молчим", р2.потеряноГлавное === false);
  ok("…а снимок убран", одно(р2.photos, [Б, В]));

  const р3 = убрать([А], А, 0);
  ok("удалили последнее фото — главного нет", р3.главное === "" && одно(р3.photos, []));
  ok("…и это не считается потерей молча", р3.потеряноГлавное === true);

  ok("мимо списка — ничего не удаляется", одно(убрать([А, Б], А, 7).photos, [А, Б]));

  // Один и тот же адрес дважды: удалили одну копию — главный ещё на месте.
  const р4 = убрать([А, А, Б], А, 0);
  ok("дубль удалён, а главный остался", р4.главное === А && р4.потеряноГлавное === false);
}

// ---------- добавление ----------
{
  ok("снимок дописывается в конец", одно(добавить([А], Б), [А, Б]));
  ok("тот же адрес второй раз не добавляется", одно(добавить([А, Б], А), [А, Б]));
  ok("пустое не добавляется", одно(добавить([А], "   "), [А]));
}

// ---------- порядок и выбор доживают до базы и обратно ----------
{
  // Записали в товар — прочитали из товара. Именно это и значит
  // «после обновления страницы порядок остался прежним».
  const товар = { photos: [А, Б, В], photo_url: А };
  const порядок = переставить(снимки(товар), 2, 0);          // [В, А, Б]
  const аватар = сделатьГлавным(порядок, 2);                 // Б
  const вБазу = поляТовара(порядок, аватар);
  const изБазы = { ...товар, ...вБазу };                     // как придёт из базы
  ok("после перезагрузки порядок тот же", одно(снимки(изБазы), [В, А, Б]));
  ok("после перезагрузки главное то же", главноеФото(изБазы) === Б);
  ok("в базу уходит ровно два поля", одно(Object.keys(вБазу).sort(), ["photo_url", "photos"]));
}

// ---------- пересжатие фото не сбрасывает выбор ----------
{
  // js/perezhat.js меняет адреса снимков, порядок остаётся тем же.
  const были = [А, Б, В];
  const стали = ["https://x/a2.jpg", "https://x/b2.jpg", "https://x/c2.jpg"];
  ok("главный снимок остался тем же снимком, но по новому адресу",
    переназначить(были, стали, Б) === "https://x/b2.jpg");
  ok("главным был первый — им и остался", переназначить(были, стали, А) === "https://x/a2.jpg");
  // Снимок потерялся при пересжатии — берём первый из новых, а не пустоту.
  ok("главного больше нет в списке — берём первый новый",
    переназначить(были, стали, "https://x/нет.jpg") === "https://x/a2.jpg");
}

// ---------- на руках не товар, а два поля (внутри редактора) ----------
{
  ok("главноеИз: выбранный снимок", главноеИз([А, Б], Б) === Б);
  ok("главноеИз: выбор не из списка — первый", главноеИз([А, Б], В) === А);
  ok("главноеИз: пусто — пустая строка", главноеИз([], "") === "");
}

console.log("");
console.log(плохо ? плохо + " ОШИБОК" : "ВСЁ ВЕРНО");
process.exit(плохо ? 1 : 0);
