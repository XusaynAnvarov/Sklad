// ========================================================================
//  НОМЕРА КОРОБОК В НАКЛАДНОЙ.   node _tools/tests/t-invoice-boxes.mjs
//
//  Номер коробки подсказывает клиенту, где искать товар, когда заказ
//  приехал в пяти местах. Проверяем три вещи:
//
//   1. Колонки не наезжают друг на друга — ни с коробками, ни без них.
//      Ровно на этом накладная уже обжигалась: «3 600 000 сум» не
//      влезало и наезжало на соседнюю колонку.
//   2. Пока коробки не проставлены, колонки нет вовсе и ширина
//      названия остаётся прежней. Пустой столбец отнимал бы место.
//   3. Текст накладной для Telegram показывает номер коробки.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { колонкиНакладной } = await import(new URL("api/lib/pdf.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// Поддельные шрифты: ширина буквы — постоянная, этого хватает, чтобы
// проверить саму раскладку. Настоящие метрики проверяет глаз на PDF.
const шрифт = (к) => ({ widthOfTextAtSize: (s, size) => String(s).length * size * к });
const reg = шрифт(0.5), bold = шрифт(0.55);
const M = 40, R = 555, PAD = 6;

const позиция = (n, кор = "") => ({
  n: String(n), имя: "Лапка сборка аверлок коттаси 747", кво: "12", кор,
  цена: "3 600 000 сум", сумма: "43 200 000 сум",
});

// ---------------- 1. без коробок ----------------
{
  const позиции = [позиция(1), позиция(2)];
  const к = колонкиНакладной({ позиции, reg, bold, M, R, PAD });
  ok("без коробок колонки нет", к.кор === null && к.ширины.шКор === 0);
  ok("ширины складываются в полную строку",
    Math.abs(к.ширины.шN + к.ширины.шКор + к.ширины.шИмя + к.ширины.шКво + к.ширины.шЦена + к.ширины.шСумма - (R - M)) < 0.001);
  ok("название начинается после номера", к.имя > к.n);
  ok("предел названия не заходит на «кол-во»", к.имяПредел <= к.квоR - к.ширины.шКво + PAD);
  ok("колонки идут слева направо", к.квоR < к.ценаR && к.ценаR < к.суммаR);
  ok("сумма прижата к правому полю", Math.abs(к.суммаR - (R - PAD)) < 0.001);
}

// ---------------- 2. с коробками ----------------
{
  const позиции = [позиция(1, "1"), позиция(2, "12"), позиция(3, "")];
  const к = колонкиНакладной({ позиции, reg, bold, M, R, PAD });
  ok("хотя бы одна коробка — колонка появляется", к.кор !== null && к.ширины.шКор > 0);
  ok("коробка стоит между номером и названием", к.n < к.кор && к.кор < к.имя);
  ok("ширины по-прежнему складываются в полную строку",
    Math.abs(к.ширины.шN + к.ширины.шКор + к.ширины.шИмя + к.ширины.шКво + к.ширины.шЦена + к.ширины.шСумма - (R - M)) < 0.001);
  ok("предел названия не заходит на «кол-во»", к.имяПредел <= к.квоR - к.ширины.шКво + PAD);
  ok("колонки идут слева направо", к.имя < к.квоR && к.квоR < к.ценаR && к.ценаR < к.суммаR);

  const без = колонкиНакладной({ позиции: позиции.map(п => ({ ...п, кор: "" })), reg, bold, M, R, PAD });
  ok("место под коробку отнимается у названия, а не у цифр",
    Math.abs((без.ширины.шИмя - к.ширины.шИмя) - к.ширины.шКор) < 0.001
    && без.ширины.шЦена === к.ширины.шЦена && без.ширины.шСумма === к.ширины.шСумма);
}

// ---------------- 3. длинные подписи коробок ----------------
{
  // Коробки подписывают и буквами: «верх-левая», «А-3». Колонка должна
  // растянуться под самую длинную подпись, а не обрезать её.
  const позиции = [позиция(1, "А-3"), позиция(2, "верх-левая")];
  const к = колонкиНакладной({ позиции, reg, bold, M, R, PAD });
  const узкая = колонкиНакладной({ позиции: позиции.map(п => ({ ...п, кор: "1" })), reg, bold, M, R, PAD });
  ok("длинная подпись коробки расширяет колонку", к.ширины.шКор > узкая.ширины.шКор);
  ok("название при этом только сужается", к.ширины.шИмя < узкая.ширины.шИмя);
}

// ---------------- 4. позиции накладной ----------------
{
  // Как позиция превращается в строку таблицы — ровно так же, как в
  // buildInvoicePDF. Сам buildText из js/pages/sales.js здесь не
  // запускается: он тянет за собой весь браузерный слой данных.
  const вПозицию = (it, i) => ({ n: String(i + 1), кор: String(it.box ?? "").trim() });
  const строки = [{ box: 3 }, { box: " 2 " }, {}, { box: "" }].map(вПозицию);
  ok("номер коробки берётся числом и строкой", строки[0].кор === "3" && строки[1].кор === "2");
  ok("без коробки остаётся пусто", строки[2].кор === "" && строки[3].кор === "");

  const к = колонкиНакладной({ позиции: строки.map((с, i) => ({ ...позиция(i + 1), кор: с.кор })), reg, bold, M, R, PAD });
  ok("часть позиций с коробками — колонка всё равно есть", к.кор !== null);
}

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
