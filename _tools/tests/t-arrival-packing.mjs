// ========================================================================
//  ПРИХОД С ПЕРЕСЧЁТОМ ПО УПАКОВКЕ.
//  node _tools/tests/t-arrival-packing.mjs
//
//  Поставщик продаёт шпульки штуками, у нас они лежат пачками по 10.
//  Проверяется не «считается ли», а СХОДЯТСЯ ЛИ ДЕНЬГИ: сколько закупили,
//  столько и должно прибавиться к стоимости запасов, в каких бы единицах
//  склад это ни считал. И ещё одно, не менее важное: старые документы
//  обязаны остаться посчитанными по-старому, даже если упаковку потом
//  поменяли. Иначе прошлогодний приход однажды утром станет другим.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const A = await import(new URL("js/arrival.js", корень));
const { consumeFIFO } = await import(new URL("js/inventory.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const почти = (a, b) => Math.abs(Number(a) - Number(b)) < 1e-6;

const приход = (items, доп = {}) => ({
  id: "пр-1", supplier: "JACK", currency: "yuan",
  date: "2026-11-03T05:55:27.072Z", kind: "supplier", items, ...доп,
});

// Шпулька: берём штуками, храним и продаём пачками по 10.
const шпулька = (доп = {}) => ({
  id: "ш1", name: "Шпулька", stock_qty: 0, batches: [],
  cost_yuan: 0, cost_usd: 0,
  unit: "пачка", pack_size: 10, buy_unit: "шт", sell_unit: "пачка",
  auto_convert: true, odd_rule: "keep", packing_ver: 1, ...доп,
});

// ---------- пример из задания: 100 штук по 2000 ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  const rows = A.arrivalRows(п, товары);
  ok("100 штук легли как 10 пачек", rows[0].stock_qty === 10);
  ok("в партии тоже 10 пачек", rows[0].batches.at(-1).qty === 10);
  ok("себестоимость пачки 20 000", rows[0].batches.at(-1).cost_yuan === 20000);
  ok("ДЕНЬГИ СХОДЯТСЯ: 10 × 20 000 = 100 × 2 000",
    почти(rows[0].stock_qty * rows[0].batches.at(-1).cost_yuan, 100 * 2000));
  ok("партия помечена номером прихода", rows[0].batches.at(-1).src === "пр-1");
}

// ---------- неполная пачка: 105 штук ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 105, unit_cost: 2000, currency: "yuan" }]);
  const rows = A.arrivalRows(п, товары);
  ok("105 штук — это 10,5 пачки, а не 11", почти(rows[0].stock_qty, 10.5));
  ok("ДЕНЬГИ СХОДЯТСЯ и на неполной пачке",
    почти(rows[0].stock_qty * rows[0].batches.at(-1).cost_yuan, 105 * 2000));
  const реш = A.позицияПрихода(п.items[0], товары[0]);
  ok("система знает про 10 целых и 5 штук", реш.полных === 10 && почти(реш.остатокШтук, 5));
  ok("ничего не отложено — правило «оставить как есть»", реш.отложеноШтук === 0);
}

// ---------- коробки: 1 коробка = 20 пачек = 200 штук ----------
{
  const товары = [шпулька({ box_size: 20, buy_unit: "коробка" })];
  const п = приход([{ product_id: "ш1", qty: 3, unit_cost: 400000, currency: "yuan" }]);
  const rows = A.arrivalRows(п, товары);
  ok("3 коробки легли как 60 пачек", rows[0].stock_qty === 60);
  ok("себестоимость пачки 20 000", rows[0].batches.at(-1).cost_yuan === 20000);
  ok("ДЕНЬГИ СХОДЯТСЯ: 60 × 20 000 = 3 × 400 000",
    почти(rows[0].stock_qty * rows[0].batches.at(-1).cost_yuan, 3 * 400000));
}

// ---------- товары без настроек трогать нельзя ----------
{
  const обычный = { id: "t9", name: "Лапка", stock_qty: 0, batches: [], cost_yuan: 10, cost_usd: 1.4 };
  const п = приход([{ product_id: "t9", qty: 7, unit_cost: 5, currency: "yuan" }]);
  const rows = A.arrivalRows(п, [обычный]);
  ok("без настроек приход идёт один к одному", rows[0].stock_qty === 7);
  ok("и цена из накладной не трогается", rows[0].batches.at(-1).cost_yuan === 5);
  ok("решение честно помечено как «без пересчёта»",
    A.позицияПрихода(п.items[0], обычный).пересчитано === false);
}

// ---------- выключенный автопересчёт ----------
{
  const товары = [шпулька({ auto_convert: false })];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  ok("выключенный пересчёт не применяется", A.arrivalRows(п, товары)[0].stock_qty === 100);
}

// ---------- упаковка настроена с противоречием — пересчитывать нельзя ----------
{
  // Закупка коробками, а сколько пачек в коробке — не сказано.
  const товары = [шпулька({ buy_unit: "коробка", box_size: null })];
  const п = приход([{ product_id: "ш1", qty: 3, unit_cost: 400000, currency: "yuan" }]);
  const реш = A.позицияПрихода(п.items[0], товары[0]);
  ok("при противоречии ничего не выдумываем", реш.пересчитано === false);
  ok("и приходуем как раньше", A.arrivalRows(п, товары)[0].stock_qty === 3);
}

// ---------- правило «отложить»: на полку только полные упаковки ----------
{
  const товары = [шпулька({ odd_rule: "wait" })];
  const п = приход([{ product_id: "ш1", qty: 105, unit_cost: 2000, currency: "yuan" }]);
  const реш = A.позицияПрихода(п.items[0], товары[0]);
  ok("на склад идут только 10 полных пачек", реш.складских === 10);
  ok("а 5 штук записаны отложенными, не потеряны", почти(реш.отложеноШтук, 5));
  ok("на полке ровно 10 пачек", A.arrivalRows(п, товары)[0].stock_qty === 10);
}

// ---------- ИСТОРИЯ ЗАМОРОЖЕНА ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  const запись = A.записьПрихода(
    A.позицияПрихода(п.items[0], товары[0]), "2026-11-03T10:00:00.000Z", "админ");
  п.items[0].приход = запись;

  ok("в документе записана исходная единица", запись.ед === "шт");
  ok("…исходное количество", запись.кол === 100);
  ok("…исходная цена", запись.цена === 2000);
  ok("…коэффициент", почти(запись.коэффициент, 0.1));
  ok("…версия настроек упаковки", запись.версия === 1);
  ok("…итог на складе", запись.складских === 10);
  ok("…итоговая себестоимость", запись.себестоимость === 20000);
  ok("…когда и кто подтвердил", !!запись.когда && запись.кто === "админ");

  // Владелец поменял упаковку: в пачке стало 12, версия выросла.
  const поменяли = шпулька({ pack_size: 12, packing_ver: 2 });
  const снова = A.позицияПрихода(п.items[0], поменяли);
  ok("СТАРЫЙ документ считается ПО-СТАРОМУ",
    снова.складских === 10 && почти(снова.коэффициент, запись.коэффициент));
  ok("и помнит прежнюю версию настроек", снова.версия === 1);

  const новый = A.позицияПрихода({ product_id: "ш1", qty: 120, unit_cost: 2000 }, поменяли);
  ok("а НОВЫЙ приход считается по новым правилам", новый.складских === 10 && новый.версия === 2);
}

// ---------- повторное нажатие не задваивает ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  const первый = A.arrivalRows(п, товары);
  const послеЗаписи = первый.map(r => ({ ...товары.find(x => x.id === r.id), ...r }));
  ok("второе нажатие ничего не добавляет", A.arrivalRows(п, послеЗаписи).length === 0);
  ok("остаток остался 10 пачек", послеЗаписи[0].stock_qty === 10);
}

// ---------- откат снимает ровно то, что положил ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  const rows = A.arrivalRows(п, товары);
  const послеЗаписи = rows.map(r => ({ ...товары.find(x => x.id === r.id), ...r }));
  ok("после отката на складе пусто",
    A.откатитьПриход(п, послеЗаписи, consumeFIFO)[0].stock_qty === 0);
}

// ---------- история пишется в документ ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  let записано = null;
  const db = {
    products: { async upsertMany(r) { return r; } },
    purchases: { async upsert(o) { записано = o; return o; } },
  };
  await A.applyArrival(db, п, товары, null, { кто: "владелец" });
  ok("документ дописан", !!записано && записано.id === "пр-1");
  ok("в позиции появилась запись прихода", !!записано.items[0].приход);
  ok("…с исходным количеством из накладной", записано.items[0].приход.кол === 100);
  ok("…и итогом на складе", записано.items[0].приход.складских === 10);
  ok("число в самой накладной не подменили", записано.items[0].qty === 100);

  записано = null;
  await A.записатьИсторию(db, п, товары, "кто-то другой");
  ok("повторная запись истории документ не трогает", записано === null);
}

// ---------- разбор всего прихода разом (для предпросмотра) ----------
{
  const товары = [шпулька(), { id: "t9", name: "Лапка", stock_qty: 0, batches: [], cost_yuan: 10 }];
  const п = приход([
    { product_id: "ш1", qty: 105, unit_cost: 2000, currency: "yuan" },
    { product_id: "t9", qty: 7, unit_cost: 5, currency: "yuan" },
  ]);
  const разбор = A.пересчётПрихода(п, товары);
  ok("разобраны обе позиции", разбор.length === 2);
  ok("первая пересчитана", разбор[0].решение.пересчитано === true);
  ok("вторая — как раньше", разбор[1].решение.пересчитано === false);
  ok("предпросмотр показывает неполную упаковку", разбор[0].решение.ровно === false);
}

console.log("");
console.log(плохо ? плохо + " ОШИБОК" : "ПРИХОД С УПАКОВКОЙ СЧИТАЕТСЯ ВЕРНО");
process.exit(плохо ? 1 : 0);
