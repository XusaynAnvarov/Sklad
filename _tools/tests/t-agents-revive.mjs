// ========================================================================
//  АГЕНТЫ ОЖИВАЮТ ПОСЛЕ МИГРАЦИИ.   node _tools/tests/t-agents-revive.mjs
//
//  Воспроизводит то, что случилось на боевом 23 ноября:
//   1. сервер работает, а таблиц агентов нет — ядро молчит;
//   2. владелец выполняет db/agents-migration.sql;
//   3. агенты должны заработать САМИ, без перезапуска сервера.
//
//  Раньше ядро запоминало «таблиц нет» навсегда, а строки агентов
//  заводились, только когда владелец открывал раздел в складе. Вместе
//  это значило: миграцию выполнили — а агенты молчат до перезапуска и
//  до первого захода в раздел.
// ========================================================================
const корень = new URL("../../", import.meta.url);
process.env.SUPABASE_URL = "http://db.test";
process.env.SUPABASE_SERVICE_KEY = "k";
process.env.DB_MODE = "supabase";

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// Поддельная база: пока миграции нет, любая таблица agent_* «не существует».
let миграцияЕсть = false;
const база = { agent_state: [], agent_runs: [], agent_notices: [], agent_approvals: [], agent_subruns: [] };
let обращений = 0;

globalThis.fetch = async (адрес, опции = {}) => {
  const u = new URL(String(адрес));
  const ответ = (d, s = 200) => ({ ok: s < 400, status: s, json: async () => d, text: async () => (typeof d === "string" ? d : JSON.stringify(d)) });
  if (u.hostname !== "db.test") return ответ({ ok: true });
  const таблица = u.pathname.replace("/rest/v1/", "");
  if (таблица.startsWith("agent_")) {
    обращений++;
    if (!миграцияЕсть) return ответ(`{"code":"PGRST205","message":"Could not find the table 'public.${таблица}' in the schema cache"}`, 404);
  }
  база[таблица] ||= [];
  const метод = (опции.method || "GET").toUpperCase();
  const тело = опции.body ? JSON.parse(опции.body) : null;
  if (метод === "GET") {
    // фильтры не важны для этого теста, кроме «кому пора» — его отдаём пустым
    if (таблица === "agent_state" && u.searchParams.has("next_run_at")) return ответ([]);
    return ответ(база[таблица]);
  }
  if (метод === "POST") { for (const с of [].concat(тело)) база[таблица].push({ ...с }); return ответ([].concat(тело)); }
  if (метод === "PATCH") return ответ([]);
  return ответ([]);
};

const C = await import(new URL("api/lib/agents/core.js", корень));
let сейчас = Date.parse("2026-11-23T10:00:00Z");
C._установитьЧасы(() => сейчас);

// 1. Таблиц нет — ядро молчит и не долбит базу каждую минуту.
{
  const r1 = await C.тик(сейчас);
  ok("без таблиц тик честно говорит «не готово»", r1.готово === false);
  ok("раздел знает, что таблиц нет", C.таблицыГотовы() === false);

  const до = обращений;
  сейчас += 60e3; await C.тик(сейчас);
  сейчас += 60e3; await C.тик(сейчас);
  ok("пока не истёк срок перепроверки, базу не дёргаем каждую минуту", обращений === до);
}

// 2. Владелец выполнил миграцию.
миграцияЕсть = true;

// 3. До срока перепроверки — ещё молчим (это нормально, пять минут).
{
  const r = await C.тик(сейчас);
  ok("через минуту после миграции ещё ждём перепроверки", r.готово === false);
}

// 4. Срок перепроверки прошёл — агенты оживают сами, без перезапуска.
{
  сейчас += 5 * 60e3;
  const r = await C.тик(сейчас);
  ok("после перепроверки ядро видит таблицы", r.готово === true);
  ok("раздел тоже видит, что таблицы есть", C.таблицыГотовы() === true);
  ok("строки всех пяти агентов заведены самим тиком, без захода в раздел",
    база.agent_state.length === C.ОПИСАНИЯ.length && C.ОПИСАНИЯ.length === 5);
  ok("у каждого агента есть срок первого запуска", база.agent_state.every((с) => !!с.next_run_at));
}

// 5. Строки заводятся один раз, а не на каждом тике.
{
  const было = база.agent_state.length;
  сейчас += 60e3; await C.тик(сейчас);
  сейчас += 60e3; await C.тик(сейчас);
  ok("повторные тики не плодят строки агентов", база.agent_state.length === было);
}

C._установитьЧасы(null);
console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
