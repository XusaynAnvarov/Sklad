// ========================================================================
//  ЦЕНЫ, ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ И МАРЖА.
//  node _tools/tests/t-pricing.mjs
//
//  Здесь проверяется не «считается ли», а СХОДЯТСЯ ЛИ ДЕНЬГИ. Два места,
//  где они обычно и теряются:
//
//    1. Расход делится между позициями. Сумма долей обязана РАВНЯТЬСЯ
//       расходу — не «примерно», а до копейки. Поэтому ниже много
//       нарочно неудобных чисел: 100 на три позиции, одна копейка на
//       три позиции, расход, который не делится ни на что.
//
//    2. Расход ложится в себестоимость. Товара и денег должно стать
//       ровно столько, сколько закупили ПЛЮС расход, в каких бы
//       единицах склад это ни считал.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const P = await import(new URL("js/pricing.js", корень));
const A = await import(new URL("js/arrival.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const почти = (a, b, точность = 1e-6) => Math.abs(Number(a) - Number(b)) < точность;
const сумма = (список) => список.reduce((t, x) => t + (Number(x) || 0), 0);

// Шпулька: берём штуками, храним пачками по 10, в коробке 20 пачек.
const шпулька = (доп = {}) => ({
  id: "ш1", name: "Шпулька", stock_qty: 0, batches: [],
  cost_yuan: 0, cost_usd: 0,
  unit: "пачка", pack_size: 10, buy_unit: "шт", sell_unit: "пачка", box_size: 20,
  auto_convert: true, odd_rule: "keep", packing_ver: 1, ...доп,
});
const лапка = (доп = {}) => ({ id: "t9", name: "Лапка", stock_qty: 0, batches: [], cost_yuan: 10, ...доп });

const приход = (items, доп = {}) => ({
  id: "пр-1", supplier: "JACK", currency: "yuan", kind: "supplier",
  date: "2026-11-03T05:55:27.072Z", items, ...доп,
});

// ---------- 1. ЦЕНА НА КАЖДОМ УРОВНЕ УПАКОВКИ ----------
{
  const у = P.уровниЦен(шпулька(), { цена: 2000, ед: "пачка" });
  const по = Object.fromEntries(у.map(x => [x.ед, x]));
  ok("пачка стоит 2 000 — как и вписали", по["пачка"].цена === 2000);
  ok("штука из неё — 200", по["шт"].цена === 200);
  ok("коробка из 20 пачек — 40 000", по["коробка"].цена === 40000);
  ok("в коробке 200 штук (пример из задания)", по["коробка"].штук === 200);
  ok("уровни идут от мелкого к крупному", у.map(x => x.ед).join(",") === "шт,пачка,коробка");
  ok("исходный уровень помечен", по["пачка"].исходный === true && по["шт"].исходный === false);
}
{
  // Та же цена, названная за коробку, — обратный ход.
  const по = Object.fromEntries(P.уровниЦен(шпулька(), { цена: 40000, ед: "коробка" }).map(x => [x.ед, x.цена]));
  ok("из цены коробки выходит та же цена пачки", по["пачка"] === 2000);
  ok("…и та же цена штуки", по["шт"] === 200);
}
{
  const у = P.уровниЦен(лапка(), { цена: 10 });
  ok("у товара без упаковки уровень один — штука", у.length === 1 && у[0].ед === "шт" && у[0].цена === 10);
}

// ---------- 2. РАСХОДЫ ДОКУМЕНТА ----------
{
  ok("без расходов — пусто", P.расходы(приход([])).есть === false);
  ok("правило по умолчанию — по стоимости", P.расходы(приход([])).правило === "value");
  const р = P.расходы(приход([], { extra: { сумма: 500, правило: "мусор" } }));
  ok("сумма прочитана", р.сумма === 500 && р.есть === true);
  ok("неизвестное правило не ломает расчёт", р.правило === "value");
  ok("валюта по умолчанию — валюта прихода", р.валюта === "yuan");
  ok("ноль не записывается вовсе", P.поляРасходов({ сумма: 0 }) === null);
  ok("отрицательный расход не записывается", P.поляРасходов({ сумма: -100 }) === null);
}

// ---------- 3. ДЕЛЁЖ БЕЗ ПОТЕРЬ ----------
{
  // 100 на три равные позиции: 33,34 + 33,33 + 33,33. Ни больше, ни меньше.
  const п = приход([
    { product_id: "a", qty: 1, unit_cost: 10 },
    { product_id: "b", qty: 1, unit_cost: 10 },
    { product_id: "c", qty: 1, unit_cost: 10 },
  ], { extra: { сумма: 100, правило: "items" } });
  const д = P.доплаты(п, []);
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (100 на три)", почти(сумма(д), 100));
  ok("лишняя копейка досталась одной позиции", д.filter(x => x === 33.34).length === 1);
}
{
  // Одна копейка на три позиции. Пропасть ей нельзя — и размножиться тоже.
  const п = приход([
    { product_id: "a", qty: 1, unit_cost: 1 },
    { product_id: "b", qty: 1, unit_cost: 1 },
    { product_id: "c", qty: 1, unit_cost: 1 },
  ], { extra: { сумма: 0.01, правило: "items" } });
  const д = P.доплаты(п, []);
  ok("одна копейка на три позиции не исчезла", почти(сумма(д), 0.01));
  ok("…и не размножилась", д.filter(x => x > 0).length === 1);
}
{
  // По стоимости: позиция на 900 и позиция на 100 делят 100.
  const п = приход([
    { product_id: "a", qty: 9, unit_cost: 100 },
    { product_id: "b", qty: 1, unit_cost: 100 },
  ], { extra: { сумма: 100, правило: "value" } });
  const д = P.доплаты(п, []);
  ok("дорогая позиция забрала 90", почти(д[0], 90));
  ok("дешёвая — 10", почти(д[1], 10));
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (по стоимости)", почти(сумма(д), 100));
}
{
  // Неудобное число, которое не делится ни на что ровно.
  const п = приход([
    { product_id: "a", qty: 7, unit_cost: 3.33 },
    { product_id: "b", qty: 11, unit_cost: 1.07 },
    { product_id: "c", qty: 3, unit_cost: 19.99 },
  ], { extra: { сумма: 1000.07, правило: "value" } });
  const д = P.доплаты(п, []);
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (1000,07 на три разные цены)", почти(сумма(д), 1000.07));
  ok("каждая доля — целое число копеек", д.every(x => почти(x * 100, Math.round(x * 100))));
}
{
  // По штукам: шпульки берут штуками, лапки — штуками же, но у шпульки
  // пачка по 10 — а в накладной стоят ЗАКУПОЧНЫЕ единицы, то есть штуки.
  const п = приход([
    { product_id: "ш1", qty: 100, unit_cost: 1 },
    { product_id: "t9", qty: 100, unit_cost: 50 },
  ], { extra: { сумма: 300, правило: "pieces" } });
  const д = P.доплаты(п, [шпулька(), лапка()]);
  ok("по штукам делится поровну, цена не важна", почти(д[0], 150) && почти(д[1], 150));
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (по штукам)", почти(сумма(д), 300));
}
{
  const п = приход([{ product_id: "a", qty: 1, unit_cost: 10 }], { kind: "shop", extra: { сумма: 500 } });
  ok("из магазина расходы не раскладываются — цена там наша", P.доплаты(п, [])[0] === 0);
}
{
  // Цены ещё не вписали — делить по стоимости не из чего. Делим поровну,
  // а не теряем расход целиком.
  const п = приход([
    { product_id: "a", qty: 1, unit_cost: 0 },
    { product_id: "b", qty: 1, unit_cost: 0 },
  ], { extra: { сумма: 50, правило: "value" } });
  const д = P.доплаты(п, []);
  ok("без цен расход делится поровну", почти(д[0], 25) && почти(д[1], 25));
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (без цен)", почти(сумма(д), 50));
}
{
  ok("у документа без позиций делить нечего", P.доплаты(приход([], { extra: { сумма: 100 } }), []).length === 0);
}

// ---------- 4. ЦЕНА ЗАКУПОЧНОЙ ЕДИНИЦЫ С РАСХОДАМИ ----------
{
  ok("без расходов цена не меняется", P.ценаСРасходами(100, 25, 0) === 25);
  ok("расход делится на количество", P.ценаСРасходами(100, 25, 500) === 30);
  ok("нулевое количество не делим", P.ценаСРасходами(0, 25, 500) === 25);
  // Копейка на 105 штук — в копейках не умещается, но пропасть не должна.
  ok("дробная доля расхода не округляется до нуля", P.ценаСРасходами(105, 10, 0.01) > 10);
}

// ---------- 5. МАРЖА ----------
{
  const м = P.маржа({ себестоимость: 20000, цена: 25000 });
  ok("прибыль — разница", м.прибыль === 5000);
  ok("маржа — доля прибыли в цене", м.маржа === 20);
  ok("наценка — насколько дороже себестоимости", м.наценка === 25);
  ok("в минус не ушли", м.вМинус === false);
}
{
  const м = P.маржа({ себестоимость: 100, цена: 200 });
  ok("наценка 100% — это маржа 50% (их легко спутать)", м.наценка === 100 && м.маржа === 50);
}
{
  const м = P.маржа({ себестоимость: 30000, цена: 25000 });
  ok("продажа ниже себестоимости видна", м.вМинус === true && м.прибыль === -5000);
}
{
  const м = P.маржа({ себестоимость: 100, цена: 0 });
  ok("без цены продажи маржи нет, и ноль не выдумывается", м.есть === false && м.маржа === 0);
}

// ---------- 6. РАСХОДЫ ЛОЖАТСЯ В СЕБЕСТОИМОСТЬ ----------
{
  // 100 штук по ¥2 000 плюс ¥20 000 доставки. На полку ляжет 10 пачек,
  // и стоить они должны ¥220 000, а не ¥200 000.
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }],
    { extra: { сумма: 20000, валюта: "yuan", правило: "value" } });
  const rows = A.arrivalRows(п, товары);
  ok("на склад легли те же 10 пачек — расход количество не меняет", rows[0].stock_qty === 10);
  ok("себестоимость пачки выросла до 22 000", rows[0].batches.at(-1).cost_yuan === 22000);
  ok("ДЕНЬГИ СХОДЯТСЯ: 10 × 22 000 = 100 × 2 000 + 20 000",
    почти(rows[0].stock_qty * rows[0].batches.at(-1).cost_yuan, 100 * 2000 + 20000));
}
{
  // Неполная упаковка вместе с расходом — самое неудобное сочетание.
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 105, unit_cost: 2000, currency: "yuan" }],
    { extra: { сумма: 1234.56, валюта: "yuan", правило: "value" } });
  const реш = A.позицияПрихода(п.items[0], товары[0], P.доплаты(п, товары)[0]);
  ok("доля расходов записана в позицию", почти(реш.доп, 1234.56));
  ok("цена из накладной не подменена", реш.цена === 2000);
  ok("количество по-прежнему 10,5 пачки", почти(реш.складских, 10.5));
  // Себестоимость одной пачки округлена до копейки — значит итог может
  // разойтись на половину копейки на пачку, но не больше.
  const итог = реш.складских * реш.себестоимость;
  ok("ДЕНЬГИ СХОДЯТСЯ и на неполной упаковке с расходом",
    почти(итог, 105 * 2000 + 1234.56, 0.005 * реш.складских + 1e-6));
}
{
  // Товар без настроенной упаковки. Расход к упаковке отношения не имеет
  // и обязан лечь в себестоимость всё равно.
  const п = приход([{ product_id: "t9", qty: 10, unit_cost: 100, currency: "yuan" }],
    { extra: { сумма: 50, валюта: "yuan", правило: "value" } });
  const rows = A.arrivalRows(п, [лапка()]);
  ok("у ненастроенного товара количество как в накладной", rows[0].stock_qty === 10);
  ok("а себестоимость — с расходом: 105 вместо 100", rows[0].batches.at(-1).cost_yuan === 105);
}
{
  // Два товара, расход по стоимости. Общие деньги должны сойтись.
  const товары = [шпулька(), лапка()];
  const п = приход([
    { product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" },
    { product_id: "t9", qty: 50, unit_cost: 40, currency: "yuan" },
  ], { extra: { сумма: 5000, валюта: "yuan", правило: "value" } });
  const доли = P.доплаты(п, товары);
  ok("СУММА ДОЛЕЙ РАВНА РАСХОДУ (две позиции прихода)", почти(сумма(доли), 5000));
  const rows = A.arrivalRows(п, товары);
  const стоимость = rows.reduce((t, r) => t + r.batches.at(-1).qty * r.batches.at(-1).cost_yuan, 0);
  ok("ДЕНЬГИ СХОДЯТСЯ по всему приходу: товар + расходы",
    почти(стоимость, 100 * 2000 + 50 * 40 + 5000, 0.01));
}

// ---------- 7. ИСТОРИЯ С РАСХОДАМИ ЗАМОРОЖЕНА ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }],
    { extra: { сумма: 20000, валюта: "yuan", правило: "value" } });
  const запись = A.записьПрихода(
    A.позицияПрихода(п.items[0], товары[0], P.доплаты(п, товары)[0]),
    "2026-11-03T10:00:00.000Z", "админ");
  п.items[0].приход = запись;

  ok("в документе осталась доля расходов", почти(запись.доп, 20000));
  ok("…и цена закупочной единицы вместе с ней", почти(запись.ценаСДоп, 2200));
  ok("…и итоговая себестоимость", запись.себестоимость === 22000);

  // Владелец передумал и убрал расходы из документа.
  const безРасходов = { ...п, extra: null };
  const снова = A.позицияПрихода(безРасходов.items[0], товары[0], P.доплаты(безРасходов, товары)[0]);
  ok("СТАРЫЙ документ считается ПО-СТАРОМУ, с прежним расходом",
    снова.себестоимость === 22000 && почти(снова.доп, 20000));

  // И повторное оприходование не задваивает остаток, как и раньше.
  const rows = A.arrivalRows(п, товары);
  const после = rows.map(r => ({ ...товары.find(x => x.id === r.id), ...r }));
  ok("второе нажатие ничего не добавляет", A.arrivalRows(п, после).length === 0);
  ok("себестоимость партии осталась с расходом", после[0].batches.at(-1).cost_yuan === 22000);
}

// ---------- 8. ПРИХОД БЕЗ РАСХОДОВ СЧИТАЕТСЯ РОВНО КАК ДО ЭТОЙ РАБОТЫ ----------
{
  const товары = [шпулька()];
  const п = приход([{ product_id: "ш1", qty: 100, unit_cost: 2000, currency: "yuan" }]);
  const реш = A.позицияПрихода(п.items[0], товары[0], P.доплаты(п, товары)[0]);
  ok("себестоимость прежняя", реш.себестоимость === 20000);
  ok("и поля расходов в документе не появилось", реш.доп === undefined && реш.ценаСДоп === undefined);
}

console.log("");
console.log(плохо ? плохо + " ОШИБОК" : "ЦЕНЫ, РАСХОДЫ И МАРЖА СЧИТАЮТСЯ ВЕРНО");
process.exit(плохо ? 1 : 0);
