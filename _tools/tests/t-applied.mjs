// ========================================================================
//  ЧТО СЧИТАЕТСЯ СПИСАННЫМ СО СКЛАДА.  node _tools/tests/t-applied.mjs
//
//  От этого правила зависит, вернётся ли товар при удалении накладной и не
//  спишется ли он дважды при повторном оформлении. Ошибиться тут дорого:
//  оба раза остаток расходится с полкой, а замечают это через недели.
//
//  В боевой базе два поколения накладных:
//    • до июля 2026 отметки applied не было вовсе — 1369 позиций без неё,
//      но у 1083 записана себестоимость, то есть склад по ним трогали;
//    • с августа отметка стоит у всех.
//  Плюс отдельный случай: у оформленной накладной статус мог откатиться
//  в «подтверждён» — клиент нажимал старую кнопку в чате бота.
// ========================================================================
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const ч = (f) => readFileSync(join(КОРЕНЬ, f), "utf8");
const { списанные, isUnapplied } = await import(new URL("../../js/stockcheck.js", import.meta.url));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const сколько = (sale) => списанные(sale).length;

// ---------- новые накладные: есть отметка ----------
{
  const s = { status: "final", items: [{ product_id: "a", qty: 1, applied: true }] };
  ok("оформленная с отметкой — списана", сколько(s) === 1);
}

// ---------- старые накладные: отметки нет, но склад трогали ----------
{
  // Так выглядит больше тысячи позиций в боевой базе: поля applied нет,
  // зато записана себестоимость. Судить о них только по отметке нельзя —
  // их удаление не вернуло бы товар на склад.
  const s = { status: "final", items: [{ product_id: "a", qty: 2, cogs_yuan: 74, cogs_usd: 11 }] };
  ok("оформленная без отметки (старая) — тоже списана", сколько(s) === 1);
}

// ---------- заказ: склад ещё не трогали ----------
{
  ok("новый заказ не списан", сколько({ status: "order", items: [{ product_id: "a", qty: 1 }] }) === 0);
  ok("заказ с ценами не списан", сколько({ status: "pending_confirm", items: [{ product_id: "a", qty: 1 }] }) === 0);
  ok("подтверждённый клиентом не списан", сколько({ status: "confirmed", items: [{ product_id: "a", qty: 1 }] }) === 0);
  ok("черновик не списан", сколько({ status: "draft", items: [{ product_id: "a", qty: 1 }] }) === 0);
}

// ---------- откат статуса: главный случай ----------
{
  // Владелец оформил заказ — товар списался, отметка встала. Потом клиент
  // нажал старую кнопку «Подтвердить» в чате, и статус откатился.
  // Товар при этом остался списанным.
  const s = { status: "confirmed", items: [{ product_id: "a", qty: 1, applied: true, cogs_yuan: 970 }] };
  ok("откатившийся статус не отменяет списания", сколько(s) === 1);
}

// ---------- смешанная накладная ----------
{
  const s = { status: "final", items: [
    { product_id: "a", qty: 1, applied: true },
    { product_id: "b", qty: 2 },                      // старая позиция без отметки
    { product_id: "c", qty: 3, applied: false },      // явно помечена как НЕ списанная
  ] };
  const вернём = списанные(s).map(i => i.product_id);
  ok("явное applied: false уважается: вернём " + вернём.join(","), вернём.join(",") === "a,b");
}

// ---------- мусор на входе ----------
{
  ok("без накладной — пусто", сколько(null) === 0);
  ok("без позиций — пусто", сколько({ status: "final" }) === 0);
}

// ---------- проверка склада ищет непроведённые ----------
{
  ok("оформленная без отметки попадает в «не списано»",
     isUnapplied({ status: "final", items: [{ product_id: "a", qty: 1 }] }) === true);
  ok("заказ туда не попадает",
     isUnapplied({ status: "order", items: [{ product_id: "a", qty: 1 }] }) === false);
}

// ---------- правило берут все места, где двигается склад ----------
{
  for (const f of ["js/pages/sales.js", "js/sklad/screens/orders.js", "js/sklad/screens/docs.js"]) {
    ok(f.split("/").pop() + ": берёт общее правило", ч(f).includes("stockcheck.js"));
    ok(f.split("/").pop() + ": не решает по статусу сам", !/wasDeducted = sale\.status/.test(ч(f)));
  }
}

// ---------- «Проверка склада» не поднимает ложных тревог ----------
{
  // Старая накладная без отметки, но с записанной себестоимостью: склад по
  // ней списан. Раньше проверка предлагала списать её ВТОРОЙ раз — таких
  // накладных в базе больше сотни.
  ok("старая накладная с себестоимостью — не тревога",
     isUnapplied({ status: "final", items: [{ product_id: "a", qty: 2, cogs_yuan: 74 }] }) === false);
  ok("хватает и себестоимости в долларах",
     isUnapplied({ status: "final", items: [{ product_id: "a", qty: 2, cogs_usd: 11 }] }) === false);
  ok("нулевая себестоимость — тоже след списания",
     isUnapplied({ status: "final", items: [{ product_id: "a", qty: 2, cogs_yuan: 0 }] }) === false);
  // А вот когда следов нет вовсе — это настоящая непроведённая накладная.
  ok("без отметки и без себестоимости — настоящая тревога",
     isUnapplied({ status: "final", items: [{ product_id: "a", qty: 2 }] }) === true);
  ok("одной непроведённой позиции хватает",
     isUnapplied({ status: "final", items: [{ product_id: "a", applied: true }, { product_id: "b", qty: 1 }] }) === true);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nСКЛАД ДВИГАЕТСЯ ПО ОДНОМУ ПРАВИЛУ");
process.exit(плохо ? 1 : 0);
