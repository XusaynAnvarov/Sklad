// ========================================================================
//  КОРОТКАЯ ПАМЯТЬ СЕРВЕРА.  node _tools/tests/t-memcache.mjs
//
//  Склад просил у базы все 940 товаров на каждой странице — по полторы
//  секунды на запрос. Теперь список несколько секунд живёт в памяти.
//  Главное правило: своя запись стирает память сразу, иначе склад покажет
//  старый остаток.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { помнить, забыть, взять, положить, размерПамяти } = await import(new URL("api/lib/memcache.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const ждать = (мс) => new Promise(r => setTimeout(r, мс));

{
  let считали = 0;
  const дай = () => помнить("db:products:все", 1, async () => { считали++; return [{ id: "a" }]; });
  const первый = await дай();
  const второй = await дай();
  ok("второй раз берётся из памяти, база не тревожится", считали === 1 && второй === первый);

  забыть("db:products:");
  await дай();
  ok("после записи в таблицу память стёрта — читаем заново", считали === 2);

  await ждать(1100);
  await дай();
  ok("через отведённое время память протухает сама", считали === 3);
}

{
  положить("db:sales:все", [1], 5);
  положить("db:products:все", [2], 5);
  положить("catalog:товары", [3], 5);
  забыть("db:sales:");
  ok("забываем только свою таблицу", взять("db:sales:все") === undefined && взять("db:products:все") !== undefined);
  забыть("catalog");
  ok("каталог забывается отдельно", взять("catalog:товары") === undefined);
  забыть();
  ok("без приставки забываем всё", взять("db:products:все") === undefined);
}

{
  // ошибку не запоминаем: иначе на минуту застрянет отказ базы
  let попыток = 0;
  const дай = () => помнить("db:x:все", 60, async () => { попыток++; throw new Error("база недоступна"); });
  for (const _ of [1, 2]) { try { await дай(); } catch { } }
  ok("ошибка не запоминается — следующий запрос пробует снова", попыток === 2);
}

{
  забыть();
  for (let i = 0; i < 300; i++) положить("k" + i, i, 60);
  ok("память не растёт без предела: " + размерПамяти(), размерПамяти() <= 200);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nПАМЯТЬ СЕРВЕРА В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
