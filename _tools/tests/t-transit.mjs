// ========================================================================
//  ТОВАР В ДОРОГЕ.  node _tools/tests/t-transit.mjs
//
//  Владелец: «какие товары есть в дороге — показывать в товарах, есть в
//  наличии или нет, всё равно. Если в дороге цена дороже, чем сейчас, —
//  тоже показывать. А товар, которого нет в складе, но он едет, не должен
//  числиться там, где «нет в складе».»
//
//  Здесь проверяется счёт: сколько едет, от кого, дороже ли едущая партия
//  той, что продаётся сейчас.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { картаДороги, вДороге, дорожеСейчас, едетВместоНет, подписьДороги } =
  await import(new URL("js/transit.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const товар = (id, stock, цена, партии) => ({
  id, name: "Товар " + id, stock_qty: stock, cost_yuan: цена, cost_usd: цена * 0.14,
  batches: партии === undefined
    ? (stock > 0 ? [{ qty: stock, cost_yuan: цена, cost_usd: цена * 0.14, date: "2026-08-01" }] : [])
    : партии,
});
const приход = (status, supplier, items, currency = "yuan") => ({ id: "p" + supplier, status, supplier, currency, items });

// ---------- считаем только то, что ещё не пришло ----------
{
  const карта = картаДороги([
    приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 13 }]),
    приход("arrived", "KDP", [{ product_id: "1", qty: 500, unit_cost: 12 }]),
  ]);
  ok("оприходованный приход в дорогу не попадает", карта["1"].qty === 300);
  ok("поставщик запомнен", карта["1"].поставщики.join() === "JACK");
}

// ---------- несколько приходов складываются ----------
{
  const карта = картаДороги([
    приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 13 }]),
    приход("in_transit", "KDP", [{ product_id: "1", qty: 200, unit_cost: 11 }]),
    приход("in_transit", "JACK", [{ product_id: "1", qty: 100, unit_cost: 12 }]),
  ]);
  ok("количество сложилось", карта["1"].qty === 600);
  ok("поставщики без повторов", карта["1"].поставщики.join(", ") === "JACK, KDP");
  ok("цена берётся самая высокая", карта["1"].cost_yuan === 13);
}

// ---------- пустые и нулевые строки ----------
{
  const карта = картаДороги([
    приход("in_transit", "", [{ product_id: "", qty: 10, unit_cost: 5 }, { product_id: "2", qty: 0, unit_cost: 5 }]),
    null,
  ]);
  ok("строки без товара и с нулём пропущены", Object.keys(карта).length === 0);
}

// ---------- цена в другой валюте приводится к юаню ----------
{
  const карта = картаДороги([приход("in_transit", "США", [{ product_id: "1", qty: 10, unit_cost: 2, currency: "usd" }])]);
  ok("доллары пересчитаны в юани", карта["1"].cost_yuan > 10 && карта["1"].cost_usd === 2);
}

// ---------- едет дороже, чем продаём сейчас ----------
{
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 13 }])]);
  const p = товар("1", 900, 12.5);
  const д = дорожеСейчас(вДороге(карта, p), p);
  ok("дороже — видно", д && д.было.yuan === 12.5 && д.станет.yuan === 13 && д.разница === 0.5);
  ok("валюта сравнения — юань", д.валюта === "yuan");
  ok("процент посчитан", д.процент === 4);
}
{
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 12 }])]);
  const p = товар("1", 900, 12.5);
  ok("дешевле — не предупреждаем", дорожеСейчас(вДороге(карта, p), p) === null);
}
{
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 12.5 }])]);
  const p = товар("1", 900, 12.5);
  ok("та же цена — не предупреждаем", дорожеСейчас(вДороге(карта, p), p) === null);
}

// ---------- сравниваем с ТЕКУЩЕЙ партией, а не со средней ----------
{
  // продаётся дешёвая партия, следом дорогая; едет ещё дороже
  const p = товар("1", 100, 0, [
    { qty: 60, cost_yuan: 10, cost_usd: 1.4, date: "2026-07-01" },
    { qty: 40, cost_yuan: 14, cost_usd: 2, date: "2026-09-01" },
  ]);
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 50, unit_cost: 12 }])]);
  const д = дорожеСейчас(вДороге(карта, p), p);
  ok("сравнение с той партией, что продаётся сейчас", д && д.было.yuan === 10 && д.станет.yuan === 12);
}

// ---------- склад пуст: берём последнюю известную цену ----------
{
  const p = товар("1", 0, 9, []);
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 50, unit_cost: 11 }])]);
  const д = дорожеСейчас(вДороге(карта, p), p);
  ok("пустой склад — сравниваем с ценой карточки", д && д.было.yuan === 9 && д.станет.yuan === 11);
}
{
  const p = товар("1", 0, 0, []);
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 50, unit_cost: 11 }])]);
  ok("цены не было вовсе — не выдумываем предупреждение", дорожеСейчас(вДороге(карта, p), p) === null);
}

// ---------- «нет в складе», но едет ----------
{
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 13 }])]);
  ok("нет на складе и едет → это «в дороге»", едетВместоНет(карта, товар("1", 0, 12)) === true);
  ok("есть на складе и едет → не прячем остаток", едетВместоНет(карта, товар("1", 5, 12)) === false);
  ok("нет на складе и не едет → так и есть «нет»", едетВместоНет(карта, товар("9", 0, 12)) === false);
  ok("минус и едет → тоже «в дороге»", едетВместоНет(карта, товар("1", -20, 12)) === true);
}

// ---------- подпись ----------
{
  const карта = картаДороги([
    приход("in_transit", "JACK", [{ product_id: "1", qty: 300, unit_cost: 13 }]),
    приход("in_transit", "KDP", [{ product_id: "1", qty: 200, unit_cost: 11 }]),
  ]);
  ok("подпись читается", подписьДороги(карта["1"]) === "В дороге: 500 шт · JACK, KDP");
  ok("без записи подпись пустая", подписьДороги(null) === "");
}

// ---------- товар, который есть в наличии, тоже показывает дорогу ----------
{
  const карта = картаДороги([приход("in_transit", "JACK", [{ product_id: "1", qty: 40, unit_cost: 5 }])]);
  ok("есть в наличии — дорога всё равно видна", !!вДороге(карта, товар("1", 900, 5)));
}

// ---------- товар с ценой только в долларах ----------
{
  const p = { id: "1", name: "Только доллары", stock_qty: 10, cost_yuan: 0, cost_usd: 2,
    batches: [{ qty: 10, cost_yuan: 0, cost_usd: 2, date: "2026-08-01" }] };
  const карта = картаДороги([приход("in_transit", "США", [{ product_id: "1", qty: 5, unit_cost: 3, currency: "usd" }])]);
  const д = дорожеСейчас(вДороге(карта, p), p);
  ok("без юаней сравниваем по долларам", д && д.валюта === "usd" && д.было.usd === 2 && д.станет.usd === 3);
}

console.log(плохо ? "\n❌ ошибок: " + плохо : "\n✅ всё сошлось");
process.exit(плохо ? 1 : 0);
