// ========================================================================
//  ПОРЯДОК КОРОБОК В НАКЛАДНОЙ.   node _tools/tests/t-invoice-box-order.mjs
//
//  Владелец 23.11: «сначала всё из 1-й коробки, потом 2-я, потом 3-я»,
//  а гилдирак 960 штук по 120 в мешке — это мешки 1-8 (промежуток).
//  Проверяем разбор номера, порядок строк и подсчёт мест.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const К = await import(new URL("js/boxes.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// ---------------------------------------------------------------- разбор
{
  ok("одна коробка", К.видКоробки(" 2 ") === "2");
  ok("промежуток через дефис становится тире", К.видКоробки("4-11") === "4–11");
  ok("промежуток с пробелами и длинным тире", К.видКоробки("4 — 11") === "4–11");
  ok("через запятую", К.видКоробки("1 ,3") === "1, 3");
  ok("подпись буквами остаётся подписью", К.видКоробки("А-3") === "А-3" && К.разобратьКоробку("А-3").номера.length === 0);
  ok("перевёрнутый промежуток — подпись, а не 0 мест", К.разобратьКоробку("8-1").номера.length === 0);
  ok("«1-9999» — опечатка, не 9999 мешков", К.разобратьКоробку("1-9999").номера.length === 0);
  ok("ноль впереди убирается", К.видКоробки("02") === "2");
  ok("пусто — пусто", К.видКоробки("") === "" && К.видКоробки(null) === "" && К.видКоробки(undefined) === "");
  ok("число, а не строка", К.видКоробки(3) === "3");
}

// ---------------------------------------------------------------- порядок
{
  // Накладная владельца от 23.11 в сокращении: коробки вперемешку,
  // у двух позиций коробки нет.
  const позиции = [
    { name: "Бачок дазмол", box: "2" },
    { name: "Челнок ярим ой", box: "1" },
    { name: "Матор аверлок" },
    { name: "Лапка набор", box: "3" },
    { name: "Гел калиш", box: 2 },
    { name: "Гилдирак", box: "4-11" },
    { name: "Иглодержател", box: "1" },
    { name: "Верхняя", box: "верх" },
    { name: "Регулятор", box: "" },
  ];
  const имена = К.поКоробкам(позиции).map((п) => п.name);
  ok("сначала коробка 1, внутри — порядок ввода",
    имена[0] === "Челнок ярим ой" && имена[1] === "Иглодержател");
  ok("потом коробка 2", имена[2] === "Бачок дазмол" && имена[3] === "Гел калиш");
  ok("потом 3 и мешки 4–11", имена[4] === "Лапка набор" && имена[5] === "Гилдирак");
  ok("подписи буквами после чисел", имена[6] === "Верхняя");
  ok("без коробки — в конце, в порядке ввода", имена[7] === "Матор аверлок" && имена[8] === "Регулятор");
  ok("исходный список не тронут", позиции[0].name === "Бачок дазмол");
  ok("ничего не потерялось", имена.length === позиции.length);

  ok("та же коробка у «2» и 2", К.таЖеКоробка("2", 2));
  ok("«1» и «2» — разные", !К.таЖеКоробка("1", "2"));
  ok("пустые — одна группа", К.таЖеКоробка("", undefined));
}

// ---------------------------------------------------------------- места
{
  ok("1, 2, 3 и мешки 4–11 — 11 мест", К.местВсего([{ box: "1" }, { box: "1" }, { box: "2" }, { box: "3" }, { box: "4-11" }]) === 11);
  ok("пересечение не считается дважды", К.местВсего([{ box: "1-3" }, { box: "2" }]) === 3);
  ok("подписи считаются без учёта регистра", К.местВсего([{ box: "Верх" }, { box: "верх" }, { box: "1" }]) === 2);
  ok("без коробок — 0", К.местВсего([{}, { box: "" }]) === 0);
}

// ------------------------------------------------- PDF собирается целиком
{
  const { buildInvoicePDF } = await import(new URL("api/lib/pdf.js", корень));
  const products = [
    { id: "a", name: "Бачок дазмол" }, { id: "b", name: "Челнок ярим ой (Онг)" },
    { id: "c", name: "Гилдирак" }, { id: "d", name: "Матор аверлок" },
  ];
  const sale = {
    id: "1c67d0-test", date: "2026-11-23T10:00:00Z", currency: "som", boxes: 3,
    items: [
      { product_id: "a", qty: 2, unit_price: 40000, box: "2" },
      { product_id: "b", qty: 100, unit_price: 13500, box: "1" },
      { product_id: "d", qty: 60, unit_price: 85000 },
      { product_id: "c", qty: 960, unit_price: 9000, box: "4-11" },
    ],
  };
  const pdf = await buildInvoicePDF({ sale, customer: { name: "Тест" }, products, status: "partial" });
  ok("PDF с промежутком собирается", pdf && pdf.length > 1000);
}

console.log(плохо ? `\n${плохо} проверок не прошло` : "\nВсе проверки прошли");
process.exit(плохо ? 1 : 0);
