// ========================================================================
//  МАССОВАЯ НАСТРОЙКА УПАКОВОК.
//  node _tools/tests/t-packingbulk.mjs
//
//  Проверяется то, из-за чего массовая правка и бывает опасной:
//
//    • пустое поле не должно затирать чужую настройку;
//    • товар, у которого ничего не меняется, не должен записываться
//      вовсе — иначе у него без причины вырастет версия упаковки, по
//      которой приход объясняет, как он посчитан;
//    • смена складской единицы двигает ВЕСЬ остаток, и без отдельного
//      разрешения такой товар записываться не должен;
//    • если перевод всё же разрешён — товара и денег на складе обязано
//      остаться столько же.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const B = await import(new URL("js/packingbulk.js", корень));
const { настройки, статус } = await import(new URL("js/packing.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const почти = (a, b, т = 1e-6) => Math.abs(Number(a) - Number(b)) < т;

// Шпулька: настроена, берут штуками, лежит пачками по 10.
const шпулька = (доп = {}) => ({
  id: "ш1", name: "Шпулька", stock_qty: 30, cost_yuan: 20000, cost_usd: 2800,
  batches: [{ qty: 30, cost_yuan: 20000, cost_usd: 2800 }],
  unit: "пачка", pack_size: 10, buy_unit: "шт", sell_unit: "пачка",
  auto_convert: true, odd_rule: "keep", packing_ver: 1, ...доп,
});
// Лапка: упаковку никогда не настраивали — обычные штуки.
const лапка = (доп = {}) => ({
  id: "t9", name: "Лапка", stock_qty: 4800, cost_yuan: 0.75, cost_usd: 0.11,
  batches: [{ qty: 4800, cost_yuan: 0.75, cost_usd: 0.11 }], ...доп,
});

// ---------- пустое поле = «не менять» ----------
{
  // Владелец заполнил ТОЛЬКО автопересчёт. Всё остальное у каждого товара
  // обязано остаться своим.
  const план = B.планПравки([шпулька(), лапка()], { auto_convert: true });
  ok("у шпульки упаковка осталась своей", план[0].станет.вСкладской === 10 && план[0].станет.закуп === "шт");
  ok("у лапки упаковка тоже осталась своей", план[1].станет.склад === "шт" && план[1].станет.вСкладской === 1);
  ok("шпульке менять нечего — автопересчёт уже включён", план[0].меняется === false);
  ok("а лапке автопересчёт включается", план[1].меняется === true && план[1].станет.авто === true);
  ok("остаток при этом никто не двигает", план.every(x => x.двигает === false));
}
{
  const план = B.планПравки([шпулька()], { odd_rule: "ask" });
  ok("правило остатка поменялось", план[0].станет.правило === "ask");
  ok("и это единственное изменение", план[0].различия.length === 1);
  ok("остаток правило не двигает", план[0].двигает === false);
}
{
  const план = B.планПравки([шпулька()], { buy_unit: "коробка", box_size: 20 });
  ok("единица закупки и коробка меняются", план[0].станет.закуп === "коробка" && план[0].станет.вКоробке === 20);
  ok("остаток от этого не двигается", план[0].двигает === false);
  ok("складская единица осталась прежней", план[0].станет.склад === "пачка" && план[0].станет.вСкладской === 10);
}

// ---------- товары без изменений не записываются ----------
{
  const план = B.планПравки([шпулька(), шпулька({ id: "ш2" })], { auto_convert: true });
  ok("менять нечего", B.сводка(план).меняется === 0);
  ok("И НИЧЕГО НЕ ЗАПИСЫВАЕТСЯ", B.строкиДляЗаписи(план).length === 0);
  // Это и есть защита версии: версия растёт только при настоящей правке.
  ok("версия упаковки не поднимается без причины", план[0].поля.packing_ver === 2 && !план[0].меняется);
}
{
  // «Отметить настроенной» — для товаров, у которых и так всё верно.
  const план = B.планПравки([шпулька(), лапка()], { подтвердить: true });
  ok("у настроенной шпульки подтверждать нечего", план[0].меняется === false);
  ok("ненастроенная лапка отмечается настроенной", план[1].меняется === true && план[1].толькоПодтверждение === true);
  const строки = B.строкиДляЗаписи(план);
  ok("записывается только лапка", строки.length === 1 && строки[0].id === "t9");
  ok("и становится «Настроено»", статус({ ...лапка(), ...строки[0] }).код === "set");
  ok("остаток лапки при этом не трогается", строки[0].stock_qty === undefined);
}

// ---------- смена складской единицы: без разрешения не пишем ----------
{
  // Настоящий случай: 4800 штук по ¥0,75 переводят в пачки по 12.
  const план = B.планПравки([лапка()], { unit: "пачка", pack_size: 12 });
  const x = план[0];
  ok("система видит, что это двигает остаток", x.двигает === true);
  ok("БЕЗ РАЗРЕШЕНИЯ НЕ ЗАПИСЫВАЕТСЯ", B.строкиДляЗаписи(план).length === 0);
  ok("в сводке такой товар посчитан отдельно", B.сводка(план).переводовСОстатком === 1);
  ok("4800 штук станут 400 пачками", почти(x.перевод.stock_qty, 400));
  ok("а цена пачки — ¥9", почти(x.перевод.cost_yuan, 9));
  ok("объяснение показывает и количество, и цену",
    B.объяснитьПеревод(x).includes("4800 шт → 400 пачек") && B.объяснитьПеревод(x).includes("¥0.75 → ¥9"));
}
{
  const план = B.планПравки([лапка()], { unit: "пачка", pack_size: 12 });
  const строки = B.строкиДляЗаписи(план, { переводить: true });
  ok("с разрешением записывается", строки.length === 1);
  ok("остаток пересчитан", почти(строки[0].stock_qty, 400));
  ok("ДЕНЕГ НА СКЛАДЕ СТОЛЬКО ЖЕ", почти(строки[0].stock_qty * строки[0].cost_yuan, 4800 * 0.75));
  ok("и партии пересчитаны тоже",
    строки[0].batches.length === 1 && почти(строки[0].batches[0].qty, 400) && почти(строки[0].batches[0].cost_yuan, 9));
  ok("упаковка записана", строки[0].unit === "пачка" && строки[0].pack_size === 12);
}
{
  // Остаток не делится нацело — об этом надо сказать прямо.
  const план = B.планПравки([лапка({ stock_qty: 4805, batches: [{ qty: 4805, cost_yuan: 0.75, cost_usd: 0.11 }] })],
    { unit: "пачка", pack_size: 12 });
  ok("дробный перевод помечен", план[0].перевод.делитсяРовно === false);
  ok("и посчитан в сводке", B.сводка(план).дробных === 1);
  ok("в объяснении про это сказано", B.объяснитьПеревод(план[0]).includes("не делится нацело"));
}
{
  // У пустого склада переводить нечего, но настройку записать надо.
  const план = B.планПравки([лапка({ stock_qty: 0, batches: [] })], { unit: "пачка", pack_size: 12 });
  ok("перевод всё равно считается движением меры", план[0].двигает === true);
  ok("но остатка нет, и в сводке это видно", B.сводка(план).переводовСОстатком === 0);
  const строки = B.строкиДляЗаписи(план, { переводить: true });
  ok("с разрешением записывается и пустой склад", строки.length === 1 && строки[0].stock_qty === 0);
}

// ---------- противоречия видны до записи ----------
{
  // Складская единица «пачка», а сколько штук внутри — не сказано.
  const план = B.планПравки([лапка()], { unit: "пачка" });
  ok("пачка без размера остаётся пачкой по одной штуке", план[0].станет.вСкладской === 1);
  ok("и это требует проверки", план[0].статус.код === "check");
  ok("сводка про это предупреждает", B.сводка(план).требуютПроверки === 1);
}
{
  const план = B.планПравки([лапка()], { buy_unit: "коробка", auto_convert: true });
  ok("закупка коробками без размера коробки — требует проверки", план[0].статус.код === "check");
  ok("и автопересчёт у такого товара не применится",
    план[0].статус.причины.some(т => т.includes("Автопреобразование")));
}

// ---------- включение автопересчёта считается отдельно ----------
{
  const план = B.планПравки([шпулька({ auto_convert: false }), лапка()], { auto_convert: true });
  ok("автопересчёт включается у двух товаров", B.сводка(план).включитсяАвто === 2);
}

// ---------- однофамильцы: показываем, но НЕ объединяем ----------
{
  const товары = [
    { id: "a", name: "Нож-70" }, { id: "b", name: "нож-70 " }, { id: "c", name: "Шпулька" },
  ];
  const двойные = B.однофамильцы(товары);
  ok("одинаковое название замечено", двойные.get("нож-70") === 2);
  ok("уникальное название не помечено", !двойные.has("шпулька"));
  const план = B.планПравки(товары, { auto_convert: true });
  ok("и товары остались РАЗНЫМИ — ничего не объединилось", план.length === 3);
  ok("у каждого свой номер", new Set(план.map(x => x.p.id)).size === 3);
}

// ---------- план ничего не меняет на месте ----------
{
  const т = шпулька();
  const снимок = JSON.stringify(т);
  B.планПравки([т], { unit: "шт", auto_convert: false, odd_rule: "ask" });
  ok("ПЛАН НЕ ТРОГАЕТ ТОВАР — только считает", JSON.stringify(т) === снимок);
}

console.log("");
console.log(плохо ? плохо + " ОШИБОК" : "МАССОВАЯ НАСТРОЙКА УПАКОВОК БЕЗОПАСНА");
process.exit(плохо ? 1 : 0);
