// ========================================================================
//  АГЕНТ БЕЗОПАСНОСТИ.   node _tools/tests/t-agents-security.mjs
//
//  ЭТОТ ТЕСТ — УСЛОВИЕ ВЫХОДА ЭТАПА. Агент безопасности читает
//  переменные окружения и ответы Telegram, то есть держит в руках все
//  секреты сразу. Если он однажды вынесет хоть один в отчёт, тот
//  осядет в базе и уйдёт сообщением в Telegram.
//
//  Поэтому проверяем не «правильно ли он считает», а в первую очередь
//  «что он выносит наружу»: ни одно значение секрета не должно попасть
//  ни в сводку, ни в детали, ни в уведомление.
// ========================================================================
const корень = new URL("../../", import.meta.url);

// Поддельные, но правдоподобные секреты: если хоть один всплывёт в
// отчёте, тест это поймает по точному совпадению.
const СЕКРЕТЫ = {
  SITE_JWT_SECRET: "oчень-длинный-секрет-подписи-9f3a2b7c4d5e6f70",
  TELEGRAM_WEBHOOK_SECRET: "webhook-secret-a1b2c3d4e5f60718293a4b5c",
  SUPABASE_SERVICE_KEY: "eyJhbGciOiJIUzI1NiJ9.eyJyb2xlIjoic2VydmljZV9yb2xlIn0.подпись-ключа-1234567890",
  TELEGRAM_BOT_TOKEN: "7654321098:AAFakeBotTokenForTestsOnly1234567890",
  ADMIN_PASSWORD: "СуперПароль2026!",
  ADMIN_CHAT_ID: "837138321",
  CLIENT_BOT_TOKEN: "1234567890:AAFakeClientBotToken0987654321abcdef",
  PUBLIC_URL: "https://generalmodern.uz",
};
Object.assign(process.env, СЕКРЕТЫ);
process.env.SUPABASE_URL = "http://db.test";

const S = await import(new URL("api/lib/agents/security.js", корень));
const Ч = await import(new URL("api/lib/agents/чисто.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const СУТКИ = 86400e3;
const СЕЙЧАС = Date.parse("2026-11-23T06:00:00Z");
const назад = (д) => new Date(СЕЙЧАС - д * СУТКИ).toISOString();

// Ищем значения секретов в любом виде — в строках, в числах, в ключах.
function утечки(что) {
  const текст = JSON.stringify(что);
  return Object.entries(СЕКРЕТЫ)
    .filter(([имя, значение]) => значение.length >= 8 && текст.includes(значение))
    .map(([имя]) => имя);
}

// ======================================================================
//  1. ДОСТУПЫ: выводы без значений
// ======================================================================
{
  const р = S.проверитьДоступы(process.env, false);
  ok("при заданных ключах претензий к ним нет",
    !р.находки.some((н) => н.компонент === "SITE_JWT_SECRET"));
  ok("двухфакторная распознана как включённая", р.двеФазы === true);
  // Про ключ наружу уходят ровно три поля — и значения среди них нет.
  const поля = new Set(р.ключи.flatMap((к) => Object.keys(к)));
  ok("о ключе сообщается только имя, факт и длина",
    поля.size === 3 && поля.has("имя") && поля.has("задан") && поля.has("длина"));

  const найдено = утечки(р);
  if (найдено.length) console.log("   утекло:", найдено.join(", "));
  ok("ЗНАЧЕНИЙ КЛЮЧЕЙ В ОТВЕТЕ НЕТ", найдено.length === 0);
}

{
  // Выключенная двухфакторная — это находка, и серьёзная.
  const env = { ...process.env, ADMIN_2FA: "off" };
  const р = S.проверитьДоступы(env, false);
  const н = р.находки.find((x) => x.тип === "вход без кода");
  ok("ADMIN_2FA=off замечен", !!н && н.уровень >= 80);
  ok("у находки есть компонент, последствия и решение",
    !!н.компонент && !!н.последствия && !!н.решение && !!н.когда);
  ok("в находке нет значений секретов", утечки(р).length === 0);
}

{
  // Пустой ключ подписи — самое опасное.
  const env = { ...process.env };
  delete env.SITE_JWT_SECRET;
  const старый = process.env.SITE_JWT_SECRET;
  delete process.env.SITE_JWT_SECRET;
  const р = S.проверитьДоступы(env, false);
  process.env.SITE_JWT_SECRET = старый;
  const н = р.находки.find((x) => x.компонент === "SITE_JWT_SECRET");
  ok("отсутствие ключа подписи — находка высшего уровня", !!н && н.уровень >= 90);
}

{
  // Слабый ключ.
  const старый = process.env.TELEGRAM_WEBHOOK_SECRET;
  process.env.TELEGRAM_WEBHOOK_SECRET = "secret123";
  const р = S.проверитьДоступы({ ...process.env, TELEGRAM_WEBHOOK_SECRET: "secret123" }, false);
  process.env.TELEGRAM_WEBHOOK_SECRET = старый;
  const н = р.находки.find((x) => x.тип === "слабый ключ");
  ok("короткий ключ помечен слабым", !!н);
  ok("само слабое значение в отчёт не попало", !JSON.stringify(р).includes("secret123"));
}

{
  // Пароль и в .env, и в файле — смена пароля не подействует.
  const р = S.проверитьДоступы(process.env, true);
  const н = р.находки.find((x) => x.компонент === "ADMIN_PASSWORD");
  ok("лишний пароль в окружении замечен", !!н);
  ok("сам пароль в отчёт не попал", !JSON.stringify(р).includes(СЕКРЕТЫ.ADMIN_PASSWORD));
}

// ======================================================================
//  2. ЖУРНАЛ ВХОДОВ
// ======================================================================
{
  const события = [
    ...Array.from({ length: 6 }, () => ({ kind: "login_fail", ip_hash: "aaaabbbbccccdddd", created_at: назад(1) })),
    { kind: "login_fail", ip_hash: "другой-хэш", created_at: назад(1) },
    { kind: "login_ok", ip_hash: "aaaabbbbccccdddd", created_at: назад(1) },
    { kind: "site_visit", risk: 85, created_at: назад(2) },
    { kind: "site_visit", risk: 10, created_at: назад(2) },
    { kind: "login_ok", flags: { impersonation: true }, created_at: назад(3) },
    // старое — за окном
    ...Array.from({ length: 9 }, () => ({ kind: "login_fail", ip_hash: "aaaabbbbccccdddd", created_at: назад(40) })),
  ];
  const р = S.разобратьСобытия(события, { сейчас: СЕЙЧАС });

  ok("подбор пароля найден", р.находки.some((н) => н.тип === "подбор пароля"));
  ok("одиночная неудача подбором не считается",
    р.находки.filter((н) => н.тип === "подбор пароля").length === 1);
  ok("старые события за окно не берутся", р.неудачныхВходов === 7);
  ok("рискованные события посчитаны", р.рискованных === 1);
  ok("вход под клиентом замечен", р.находки.some((н) => н.тип === "вход под клиентом"));
  ok("подтверждённое и подозрительное разделены",
    р.подтверждено === 1 && р.подозрительно === 2);
  ok("в отчёте по журналу нет секретов", утечки(р).length === 0);

  const пусто = S.разобратьСобытия([], { сейчас: СЕЙЧАС });
  ok("на пустом журнале ничего не падает", пусто.находки.length === 0 && пусто.всего === 0);
}

// ======================================================================
//  3. СЕРТИФИКАТ: без сети — честный отказ, а не выдуманная дата
// ======================================================================
{
  const л = await S.проверитьСертификат("http://localhost:3000");
  ok("локальный адрес: сертификата нет и мы это говорим",
    л.проверен === false && /локальн/.test(л.причина));

  const п = await S.проверитьСертификат("");
  ok("без адреса сайта — честная причина", п.проверен === false && /PUBLIC_URL/.test(п.причина));

  const н = await S.проверитьСертификат("https://не-существует-такого-домена-12345.uz", { таймаут: 4000 });
  ok("недоступный домен не даёт выдуманной даты",
    н.проверен === false && !("осталосьДней" in н));
}

// ======================================================================
//  4. ВЕБХУК
// ======================================================================
{
  const без = await S.проверитьВебхук("", "https://generalmodern.uz");
  ok("без токена — честный отказ", без.проверен === false);
}

{
  // Подменяем сеть: Telegram отвечает чужим адресом вебхука.
  const настоящий = globalThis.fetch;
  globalThis.fetch = async () => ({
    json: async () => ({ ok: true, result: { url: "https://злой-сервер.example/api/bot", pending_update_count: 120, last_error_message: "Wrong response from the webhook" } }),
  });
  const р = await S.проверитьВебхук(СЕКРЕТЫ.TELEGRAM_BOT_TOKEN, "https://generalmodern.uz");
  globalThis.fetch = настоящий;

  ok("чужой адрес вебхука — высший уровень",
    р.находки.some((н) => н.тип === "чужой адрес вебхука" && н.уровень >= 90));
  ok("завал обновлений замечен", р.находки.some((н) => н.тип === "завал обновлений"));
  ok("ошибка вебхука замечена", р.находки.some((н) => н.тип === "ошибка вебхука"));
  ok("ТОКЕН БОТА В ОТЧЁТ НЕ ПОПАЛ", утечки(р).length === 0);
}

// ======================================================================
//  5. КОПИИ
// ======================================================================
{
  const р = await S.проверитьКопии("");
  ok("без настроенной папки копий — честная причина",
    р.проверен === false && /config\.копии/.test(р.причина));

  const нет = await S.проверитьКопии("C:/такой/папки/нет/совсем");
  ok("нечитаемая папка не выдаёт ложного «всё хорошо»", нет.проверен === false);
}

// ======================================================================
//  6. ГЛАВНОЕ: ПОЛНЫЙ ПРОГОН НИЧЕГО НЕ ВЫНОСИТ
// ======================================================================
{
  const уведомления = [];
  const ctx = {
    agentId: "security", config: {},
    читать: async () => ([
      ...Array.from({ length: 7 }, () => ({ kind: "login_fail", ip_hash: "ffffeeeeddddcccc", created_at: назад(1) })),
      { kind: "site_visit", risk: 90, created_at: назад(1) },
    ]),
    уведомить: async (у) => { уведомления.push(у); return у; },
    согласовать: async (с) => с,
  };

  // Сеть глушим: Telegram в тесте не дёргаем.
  const настоящий = globalThis.fetch;
  globalThis.fetch = async () => { throw new Error("сеть в тесте отключена"); };
  const итог = await S.прогон(ctx);
  globalThis.fetch = настоящий;

  ok("прогон даёт сводку", typeof итог.сводка === "string" && итог.сводка.length > 0);
  ok("находки отсортированы по уровню риска",
    итог.детали.находки.every((н, i, a) => i === 0 || a[i - 1].уровень >= н.уровень));
  ok("агент честно перечисляет, чего не проверял",
    итог.детали.неПроверено.length >= 2 && итог.детали.неПроверено.some((с) => /npm audit|Dependabot/.test(с)));

  const найдено = утечки(итог);
  if (найдено.length) console.log("   УТЕКЛО:", найдено.join(", "));
  ok("В ПОЛНОМ ОТЧЁТЕ НЕТ НИ ОДНОГО СЕКРЕТА", найдено.length === 0);

  const вУведомлениях = утечки(уведомления);
  if (вУведомлениях.length) console.log("   УТЕКЛО В УВЕДОМЛЕНИЯХ:", вУведомлениях.join(", "));
  ok("В УВЕДОМЛЕНИЯХ НЕТ НИ ОДНОГО СЕКРЕТА", вУведомлениях.length === 0);

  // Вторая линия обороны: даже если агент ошибётся, ядро вычистит.
  const черезЯдро = Ч.безопасныйОбъект(итог);
  ok("ядро дочищает отчёт", утечки(черезЯдро).length === 0);

  // И контрольный выстрел: нарочно испорченный отчёт ядро чистит.
  const грязный = Ч.безопасныйОбъект({ beda: "ключ " + СЕКРЕТЫ.SUPABASE_SERVICE_KEY + " утёк" });
  ok("нарочно вставленный ключ ядро вычищает", утечки(грязный).length === 0);
}

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
