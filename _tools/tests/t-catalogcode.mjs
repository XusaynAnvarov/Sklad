// ========================================================================
//  ПОСТОЯННЫЕ КОДЫ ТОВАРОВ.  node _tools/tests/t-catalogcode.mjs
//
//  Код печатается в каталоге, каталог живёт у клиента месяцами. Поэтому:
//  коды не повторяются, не меняются и не переезжают на другой товар.
// ========================================================================
const {
  БУКВЫ, раздел, буквыРаздела, разобратьКод, компактныйКод, следующийКод, раздатьКоды, латиницей,
  естьКолонкаКода, привестиКод, кодДляНового, следующийПосле, кодПриСохранении,
} = await import(new URL("../../js/catalogcode.js", import.meta.url));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// ---------- таблица букв ----------
{
  // Разделы, которые есть на боевом складе (сентябрь 2026).
  const РАЗДЕЛЫ = ["Лапки", "Приборы для машин", "Улитки", "Ножы", "Нинала", "Аппараты", "Утюги",
    "Пластина", "Чельнок", "Крышки", "Ремень", "Петлител", "Регулятор", "Иглодержател", "Калиш",
    "Светилник", "Насатки", "Мокки", "Бабина стойки", "Тиш", "Тень", "Магниты", "Диск", "Шпулка",
    "Метры", "Шестеренки", "Пинцеты", "Болть", "Без категории"];
  ok("у всех 29 разделов есть буквы", РАЗДЕЛЫ.every(r => /^[A-Z]{2}$/.test(БУКВЫ[r] || "")));
  const буквы = РАЗДЕЛЫ.map(r => БУКВЫ[r]);
  ok("буквы не повторяются", new Set(буквы).size === буквы.length);
  ok("лапки — LP, ножи — NJ, улитки — UL", БУКВЫ["Лапки"] === "LP" && БУКВЫ["Ножы"] === "NJ" && БУКВЫ["Улитки"] === "UL");
  ok("таблица защищена от случайной правки", Object.isFrozen(БУКВЫ));
}

// ---------- раздел и новый раздел ----------
{
  ok("пустая категория — «Без категории»", раздел("") === "Без категории" && раздел(null) === "Без категории");
  ok("пробелы по краям не создают новый раздел", буквыРаздела("  Лапки ", { ...БУКВЫ }) === "LP");
  ok("регистр не создаёт новый раздел", буквыРаздела("лапки", { ...БУКВЫ }) === "LP");

  const т = { ...БУКВЫ };
  const новые = буквыРаздела("Лента кант", т);
  ok("новый раздел получает латинские буквы: " + новые, /^[A-Z]{2}$/.test(новые));
  ok("и они не совпадают с занятыми", !Object.values(БУКВЫ).includes(новые));
  ok("и запоминаются в таблице", т["Лента кант"] === новые && буквыРаздела("Лента кант", т) === новые);

  // Раздел, чьи очевидные буквы уже заняты: «Лампы» → LA? LM? — только не LP.
  const т2 = { ...БУКВЫ };
  const лп = буквыРаздела("Лп", т2);
  ok("занятые буквы новому разделу не достаются: " + лп, лп !== "LP" && /^[A-Z]{2}$/.test(лп));
  ok("узбекские буквы переводятся", латиницей("Қайчи ўткир") === "QAYCI OTKIR");
}

// ---------- разбор кода ----------
{
  ok("LP-017 разбирается", JSON.stringify(разобратьКод("LP-017")) === JSON.stringify({ буквы: "LP", номер: 17 }));
  ok("четырёхзначный номер тоже", разобратьКод("LP-1024").номер === 1024);
  ok("чужой формат — null", разобратьКод("KDP-10") === null && разобратьКод("LP17") === null && разобратьКод("") === null);
  ok("как пишут клиенты: lp17, LP 017, lp-0017 — одно и то же",
     ["lp17", "LP 017", "lp-0017", "LP-017", "Lp_17"].every(s => компактныйКод(s) === "LP17"));
  ok("не код — пусто", компактныйКод("Лапка бека") === "" && компактныйКод("17") === "");
}

// ---------- следующий номер ----------
{
  ok("первый код раздела — 001", следующийКод("LP", []) === "LP-001");
  ok("следующий после наибольшего", следующийКод("LP", ["LP-001", "LP-007", "NJ-099"]) === "LP-008");
  // Номер, однажды напечатанный в каталоге, не должен достаться другому товару.
  ok("дыры после удалённых не занимаем", следующийКод("LP", ["LP-001", "LP-005"]) === "LP-006");
  ok("после 999 — четыре цифры", следующийКод("LP", ["LP-999"]) === "LP-1000");
}

// ---------- раздача ----------
{
  const товары = [
    { id: "a", name: "Лапка бека (6-4)", category: "Лапки", created_at: "2026-06-06T10:00:02Z" },
    { id: "b", name: "Лапка бека (5-6)", category: "Лапки", created_at: "2026-06-06T10:00:01Z" },
    { id: "c", name: "Кайчи (10) KDP", category: "Ножы", created_at: "2026-06-06T10:00:00Z" },
    { id: "d", name: "Старый нож", category: "Ножы", code: "NJ-004", created_at: "2026-06-01T00:00:00Z" },
    { id: "e", name: "Без раздела", category: "", created_at: "2026-06-06T10:00:03Z" },
  ];
  const { выдать } = раздатьКоды(товары);
  const код = Object.fromEntries(выдать.map(x => [x.id, x.code]));

  ok("код получают только те, у кого его нет", выдать.length === 4 && !код.d);
  ok("старый товар получает меньший номер: b → LP-001, a → LP-002", код.b === "LP-001" && код.a === "LP-002");
  ok("номер продолжает уже выданные: c → NJ-005 после NJ-004", код.c === "NJ-005");
  ok("товар без раздела — XX-001", код.e === "XX-001");
  ok("все выданные коды разные", new Set(выдать.map(x => x.code)).size === выдать.length);

  // Товар перенесли в другой раздел — код остаётся прежним.
  const перенесли = товары.map(p => (p.id === "d" ? { ...p, category: "Лапки" } : p));
  ok("выданный код не меняется при переносе в другой раздел",
     !раздатьКоды(перенесли).выдать.some(x => x.id === "d"));

  // Повторная раздача после записи ничего не выдаёт.
  const записали = товары.map(p => ({ ...p, code: p.code || код[p.id] }));
  ok("повторная раздача ничего не меняет", раздатьКоды(записали).выдать.length === 0);

  // Новый товар встаёт в конец своего раздела.
  const сНовым = [...записали, { id: "f", name: "Новая лапка", category: "Лапки", created_at: "2026-09-14T00:00:00Z" }];
  const новый = раздатьКоды(сНовым).выдать;
  ok("новый товар — следующий номер раздела: " + (новый[0] && новый[0].code), новый.length === 1 && новый[0].code === "LP-003");

  ok("исходная таблица букв не портится", !("Лента кант" in БУКВЫ));
  ok("пустой список — пусто", раздатьКоды([]).выдать.length === 0 && раздатьКоды(null).выдать.length === 0);
}

// ---------- объём боевого склада ----------
{
  // 931 товар в 29 разделах — раздача должна быть мгновенной.
  const много = [];
  const разделы = Object.keys(БУКВЫ);
  for (let i = 0; i < 931; i++) много.push({ id: "p" + i, name: "Товар " + i, category: разделы[i % 29], created_at: new Date(1e12 + i).toISOString() });
  const t0 = Date.now();
  const { выдать } = раздатьКоды(много);
  const мс = Date.now() - t0;
  ok("931 товар раздаётся за " + мс + " мс", выдать.length === 931 && мс < 500);
  ok("и без единого повтора", new Set(выдать.map(x => x.code)).size === 931);
}

// ---------- код при сохранении товара ----------
{
  const склад = [
    { id: "a", name: "Лапка бека", category: "Лапки", code: "LP-001" },
    { id: "b", name: "Лапка кант", category: "Лапки", code: "LP-002" },
    { id: "c", name: "Лента кант", category: "Ленты", code: "LK-001" },   // раздел заведён раздачей
    { id: "d", name: "Кайчи", category: "Ножы", code: null },
  ];

  // До миграции колонки code нет — писать её нельзя, иначе база отвергнет товар.
  ok("колонка кода видна по списку товаров", естьКолонкаКода(склад) === true);
  ok("до миграции её нет", естьКолонкаКода([{ id: "x", name: "т" }]) === false);

  ok("lp17 приводится к LP-017", привестиКод("lp17") === "LP-017" && привестиКод("LP 0017") === "LP-017");
  ok("не код — пусто", привестиКод("Лапка") === "");
  ok("следующий после LP-017 — LP-018", следующийПосле("LP-017") === "LP-018");

  // новый товар
  const новый = кодПриСохранении({ товар: {}, вписано: "", категория: "Лапки", товары: склад });
  ok("новый товар получает следующий код раздела: " + новый.code, новый.code === "LP-003");
  const новыйНовыйРаздел = кодПриСохранении({ товар: {}, вписано: "", категория: "Ленты", товары: склад });
  ok("раздел, заведённый раздачей, берёт свои буквы: " + новыйНовыйРаздел.code, новыйНовыйРаздел.code === "LK-002");

  // вписанный руками
  ok("вписанный код принимается и приводится", кодПриСохранении({ товар: { id: "d" }, вписано: "nj 5", категория: "Ножы", товары: склад }).code === "NJ-005");
  const занят = кодПриСохранении({ товар: { id: "d" }, вписано: "lp-1", категория: "Ножы", товары: склад });
  ok("чужой код не даётся: " + занят.ошибка, !!занят.ошибка && занят.ошибка.includes("Лапка бека"));
  ok("свой же код оставить можно", кодПриСохранении({ товар: { id: "a", code: "LP-001" }, вписано: "LP-001", категория: "Лапки", товары: склад }).code === "LP-001");
  ok("кривой код — понятная ошибка", кодПриСохранении({ товар: { id: "d" }, вписано: "XYZ", категория: "Ножы", товары: склад }).ошибка === "Код должен быть вида LP-017");

  // поле очистили — код не стирается: он мог уже уйти в каталог
  ok("очищенное поле не стирает код", кодПриСохранении({ товар: { id: "a", code: "LP-001" }, вписано: "", категория: "Лапки", товары: склад }).code === "LP-001");

  // старый товар без кода: коды уже розданы — получает следующий
  ok("старый товар без кода после раздачи — получает код", кодПриСохранении({ товар: { id: "d" }, вписано: "", категория: "Ножы", товары: склад }).code === "NJ-001");

  // до раздачи старому товару номер не выдаём: порядок задаст общая раздача
  const доРаздачи = [{ id: "a", name: "т", category: "Лапки", code: null }, { id: "b", name: "т2", category: "Лапки", code: null }];
  ok("до раздачи старый товар ждёт общей раздачи", кодПриСохранении({ товар: { id: "a" }, вписано: "", категория: "Лапки", товары: доРаздачи }).code === null);
  ok("а новый даже до раздачи получает код", кодПриСохранении({ товар: { id: "z" }, вписано: "", категория: "Лапки", товары: доРаздачи }).code === "LP-001");
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nКОДЫ НЕ ПОВТОРЯЮТСЯ И НЕ МЕНЯЮТСЯ");
process.exit(плохо ? 1 : 0);
