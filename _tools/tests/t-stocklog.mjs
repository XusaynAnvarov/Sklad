// ========================================================================
//  ЖУРНАЛ ИЗМЕНЕНИЙ ОСТАТКОВ.  node _tools/tests/t-stocklog.mjs
//
//  Склад хранил только нынешний остаток, поэтому на вопрос «откуда взялись
//  эти 300 штук» ответить было нечем. Журнал пишет сервер при каждой
//  записи остатка — и не мешает работать, даже если таблицы ещё нет.
// ========================================================================
process.env.SUPABASE_URL = "http://база";
process.env.SUPABASE_SERVICE_KEY = "тест";

const корень = new URL("../../", import.meta.url);

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// подставная база: помним, что записали в журнал
function база({ таблицаЕсть = true } = {}) {
  const журнал = [];
  const запросы = [];
  globalThis.fetch = async (url, opt = {}) => {
    const u = String(url);
    запросы.push(u);
    if (u.includes("/stock_log")) {
      if (!таблицаЕсть) return { ok: false, status: 404, text: async () => JSON.stringify({ code: "PGRST205", message: "Could not find the table 'public.stock_log' in the schema cache" }) };
      журнал.push(...JSON.parse(opt.body));
      return { ok: true, status: 201, text: async () => "" };
    }
    // products?id=in.(...) — остатки «до»
    return { ok: true, status: 200, json: async () => [
      { id: "t1", name: "Лапка", stock_qty: 10 },
      { id: "t2", name: "Нож", stock_qty: 5 },
    ], text: async () => "[]" };
  };
  return { журнал, запросы };
}

// ---------- обычная запись ----------
{
  const { журнал } = база();
  const { остаткиДо, записать } = await import(new URL("api/lib/stocklog.js", корень) + "?1");
  const было = await остаткиДо(["t1", "t2"]);
  ok("остатки «до» прочитаны", было.t1.stock_qty === 10 && было.t2.stock_qty === 5);

  await записать([{ id: "t1", stock_qty: 12 }, { id: "t2", stock_qty: 5 }], было, { причина: "Приход: JACK", документ: "пр-1", кто: "admin" });
  ok("записана только та строка, где остаток изменился", журнал.length === 1);
  const з = журнал[0];
  ok("было → стало и разница", з.before_qty === 10 && з.after_qty === 12 && з.diff === 2);
  ok("причина, документ и кто сохранены", з.reason === "Приход: JACK" && з.doc === "пр-1" && з.who === "admin");
  ok("название товара записано", з.name === "Лапка");
}

// ---------- списание и товар без остатка в строке ----------
{
  const { журнал } = база();
  const { остаткиДо, записать } = await import(new URL("api/lib/stocklog.js", корень) + "?2");
  const было = await остаткиДо(["t1"]);
  await записать([{ id: "t1", stock_qty: 3 }, { id: "t2", name: "Нож", price_som: 100 }], было, { причина: "Накладная: Комил Ака" });
  ok("правка цены без остатка в журнал не попадает", журнал.length === 1 && журнал[0].after_qty === 3);
  ok("уход в минус отмечен отрицательной разницей", журнал[0].diff === -7);
}

// ---------- таблицы ещё нет ----------
{
  const { журнал } = база({ таблицаЕсть: false });
  const { остаткиДо, записать, журналВедётся } = await import(new URL("api/lib/stocklog.js", корень) + "?3");
  const было = await остаткиДо(["t1"]);
  const n = await записать([{ id: "t1", stock_qty: 99 }], было, { причина: "Правка" });
  ok("без таблицы ничего не пишем и не падаем", n === 0 && журнал.length === 0);
  ok("и больше не пробуем — склад не тормозит", журналВедётся() === false);
}

// ---------- чужие номера товаров не пускаем в запрос ----------
{
  const { запросы } = база();
  const { остаткиДо } = await import(new URL("api/lib/stocklog.js", корень) + "?4");
  await остаткиДо(["хороший-id", "плохой id\" or 1=1"]);
  ok("в запрос уходят только безопасные номера", запросы.every(u => !u.includes("or 1=1")));
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nЖУРНАЛ ОСТАТКОВ В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
