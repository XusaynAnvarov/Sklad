// ========================================================================
//  КОД ИЗ БУФЕРА.  node _tools/tests/t-kodizbufera.mjs
//
//  Владелец: «когда приходит код из бота — чтобы сразу вставлялось».
//  Страница читать Telegram не может, поэтому код в боте сделан
//  нажимаемым (одно касание копирует), а сайт при возвращении на вкладку
//  сам заглядывает в буфер.
//
//  Главная опасность здесь — подставить НЕ ТО. В буфере может лежать
//  номер телефона, сумма из накладной, ссылка. Вставлять нужно только
//  то, что действительно похоже на код: ровно шесть цифр и ничего
//  лишнего. Это и проверяется.
// ========================================================================

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const корень = new URL("../../", import.meta.url);
const { кодИзТекста, следитьЗаБуфером } = await import(new URL("js/kodizbufera.js", корень));

// ---------- 1. Что считаем кодом ----------
{
  ok("голые шесть цифр", кодИзТекста("481294", 6) === "481294");
  ok("код среди слов", кодИзТекста("Ваш код: 481294", 6) === "481294");
  ok("код с переносами из сообщения бота",
     кодИзТекста("🔐 Код для входа\n\n481294\n\nДействует 5 минут", 6) === "481294");
  ok("разорванные цифры кодом не считаем", кодИзТекста("48 12 94", 6) === "");
  ok("ведущие нули не теряются", кодИзТекста("000123", 6) === "000123");
}

// ---------- 2. Что кодом НЕ считаем ----------
{
  ok("номер телефона не берём", кодИзТекста("+998 90 111 22 33", 6) === "");
  ok("сумму из накладной не берём", кодИзТекста("841 772 сум", 6) === "");
  ok("пять цифр мало", кодИзТекста("48129", 6) === "");
  ok("семь цифр много", кодИзТекста("4812945", 6) === "");
  ok("ссылку не берём", кодИзТекста("https://generalmodern.uz/p/123456/abc", 6) === "");
  ok("пустой буфер", кодИзТекста("", 6) === "" && кодИзТекста(null, 6) === "");
  ok("текст без цифр", кодИзТекста("Здравствуйте!", 6) === "");
}

// ---------- 3. Слежение за буфером ----------
// Подделываем браузер: буфер, вкладку и события.
function окружение(буферТекст) {
  const слушатели = {};
  globalThis.document = {
    visibilityState: "visible",
    addEventListener: (имя, фн) => { (слушатели[имя] ||= []).push(фн); },
    removeEventListener: (имя, фн) => { слушатели[имя] = (слушатели[имя] || []).filter(x => x !== фн); },
  };
  globalThis.window = {
    addEventListener: (имя, фн) => { (слушатели[имя] ||= []).push(фн); },
    removeEventListener: (имя, фн) => { слушатели[имя] = (слушатели[имя] || []).filter(x => x !== фн); },
  };
  const нав = буферТекст === null
    ? {}                                   // буфера нет вовсе (старый браузер)
    : { clipboard: { readText: async () => {
        if (буферТекст === "ОТКАЗ") throw new Error("NotAllowedError");  // Safari
        return буферТекст;
      } } };
  // В Node 24 globalThis.navigator — только для чтения, присвоить нельзя.
  Object.defineProperty(globalThis, "navigator", { value: нав, configurable: true, writable: true });
  return { позвать: (имя) => (слушатели[имя] || []).forEach(ф => ф()), слушатели };
}
const ждём = () => new Promise(r => setTimeout(r, 0));

{
  const о = окружение("481294");
  let вставлено = [], неВышло = 0;
  const н = следитьЗаБуфером({ длина: 6, занято: () => false, вставить: (к) => вставлено.push(к), неВышло: () => неВышло++ });
  await ждём(); await ждём();
  ok("код из буфера подставился сам", вставлено[0] === "481294");

  // Тот же код второй раз не вставляем: человек мог стереть его вручную,
  // и подставлять обратно против его воли нельзя.
  о.позвать("focus"); await ждём(); await ждём();
  ok("один и тот же код не вставляем дважды", вставлено.length === 1);
  н.стоп();
  ok("после стоп() слушателей не осталось",
     (о.слушатели.visibilitychange || []).length === 0 && (о.слушатели.focus || []).length === 0);
}

{
  const о = окружение("481294");
  let вставлено = 0;
  const н = следитьЗаБуфером({ длина: 6, занято: () => true, вставить: () => вставлено++, неВышло: () => {} });
  await ждём(); await ждём();
  о.позвать("focus"); await ждём(); await ждём();
  ok("набранное руками не перетираем", вставлено === 0);
  н.стоп();
}

{
  const о = окружение("ОТКАЗ");           // Safari: молча читать не даёт
  let неВышло = 0, вставлено = 0;
  const н = следитьЗаБуфером({ длина: 6, занято: () => false, вставить: () => вставлено++, неВышло: () => неВышло++ });
  await ждём(); await ждём();
  ok("при отказе в доступе предлагаем кнопку", неВышло > 0 && вставлено === 0);
  ok("по нажатию честно возвращаем «не вышло»", (await н.попробовать()) === false);
  н.стоп();
}

{
  окружение(null);                         // буфера нет вовсе
  let неВышло = 0;
  const н = следитьЗаБуфером({ длина: 6, занято: () => false, вставить: () => {}, неВышло: () => неВышло++ });
  await ждём(); await ждём();
  ok("без буфера в браузере не падаем", неВышло > 0);
  н.стоп();
}

{
  const о = окружение("841 772 сум");
  let вставлено = 0;
  const н = следитьЗаБуфером({ длина: 6, занято: () => false, вставить: () => вставлено++, неВышло: () => {} });
  await ждём(); await ждём();
  о.позвать("visibilitychange"); await ждём(); await ждём();
  ok("чужое из буфера не подставляем", вставлено === 0);
  н.стоп();
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nКОД ИЗ БУФЕРА В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
