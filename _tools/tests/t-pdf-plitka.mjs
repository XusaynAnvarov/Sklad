// ========================================================================
//  PDF: ТАБЛИЦА В НАКЛАДНОЙ, ПЛИТКА В ЗАКАЗЕ ПОСТАВЩИКУ.
//  node _tools/tests/t-pdf-plitka.mjs
//
//  Две разные формы, и это выбор владельца:
//
//  • НАКЛАДНАЯ — таблица БЕЗ ФОТО. Снимок есть не у каждого товара, и
//    накладная на три позиции состояла из серых окон «без фото»; к тому
//    же её отправляют клиенту в Telegram, а каждый снимок — лишняя
//    четверть мегабайта.
//

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const корень = new URL("../../", import.meta.url);
const { сеткаПлиток, buildInvoicePDF, buildSupplierOrderPDF } = await import(new URL("api/lib/pdf.js", корень));
const { PDFDocument } = await import("pdf-lib");

const M = 45, R = 595 - 45;

// ---------- 1. Сетка ----------
{
  const мало = сеткаПлиток(6, M, R);
  ok("до двенадцати позиций — две колонки", мало.колонок === 2);
  ok("две колонки с зазором занимают всю ширину",
     Math.abs(мало.ширина * 2 + мало.зазор - (R - M)) < 0.01);
  ok("снимок в две колонки крупный", мало.высотаФото === 100);

  const много = сеткаПлиток(27, M, R);
  ok("с тринадцатой позиции — три колонки", много.колонок === 3);
  ok("три колонки с зазорами занимают всю ширину",
     Math.abs(много.ширина * 3 + много.зазор * 2 - (R - M)) < 0.01);
  ok("в плотной сетке плитка ниже", много.высота < мало.высота);
  ok("граница ровно на двенадцати", сеткаПлиток(12, M, R).колонок === 2 && сеткаПлиток(13, M, R).колонок === 3);

  // сколько влезает на лист: от верха 842−55 до низа 132
  const наЛист = (с) => Math.floor((842 - 55 - 132) / (с.высота + с.зазор)) * с.колонок;
  ok("в две колонки на лист входит не меньше восьми", наЛист(мало) >= 8);
  ok("в три колонки на лист входит не меньше пятнадцати", наЛист(много) >= 15);
  ok("самая длинная накладная (117) уложится в десять листов",
     Math.ceil(117 / наЛист(сеткаПлиток(117, M, R))) <= 10);
}

// ---------- подготовка данных ----------
const товар = (i) => ({
  id: "p" + i,
  name: "Линейный нож (2,8) усиленный образец " + i,
  photo_url: "",            // без сети: снимка не будет, рисуется «без фото»
});
const продажа = (сколько) => ({
  id: "sale-00042",
  date: new Date("2026-10-30").toISOString(),
  currency: "som",
  items: Array.from({ length: сколько }, (_, i) => ({ product_id: "p" + i, qty: 2 + i, unit_price: 118000, paid: false })),
});
const товары = (сколько) => Array.from({ length: сколько }, (_, i) => товар(i));

const листов = async (байты) => (await PDFDocument.load(байты)).getPageCount();

// ---------- 2. Накладная собирается ----------
{
  const байты = await buildInvoicePDF({
    sale: продажа(3), customer: { name: "Магазин «Олтин»", contact: "+998 90 123-45-67" }, products: товары(3),
  });
  ok("короткая накладная собралась", байты && байты.length > 1000);
  const n = await листов(байты);
  ok("короткая накладная — один лист", n === 1);

}

// ---------- 3. Длинная накладная не разрастается ----------
{
  const байты = await buildInvoicePDF({
    sale: продажа(30), customer: { name: "Магазин «Олтин»" }, products: товары(30),
  });
  const n = await листов(байты);
  ok("накладная на 30 позиций собралась", байты.length > 1000);
  ok(`накладная на 30 позиций — не больше двух листов (вышло ${n})`, n <= 2);
}

// ---------- 4. Самая длинная из тех, что есть в базе ----------
{
  const байты = await buildInvoicePDF({
    sale: продажа(117), customer: { name: "Магазин «Олтин»" }, products: товары(117),
  });
  const n = await листов(байты);
  ok(`накладная на 117 позиций — не больше пяти листов (вышло ${n})`, n <= 5);
}

// ---------- 4б. В накладной нет снимков и она лёгкая ----------
// Главное обещание клиенту: файл, который не стыдно слать в Telegram.
{
  const сФото = товары(8).map(t => ({
    ...t,
    photo_url: "https://juhnnhwjnmxnamqekwjy.supabase.co/storage/v1/object/public/product-photos/x.jpg",
  }));
  const байты = await buildInvoicePDF({
    sale: продажа(8), customer: { name: "Магазин «Олтин»" }, products: сФото,
  });
  const док = await PDFDocument.load(байты);
  // pdf-lib кладёт каждую картинку отдельным объектом-потоком с /Subtype /Image
  const сырой = Buffer.from(байты).toString("latin1");
  ok("в накладной нет вложенных снимков", !сырой.includes("/Subtype /Image") && !сырой.includes("/Subtype/Image"));
  ok("накладная на 8 позиций — один лист", док.getPageCount() === 1);
  ok(`накладная весит меньше мегабайта (${Math.round(байты.length / 1024)} КБ)`, байты.length < 1024 * 1024);
}

// ---------- 5. Заказ поставщику ----------
{
  const items = Array.from({ length: 5 }, (_, i) => ({ product_id: "p" + i, qty: 4, cost: 118, currency: "yuan" }));
  const байты = await buildSupplierOrderPDF({ items, supplier: "1688 / Гуанчжоу", currency: "yuan", products: товары(5), lang: "ru" });
  ok("заказ поставщику собрался", байты && байты.length > 1000);
  ok("заказ поставщику — один лист", (await листов(байты)) === 1);
}

// ---------- 6. Товар без имени и без полей не роняет сборку ----------
{
  const кривые = [{ id: "p0" }, { id: "p1", name: "" }];
  const байты = await buildInvoicePDF({
    sale: { id: "s", date: new Date().toISOString(), currency: "som",
            items: [{ product_id: "p0", qty: 1, unit_price: 10 }, { product_id: "p1", qty: 1, unit_price: 10 }] },
    customer: null, products: кривые,
  });
  ok("пустые поля товара не роняют накладную", байты && байты.length > 1000);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nПЛИТКА В PDF В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
