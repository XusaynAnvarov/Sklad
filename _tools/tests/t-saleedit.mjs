// ========================================================================
//  ПРАВКА НАКЛАДНОЙ И СКЛАД.  node _tools/tests/t-saleedit.mjs
//
//  29 сентября 2026: владелец поправил накладную «Нурбек Ака» — убрал
//  несколько товаров и уменьшил количество. Склад списал ВСЁ заново:
//  у «Дазмол крышка» остаток стал −20, хотя её никто не трогал.
//  Причина: между возвратом старых позиций и списанием новых остаток
//  сверялся с партиями, и возврат срезался как «лишний».
//
//  Правило, которое проверяем: правка накладной меняет остаток ровно на
//  разницу «было в накладной → стало в накладной». Ни больше ни меньше.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { пересчитатьСклад } = await import(new URL("js/saleedit.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const товар = (id, имя, остаток, цена = 10) => ({
  id, name: имя, stock_qty: остаток, cost_yuan: цена, cost_usd: цена * 0.14,
  batches: остаток === 0 ? [] : [{ qty: остаток, cost_yuan: цена, cost_usd: цена * 0.14, date: "2026-09-01" }],
});
const позиция = (id, qty, { применена = true, цена = 10 } = {}) => ({
  product_id: id, qty, unit_price: 100,
  ...(применена ? { applied: true, cogs_yuan: цена * qty, cogs_usd: цена * 0.14 * qty } : {}),
});
const склад = (...список) => Object.fromEntries(список.map(p => [p.id, p]));
const остаток = (rows, id) => (rows.find(r => r.id === id) || {}).stock_qty;

// ---------- количество уменьшили ----------
{
  // было продано 20, на складе осталось 80; в накладной оставили 5
  const товары = склад(товар("t1", "Дазмол крышка", 80));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 20)] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 5, { применена: false })] });
  ok("уменьшили 20 → 5: на складе стало 95", остаток(rows, "t1") === 95);
}

// ---------- количество не меняли ----------
{
  const товары = склад(товар("t1", "Дазмол крышка", 80));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 20)] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 20, { применена: false })] });
  ok("не меняли — остаток как был: 80", остаток(rows, "t1") === 80);
  ok("и в минус не уходит", остаток(rows, "t1") >= 0);
}

// ---------- товар убрали из накладной ----------
{
  const товары = склад(товар("t1", "Аверлок нож", 220), товар("t2", "Лапка", 500));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 100), позиция("t2", 50)] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t2", 50, { применена: false })] });
  ok("убранный товар вернулся: 220 → 320", остаток(rows, "t1") === 320);
  ok("оставшийся не тронут: 500", остаток(rows, "t2") === 500);
}

// ---------- количество увеличили ----------
{
  const товары = склад(товар("t1", "Бурун чок", 1400));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 100)] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 130, { применена: false })] });
  ok("увеличили 100 → 130: списали ещё 30", остаток(rows, "t1") === 1370);
}

// ---------- добавили новый товар ----------
{
  const товары = склад(товар("t1", "Нож", 50), товар("t2", "Улитка", 40));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 10)] };
  const { rows, cogs } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 10, { применена: false }), позиция("t2", 7, { применена: false })] });
  ok("старый не тронут: 50", остаток(rows, "t1") === 50);
  ok("новый списан: 40 → 33", остаток(rows, "t2") === 33);
  ok("себестоимость списания посчитана", cogs.t2 && cogs.t2.cogs_yuan === 70);
}

// ---------- новая накладная (правим не существующую) ----------
{
  const товары = склад(товар("t1", "Нож", 30));
  const { rows } = пересчитатьСклад({ товары, старая: null, позиции: [позиция("t1", 12, { применена: false })] });
  ok("новая накладная просто списывает: 30 → 18", остаток(rows, "t1") === 18);
}

// ---------- накладная, которая склад НЕ трогала ----------
{
  // заказ: позиции без отметки applied и без себестоимости — возвращать нечего
  const товары = склад(товар("t1", "Нож", 30));
  const старая = { id: "n1", status: "order", date: "2026-09-23", items: [{ product_id: "t1", qty: 10 }] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 10, { применена: false })] });
  ok("заказ списывается один раз: 30 → 20", остаток(rows, "t1") === 20);
}

// ---------- две строки одного товара ----------
{
  const товары = склад(товар("t1", "Нож", 100));
  const старая = { id: "n1", status: "final", date: "2026-09-23", items: [позиция("t1", 10)] };
  const { rows } = пересчитатьСклад({ товары, старая, позиции: [позиция("t1", 4, { применена: false }), позиция("t1", 3, { применена: false })] });
  ok("две строки складываются: 110 − 7 = 103", остаток(rows, "t1") === 103);
}

// ---------- товар продан в минус ----------
{
  const товары = склад({ id: "t1", name: "Кулок", stock_qty: 0, cost_yuan: 5, cost_usd: 0.7, batches: [] });
  const { rows } = пересчитатьСклад({ товары, старая: null, позиции: [позиция("t1", 80, { применена: false })] });
  ok("продали, чего нет: −80 (долг по товару)", остаток(rows, "t1") === -80);
}

// ---------- карточку товара удалили ----------
{
  const товары = склад(товар("t1", "Нож", 10));
  const { rows, ненайденные } = пересчитатьСклад({ товары, старая: null, позиции: [позиция("t1", 2, { применена: false }), позиция("нет-такого", 5, { применена: false })] });
  ok("пропавший товар отмечен отдельно", ненайденные.length === 1 && ненайденные[0] === "нет-такого");
  ok("остальное записалось: 10 → 8", остаток(rows, "t1") === 8);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nПРАВКА НАКЛАДНОЙ СЧИТАЕТСЯ ВЕРНО");
process.exit(плохо ? 1 : 0);
