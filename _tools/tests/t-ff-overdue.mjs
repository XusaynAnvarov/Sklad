// ========================================================================
//  СРЕЗ «ПРОСРОЧЕНЫ» НА ДОСКЕ.   node _tools/tests/t-ff-overdue.mjs
//
//  Просрочка — это ВЗГЛЯД, а не этап: заказ остаётся в своей колонке,
//  журнал не пишется, карточка никуда не переезжает. Проверяем, что
//  счёт совпадает со счётом агента заказов (api/lib/agents/orders-math.js)
//  — иначе на доске будет одно число, а в отчёте другое.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const Д = await import(new URL("js/fulfillment-core.js", корень));
const А = await import(new URL("api/lib/agents/orders-math.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const СУТКИ = 86400e3;
const СЕЙЧАС = Date.parse("2026-11-23T06:00:00Z");
const назад = (д) => СЕЙЧАС - д * СУТКИ;

// Карточка доски: tЭтапа — когда заказ попал на нынешний этап.
const карточка = (stage, днейНаЭтапе, extra = {}) => ({
  id: "x" + Math.random(), stage, t: назад(днейНаЭтапе + 1), tЭтапа: назад(днейНаЭтапе), ...extra,
});

ok("пороги доски и агента совпадают",
  JSON.stringify(Д.ПОРОГИ_ПРОСРОЧКИ) === JSON.stringify(А.ПОРОГИ));

ok("оформлен 3 дня при норме 2 — просрочен",
  Д.просрочен(карточка("placed", 3), undefined, СЕЙЧАС) === true);
ok("оформлен 2 дня — ещё не просрочен",
  Д.просрочен(карточка("placed", 2), undefined, СЕЙЧАС) === false);
ok("собран 2 дня при норме 1 — просрочен",
  Д.просрочен(карточка("packed", 2), undefined, СЕЙЧАС) === true);
ok("отправленный просроченным не бывает",
  Д.просрочен(карточка("shipped", 99), undefined, СЕЙЧАС) === false);
ok("свои пороги работают",
  Д.просрочен(карточка("placed", 3), { placed: 10 }, СЕЙЧАС) === false);
ok("без времени этапа ничего не выдумываем",
  Д.просрочен({ stage: "placed", t: 0, tЭтапа: 0 }, undefined, СЕЙЧАС) === false);

// Доска и агент должны давать одно и то же число.
{
  const дни = [0, 1, 2, 3, 5, 10];
  for (const э of ["placed", "packed"]) {
    const наДоске = дни.map((д) => Д.просрочен(карточка(э, д), undefined, СЕЙЧАС));
    const уАгента = дни.map((д) => А.просрочен({ этап: э, днейНаЭтапе: д }, А.ПОРОГИ));
    ok(`доска и агент сходятся на этапе ${э}`, JSON.stringify(наДоске) === JSON.stringify(уАгента));
  }
}

// Фильтр доски.
{
  const заказы = [
    карточка("placed", 5), карточка("placed", 0),
    карточка("packed", 3), карточка("shipped", 40),
  ];
  const все = Д.отфильтровать(заказы, {});
  const только = Д.отфильтровать(заказы, { overdue: true });
  ok("без среза видно всё", все.length === 4);
  ok("срез оставляет только просроченные", только.length === 2);
  ok("отправленный в срез не попадает", !только.some((z) => z.stage === "shipped"));
  ok("счётчик считает по всем заказам", Д.считатьПросрочки(заказы, undefined, СЕЙЧАС) === 2);
  ok("срез уживается с фильтром по этапу",
    Д.отфильтровать(заказы, { overdue: true, stage: "packed" }).length === 1);
}

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
