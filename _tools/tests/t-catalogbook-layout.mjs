// ========================================================================
//  ПЕЧАТНЫЙ КАТАЛОГ: РАСКЛАДКА.  node _tools/tests/t-catalogbook-layout.mjs
//
//  Книгу печатают тиражом — ошибка в номере страницы в содержании или
//  налезший на соседа текст исправить потом нельзя. Проверяем раскладку
//  и собираем небольшую книгу целиком, без снимков.
// ========================================================================
import { readFileSync } from "node:fs";

const корень = new URL("../../", import.meta.url);
const К = await import(new URL("api/lib/catalogbook.js", корень));
const { ПОДПИСИ, РАЗДЕЛЫ, названиеРаздела, ЯЗЫКИ } = await import(new URL("js/catalogbook-text.js", корень));
const { БУКВЫ, раздатьКоды } = await import(new URL("js/catalogcode.js", корень));
const { PDFDocument, PDFName } = await import("pdf-lib");
const fontkit = (await import("@pdf-lib/fontkit")).default;

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// Склад, похожий на боевой: 29 разделов, размеры как в сентябре 2026.
const РАЗМЕРЫ = { "Лапки": 233, "Приборы для машин": 131, "Улитки": 79, "Ножы": 76, "Нинала": 66, "Аппараты": 52,
  "Утюги": 30, "Пластина": 25, "Крышки": 21, "Чельнок": 21, "Ремень": 20, "Петлител": 18, "Регулятор": 16,
  "Иглодержател": 15, "Калиш": 15, "Светилник": 15, "Насатки": 14, "Мокки": 12, "Бабина стойки": 11, "Тень": 11,
  "Тиш": 11, "Магниты": 10, "Диск": 9, "Метры": 6, "Шпулка": 6, "Шестеренки": 4, "Пинцеты": 3, "Болть": 2, "Без категории": 1 };
let товары = [];
let n = 0;
for (const [раздел, сколько] of Object.entries(РАЗМЕРЫ)) {
  for (let i = 0; i < сколько; i++) {
    товары.push({ id: "p" + n, name: `${раздел} товар ${i + 1}`, category: раздел === "Без категории" ? "" : раздел,
      created_at: new Date(1e12 + n++).toISOString() });
  }
}
const { выдать } = раздатьКоды(товары);
const код = Object.fromEntries(выдать.map(x => [x.id, x.code]));
товары = товары.map(p => ({ ...p, code: код[p.id] }));

// ---------- разделы ----------
const разделы = К.собратьРазделы(товары);
{
  ok("29 разделов", разделы.length === 29);
  ok("от большого к малому, «Без категории» в конце",
     разделы[0].ключ === "Лапки" && разделы[28].ключ === "Без категории"
     && разделы.slice(0, 28).every((р, i, a) => !i || a[i - 1].товары.length >= р.товары.length));
  ok("буквы разделов — по выданным кодам", разделы.every(р => р.товары.every(p => p.code.startsWith(р.буквы + "-"))));
  ok("внутри раздела — по номеру кода", разделы.every(р => р.товары.every((p, i, a) => !i || a[i - 1].code < p.code)));
  const скрыт = К.собратьРазделы([...товары, { id: "h", name: "скрытый", category: "Лапки", hidden: true }]);
  ok("скрытые товары в книгу не идут", скрыт[0].товары.length === 233);
}

// ---------- раскладка ----------
const { страницы, разделы: сНомерами } = К.разметить(разделы);
{
  ok("всего страниц кратно 4: " + страницы.length, страницы.length % 4 === 0);
  ok("1 — обложка, 2 — о компании, 3 — содержание, последняя — задняя",
     страницы[0].вид === "обложка" && страницы[1].вид === "о компании" && страницы[2].вид === "содержание"
     && страницы.at(-1).вид === "задняя");
  ok("номера страниц идут подряд", страницы.every((s, i) => s.номер === i + 1));

  const вводные = страницы.filter(s => s.вид === "вводная");
  ok("вводные — только на чётных (левых) страницах", вводные.length > 0 && вводные.every(s => s.номер % 2 === 0));
  ok("после вводной сразу сетка её раздела",
     вводные.every(s => { const след = страницы[s.номер]; return след.вид === "сетка" && след.блоки[0].раздел.ключ === s.раздел.ключ; }));
  ok("вводные только у больших разделов", вводные.every(s => s.раздел.товары.length >= К.ПОРОГ_ВВОДНОЙ));
  ok("пустых страниц посреди книги нет",
     страницы.slice(0, страницы.findIndex(s => s.вид === "заметки") >>> 0).every(s => s.вид !== "заметки"));

  const сетки = страницы.filter(s => s.вид === "сетка");
  ok("не больше 20 карточек на странице", сетки.every(s => s.блоки.reduce((m, b) => m + b.ряды.flat().length, 0) <= 20));
  ok("в ряду не больше 4 карточек", сетки.every(s => s.блоки.every(b => b.ряды.every(r => r.length <= 4))));
  const С = К.СЕТКА;
  const высота = (s) => s.блоки.reduce((h, b, i) => h + (i ? С.междуРазделами : 0) + С.полоса + С.послеПолосы
    + b.ряды.length * С.карточка + Math.max(0, b.ряды.length - 1) * С.зазор, 0);
  ok("ничего не вылезает за низ страницы", сетки.every(s => высота(s) <= С.высота + 0.01));
  ok("у полосы раздела всегда есть хотя бы один ряд под ней", сетки.every(s => s.блоки.every(b => b.ряды.length > 0)));

  const напечатано = сетки.flatMap(s => s.блоки.flatMap(b => b.ряды.flat()));
  ok("каждый товар напечатан ровно один раз: " + напечатано.length,
     напечатано.length === товары.length && new Set(напечатано.map(p => p.id)).size === товары.length);

  // номер в содержании = первая страница раздела на самом деле
  const настоящая = (ключ) => {
    const s = страницы.find(s => (s.вид === "вводная" && s.раздел.ключ === ключ)
      || (s.вид === "сетка" && s.блоки.some(b => b.раздел.ключ === ключ && !b.продолжение)));
    return s && s.номер;
  };
  ok("номера страниц в содержании совпадают с настоящими", сНомерами.every(р => р.страница === настоящая(р.ключ)));
  ok("продолжение раздела помечено", сетки.some(s => s.блоки.some(b => b.продолжение)));
}

// ---------- образец ----------
{
  const номера = К.страницыОбразца(страницы);
  const виды = номера.map(n => страницы[n - 1].вид);
  ok("образец: " + номера.join(","), номера.length === 7 && виды.includes("обложка") && виды.includes("содержание")
     && виды.includes("вводная") && виды.includes("задняя") && виды.filter(v => v === "сетка").length >= 2);
}

// ---------- тексты ----------
{
  const шрифт = await (async () => { const d = await PDFDocument.create(); d.registerFontkit(fontkit); return d.embedFont(readFileSync(new URL("fonts/NotoSans-Regular.ttf", корень))); })();
  const ш = К.СЕТКА.шКарточки - К.КАРТОЧКА.отступ * 2;
  const строки = К.перенести("Приспособление для регулирование резинки (BIG SIZE) и ещё очень длинное продолжение", шрифт, К.КАРТОЧКА.кегльИмени, ш, 2);
  ok("длинное название — две строки и многоточие", строки.length === 2 && строки[1].endsWith("…"));
  ok("и ни одна строка не шире карточки", строки.every(t => шрифт.widthOfTextAtSize(t, К.КАРТОЧКА.кегльИмени) <= ш + 0.01));
  const слово = К.перенести("ОченьДлинноеСловоБезПробеловКотороеНикакНеВлезаетВОднуСтроку", шрифт, 7.6, 60, 2);
  ok("слово без пробелов режется и не вылезает", слово.length === 2 && слово.every(t => шрифт.widthOfTextAtSize(t, 7.6) <= 60.01));
  ok("короткое — как есть", JSON.stringify(К.перенести("Лапка (P304)", шрифт, 7.6, ш, 2)) === JSON.stringify(["Лапка (P304)"]));
  ok("пустое название не падает", К.перенести("", шрифт, 7.6, ш, 2).length === 0);

  ok("все 29 разделов переведены на uz и en",
     Object.keys(БУКВЫ).every(r => РАЗДЕЛЫ[r] && РАЗДЕЛЫ[r].uz && РАЗДЕЛЫ[r].en && РАЗДЕЛЫ[r].ru));
  ok("правка владельца важнее таблицы", названиеРаздела("Ножы", "uz", { "Ножы": { uz: "Pichoq" } }) === "Pichoq"
     && названиеРаздела("Ножы", "en", { "Ножы": { uz: "Pichoq" } }) === "Knives");
  ok("новый раздел без перевода — как в складе", названиеРаздела("Ленты", "en") === "Ленты");
  ok("подписи на всех языках одинаковые по составу",
     ЯЗЫКИ.every(я => Object.keys(ПОДПИСИ[я]).join() === Object.keys(ПОДПИСИ.ru).join()));
  ok("склонение: 1 товар, 3 товара, 11 товаров, 21 товар",
     ПОДПИСИ.ru.товаров(1) === "1 товар" && ПОДПИСИ.ru.товаров(3) === "3 товара"
     && ПОДПИСИ.ru.товаров(11) === "11 товаров" && ПОДПИСИ.ru.товаров(21) === "21 товар");

  ok("путь снимка из ссылки Supabase",
     К.путьСнимка({ photo_url: "https://x.supabase.co/storage/v1/object/public/product-photos/1_a.jpg" }) === "product-photos/1_a.jpg");
  ok("первый снимок из photos важнее photo_url",
     К.путьСнимка({ photos: ["product-photos/2.jpg"], photo_url: "product-photos/1.jpg" }) === "product-photos/2.jpg");
  ok("чужая ссылка — без снимка", К.путьСнимка({ photo_url: "https://evil.example/a.jpg" }) === "");
  const лучшие = К.лучшиеСнимки([
    { photo_url: "product-photos/a.jpg" }, { photo_url: "product-photos/a.jpg" },
    { photo_url: "product-photos/b.jpg" }, { photo_url: "product-photos/c_ChatGPT_Image_1.jpg" },
  ], 3);
  ok("снимки для обложки без повторов, сперва на белом фоне",
     лучшие.length === 3 && /ChatGPT/.test(лучшие[0].photo_url) && new Set(лучшие.map(p => p.photo_url)).size === 3);
}

// ---------- книга целиком, на трёх языках ----------
{
  const шрифты = К.шрифтыСДиска(корень);
  // один настоящий снимок, чтобы проверить встраивание
  const png = readFileSync(new URL("icon-192.png", корень));
  const достатьСнимок = async (путь) => (путь.endsWith("1.png") ? png : null);
  const сФото = товары.map((p, i) => (i === 0 ? { ...p, photo_url: "product-photos/1.png" } : p));
  for (const язык of ЯЗЫКИ) {
    const t0 = Date.now();
    let последний = null;
    const итог = await К.собрать({ товары: сФото, язык, инфо: { телефоны: "+998 90 000 00 00", адрес: "Ташкент", оКомпании: { ru: "Текст о компании." } },
      достатьСнимок, шрифты, наПрогресс: (p) => { последний = p; } });
    const pdf = await PDFDocument.load(итог.байты);
    const стр = pdf.getPages();
    ok(`${язык}: собрана вся книга — ${стр.length} стр. за ${Date.now() - t0} мс`, стр.length === страницы.length);
    const [pw, ph] = [стр[0].getWidth(), стр[0].getHeight()];
    ok(`${язык}: формат A4 + 3 мм под обрез`, Math.abs(pw - (К.W + К.ОБРЕЗ * 2)) < 0.01 && Math.abs(ph - (К.H + К.ОБРЕЗ * 2)) < 0.01);
    ok(`${язык}: у страниц размечен обрез для типографии`, стр.every(p => p.node.get(PDFName.of("TrimBox"))));
    ok(`${язык}: ход сборки дошёл до конца`, последний && последний.готово === последний.всего);
  }
  const образец = await К.собрать({ товары, язык: "ru", образец: true, шрифты });
  ok("образец — 7 страниц с настоящими номерами", образец.страниц === 7 && образец.номера[0] === 1 && образец.номера.at(-1) === страницы.length);
}


console.log(плохо ? `\n${плохо} ОШИБОК` : "\nРАСКЛАДКА КАТАЛОГА В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
