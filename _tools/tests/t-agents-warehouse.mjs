// ========================================================================
//  АГЕНТ СКЛАДА.   node _tools/tests/t-agents-warehouse.mjs
//
//  Проверяем арифметику из api/lib/agents/sales-math.js на выборке, где
//  нарочно собрано всё, на чём такой счёт обычно врёт:
//   • оформленный, но не выданный заказ — это НЕ продажа;
//   • возврат уже идёт с минусом, вычитать его второй раз нельзя;
//   • отменённый заказ не считается ни продажей, ни резервом;
//   • при короткой истории сезон и прошлый год не считаются вовсе.
//
//  Плюс сроки поставки: они берутся из приходов, а не из настроек.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const M = await import(new URL("api/lib/agents/sales-math.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const СУТКИ = 86400e3;
const СЕЙЧАС = Date.parse("2026-11-23T06:00:00Z");   // 11:00 в Ташкенте
const днейНазад = (д) => new Date(СЕЙЧАС - д * СУТКИ).toISOString();
const курсы = { yuan: 0.14, som: 1 / 12600 };

// ======================================================================
//  1. СПИСОК НЕВЫДАННЫХ СТАТУСОВ НЕ РАСХОДИТСЯ СО СКЛАДОМ
// ======================================================================
{
  const debt = await import(new URL("js/debt.js", корень)).catch(() => null);
  if (debt) {
    const свои = [...M.НЕ_ВЫДАНО].sort().join(",");
    // js/debt.js список не экспортирует, но экспортирует проверку —
    // сверяем поведение, а не текст.
    const одинаково = M.НЕ_ВЫДАНО.every((s) => !debt.isIssued({ status: s }))
      && ["final", "shipped"].every((s) => debt.isIssued({ status: s }) === M.выдана({ status: s }));
    ok("невыданные статусы совпадают с js/debt.js (" + свои + ")", одинаково);
  } else {
    console.log("⏭  js/debt.js не импортируется в node — сверка пропущена");
  }
}

// ======================================================================
//  2. ЧТО СЧИТАЕТСЯ ПРОДАЖЕЙ
// ======================================================================
const продажи = [
  // обычные выдачи
  { status: "final", date: днейНазад(2),  items: [{ product_id: "p1", qty: 4, unit_price: 10, currency: "usd", cogs_usd: 24 }] },
  { status: "final", date: днейНазад(10), items: [{ product_id: "p1", qty: 6, unit_price: 10, currency: "usd", cogs_usd: 36 }] },
  { status: "final", date: днейНазад(40), items: [{ product_id: "p1", qty: 20, unit_price: 10, currency: "usd", cogs_usd: 120 }] },
  // возврат: количество отрицательное, вычитается само
  { status: "final", source: "refund", date: днейНазад(5), items: [{ product_id: "p1", qty: -2, unit_price: 10, currency: "usd", cogs_usd: -12 }] },
  // заказ оформлен, но не выдан — не продажа, зато резерв
  { status: "order", date: днейНазад(1), items: [{ product_id: "p1", qty: 50, unit_price: 10, currency: "usd" }] },
  // отменённый заказ — ни продажа, ни резерв
  { status: "canceled", date: днейНазад(1), items: [{ product_id: "p1", qty: 99, unit_price: 10, currency: "usd" }] },
  // чужая валюта — для проверки приведения к доллару
  { status: "final", date: днейНазад(3), items: [{ product_id: "p2", qty: 10, unit_price: 100, currency: "yuan", cogs_usd: 5 }] },
  // давно не продавался
  { status: "final", date: днейНазад(200), items: [{ product_id: "p3", qty: 1, unit_price: 1, currency: "usd" }] },
];

{
  const за30 = M.поТоварам(продажи, { от: СЕЙЧАС - 30 * СУТКИ, до: СЕЙЧАС, курсы });
  const p1 = за30.get("p1");
  ok("оформленный заказ не попал в продажи", p1.кол === 8);           // 4 + 6 − 2
  ok("возврат вычтен ровно один раз", p1.выручкаUSD === 80);          // (4+6−2) × 10
  ok("отменённый заказ не попал никуда", p1.кол !== 107 && p1.кол !== 8 + 99);
  ok("возврат отмечен отдельно", p1.возвратов === 1);
  ok("прибыль = выручка − себестоимость", p1.прибыльUSD === 80 - 48);

  const p2 = за30.get("p2");
  ok("юани приведены к доллару", Math.abs(p2.выручкаUSD - 10 * 100 * 0.14) < 1e-9);

  const за365 = M.поТоварам(продажи, { от: СЕЙЧАС - 365 * СУТКИ, до: СЕЙЧАС, курсы });
  ok("товар за пределами окна не теряется на большом окне", за365.has("p3"));
  ok("и не попадает в короткое окно", !за30.has("p3"));
}

// ======================================================================
//  3. РЕЗЕРВ И ТОВАР В ПУТИ
// ======================================================================
{
  const р = M.зарезервировано(продажи);
  ok("обещанное клиенту считается резервом", р.get("p1") === 50);

  const приходы = [
    { status: "in_transit", date: днейНазад(10), supplier: "Кампир", items: [{ product_id: "p1", qty: 100 }] },
    { status: "ordered",    date: днейНазад(3),  supplier: "Кампир", items: [{ product_id: "p1", qty: 50 }] },
    { status: "arrived",    date: днейНазад(60), supplier: "Кампир", items: [{ product_id: "p1", qty: 999, приход: { когда: днейНазад(20) } }] },
  ];
  const путь = M.вПути(приходы);
  ok("в пути: и «в дороге», и «заказано»", путь.get("p1") === 150);
  ok("приехавшее в пути не числится", путь.get("p1") !== 1149);
}

// ======================================================================
//  4. СРОКИ ПОСТАВКИ — ИЗ ИСТОРИИ, А НЕ ИЗ НАСТРОЕК
// ======================================================================
{
  const приходы = [
    { status: "arrived", date: днейНазад(90), supplier: "Кампир", items: [{ product_id: "p1", qty: 1, приход: { когда: днейНазад(47) } }] },  // 43
    { status: "arrived", date: днейНазад(80), supplier: "Кампир", items: [{ product_id: "p1", qty: 1, приход: { когда: днейНазад(48) } }] },  // 32
    { status: "arrived", date: днейНазад(70), supplier: "Кампир", items: [{ product_id: "p2", qty: 1, приход: { когда: днейНазад(31) } }] },  // 39
    { status: "arrived", date: днейНазад(5),  supplier: "Сирож Акам", items: [{ product_id: "p3", qty: 1, приход: { когда: днейНазад(5) } }] }, // 0
    // мусор: приход раньше заказа
    { status: "arrived", date: днейНазад(5),  supplier: "Кампир", items: [{ product_id: "p1", qty: 1, приход: { когда: днейНазад(9) } }] },
  ];
  const сроки = M.срокиПоставщиков(приходы);
  const кампир = сроки.get("Кампир");
  ok("срок считается по датам прихода", кампир.дней === 39);          // медиана 32/39/43
  ok("отрицательный срок отброшен как мусор", кампир.наблюдений === 3);
  ok("по трём поставкам срок считается надёжным", кампир.надёжно === true);
  ok("местный магазин — ноль дней", сроки.get("Сирож Акам").дней === 0);
  ok("по одной поставке надёжности нет", сроки.get("Сирож Акам").надёжно === false);

  const ктоВозит = M.поставщикиТоваров(приходы);
  ok("поставщик товара — тот, кто привозил последним", ктоВозит.get("p1").поставщик === "Кампир");
}

// ======================================================================
//  5. ПРОГНОЗ И СВЕТОФОР
// ======================================================================
{
  // Продаётся 2 шт/день, лежит 10, обещано 4, срок поставки 30 дней.
  const п = M.прогноз({ остаток: 10, зарезервировано: 4, вПути: 0, скорость30: 2, срокДней: 30, страховкаДней: 7 });
  ok("свободный остаток = лежит − обещано", п.свободно === 6);
  ok("хватит на три дня", п.хватитДней === 3);
  ok("точка заказа = скорость × (срок + запас)", п.точкаЗаказа === 2 * 37);
  ok("заказать с запасом на срок и две страховки", п.рекомендовано === Math.ceil(2 * 44) - 6);
  ok("ничего не мешает счёту", п.нет.length === 0);

  const с = M.светофор({ ...п, остаток: 10, срокДней: 30 });
  ok("кончится раньше поставки — оранжевый", с.цвет === "🟠" && с.код === "срочно");

  ok("пустой склад — красный", M.светофор({ остаток: 0, свободно: 0, вДень: 2 }).цвет === "🔴");
  ok("лежит и не продаётся — белый", M.светофор({ остаток: 50, свободно: 50, вДень: 0 }).цвет === "⚪");
  ok("запаса много — зелёный",
    M.светофор({ остаток: 500, свободно: 500, вДень: 1, хватитДней: 500, срокДней: 30, точкаЗаказа: 37 }).цвет === "🟢");
  ok("подошёл к точке заказа — жёлтый",
    M.светофор({ остаток: 30, свободно: 30, вДень: 1, хватитДней: 30, срокДней: 7, точкаЗаказа: 37 }).цвет === "🟡");
}

{
  // Без продаж и без срока поставки агент не советует, а перечисляет,
  // чего не хватает.
  const п = M.прогноз({ остаток: 5, скорость30: 0, срокДней: null });
  ok("без продаж рекомендации нет", п.рекомендовано === null);
  ok("названы обе нехватки", п.нет.includes("нет продаж за 90 дней") && п.нет.includes("неизвестен срок поставки"));
}

{
  // Самая свежая скорость берётся самой осторожной: товар разогнался
  // за неделю — считаем по ней, а не по спокойному кварталу.
  const п = M.прогноз({ остаток: 100, скорость7: 10, скорость30: 2, скорость90: 1, срокДней: 10 });
  ok("берётся наибольшая из скоростей", п.вДень === 10);
  ok("запас в днях по быстрой скорости", п.хватитДней === 10);
}

// ======================================================================
//  6. КОРОТКАЯ ИСТОРИЯ: СЕЗОН И ПРОШЛЫЙ ГОД НЕ СЧИТАЮТСЯ
// ======================================================================
{
  const г = M.глубинаИстории(продажи);
  ok("глубина истории считается по выданным накладным", г.дней === 198);

  const сезон = M.сезонныйКоэффициент(продажи, СЕЙЧАС);
  ok("сезонный коэффициент при короткой истории не выдумывается",
    сезон.известен === false && сезон.коэффициент === 1 && /истории 198 дн/.test(сезон.причина));

  const сравн = M.сравнитьСПрошлымГодом(продажи, M.диапазон("месяц", { когда: СЕЙЧАС }), { курсы });
  ok("сравнение с прошлым годом честно отказано", сравн.хватает === false && /прошлым годом/.test(сравн.причина));
}

// ======================================================================
//  7. ПЕРИОДЫ ПО ТАШКЕНТУ
// ======================================================================
{
  const д = M.диапазон("день", { когда: СЕЙЧАС });
  ok("день начинается в полночь по Ташкенту", new Date(д.от).toISOString() === "2026-11-22T19:00:00.000Z");

  const н = M.диапазон("неделя", { когда: СЕЙЧАС });
  // 23 ноября 2026 — понедельник, значит неделя началась в этот же день.
  ok("неделя начинается с понедельника", new Date(н.от).toISOString() === "2026-11-22T19:00:00.000Z");

  const м = M.диапазон("месяц", { когда: СЕЙЧАС });
  ok("месяц — с первого числа", new Date(м.от).toISOString() === "2026-10-31T19:00:00.000Z");

  const к = M.диапазон("квартал", { когда: СЕЙЧАС });
  ok("квартал — с октября", new Date(к.от).toISOString() === "2026-09-30T19:00:00.000Z");

  const с = M.диапазон("сезон", { когда: СЕЙЧАС });
  ok("ноябрь — это осень", с.имя === "сезон · осень");

  // Зима перескакивает через новый год: январь принадлежит зиме,
  // которая началась в декабре прошлого года.
  const зима = M.диапазон("сезон", { когда: Date.parse("2027-01-15T06:00:00Z") });
  ok("январь относится к зиме, начавшейся в декабре",
    зима.имя === "сезон · зима" && new Date(зима.от).toISOString() === "2026-11-30T19:00:00.000Z");

  ok("свой период с перепутанными границами отвергается",
    M.диапазон("свой", { от: СЕЙЧАС, до: СЕЙЧАС - СУТКИ }) === null);
  ok("непонятный вид периода отвергается", M.диапазон("пятилетка") === null);
}

// ======================================================================
//  8. КЛАССЫ ТОВАРОВ
// ======================================================================
{
  const кл = M.классы(продажи, { сейчас: СЕЙЧАС, курсы });
  ok("постоянный — тот, что продавался в разные дни", кл.постоянные.some((x) => x.id === "p1"));
  ok("разовая продажа постоянным не считается", !кл.постоянные.some((x) => x.id === "p2"));
  ok("за полгода не продавался — мёртвый", кл.мёртвые.every((x) => x.id !== "p1"));
  ok("прибыльные отсортированы по прибыли",
    кл.прибыльные.every((x, i, a) => i === 0 || a[i - 1].прибыльUSD >= x.прибыльUSD));
}

// ======================================================================
//  9. КУРСЫ ИЗ НАСТРОЕК
// ======================================================================
{
  const к = M.курсыИзНастроек({ rate_yuan_usd: 7.1, rate_som_usd: 12600 });
  ok("курс переворачивается в «долларов за единицу»",
    Math.abs(к.yuan - 1 / 7.1) < 1e-12 && Math.abs(к.som - 1 / 12600) < 1e-15);
  ok("пустые настройки не дают деления на ноль",
    M.курсыИзНастроек({}).yuan === 0 && M.вUSD(100, "yuan", M.курсыИзНастроек({})) === 0);
}

// ======================================================================
//  10. ШЕСТЬ ЛИСТОВ ПЛАНА ЗАКУПКИ
//
//  Колонки файла описаны в браузерном js/xlsx-export.js, а строки
//  приходят от агента. Если эти два списка разойдутся, колонка в Excel
//  молча опустеет — поэтому сверяем их прямо здесь.
// ======================================================================
{
  const { листы } = await import(new URL("api/lib/agents/warehouse.js", корень));
  const { ЗАКУПКА_КОЛОНКИ } = await import(new URL("js/xlsx-export.js", корень));

  const строка = (о) => ({
    id: о.id, код: о.код, имя: о.имя, категория: "", остаток: о.остаток ?? 0, свободно: о.остаток ?? 0,
    резерв: 0, вПути: 0, вДень: о.вДень ?? 0, хватитДней: о.хватитДней ?? null,
    точкаЗаказа: null, рекомендовано: о.рекомендовано ?? 0, поставщик: "Кампир",
    срокДней: 39, срокОткуда: "история", ценаUSD: 10, себестUSD: о.себестUSD ?? 5,
    цвет: о.цвет, состояние: о.состояние, пояснение: "", нет: [],
    продаж30: о.продаж30 ?? 0, кончится: "2026-12-01", приоритет: "Срочно", причина: "почему",
  });

  const строки = [
    строка({ id: "a", код: "AP-052", имя: "Кончился ходовой", остаток: 0, вДень: 2, продаж30: 60, цвет: "🔴", состояние: "нет", рекомендовано: 100 }),
    строка({ id: "b", код: "LP-001", имя: "Кончится раньше поставки", остаток: 5, вДень: 1, хватитДней: 5, продаж30: 30, цвет: "🟠", состояние: "срочно", рекомендовано: 50 }),
    строка({ id: "c", код: "LP-002", имя: "Пора заказывать", остаток: 40, вДень: 1, хватитДней: 40, продаж30: 30, цвет: "🟡", состояние: "пора", рекомендовано: 10 }),
    строка({ id: "d", код: "NJ-001", имя: "Хватает надолго", остаток: 900, вДень: 1, хватитДней: 900, продаж30: 30, цвет: "🟢", состояние: "хватает" }),
    строка({ id: "e", код: "NJ-002", имя: "Кончится через три недели", остаток: 21, вДень: 1, хватитДней: 21, продаж30: 30, цвет: "🟢", состояние: "хватает" }),
    строка({ id: "f", код: "SV-001", имя: "Лежит без движения", остаток: 300, вДень: 0, цвет: "⚪", состояние: "стоит", себестUSD: 2 }),
    строка({ id: "g", код: "SV-002", имя: "Нет и не продаётся", остаток: 0, вДень: 0, цвет: "🔴", состояние: "нет" }),
  ];

  const л = листы(строки, {
    сезон: { известен: false, причина: "истории 198 дн., для сезонности нужно от 400 дн." },
    история: { дней: 198, от: Date.parse("2026-05-22T00:00:00Z") },
    сроки: [{ поставщик: "Кампир", дней: 39, поставок: 3, надёжно: true }],
    цвета: { "🔴": 2, "🟠": 1, "🟡": 1, "🟢": 2, "⚪": 1 },
    кл: { постоянные: [1, 2], частые: [1], мёртвые: [], просевшие: [], новые: [] },
  });

  ok("в срочную попали кончившийся ходовой и тот, что не дождётся поставки",
    л.срочная.map((с) => с.код).sort().join() === "AP-052,LP-001");
  ok("кончившийся и не продающийся в срочную не попал", !л.срочная.some((с) => с.код === "SV-002"));
  ok("в «скоро» попали точка заказа и трёхнедельный запас",
    л.скоро.map((с) => с.код).sort().join() === "LP-002,NJ-002");
  ok("товар с запасом на 900 дней в «скоро» не попал", !л.скоро.some((с) => с.код === "NJ-001"));
  ok("сезонный лист пуст и объясняет почему",
    л.сезонная.length === 0 && /для сезонности нужно/.test(л.сезоннаяПричина));
  ok("в постоянных только то, что продавалось", л.постоянные.every((с) => с.продаж30 > 0));
  ok("медленные — только лежачие с остатком", л.медленные.map((с) => с.код).join() === "SV-001");
  ok("деньги на полке посчитаны", л.аналитика.деньгиНаПолке === 600);
  ok("аналитика несёт глубину истории", л.аналитика.историяДней === 198 && л.аналитика.историяОт === "2026-05-22");

  // Главная сверка: каждой колонке файла есть что показать.
  const поля = new Set(Object.keys(строки[0]));
  const осиротевшие = ЗАКУПКА_КОЛОНКИ
    .map((к) => к.ключ)
    .filter((к) => к !== "сумма" && !поля.has(к));   // «сумма» считается формулой в самом Excel
  ok("каждая колонка Excel имеет пару в строках агента" + (осиротевшие.length ? ": нет " + осиротевшие.join(", ") : ""),
    осиротевшие.length === 0);
  ok("колонок столько, сколько ждёт вёрстка листа", ЗАКУПКА_КОЛОНКИ.length === 16);
}

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
