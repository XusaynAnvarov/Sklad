// ========================================================================
//  ОПРИХОДОВАНИЕ ПРИХОДА.  node _tools/tests/t-arrival.mjs
//
//  Сентябрь 2026: приход JACK на 43 позиции писался по одному товару,
//  почти минуту. Владелец решил, что зависло, и нажал «Оприходовать»
//  второй раз — 30 позиций легли на склад дважды, 9 не легли вовсе,
//  а сам приход так и остался «в дороге».
//  Поэтому: повторное нажатие не задваивает, прерванный приход
//  дописывается, откат убирает ровно то, что положил этот приход.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const A = await import(new URL("js/arrival.js", корень));
const { consumeFIFO, sumQty } = await import(new URL("js/inventory.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const товар = (id, name, stock, batches) => ({ id, name, stock_qty: stock, batches: batches || [], cost_yuan: 10, cost_usd: 1.4 });
const приход = (items, доп = {}) => ({ id: "пр-1", supplier: "JACK", currency: "yuan", date: "2026-09-03T05:55:27.072Z", kind: "supplier", items, ...доп });

// ---------- обычное оприходование ----------
{
  const товары = [товар("t1", "Лапка", 5, [{ qty: 5, cost_yuan: 8, cost_usd: 1.1, date: "2026-08-01" }]), товар("t2", "Нож", 0, [])];
  const п = приход([{ product_id: "t1", qty: 20, unit_cost: 34, currency: "yuan" }, { product_id: "t2", qty: 10, unit_cost: 5, currency: "yuan" }]);
  const rows = A.arrivalRows(п, товары);
  ok("строка на каждый товар", rows.length === 2);
  ok("остаток вырос: 5 + 20 = 25", rows[0].stock_qty === 25 && rows[1].stock_qty === 10);
  ok("новая партия помечена номером прихода", rows.every(r => r.batches.at(-1).src === "пр-1"));
  ok("старая партия не тронута", rows[0].batches[0].qty === 5 && rows[0].batches[0].src === undefined);
  ok("цена прихода записана в партию", rows[0].batches.at(-1).cost_yuan === 34);
  ok("себестоимость берётся по первой партии на полке (FIFO)", rows[0].cost_yuan === 8);
}

// ---------- повторное нажатие ----------
{
  const товары = [товар("t1", "Лапка", 5, []), товар("t2", "Нож", 0, [])];
  const п = приход([{ product_id: "t1", qty: 20, unit_cost: 34 }, { product_id: "t2", qty: 10, unit_cost: 5 }]);
  const первый = A.arrivalRows(п, товары);
  // записали в базу — карточки товаров стали такими
  const послеЗаписи = первый.map(r => ({ ...товары.find(p => p.id === r.id), ...r }));
  const второй = A.arrivalRows(п, послеЗаписи);
  ok("второе нажатие ничего не добавляет", второй.length === 0);
  ok("остаток не задвоился", послеЗаписи[0].stock_qty === 25);
}

// ---------- приход оборвался на середине ----------
{
  const товары = [товар("t1", "Лапка", 0, []), товар("t2", "Нож", 0, []), товар("t3", "Улитка", 0, [])];
  const п = приход([{ product_id: "t1", qty: 20, unit_cost: 34 }, { product_id: "t2", qty: 10, unit_cost: 5 }, { product_id: "t3", qty: 7, unit_cost: 9 }]);
  const rows = A.arrivalRows(п, товары);
  // до базы дошёл только первый товар — как в приходе JACK
  const состояние = [{ ...товары[0], ...rows[0] }, товар("t2", "Нож", 0, []), товар("t3", "Улитка", 0, [])];
  const добор = A.arrivalRows(п, состояние);
  ok("дописываются только недошедшие позиции", добор.length === 2 && добор.map(r => r.id).join() === "t2,t3");
  ok("уже зачисленный товар второй раз не трогается", !добор.some(r => r.id === "t1"));
}

// ---------- откат «−1 оприходование» ----------
{
  const товары = [товар("t1", "Лапка", 5, [{ qty: 5, cost_yuan: 8, cost_usd: 1.1, date: "2026-08-01" }])];
  const п = приход([{ product_id: "t1", qty: 20, unit_cost: 34 }]);
  // положили дважды (как получилось у JACK)
  const r1 = A.arrivalRows(п, товары);
  const дважды = [{ ...товары[0], ...r1[0], batches: [...r1[0].batches, { qty: 20, cost_yuan: 34, cost_usd: 4.8, date: "2026-09-03", src: "пр-1" }] }];
  дважды[0].stock_qty = sumQty(дважды[0].batches);
  ok("до отката остаток 45", дважды[0].stock_qty === 45);
  const назад = A.откатитьПриход(п, дважды, consumeFIFO);
  ok("после отката остаток 25 — лишнее ушло", назад[0].stock_qty === 25);
  ok("осталась одна партия этого прихода", назад[0].batches.filter(b => b.src === "пр-1").length === 1);
  ok("старая партия на месте", назад[0].batches[0].qty === 5);
  // ещё один откат — убирает и вторую
  const ещё = A.откатитьПриход(п, [{ ...дважды[0], ...назад[0] }], consumeFIFO);
  ok("второй откат убирает и последнюю партию прихода", ещё[0].stock_qty === 5 && !ещё[0].batches.some(b => b.src === "пр-1"));
}

// ---------- старый приход без меток ----------
{
  const товары = [товар("t1", "Лапка", 30, [{ qty: 30, cost_yuan: 8, cost_usd: 1.1, date: "2026-07-01" }])];
  const старый = приход([{ product_id: "t1", qty: 20, unit_cost: 34 }], { id: "старый" });
  const назад = A.откатитьПриход(старый, товары, consumeFIFO);
  ok("без меток списываем количество позиции, как раньше", назад[0].stock_qty === 10);
}

// ---------- приход гасит долг ----------
{
  const товары = [товар("t1", "Лапка", -6, [{ qty: -6, cost_yuan: 8, cost_usd: 1.1, date: "2026-08-20" }])];
  const п = приход([{ product_id: "t1", qty: 20, unit_cost: 34 }]);
  const rows = A.arrivalRows(п, товары);
  ok("долг закрыт, на полке 14", rows[0].stock_qty === 14);
  ok("долговая партия исчезла, осталась одна новая", rows[0].batches.length === 1 && rows[0].batches[0].src === "пр-1");
}

// ---------- запись пачкой ----------
{
  const rows = [{ id: "a", stock_qty: 1, batches: [] }, { id: "b", stock_qty: 2, batches: [] }];
  let пачкой = 0, поодиночке = 0;
  const db = { products: { async upsertMany(r) { пачкой++; return r; }, async upsert() { поодиночке++; } } };
  await A.записатьПачкой(db, rows);
  ok("одним запросом, а не по одному", пачкой === 1 && поодиночке === 0);

  // база не знает колонку batches → повтор без неё
  let сПартиями = 0, безПартий = 0;
  const db2 = { products: {
    async upsertMany(r) { if (r[0].batches) { сПартиями++; throw new Error("нет колонки batches"); } безПартий++; return r; },
    async upsert() { поодиночке++; },
  } };
  await A.записатьПачкой(db2, rows);
  ok("не прошло с партиями — повторяем без них", сПартиями === 1 && безПартий === 1);

  // пакет не работает вовсе → по одному, с показом хода
  const шаги = [];
  const db3 = { products: { async upsertMany() { throw new Error("нет"); }, async upsert() { } } };
  await A.записатьПачкой(db3, rows, (готово, всего) => шаги.push(`${готово}/${всего}`));
  ok("иначе по одному и видно ход: " + шаги.join(" "), шаги.join(" ") === "1/2 2/2");

  // совсем не записалось — ошибка должна дойти до владельца
  const db4 = { products: { async upsertMany() { throw new Error("нет"); }, async upsert() { throw new Error("база недоступна"); } } };
  let ошибка = "";
  try { await A.записатьПачкой(db4, rows); } catch (e) { ошибка = e.message; }
  ok("об ошибке записи сообщаем, а не молчим", ошибка === "база недоступна");
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nОПРИХОДОВАНИЕ В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
