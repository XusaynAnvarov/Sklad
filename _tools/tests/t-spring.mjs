// ========================================================================
//  ПРУЖИНА И БРОСОК.  node _tools/tests/t-spring.mjs
//
//  Владелец: «сделай анимации плавными, чтобы фото тянулось за пальцем и
//  движение можно было поймать на лету».
//
//  Проверяется расчёт, на котором это держится:
//    • пружина доходит до цели и останавливается, без отскока;
//    • при затухании меньше единицы отскок есть (для броска);
//    • цель можно поменять на ходу — скорость при этом не теряется,
//      именно это и даёт перехват без рывка;
//    • бросок долетает туда, куда летел, а не до ближайшей точки;
//    • на краю сопротивление растёт, и элемент не уходит в бесконечность.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { пустить, проекция, резинка } = await import(new URL("js/spring.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

// Прокрутить пружину «во времени» без браузера.
const прокрутить = (п, секунд, шаг = 1 / 120) => {
  let где = п.где();
  for (let t = 0; t < секунд; t += шаг) где = п.шаг(шаг);
  return где;
};

// ---------- 1. Доходит и останавливается ----------
{
  const п = пустить({ от: 0, к: 100, затухание: 1, отклик: 0.4, шагВремени: true });
  const где = прокрутить(п, 1.2);
  ok("пружина доходит до цели", Math.abs(где - 100) < 1);
  ok("и останавливается", Math.abs(п.скорость()) < 2);
}

// ---------- 2. Без отскока при затухании 1 ----------
{
  const п = пустить({ от: 0, к: 100, затухание: 1, отклик: 0.4, шагВремени: true });
  let максимум = 0;
  for (let t = 0; t < 1.2; t += 1 / 120) максимум = Math.max(максимум, п.шаг(1 / 120));
  ok("при затухании 1 цель не перелетает", максимум <= 100.5);
}

// ---------- 3. С отскоком при затухании 0.8 ----------
{
  const п = пустить({ от: 0, к: 100, затухание: 0.7, отклик: 0.4, шагВремени: true });
  let максимум = 0;
  for (let t = 0; t < 1.2; t += 1 / 120) максимум = Math.max(максимум, п.шаг(1 / 120));
  ok("при затухании меньше единицы есть отскок", максимум > 101);
}

// ---------- 4. Скорость броска подхватывается ----------
{
  const стоя = пустить({ от: 0, к: 100, скорость: 0, затухание: 1, отклик: 0.4, шагВремени: true });
  const сразбегу = пустить({ от: 0, к: 100, скорость: 600, затухание: 1, отклик: 0.4, шагВремени: true });
  const а = прокрутить(стоя, 0.1), б = прокрутить(сразбегу, 0.1);
  ok("брошенное уходит дальше, чем отпущенное на месте", б > а + 10);
}

// ---------- 5. Перехват: цель меняется, скорость остаётся ----------
{
  const п = пустить({ от: 0, к: 300, затухание: 1, отклик: 0.4, шагВремени: true });
  прокрутить(п, 0.2);
  const доПерехвата = п.где();
  const скоростьДо = п.скорость();
  п.кЦели(0);                       // поймали на лету и отправили обратно
  const сразуПосле = п.где();
  ok("перехват не двигает элемент рывком", Math.abs(сразуПосле - доПерехвата) < 0.001);
  ok("скорость в момент перехвата сохраняется", Math.abs(п.скорость() - скоростьДо) < 0.001);
  ok("и дальше возвращается к новой цели", Math.abs(прокрутить(п, 1.5) - 0) < 1);
}

// ---------- 6. Куда долетит бросок ----------
{
  ok("медленный бросок почти не уносит", Math.abs(проекция(50)) < 60);
  ok("быстрый бросок уносит далеко", проекция(2000) > 900);
  ok("бросок влево уносит влево", проекция(-2000) < -900);
  ok("ноль скорости — ноль пути", проекция(0) === 0);
  // Школьная формула даёт другое число — проверяем, что взята именно
  // экспоненциальная, как у Apple.
  ok("формула экспоненциальная, а не школьная", Math.abs(проекция(1000) - 499) < 2);
}

// ---------- 7. Сопротивление на краю ----------
{
  const малый = резинка(10, 400), большой = резинка(200, 400);
  ok("малый перелёт почти свободен", малый > 5 && малый < 10);
  ok("большой перелёт сильно придержан", большой < 200 * 0.8);
  ok("сопротивление растёт, а не падает", большой > малый);
  ok("за край влево — тоже придержано", резинка(-200, 400) > -200 * 0.8);
  ok("на границе ноль", резинка(0, 400) === 0);
}

console.log(плохо ? "\nПРОВАЛЕНО: " + плохо : "\nВсё хорошо");
process.exit(плохо ? 1 : 0);
