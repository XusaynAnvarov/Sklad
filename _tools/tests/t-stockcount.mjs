// ========================================================================
//  ПЕРЕСЧЁТ ПО ЛИСТУ EXCEL.  node _tools/tests/t-stockcount.mjs
//
//  Главное, что здесь проверяется: пустая клетка — это «не считал», а не
//  ноль. Владелец обходит 941 товар не за один день; если бы незаполненные
//  строки понимались как ноль, один загруженный лист обнулил бы склад.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { сверитьЛист, строкаПересчёта, число } = await import(new URL("js/stockcount.js", корень));
const { sumQty } = await import(new URL("js/inventory.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const товар = (id, name, stock_qty, доп = {}) => ({ id, name, stock_qty, cost_yuan: 5, cost_usd: 0.7, batches: [{ qty: stock_qty, cost_yuan: 5, cost_usd: 0.7, date: "2026-08-01" }], ...доп });
const склад = [
  товар("1", "Лапка сборка P952", 280, { code: "LP-017", sku: "KDP-10" }),
  товар("2", "Кайчи (10) KDP", 20, { code: "PN-003" }),
  товар("3", "Кайчи (11) KDP", 4, { code: "PN-004" }),
  товар("4", "Лижа (Оддий)", 580),
];

// ---------- пустые клетки не обнуляют склад ----------
{
  const r = сверитьЛист([
    { code: "LP-017", name: "Лапка сборка P952", факт: "" },
    { code: "PN-003", name: "Кайчи (10) KDP", факт: null },
    { code: "PN-004", name: "Кайчи (11) KDP", факт: undefined },
    { code: "", name: "Лижа (Оддий)", факт: "   " },
  ], склад);
  ok("пустой лист ничего не меняет", r.расхождения.length === 0 && r.пустые === 4 && r.посчитано === 0);
}

// ---------- ноль — это именно ноль ----------
{
  const r = сверитьЛист([{ code: "PN-003", name: "Кайчи (10) KDP", факт: 0 }], склад);
  ok("вписанный 0 считается", r.расхождения.length === 1 && r.расхождения[0].факт === 0 && r.расхождения[0].разница === -20);
}

// ---------- сопоставление: код важнее названия ----------
{
  // в названии опечатка, но код верный — должен найтись по коду
  const r = сверитьЛист([{ code: "PN-004", name: "Кайчи 11 KDP (не то имя)", факт: 10 }], склад);
  ok("нашли по коду, не по имени", r.расхождения.length === 1 && r.расхождения[0].p.id === "3");
}
{
  const r = сверитьЛист([{ code: "", sku: "kdp-10", name: "", факт: 300 }], склад);
  ok("нашли по артикулу без учёта регистра", r.расхождения.length === 1 && r.расхождения[0].p.id === "1");
}
{
  const r = сверитьЛист([{ code: "", sku: "", name: "  лижа (оддий)  ", факт: 500 }], склад);
  ok("нашли по имени без учёта регистра и пробелов", r.расхождения.length === 1 && r.расхождения[0].p.id === "4");
}
{
  const r = сверитьЛист([{ code: "ZZ-999", name: "Товар, которого нет", факт: 5 }], склад);
  ok("чужая строка попадает в «не найдено»", r.ненайденные.length === 1 && r.расхождения.length === 0);
}

// ---------- повторы берутся один раз ----------
{
  const r = сверитьЛист([
    { code: "PN-003", name: "Кайчи (10) KDP", факт: 15 },
    { code: "PN-003", name: "Кайчи (10) KDP", факт: 7 },
  ], склад);
  ok("второй раз тот же товар не считаем", r.расхождения.length === 1 && r.расхождения[0].факт === 15 && r.повторы.length === 1);
}

// ---------- совпало и разошлось ----------
{
  const r = сверитьЛист([
    { code: "LP-017", факт: 280 },           // сошлось
    { code: "PN-003", факт: 18 },            // −2
    { code: "PN-004", факт: 9 },             // +5
    { code: "", name: "Лижа (Оддий)", факт: "" },
  ], склад);
  ok("счётчики верные", r.совпало === 1 && r.расхождения.length === 2 && r.пустые === 1);
  ok("сначала крупное расхождение", r.расхождения[0].разница === 5 && r.расхождения[1].разница === -2);
}

// ---------- числа из клеток Excel ----------
{
  ok("«1 200» → 1200", число("1 200") === 1200);
  ok("«12,5» → 12.5", число("12,5") === 12.5);
  ok("текст не число", число("много") === null && число("—") === null);
  ok("ноль не путается с пустотой", число(0) === 0 && число("") === null);
}

// ---------- что записываем ----------
{
  const p = товар("5", "Калиш 120", 100);
  const r = строкаПересчёта(p, 60);
  ok("вниз — остаток станет фактом", r.stock_qty === 60 && sumQty(r.batches) === 60);
  const r2 = строкаПересчёта(p, 130);
  ok("вверх — остаток станет фактом", r2.stock_qty === 130 && sumQty(r2.batches) === 130);
  ok("цена не поехала", r2.cost_yuan === 5);
  ok("сошлось — писать нечего", строкаПересчёта(p, 100) === null);
  ok("исходный товар не испорчен", p.stock_qty === 100 && p.batches[0].qty === 100);
}

// ---------- долг внутри партий закрывается ----------
{
  const p = { id: "6", name: "Дазмол крышка", stock_qty: 0, cost_yuan: 3, cost_usd: 0.4,
    batches: [{ qty: 20, cost_yuan: 3 }, { qty: -20, cost_yuan: 3, shortage: true }] };
  const r = строкаПересчёта(p, 12);
  const минус = r.batches.filter(b => b.qty < 0).length;
  ok("вписали 12 — внутри нет долга", r.stock_qty === 12 && минус === 0);
}

// ---------- товар без партий (старая карточка) ----------
{
  const p = { id: "7", name: "Старый товар", stock_qty: 30, cost_yuan: 4, cost_usd: 0.6 };
  const r = строкаПересчёта(p, 25);
  ok("карточка без партий пересчитывается", r.stock_qty === 25 && sumQty(r.batches) === 25);
}

// ---------- разбор колонок листа (xlsx-import) ----------
{
  const { normalize } = await import(new URL("js/xlsx-import.js", корень));
  const r = normalize({ "Код": "LP-017", "Артикул": "KDP-10", "Товар": "Лапка сборка P952", "Раздел": "Лапки", "Остаток в складе": 280, "Факт на полке": "" }, "count");
  ok("лист читается как выгрузили", r && r.code === "LP-017" && r.sku === "KDP-10" && r.name === "Лапка сборка P952");
  ok("пустая клетка не стала нулём", r.факт === "" && число(r.факт) === null);

  const r2 = normalize({ "код": "PN-003", "товар": "Кайчи (10) KDP", "факт": "15" }, "count");
  ok("короткий заголовок «Факт» тоже понимаем", r2 && число(r2.факт) === 15);

  const r3 = normalize({ "Код": "PN-004", "Товар": "", "Факт на полке": 9 }, "count");
  ok("строка без имени читается по коду", r3 && r3.code === "PN-004" && число(r3.факт) === 9);

  const r4 = normalize({ "Товар": "Лижа (Оддий)", "По факту": "0" }, "count");
  ok("синоним «По факту» понимаем, 0 сохраняется", r4 && число(r4.факт) === 0);

  // весь путь целиком: лист → разбор → сверка → строки для записи
  const лист = [
    { "Код": "LP-017", "Товар": "Лапка сборка P952", "Факт на полке": "" },
    { "Код": "PN-003", "Товар": "Кайчи (10) KDP", "Факт на полке": "18" },
    { "Код": "PN-004", "Товар": "Кайчи (11) KDP", "Факт на полке": 9 },
  ].map(r => normalize(r, "count"));
  const итог = сверитьЛист(лист, склад);
  const строки = итог.расхождения.map(r => строкаПересчёта(r.p, r.факт));
  ok("путь лист → склад даёт верные числа",
    итог.пустые === 1 && строки.length === 2
    && строки.find(s => s.id === "2").stock_qty === 18
    && строки.find(s => s.id === "3").stock_qty === 9);
}

console.log(плохо ? "\n❌ ошибок: " + плохо : "\n✅ всё сошлось");
process.exit(плохо ? 1 : 0);
