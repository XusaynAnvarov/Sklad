// ========================================================================
//  КОД ПО SMS (Eskiz.uz).  node _tools/tests/t-sms.mjs
//
//  Зачем SMS рядом с ботом:
//    • код из SMS телефон подставляет в поле САМ (autocomplete
//      "one-time-code"); для Telegram браузер такого не умеет;
//    • клиент без бота раньше не мог войти вовсе — была стена
//      «откройте @generalmodernbot».
//
//  Что здесь стережём. SMS стоят денег и уходят живым людям, поэтому
//  ошибиться тут дороже, чем обычно:
//    • пока доступы Eskiz не заданы — НИ ОДНОЙ отправки, вход работает
//      через Telegram, как раньше;
//    • номер приводится к виду, который ждёт оператор, а чужой формат
//      не отправляется вовсе;
//    • протухший токен обновляется сам, но ровно один раз — без
//      бесконечного круга запросов;
//    • отказ оператора не роняет вход: возвращаем { ok: false }, а не
//      исключение.
// ========================================================================

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const корень = new URL("../../", import.meta.url);
const { номерДляSMS, смсНастроены, каналКода, отправитьSMS } = await import(new URL("api/lib/sms.js", корень));
const { забыть } = await import(new URL("api/lib/memcache.js", корень));

// ---------- 1. Номер ----------
{
  ok("девять цифр → с кодом страны", номерДляSMS("901112233") === "998901112233");
  ok("уже с кодом страны — не трогаем", номерДляSMS("998901112233") === "998901112233");
  ok("из записи с плюсом и пробелами", номерДляSMS("+998 90 111 22 33") === "998901112233");
  ok("лишняя девятка впереди срезается", номерДляSMS("9998901112233") === "998901112233");
  ok("чужой формат не отправляем", номерДляSMS("12345") === "" && номерДляSMS("") === "");
  ok("мусор не отправляем", номерДляSMS("не телефон") === "");
}

// ---------- 2. Без доступов не шлём ничего ----------
{
  delete process.env.ESKIZ_EMAIL;
  delete process.env.ESKIZ_PASSWORD;
  let запросов = 0;
  globalThis.fetch = async () => { запросов++; throw new Error("сюда ходить не должны"); };
  ok("без доступов считаемся ненастроенными", смсНастроены() === false);
  const р = await отправитьSMS("901112233", "тест");
  ok("без доступов не отправляем", р.ok === false && запросов === 0);
  ok("и честно говорим почему", /не настроены/i.test(р.error));
}

// ---------- 3. Канал по умолчанию ничего не ломает ----------
{
  delete process.env.CODE_CHANNEL;
  ok("по умолчанию канал — Telegram", каналКода() === "telegram");
  process.env.CODE_CHANNEL = "sms";       ok("можно выбрать sms", каналКода() === "sms");
  process.env.CODE_CHANNEL = "both";      ok("можно выбрать оба", каналКода() === "both");
  process.env.CODE_CHANNEL = "ерунда";    ok("чепуха в настройке → Telegram", каналКода() === "telegram");
  delete process.env.CODE_CHANNEL;
}

// ---------- поддельный Eskiz ----------
function оператор({ токен = "ТОКЕН", падатьНа401 = false } = {}) {
  const з = { входов: 0, отправок: 0, последняя: null, заголовки: [], отказов: 0 };
  let протух = падатьНа401;
  globalThis.fetch = async (url, opt = {}) => {
    const u = String(url);
    const поля = Object.fromEntries(new URLSearchParams(opt.body || ""));
    if (u.endsWith("/api/auth/login")) {
      з.входов++;
      з.почта = поля.email; з.пароль = поля.password;
      // Свежим токен становится только после того, как старый отказал:
      // иначе первая же отправка проходила бы, и случай «токен протух»
      // не проверялся бы вовсе.
      if (з.отказов > 0) протух = false;
      return { ok: true, status: 200, text: async () => JSON.stringify({ data: { token: токен } }) };
    }
    if (u.endsWith("/api/message/sms/send")) {
      з.заголовки.push(opt.headers?.Authorization || "");
      if (протух) return { ok: false, status: 401, text: async () => JSON.stringify({ message: "Unauthenticated" }) };
      з.отправок++; з.последняя = поля;
      return { ok: true, status: 200, text: async () => JSON.stringify({ id: "7" }) };
    }
    throw new Error("неожиданный адрес: " + u);
  };
  return з;
}
const чисто = () => забыть("eskiz:");

// ---------- 4. Обычная отправка ----------
{
  чисто();
  process.env.ESKIZ_EMAIL = "sklad@generalmodern.uz";
  process.env.ESKIZ_PASSWORD = "секрет";
  process.env.ESKIZ_FROM = "4546";
  const з = оператор();
  const р = await отправитьSMS("901112233", "Kod: 481294");
  ok("SMS ушла", р.ok === true);
  ok("сначала вошли, потом отправили", з.входов === 1 && з.отправок === 1);
  ok("номер в виде оператора", з.последняя.mobile_phone === "998901112233");
  ok("текст передан как есть", з.последняя.message === "Kod: 481294");
  ok("отправитель из настройки", з.последняя.from === "4546");
  ok("токен в заголовке", з.заголовки[0] === "Bearer ТОКЕН");

  // Второй раз логиниться незачем: токен живёт в памяти сервера.
  await отправитьSMS("901112233", "ещё");
  ok("повторно в кабинет не ходим", з.входов === 1 && з.отправок === 2);
}

// ---------- 5. Протухший токен ----------
{
  чисто();
  const з = оператор({ падатьНа401: true });
  const р = await отправитьSMS("901112233", "Kod: 000111");
  ok("при отказе 401 берём токен заново и отправляем", р.ok === true);
  ok("вошли ровно дважды, не по кругу", з.входов === 2);
  ok("и отправили один раз", з.отправок === 1);
}

// ---------- 6. Оператор отказал — вход не роняем ----------
{
  чисто();
  globalThis.fetch = async (url) => {
    const u = String(url);
    if (u.endsWith("/api/auth/login")) return { ok: true, status: 200, text: async () => JSON.stringify({ data: { token: "Т" } }) };
    return { ok: false, status: 400, text: async () => JSON.stringify({ message: "Шаблон не утверждён" }) };
  };
  const р = await отправитьSMS("901112233", "что-то");
  ok("отказ оператора не бросает исключение", р.ok === false);
  ok("причину передаём наверх", /Шаблон не утверждён/.test(р.error));
}

// ---------- 7. Сеть упала ----------
{
  чисто();
  globalThis.fetch = async () => { throw new Error("сеть недоступна"); };
  const р = await отправитьSMS("901112233", "что-то");
  ok("при обрыве сети не падаем", р.ok === false && typeof р.error === "string");
}

// ---------- 8. Чужой номер денег не тратит ----------
{
  чисто();
  let запросов = 0;
  globalThis.fetch = async () => { запросов++; return { ok: true, status: 200, text: async () => "{}" }; };
  const р = await отправитьSMS("12345", "Kod: 1");
  ok("на кривой номер не отправляем", р.ok === false && запросов === 0);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nКОД ПО SMS В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
