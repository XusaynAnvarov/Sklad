// ========================================================================
//  ВОЗВРАТ ОТ КЛИЕНТА.  node _tools/tests/t-refund.mjs
//
//  Владелец: «у каждого клиента должна быть кнопка возврата, чтобы сразу
//  минусовать возврат и товар автоматически возвращался на склад. А если
//  товар куплен давно и его нет в списке — вписать сумму, и тогда мы
//  становимся должны ему или даём вместо денег товар».
//
//  Возврат записывается накладной с минусом (source="refund"), поэтому
//  здесь проверяется ровно то, от чего зависят деньги и склад:
//  сколько можно вернуть, на сколько упадёт долг и что уйдёт в товары.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { покупки, составить, этоВозврат, ВОЗВРАТ } = await import(new URL("js/refund.js", корень));
const { sumQty } = await import(new URL("js/inventory.js", корень));
const { debtByCur, onlyPositive, advance } = await import(new URL("js/debt.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const товар = (id, name, stock, цена = 5) => ({
  id, name, stock_qty: stock, cost_yuan: цена, cost_usd: цена * 0.14,
  batches: stock > 0 ? [{ qty: stock, cost_yuan: цена, cost_usd: цена * 0.14, date: "2026-08-01" }] : [],
});
const продажа = (id, когда, items, статус = "final") => ({
  id, customer_id: "c1", date: когда, status: статус, currency: "som", items,
});

const склад = [товар("1", "Лапка P952", 100), товар("2", "Нож KR23", 50, 3)];

// ---------- что клиент покупал ----------
{
  const sales = [
    продажа("s1", "2026-06-01", [{ product_id: "1", qty: 10, unit_price: 20000, currency: "som", cogs_yuan: 50 }]),
    продажа("s2", "2026-09-01", [{ product_id: "1", qty: 5, unit_price: 22000, currency: "som", cogs_yuan: 25 },
                                  { product_id: "2", qty: 3, unit_price: 10000, currency: "som" }]),
  ];
  const п = покупки(sales, "c1", склад);
  const лапка = п.find(x => x.product_id === "1");
  ok("видно всё, что купил", п.length === 2);
  ok("количество сложилось", лапка.куплено === 15);
  ok("цена берётся из последней продажи", лапка.цена === 22000);
  ok("себестоимость за штуку посчитана", лапка.cogs_yuan === 5);
  ok("вернуть можно всё купленное", лапка.осталось === 15);
}

// ---------- прошлый возврат уменьшает остаток к возврату ----------
{
  const sales = [
    продажа("s1", "2026-06-01", [{ product_id: "1", qty: 10, unit_price: 20000, currency: "som" }]),
    { id: "r1", customer_id: "c1", date: "2026-07-01", status: "final", source: "refund", currency: "som",
      items: [{ product_id: "1", qty: -4, unit_price: 20000, currency: "som" }] },
  ];
  const л = покупки(sales, "c1", склад).find(x => x.product_id === "1");
  ok("дважды одно и то же не вернёшь", л.куплено === 10 && л.возвращено === 4 && л.осталось === 6);
}

// ---------- заказы, которые не выдали, покупкой не считаются ----------
{
  const sales = [продажа("s9", "2026-10-01", [{ product_id: "1", qty: 7, unit_price: 20000 }], "order")];
  ok("неоформленный заказ не вернёшь", покупки(sales, "c1", склад).length === 0);
}

// ---------- возврат товара: склад и деньги ----------
{
  const { накладная, строки, сумма, ошибки } = составить({
    customer_id: "c1",
    товары: склад,
    позиции: [{ product_id: "1", qty: 3, unit_price: 20000, currency: "som", cogs_yuan: 5, cogs_usd: 0.7, name: "Лапка P952" }],
    дата: "2026-10-25T10:00:00Z",
  });
  ok("ошибок нет", ошибки.length === 0);
  ok("это возврат", этоВозврат(накладная) && накладная.source === ВОЗВРАТ);
  ok("накладная оформлена", накладная.status === "final");
  ok("количество с минусом", накладная.items[0].qty === -3);
  ok("себестоимость тоже с минусом", накладная.items[0].cogs_yuan === -15);
  ok("позиция помечена списанной", накладная.items[0].applied === true);
  ok("долг уменьшится на 60 000 сум", сумма.som === 60000);
  ok("товар вернулся на склад", строки.length === 1 && строки[0].stock_qty === 103);
  ok("партии сходятся с остатком", sumQty(строки[0].batches) === 103);
}

// ---------- возврат по нескольким товарам сразу ----------
{
  const { строки, сумма } = составить({
    customer_id: "c1", товары: склад,
    позиции: [
      { product_id: "1", qty: 2, unit_price: 20000, currency: "som", cogs_yuan: 5 },
      { product_id: "2", qty: 5, unit_price: 10000, currency: "som", cogs_yuan: 3 },
    ],
  });
  ok("оба товара вернулись", строки.length === 2);
  ok("сумма сложилась", сумма.som === 90000);
  ok("каждый товар на своём месте",
    строки.find(s => s.id === "1").stock_qty === 102 && строки.find(s => s.id === "2").stock_qty === 55);
}

// ---------- возврат в разных валютах не смешивается ----------
{
  const { сумма } = составить({
    customer_id: "c1", товары: склад,
    позиции: [
      { product_id: "1", qty: 1, unit_price: 20000, currency: "som" },
      { product_id: "2", qty: 2, unit_price: 6, currency: "yuan" },
    ],
  });
  ok("сум и юани считаются отдельно", сумма.som === 20000 && сумма.yuan === 12 && сумма.usd === 0);
}

// ---------- возврат ТОЛЬКО деньгами (товара нет в списке) ----------
{
  const { накладная, строки, сумма, ошибки } = составить({
    customer_id: "c1", товары: склад,
    позиции: [{ product_id: null, qty: 1, unit_price: 450000, currency: "som", name: "Возврат деньгами" }],
    причина: "старый товар, купленный до системы",
  });
  ok("склад не трогаем", строки.length === 0 && ошибки.length === 0);
  ok("долг уменьшится на 450 000", сумма.som === 450000);
  ok("в накладной видно, за что", накладная.items[0].name === "Возврат деньгами");
  ok("причина сохранена", накладная.order_from && накладная.order_from.причина.includes("старый товар"));
}

// ---------- деньги + принять товар на склад ----------
{
  const { строки, сумма } = составить({
    customer_id: "c1", товары: склад,
    позиции: [{ product_id: "2", qty: 4, unit_price: 112500, currency: "som", name: "Нож KR23" }],
  });
  ok("и деньги, и склад", сумма.som === 450000 && строки[0].stock_qty === 54);
}

// ---------- защита от ерунды ----------
{
  const { ошибки } = составить({ customer_id: "c1", товары: склад, позиции: [{ product_id: "1", qty: 0, unit_price: 100 }] });
  ok("ноль не принимаем", ошибки.length === 1);
}
{
  const { ошибки, строки } = составить({ customer_id: "c1", товары: склад, позиции: [{ product_id: "999", qty: 1, unit_price: 100, name: "Удалённый" }] });
  ok("удалённый товар — предупреждение, а не тишина", ошибки.length === 1 && строки.length === 0);
}
{
  const { ошибки } = составить({ customer_id: "c1", товары: склад, позиции: [{ product_id: "1", qty: 1, unit_price: 100, currency: "euro" }] });
  ok("чужая валюта не проходит", ошибки.length === 1);
}

// ---------- долг действительно падает (общий расчёт склада) ----------
{
  // купил на 200 000, ничего не платил
  const продажи = [продажа("s1", "2026-06-01", [{ product_id: "1", qty: 10, unit_price: 20000, currency: "som" }])];
  const клиент = { id: "c1" };
  const до = debtByCur(продажи, [], клиент);
  ok("был долг 200 000", Math.round(до.som) === 200000);

  // вернул половину
  const { накладная } = составить({
    customer_id: "c1", товары: склад,
    позиции: [{ product_id: "1", qty: 5, unit_price: 20000, currency: "som" }],
  });
  const после = debtByCur([...продажи, { ...накладная, id: "r9" }], [], клиент);
  ok("после возврата половины долг 100 000", Math.round(после.som) === 100000);

  // вернул больше, чем должен → мы должны ему
  const { накладная: большой } = составить({
    customer_id: "c1", товары: склад,
    позиции: [{ product_id: "1", qty: 12, unit_price: 20000, currency: "som" }],
  });
  const минус = debtByCur([...продажи, { ...большой, id: "r10" }], [], клиент);
  ok("вернули больше — мы должны клиенту 40 000",
    Math.round(onlyPositive(минус).som) === 0 && Math.round(advance(минус).som) === 40000);

  // «дадим вместо денег товар»: новая покупка съедает наш долг
  const новая = продажа("s2", "2026-10-26", [{ product_id: "2", qty: 4, unit_price: 10000, currency: "som" }]);
  const итог = debtByCur([...продажи, { ...большой, id: "r10" }, новая], [], клиент);
  ok("после выдачи товара остаёмся должны 0", Math.round(advance(итог).som) === 0 && Math.round(onlyPositive(итог).som) === 0);
}

// ---------- вернули деньгами: расчёт закрывается ----------
{
  const { выплаты, этоВыплата, ВЫПЛАТА } = await import(new URL("js/refund.js", корень));

  // купил на 200 000 и сразу заплатил — долга нет
  const продажи = [продажа("s1", "2026-06-01", [{ product_id: "1", qty: 10, unit_price: 20000, currency: "som" }])];
  const оплаты = [{ customer_id: "c1", amount: 200000, currency: "som", date: "2026-06-01" }];
  const клиент = { id: "c1" };
  ok("после оплаты долга нет", Math.round(debtByCur(продажи, оплаты, клиент).som) === 0);

  // вернул товар на 50 000
  const { накладная, сумма } = составить({
    customer_id: "c1", товары: склад,
    позиции: [{ product_id: "1", qty: 2, unit_price: 25000, currency: "som" }],
  });
  const сВозвратом = [...продажи, { ...накладная, id: "r1" }];
  ok("без выплаты мы должны клиенту 50 000", Math.round(advance(debtByCur(сВозвратом, оплаты, клиент)).som) === 50000);

  // отдали деньги на руки
  const выплата = выплаты({ customer_id: "c1", сумма, дата: "2026-10-25" });
  ok("выплата одна и в сумах", выплата.length === 1 && выплата[0].currency === "som");
  ok("сумма с минусом — деньги ушли", выплата[0].amount === -50000);
  ok("способ помечен", выплата[0].method === ВЫПЛАТА && этоВыплата(выплата[0]));
  ok("в комментарии видно, что это", выплата[0].note.includes("Возврат денег"));

  const итог = debtByCur(сВозвратом, [...оплаты, ...выплата], клиент);
  ok("после выплаты расчёт закрыт: ни долга, ни аванса",
    Math.round(onlyPositive(итог).som) === 0 && Math.round(advance(итог).som) === 0);
}

// ---------- выплата в нескольких валютах ----------
{
  const { выплаты } = await import(new URL("js/refund.js", корень));
  const строки = выплаты({ customer_id: "c1", сумма: { som: 30000, yuan: 12, usd: 0 } });
  ok("на каждую валюту своя строка", строки.length === 2);
  ok("нулевые валюты не записываем", !строки.some(s => s.currency === "usd"));
  ok("обе с минусом", строки.every(s => s.amount < 0));
}

console.log(плохо ? "\n❌ ошибок: " + плохо : "\n✅ всё сошлось");
process.exit(плохо ? 1 : 0);
