// ========================================================================
//  ДОЛГ ВНУТРИ ПАРТИЙ НЕ ОСТАЁТСЯ.  node _tools/tests/t-debt.mjs
//
//  6 октября 2026. На складе нашлось 16 товаров, у которых остаток 0 или
//  даже плюс, а внутри партий сидел минус: «Кулок (Арзони)» — остаток 0 и
//  долг −80, «Пинцет (JACK) учи кийшу» — остаток 40 и долг −20.
//  Долг появляется, когда товар продали, не имея его на складе. Сам остаток
//  при этом верен (это сумма партий), но consumeFIFO долговую партию
//  перешагивает: на полке «есть» товар, а внутри минус. Возврат кладёт товар
//  РЯДОМ с долгом и не гасит его — после пары возвратов и правок склад
//  начинал жить своей жизнью, и проданное будто возвращалось само.
//
//  Правило: как только появился живой товар, он гасит долг. Сумма партий
//  при гашении НЕ меняется — меняется только их устройство.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { погасить, returnToStock, consumeFIFO, sumQty, currentCost, сверитьСОстатком } = await import(new URL("js/inventory.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const минус = (b) => (b || []).filter(x => (Number(x.qty) || 0) < 0).reduce((a, x) => a + x.qty, 0);

// ---------- гашение не меняет остаток ----------
{
  const b = [{ qty: 20, cost_yuan: 5 }, { qty: -5, cost_yuan: 5, shortage: true }];
  const п = погасить(b);
  ok("остаток после гашения тот же", sumQty(п) === 15);
  ok("долга внутри больше нет", минус(п) === 0);
  ok("исходные партии не испорчены", b.length === 2 && b[1].qty === -5);
}

// ---------- долг больше прихода — остаётся только недостача ----------
{
  const п = погасить([{ qty: 4, cost_yuan: 3 }, { qty: -10, cost_yuan: 3, shortage: true }]);
  ok("покрыли частично — долг уменьшился", sumQty(п) === -6 && минус(п) === -6);
}

// ---------- возврат гасит долг ----------
{
  const п = returnToStock([{ qty: -10, cost_yuan: 3, shortage: true }], 4, 3, 0.4);
  ok("возврат 4 при долге 10 → долг 6", sumQty(п) === -6 && минус(п) === -6);
  const п2 = returnToStock([{ qty: -10, cost_yuan: 3, shortage: true }], 25, 3, 0.4);
  ok("возврат 25 при долге 10 → 15 живых", sumQty(п2) === 15 && минус(п2) === 0);
}

// ---------- возврат не прячет долг за новой партией ----------
{
  // так было до 6 октября: [+20, −20] — остаток 0, а внутри два встречных долга
  const п = returnToStock([{ qty: -20, cost_yuan: 3, shortage: true }], 20, 3, 0.4);
  ok("встречных партий не осталось", п.length === 0 && sumQty(п) === 0);
}

// ---------- сверка с остатком тоже гасит ----------
{
  const p = { stock_qty: 40, cost_yuan: 3, batches: [{ qty: -20, cost_yuan: 3, shortage: true }] };
  const b = сверитьСОстатком(p.batches, p);
  ok("сверка довела до 40 без скрытого долга", sumQty(b) === 40 && минус(b) === 0);
}

// ---------- после гашения FIFO и себестоимость честные ----------
{
  // дешёвая партия закрыта долгом, значит продаём дорогую — цена должна быть её
  const п = погасить([{ qty: 10, cost_yuan: 3 }, { qty: 10, cost_yuan: 9 }, { qty: -10, cost_yuan: 3, shortage: true }]);
  ok("осталась дорогая партия", sumQty(п) === 10 && currentCost(п).cost_yuan === 9);
  const r = consumeFIFO(п, 10);
  ok("списали по её цене", r.cogY === 90 && sumQty(r.batches) === 0);
}

console.log(плохо ? "\n❌ ошибок: " + плохо : "\n✅ всё сошлось");
process.exit(плохо ? 1 : 0);
