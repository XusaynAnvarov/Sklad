// ========================================================================
//  УПАКОВКИ И ПЕРЕСЧЁТ ПРИХОДА.  node _tools/tests/t-packing.mjs
//
//  Здесь считаются деньги, поэтому проверяем не «работает ли», а сходятся
//  ли суммы. Главное правило: ТОВАРА И ДЕНЕГ СТОЛЬКО ЖЕ, меняется только
//  то, чем мы их меряем. Если закупили на 200 000 — на складе должно
//  лежать ровно на 200 000, в каких бы единицах оно ни считалось.
//
//  Примеры взяты из задания владельца: шпулька (берём штуками, храним
//  пачками по 10) и коробки (1 коробка = 20 пачек = 200 штук).
// ========================================================================
import {
  настройки, штукВ, коэффициент, проверки, статус, СТАТУС, автоВключено,
  пересчитатьПриход, поляНастроек, нуженПереводОстатка, цепочка, описаниеЗакупки, ПРАВИЛА_ОСТАТКА,
} from "../../js/packing.js";

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const почти = (a, b, точность = 1e-6) => Math.abs(Number(a) - Number(b)) < точность;

// Шпулька: поставщик продаёт штуками, у нас лежит и продаётся пачками по 10.
const шпулька = {
  unit: "пачка", pack_size: 10,
  buy_unit: "шт", sell_unit: "пачка",
  auto_convert: true, odd_rule: "keep", packing_ver: 1,
};

// ---------- коэффициент ----------
{
  ok("штук в пачке", штукВ(настройки(шпулька), "пачка") === 10);
  ok("штук в штуке", штукВ(настройки(шпулька), "шт") === 1);
  ok("1 штука = 0,1 пачки", почти(коэффициент(шпулька), 0.1));
  // Дроби в подписях не показываем: «10 шт = 1 пачка» вместо «1 шт = 0,1 пачка».
  ok("закупка штуками объясняется целыми числами",
    описаниеЗакупки(шпулька) === "Закупаем в «шт», на склад кладём в «пачка»: 10 шт = 1 пачка.");
  ok("одинаковые единицы — так и сказано",
    описаниеЗакупки({ unit: "пачка", pack_size: 10, buy_unit: "пачка", packing_ver: 1 })
      === "Закупаем и храним одинаково — в «пачка». Пересчёт не нужен.");
  ok("закупка и склад совпадают — коэффициент 1",
    коэффициент({ unit: "пачка", pack_size: 10, buy_unit: "пачка", packing_ver: 1 }) === 1);
  ok("старый товар без настроек — коэффициент 1 (ничего не пересчитываем)",
    коэффициент({ unit: "шт" }) === 1);
}

// ---------- пример из задания: 100 штук по 2000 ----------
{
  const р = пересчитатьПриход(шпулька, { qty: 100, цена: 2000 });
  ok("100 штук → 10 пачек", почти(р.складских, 10));
  ok("пачек ровно, остатка нет", р.ровно === true && р.полных === 10);
  ok("общая закупка 200 000", почти(р.сумма, 200000));
  ok("себестоимость пачки 20 000", почти(р.себестоимость, 20000));
  ok("ДЕНЬГИ СХОДЯТСЯ: 10 пачек по 20 000 = 200 000", почти(р.складских * р.себестоимость, р.сумма));
  ok("штук посчитано верно", почти(р.штук, 100));
}

// ---------- неполная пачка: 105 штук при пачке по 10 ----------
{
  const р = пересчитатьПриход(шпулька, { qty: 105, цена: 2000 });
  ok("105 штук — это 10,5 пачки, а не 11", почти(р.складских, 10.5));
  ok("полных пачек 10", р.полных === 10);
  ok("и 5 штук отдельно", почти(р.остатокШтук, 5));
  ok("система знает, что пачка неполная", р.ровно === false);
  ok("штуки не потерялись", почти(р.штук, 105));
  ok("закупка считается по 105 штукам", почти(р.сумма, 210000));
  ok("себестоимость пачки та же — 20 000", почти(р.себестоимость, 20000));
  ok("ДЕНЬГИ СХОДЯТСЯ и на неполной пачке", почти(р.складских * р.себестоимость, р.сумма));
  ok("правило остатка попало в расчёт", р.правило === "keep");
}

// ---------- коробки: 1 коробка = 20 пачек = 200 штук ----------
{
  const коробочный = {
    unit: "пачка", pack_size: 10, box_size: 20,
    buy_unit: "коробка", sell_unit: "пачка", packing_ver: 1,
  };
  ok("в коробке 200 штук", штукВ(настройки(коробочный), "коробка") === 200);
  ok("1 коробка = 20 пачек", почти(коэффициент(коробочный), 20));

  const р = пересчитатьПриход(коробочный, { qty: 3, цена: 400000 });
  ok("3 коробки → 60 пачек", почти(р.складских, 60));
  ok("3 коробки → 600 штук", почти(р.штук, 600));
  ok("остатка нет", р.ровно === true);
  ok("себестоимость пачки 20 000", почти(р.себестоимость, 20000));
  ok("ДЕНЬГИ СХОДЯТСЯ: 60 пачек по 20 000 = 1 200 000", почти(р.складских * р.себестоимость, р.сумма));
  ok("цепочка объясняется словами", цепочка(коробочный) === "1 пачка = 10 шт · 1 коробка = 20 пачек = 200 шт");
  ok("закупка коробками объясняется целыми числами",
    описаниеЗакупки(коробочный) === "Закупаем в «коробка», на склад кладём в «пачка»: 1 коробка = 20 пачек.");
}

// ---------- склад считает коробками: «коробка» — это и есть единица ----------
{
  const вКоробках = { unit: "коробка", pack_size: 200, buy_unit: "коробка", packing_ver: 1 };
  ok("коробка как складская единица — 200 штук", штукВ(настройки(вКоробках), "коробка") === 200);
  ok("покупаем коробками, храним коробками — коэффициент 1", коэффициент(вКоробках) === 1);
}

// ---------- товары без настроек трогать нельзя ----------
{
  const старый = { unit: "шт", pack_size: 1 };
  ok("не настроено", статус(старый).код === СТАТУС.НЕТ);
  ok("автопреобразование выключено", автоВключено(старый) === false);
  // Самое важное: у старого товара с единицей «пачка», но без размера
  // упаковки НЕ должно быть «требует проверки» — иначе весь список из
  // восьмисот товаров разом окажется подозрительным и станет бесполезен.
  const полустарый = { unit: "пачка", pack_size: 1 };
  ok("старый товар с пустой упаковкой — просто «не настроено»", статус(полустарый).код === СТАТУС.НЕТ);
  const р = пересчитатьПриход(старый, { qty: 7, цена: 5 });
  ok("приход у ненастроенного товара идёт один к одному", почти(р.складских, 7) && почти(р.себестоимость, 5));
}

// ---------- противоречия ----------
{
  const безРазмера = { unit: "пачка", pack_size: 1, buy_unit: "шт", packing_ver: 2 };
  ok("настроили, но не сказали, сколько в пачке — требует проверки",
    статус(безРазмера).код === СТАТУС.ПРОВЕРИТЬ);
  ok("…и причина названа вслух", проверки(безРазмера).some(т => т.includes("сколько штук внутри")));

  const безКоробки = { unit: "пачка", pack_size: 10, buy_unit: "коробка", packing_ver: 2 };
  ok("закупка коробками без размера коробки — требует проверки",
    статус(безКоробки).код === СТАТУС.ПРОВЕРИТЬ);
  ok("коэффициент честно не считается", коэффициент(безКоробки) === 0);
  const р = пересчитатьПриход(безКоробки, { qty: 3, цена: 100 });
  ok("пересчитать нельзя — так и сказано", р.можно === false);
  ok("…и ничего не выдумано", р.складских === 0 && р.себестоимость === 0);

  const дробная = { unit: "пачка", pack_size: 10.5, buy_unit: "шт", packing_ver: 2 };
  ok("дробное число штук в упаковке — требует проверки",
    проверки(дробная).some(т => т.includes("Штук в упаковке")));

  const чужаяЕдиница = { unit: "пачка", pack_size: 10, buy_unit: "вагон", packing_ver: 2 };
  ok("неизвестная единица закупки — требует проверки",
    проверки(чужаяЕдиница).some(т => т.includes("неизвестна")));

  const авто = { unit: "пачка", pack_size: 10, buy_unit: "коробка", auto_convert: true, packing_ver: 2 };
  ok("автопреобразование без коэффициента — требует проверки",
    проверки(авто).some(т => т.includes("Автопреобразование")));
  ok("и оно НЕ применится", автоВключено(авто) === false);
}

// ---------- настроенный товар ----------
{
  ok("шпулька настроена", статус(шпулька).код === СТАТУС.ЕСТЬ);
  ok("у шпульки автопреобразование работает", автоВключено(шпулька) === true);
  ok("выключили автопреобразование — не применяется",
    автоВключено({ ...шпулька, auto_convert: false }) === false);
}

// ---------- что записывается ----------
{
  const поля = поляНастроек(шпулька, {
    unit: "пачка", pack_size: 10, buy_unit: "коробка", box_size: 20,
    sell_unit: "пачка", sell_units: ["пачка", "шт"], auto_convert: true, odd_rule: "pieces",
  });
  ok("версия настроек выросла", поля.packing_ver === 2);
  ok("коробка записалась", поля.box_size === 20);
  ok("разрешённые единицы продажи записались", поля.sell_units.join(",") === "пачка,шт");
  ok("правило остатка записалось", поля.odd_rule === "pieces");
  ok("неизвестное правило не пролезает",
    поляНастроек(шпулька, { unit: "пачка", pack_size: 10, odd_rule: "как-нибудь" }).odd_rule === "keep");
  ok("все правила из списка принимаются",
    ПРАВИЛА_ОСТАТКА.every(п => поляНастроек(шпулька, { unit: "пачка", pack_size: 10, odd_rule: п.value }).odd_rule === п.value));
  ok("версия растёт с каждого сохранения",
    поляНастроек({ ...шпулька, packing_ver: 7 }, { unit: "пачка", pack_size: 10 }).packing_ver === 8);
}

// ---------- САМОЕ ОПАСНОЕ: настройка упаковки не должна двигать остаток ----------
{
  // Меняем единицу закупки, коробку, правило остатка, автопреобразование —
  // всё это правила для БУДУЩИХ приходов. Остаток на полке тот же.
  ok("смена единицы закупки остаток не трогает",
    нуженПереводОстатка(шпулька, { unit: "пачка", pack_size: 10, buy_unit: "коробка", box_size: 20 }) === false);
  ok("правило остатка остаток не трогает",
    нуженПереводОстатка(шпулька, { unit: "пачка", pack_size: 10, odd_rule: "pieces" }) === false);
  ok("автопреобразование остаток не трогает",
    нуженПереводОстатка(шпулька, { unit: "пачка", pack_size: 10, auto_convert: false }) === false);
  ok("единица продажи остаток не трогает",
    нуженПереводОстатка(шпулька, { unit: "пачка", pack_size: 10, sell_unit: "шт" }) === false);

  // А вот это — уже перевод склада, и он требует подтверждения владельца.
  ok("смена складской единицы — это перевод остатка",
    нуженПереводОстатка(шпулька, { unit: "шт", pack_size: 1 }) === true);
  ok("смена размера упаковки — это перевод остатка",
    нуженПереводОстатка(шпулька, { unit: "пачка", pack_size: 12 }) === true);
}

// ---------- мелочь, на которой легко обжечься ----------
{
  const р0 = пересчитатьПриход(шпулька, { qty: 0, цена: 2000 });
  ok("ноль штук — ноль пачек и ноль денег", р0.складских === 0 && р0.сумма === 0);
  const рБезЦены = пересчитатьПриход(шпулька, { qty: 100 });
  ok("без цены количество всё равно считается", почти(рБезЦены.складских, 10));
  ok("…а себестоимость остаётся нулём, а не выдумывается", рБезЦены.себестоимость === 0);
  const р1 = пересчитатьПриход(шпулька, { qty: 1, цена: 2000 });
  ok("одна штука — 0,1 пачки, ничего не округлилось до нуля", почти(р1.складских, 0.1));
  ok("…полных пачек при этом ноль", р1.полных === 0);
  ok("…а штука на месте", почти(р1.остатокШтук, 1));
}

console.log("");
console.log(плохо ? плохо + " ОШИБОК" : "УПАКОВКИ И ДЕНЬГИ СХОДЯТСЯ");
process.exit(плохо ? 1 : 0);
