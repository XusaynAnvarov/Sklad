// ========================================================================
//  АГЕНТ ДИЗАЙНА.   node _tools/tests/t-agents-design.mjs
//
//  Агент ничего не рисует и не меняет — он собирает измеримые сигналы.
//  Поэтому проверяем две вещи:
//   1. Выводы делаются только при достаточных данных. Из шести визитов
//      «сайт смотрят с телефона» не следует.
//   2. Числа в сигналах — настоящие, посчитанные, а не круглые
//      «примерно половина».
// ========================================================================
const корень = new URL("../../", import.meta.url);
const Д = await import(new URL("api/lib/agents/design-math.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const визит = (device) => ({ kind: "site_visit", channel: "site", device });
const много = (n, d) => Array.from({ length: n }, () => визит(d));

// ======================================================================
//  1. УСТРОЙСТВА
// ======================================================================
{
  const у = Д.устройства([...много(77, "mobile"), ...много(45, "desktop"), ...много(6, null)]);
  ok("доля телефона считается по известным устройствам", у.доляТелефона === 63.1);
  ok("неизвестные устройства учтены отдельно", у.неясно === 6 && у.всего === 128);
  ok("данных хватает", у.хватает === true);

  const мало = Д.устройства([...много(4, "mobile"), ...много(2, "desktop")]);
  ok("на шести визитах вывода нет", мало.хватает === false);

  const с = Д.сигналы({ уст: мало });
  ok("при малых данных — сигнал «мало данных», без вывода",
    с.length === 1 && с[0].мало === true && !с[0].вывод && /нужно от 20/.test(с[0].что));

  const с2 = Д.сигналы({ уст: у });
  ok("при достаточных данных — вывод с настоящим числом",
    с2[0].вывод === "сайт смотрят в основном с телефона" && /63\.1%/.test(с2[0].что) && /77 из 122/.test(с2[0].что));

  const компьютер = Д.устройства([...много(10, "mobile"), ...много(40, "desktop")]);
  ok("когда смотрят с компьютера, про телефон не говорим", Д.сигналы({ уст: компьютер }).length === 0);
}

// ======================================================================
//  2. РОЛИК
// ======================================================================
{
  const раздражает = Д.ролик({ shown: 100, completed: 10, skipped: 80, skip_sec_sum: 160, "shown:mobile": 70 });
  ok("пропуск на 2-й секунде посчитан", раздражает.пропускСекунда === 2);
  ok("доля пропусков посчитана", раздражает.пропустилиПроцент === 80);
  const с = Д.сигналы({ рол: раздражает });
  ok("ролик, который закрывают не глядя, — сигнал",
    с[0]?.тема === "ролик" && /закрывают не глядя/.test(с[0].вывод));

  const хороший = Д.ролик({ shown: 50, completed: 30, skipped: 10, skip_sec_sum: 150 });
  const с2 = Д.сигналы({ рол: хороший });
  ok("ролик, который досматривают, трогать не советуют", /трогать не нужно/.test(с2[0]?.вывод || ""));

  const пусто = Д.ролик({});
  ok("без данных о ролике — «мало данных», не ноль процентов",
    пусто.хватает === false && Д.сигналы({ рол: пусто })[0].мало === true);
}

// ======================================================================
//  3. CSP
// ======================================================================
{
  const виденные = new Map([
    ["script-src ← https://cdn.example", { count: 12, page: "/" }],
    ["img-src ← https://img.example", { count: 3, page: "/catalog" }],
  ]);
  const к = Д.csp(виденные);
  ok("нарушения посчитаны и отсортированы", к.различных === 2 && к.всего === 15 && к.список[0].раз === 12);
  ok("CSP-нарушения дают сигнал", Д.сигналы({ кс: к })[0]?.тема === "csp");
  ok("без нарушений сигнала нет", Д.сигналы({ кс: Д.csp(new Map()) }).length === 0);
  ok("без счётчика вовсе ничего не падает", Д.csp(null).различных === 0);
}

// ======================================================================
//  4. КАТАЛОГ
// ======================================================================
{
  const товары = [
    { id: 1, code: "LP-1", stock_qty: 5, photo_url: "" },
    { id: 2, code: "LP-2", stock_qty: 3, photo_url: null },
    { id: 3, code: "LP-3", stock_qty: 0, photo_url: "" },        // нет на складе — не считаем
    { id: 4, code: "LP-4", stock_qty: 9, photo_url: "https://x" },
  ];
  const к = Д.каталог(товары, 1);
  ok("считаются только товары в наличии без фото", к.вНаличииБезФото === 2);
  ok("коды перечислены", к.безФотоКоды.join() === "LP-1,LP-2");

  const с = Д.сигналы({ кат: к });
  ok("товар в наличии без фото — самый заметный сигнал", с[0]?.тема === "фото" && /LP-1, LP-2/.test(с[0].сделать));

  const мало = Д.сигналы({ кат: Д.каталог(товары, 0) });
  ok("если карточек почти нет — сигнал о готовности карточек", мало.some((x) => x.тема === "карточки"));
  ok("без представления карточек этот сигнал не выдумывается",
    !Д.сигналы({ кат: Д.каталог(товары, null) }).some((x) => x.тема === "карточки"));
}

// ======================================================================
//  5. ПОРЯДОК И ПОЛНЫЙ ПРОГОН
// ======================================================================
{
  const все = Д.сигналы({
    уст: Д.устройства([...много(70, "mobile"), ...много(30, "desktop")]),
    рол: Д.ролик({ shown: 100, completed: 5, skipped: 90, skip_sec_sum: 180 }),
    кс: Д.csp(new Map([["x ← y", { count: 1 }]])),
    кат: Д.каталог([{ id: 1, code: "A", stock_qty: 1, photo_url: "" }], null),
  });
  ok("сигналы идут от самого заметного", все.every((с, i, a) => i === 0 || a[i - 1].вес >= с.вес));
  ok("первым — товар без фото", все[0].тема === "фото");
}

{
  const { прогон } = await import(new URL("api/lib/agents/design.js", корень));
  const уведомления = [];
  const р = await прогон({
    agentId: "design", config: {},
    читать: async (путь) => {
      if (путь.startsWith("client_events")) return [...много(60, "mobile"), ...много(20, "desktop")];
      if (путь.startsWith("products")) return [{ id: 1, code: "SV-016", stock_qty: 150, photo_url: "" }];
      if (путь.startsWith("product_card_ready")) return [];
      return [];
    },
    уведомить: async (у) => { уведомления.push(у); return у; },
  });
  ok("прогон даёт сводку с главным выводом", /Главное/.test(р.сводка));
  ok("уведомление ушло одно и с числами",
    уведомления.length === 1 && /75%/.test(уведомления[0].body) && /SV-016/.test(уведомления[0].body));
  ok("агент честно пишет, чего не умеет",
    р.детали.неУмеет.some((с) => /браузера и модели/.test(с)) && р.детали.неУмеет.some((с) => /менять сайт/.test(с)));
  ok("про CSP сказано, что счётчик обнуляется при перезапуске", /перезапуске/.test(р.детали.csp.примечание));
}

// Сообщение читает человек: «1 товар», а не «1 товаров».
ok("склонение: 1 товар, 3 товара, 5 товаров, 11 товаров, 21 товар",
  Д.товаров(1) === "1 товар" && Д.товаров(3) === "3 товара" && Д.товаров(5) === "5 товаров"
  && Д.товаров(11) === "11 товаров" && Д.товаров(21) === "21 товар");

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
