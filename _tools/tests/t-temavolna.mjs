// ========================================================================
//  ВОЛНА СМЕНЫ ТЕМЫ.  node _tools/tests/t-temavolna.mjs
//
//  Владелец прислал ролик: «тема переключается кругом из кнопки».
//  Сделано на View Transitions (js/temavolna.js).
//
//  Главное, что проверяется: тема меняется ВСЕГДА. Волна — украшение, и
//  любой её отказ (браузер не умеет, вкладка скрыта и переход отменён,
//  человек просил меньше движения) не должен оставить склад в прежней
//  теме. Отмена на скрытой вкладке — штатный случай, а не поломка.
//
//  И радиус: если взять половину экрана, круг не накроет дальний угол,
//  и в нём останется лоскут старой темы.
// ========================================================================

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };
const ждём = () => new Promise(r => setTimeout(r, 0));

// ---------- поддельное окружение браузера ----------
function окружение({ умеетПереход = true, меньшеДвижения = false, переходПадает = false } = {}) {
  const з = { применяли: 0, анимации: [], переходы: 0 };
  globalThis.window = { innerWidth: 1280, innerHeight: 800 };
  globalThis.matchMedia = () => ({ matches: меньшеДвижения });
  globalThis.document = {
    documentElement: { animate: (кадры, опции) => { з.анимации.push({ кадры, опции }); return {}; } },
    ...(умеетПереход ? {
      startViewTransition(обратно) {
        з.переходы++;
        обратно();                          // браузер зовёт колбэк сразу
        return { ready: переходПадает ? Promise.reject(new Error("InvalidStateError")) : Promise.resolve() };
      },
    } : {}),
  };
  return з;
}

const кнопка = { getBoundingClientRect: () => ({ left: 1200, top: 20, width: 40, height: 24 }) };

окружение();   // document должен существовать уже на момент загрузки модуля
const корень = new URL("../../", import.meta.url);
const { сменитьТемуВолной, умеетВолну } = await import(new URL("js/temavolna.js", корень));

// ---------- 1. Обычный случай: волна идёт, тема меняется ----------
{
  const з = окружение();
  let тема = "dark";
  сменитьТемуВолной(кнопка, () => { тема = "light"; з.применяли++; });
  await ждём(); await ждём();
  ok("браузер умеет переход", умеетВолну() === true);
  ok("тема сменилась", тема === "light");
  ok("применили ровно один раз", з.применяли === 1);
  ok("переход запущен", з.переходы === 1);
  ok("анимация поставлена", з.анимации.length === 1);

  const { кадры, опции } = з.анимации[0];
  ok("растёт именно новый кадр", опции.pseudoElement === "::view-transition-new(root)");
  ok("длительность задана", опции.duration === 520);
  ok("круг начинается с нуля", кадры.clipPath[0] === "circle(0px at 1220px 32px)");

  // дальний угол от центра (1220,32) — левый нижний: dx=1220, dy=768
  const радиус = Number(кадры.clipPath[1].match(/circle\(([\d.]+)px/)[1]);
  ok("радиус дотягивается до дальнего угла", Math.abs(радиус - Math.hypot(1220, 768)) < 0.5);
  ok("радиус больше половины диагонали", радиус > Math.hypot(1280, 800) / 2);
}

// ---------- 2. Браузер не умеет переход ----------
{
  const з = окружение({ умеетПереход: false });
  let тема = "dark";
  сменитьТемуВолной(кнопка, () => { тема = "light"; з.применяли++; });
  await ждём();
  ok("без поддержки тема всё равно сменилась", тема === "light");
  ok("без поддержки применили один раз", з.применяли === 1);
  ok("без поддержки анимаций нет", з.анимации.length === 0);
  ok("умеетВолну честно отвечает «нет»", умеетВолну() === false);
}

// ---------- 3. «Меньше движения» ----------
{
  const з = окружение({ меньшеДвижения: true });
  let тема = "dark";
  сменитьТемуВолной(кнопка, () => { тема = "light"; з.применяли++; });
  await ждём();
  ok("при «меньше движения» тема сменилась", тема === "light");
  ok("при «меньше движения» переход не запускали", з.переходы === 0);
}

// ---------- 4. Переход отменён (скрытая вкладка) ----------
{
  const з = окружение({ переходПадает: true });
  let тема = "dark";
  сменитьТемуВолной(кнопка, () => { тема = "light"; з.применяли++; });
  await ждём(); await ждём();
  ok("при отказе перехода тема всё равно сменилась", тема === "light");
  ok("при отказе анимацию не ставим", з.анимации.length === 0);
}

// ---------- 5. Кнопки нет: волна из правого верхнего угла ----------
{
  const з = окружение();
  сменитьТемуВолной(null, () => {});
  await ждём(); await ждём();
  ok("без кнопки центр — правый верхний угол", з.анимации[0].кадры.clipPath[0] === "circle(0px at 1240px 40px)");
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nВОЛНА СМЕНЫ ТЕМЫ В ПОРЯДКЕ");
process.exit(плохо ? 1 : 0);
