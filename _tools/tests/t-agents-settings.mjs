// ========================================================================
//  НАСТРОЙКИ АГЕНТОВ.   node _tools/tests/t-agents-settings.mjs
//
//  Форма в разделе «ИИ-Агенты» шлёт настройки на сервер, а сервер
//  проверяет их до записи (api/lib/agents/настройки.js). Здесь — три
//  правила, ради которых проверка существует:
//   1. Витрина не может быть служебным каналом накладных.
//   2. Папка копий — только полный путь без «..».
//   3. Правка одного поля не стирает остальные (и потолок расходов тоже).
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { проверитьНастройки } = await import(new URL("api/lib/agents/настройки.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const НАКЛАДНЫЕ = "-1002034021343";

// ---------------------------------------------------------------- 1. канал
{
  const р = проверитьНастройки("telegram", { канал: НАКЛАДНЫЕ }, { каналНакладных: НАКЛАДНЫЕ });
  ok("служебный канал накладных не принимается", !р.ok && /накладных/.test(р.ошибки.join(" ")));

  const р2 = проверитьНастройки("telegram", { канал: "  " + НАКЛАДНЫЕ + " " }, { каналНакладных: НАКЛАДНЫЕ });
  ok("и с пробелами вокруг — тоже", !р2.ok);

  const р3 = проверитьНастройки("telegram", { канал: "@generalmodern_shop" }, { каналНакладных: НАКЛАДНЫЕ });
  ok("новый канал по имени принимается", р3.ok && р3.config.канал === "@generalmodern_shop");

  const р4 = проверитьНастройки("telegram", { канал: "-1001234567890" }, { каналНакладных: НАКЛАДНЫЕ });
  ok("новый канал по номеру принимается", р4.ok);

  for (const плохой of ["@ab", "https://t.me/x", "@имя_канала", "-12345", "https://example.com/GeneralModernuz"]) {
    ok(`плохой адрес «${плохой}» не принят`, !проверитьНастройки("telegram", { канал: плохой }).ok);
  }

  // Владелец 23.11 вставил ссылку из Telegram — её надо понять.
  for (const [ввод, ждём] of [
    ["https://t.me/GeneralModernuz", "@GeneralModernuz"],
    ["t.me/GeneralModernuz/", "@GeneralModernuz"],
    ["http://telegram.me/GeneralModernuz?start=1", "@GeneralModernuz"],
    ["https://t.me/s/GeneralModernuz", "@GeneralModernuz"],
    ["GeneralModernuz", "@GeneralModernuz"],
    [" @GeneralModernuz ", "@GeneralModernuz"],
  ]) {
    const р = проверитьНастройки("telegram", { канал: ввод });
    ok(`«${ввод}» → ${ждём}`, р.ok && р.config.канал === ждём);
  }
  const приглашение = проверитьНастройки("telegram", { канал: "https://t.me/+AbCdEf123" });
  ok("ссылка-приглашение закрытого канала — понятная ошибка", !приглашение.ok && /приглашение/.test(приглашение.ошибки.join(" ")));

  const р5 = проверитьНастройки("telegram", { тест: false, цены: true });
  ok("флажки сохраняются как true/false", р5.ok && р5.config.тест === false && р5.config.цены === true);
}

// ---------------------------------------------------------- 2. папка копий
{
  for (const плохой of ["/var/backups/../../etc", "../etc", "var/backups", "/var/backups/;rm -rf", "/a/..", "C:\\backups"]) {
    ok(`путь «${плохой}» не принят`, !проверитьНастройки("security", { копии: плохой }).ok);
  }
  const р = проверитьНастройки("security", { копии: "/var/backups/sklad/" });
  ok("полный путь принят, слэш в конце убран", р.ok && р.config.копии === "/var/backups/sklad");
  const пусто = проверитьНастройки("security", { копии: "" }, { было: { копии: "/var/backups/sklad" } });
  ok("пустое поле убирает настройку", пусто.ok && !("копии" in пусто.config));
}

// ------------------------------------------- 3. частичное обновление
{
  const было = { канал: "@generalmodern_shop", тест: true, тихо: { с: "22:00", до: "08:00" }, потолок: 0, стиль: { x: 1 } };
  const р = проверитьНастройки("telegram", { цены: true }, { было });
  ok("правка флажка не трогает канал и тихие часы", р.ok && р.config.канал === "@generalmodern_shop" && р.config.тихо?.с === "22:00");
  ok("потолок расходов сохраняется", р.ok && р.config.потолок === 0);

  const чужое = проверитьНастройки("orders", { канал: "@generalmodern_shop", права: "все", просрочка: { placed: "3", packed: "" } });
  ok("чужие для агента поля отброшены", чужое.ok && !("канал" in чужое.config) && !("права" in чужое.config));
  ok("пустая норма не записывается, заданная — числом", чужое.ok && чужое.config.просрочка.placed === 3 && !("packed" in чужое.config.просрочка));

  ok("норма 45 дней не принята", !проверитьНастройки("orders", { просрочка: { placed: 45 } }).ok);
  ok("дробная норма не принята", !проверитьНастройки("orders", { просрочка: { placed: 1.5 } }).ok);
}

// ------------------------------------------------------- тихие часы
{
  ok("тихие часы через полночь приняты", проверитьНастройки("design", { тихо: { с: "22:00", до: "08:00" } }).ok);
  ok("одинаковые начало и конец — нет", !проверитьНастройки("design", { тихо: { с: "09:00", до: "09:00" } }).ok);
  ok("время 25:00 — нет", !проверитьНастройки("design", { тихо: { с: "25:00", до: "08:00" } }).ok);
  const снять = проверитьНастройки("warehouse", { тихо: { с: "", до: "" } }, { было: { тихо: { с: "22:00", до: "08:00" } } });
  ok("пустые часы снимают тишину", снять.ok && !("тихо" in снять.config));
  ok("неизвестный агент не принят", !проверитьНастройки("photo", {}).ok && !проверитьНастройки("общие", {}).ok);
}

console.log(плохо ? `\n${плохо} проверок не прошло` : "\nВсе проверки прошли");
process.exit(плохо ? 1 : 0);
