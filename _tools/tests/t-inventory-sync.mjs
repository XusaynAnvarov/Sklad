// ========================================================================
//  ПАРТИИ И ОСТАТОК ДОЛЖНЫ СХОДИТЬСЯ.  node _tools/tests/t-inventory-sync.mjs
//
//  Сентябрь 2026. Владелец: «проданный товар сам вернулся на склад, да ещё
//  и со старой датой». Так и было: если запись проходила наполовину (в базу
//  ушёл остаток, а партии — нет), следующее движение пересчитывало остаток
//  из старых партий, и проданное возвращалось.
//  Теперь при расхождении верим остатку.
// ========================================================================
const корень = new URL("../../", import.meta.url);
const { ensureBatches, сверитьСОстатком, sumQty } = await import(new URL("js/inventory.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const партия = (qty, цена, дата) => ({ qty, cost_yuan: цена, cost_usd: цена * 0.14, date: дата });

// ---------- всё сходится — ничего не трогаем ----------
{
  const p = { stock_qty: 30, batches: [партия(10, 5, "2026-06-06"), партия(20, 6, "2026-09-03")] };
  const b = ensureBatches(p);
  ok("совпало — партии как есть", b.length === 2 && sumQty(b) === 30 && b[0].qty === 10);
}

// ---------- продали, но партии не записались ----------
{
  // на складе было 300, продали 250 → остаток 50, а партии остались старые
  const p = { stock_qty: 50, cost_yuan: 5, batches: [партия(300, 5, "2026-06-06")] };
  const b = ensureBatches(p);
  ok("остаток главнее: из 300 осталось 50", sumQty(b) === 50);
  ok("срезали с начала очереди, как продажа", b.length === 1 && b[0].date === "2026-06-06");

  // самая опасная строчка: раньше здесь возвращалось 300
  const p2 = { stock_qty: 0, batches: [партия(300, 5, "2026-06-06")] };
  ok("продали всё — партий не остаётся, товар не воскресает", sumQty(ensureBatches(p2)) === 0);
}

// ---------- пришло, но партии не записались ----------
{
  const p = { stock_qty: 120, cost_yuan: 7, batches: [партия(100, 7, "2026-06-06")] };
  const b = ensureBatches(p);
  ok("нехватку дописали: стало 120", sumQty(b) === 120);
  ok("дописанная партия помечена как правка", b.at(-1).правка === true && b.at(-1).qty === 20);
  ok("цена взята с полки", b.at(-1).cost_yuan === 7);
}

// ---------- минус (продали больше, чем было) ----------
{
  const p = { stock_qty: -40, batches: [партия(-40, 5, "2026-08-01")] };
  ok("долг остаётся долгом", sumQty(ensureBatches(p)) === -40);
  const p2 = { stock_qty: -40, batches: [партия(10, 5, "2026-06-06")] };
  ok("остаток ушёл в минус — партии за ним", sumQty(ensureBatches(p2)) === -40);
}

// ---------- старые данные без партий ----------
{
  const p = { stock_qty: 75, cost_yuan: 3, created_at: "2026-06-06T00:00:00Z" };
  const b = ensureBatches(p);
  ok("без партий — одна партия из остатка, датой заведения товара",
     b.length === 1 && b[0].qty === 75 && String(b[0].date).slice(0, 10) === "2026-06-06");
  ok("пустой склад — пусто", ensureBatches({ stock_qty: 0 }).length === 0);
}

// ---------- остаток не заполнен — не выдумываем ----------
{
  const b = сверитьСОстатком([партия(10, 5, "2026-06-06")], {});
  ok("нет числа остатка — партии не трогаем", b.length === 1 && b[0].qty === 10);
}

console.log(плохо ? `\n${плохо} ОШИБОК` : "\nПАРТИИ СХОДЯТСЯ С ОСТАТКОМ");
process.exit(плохо ? 1 : 0);
