// Подставная база: upsert ведёт себя как в проекте — дописывает только
// переданные колонки, остальные у строки остаются прежними.
function база(товары) {
  const по = Object.fromEntries(товары.map(p => [p.id, { ...p }]));
  const документы = {};
  const патч = (строка) => { по[строка.id] = { ...(по[строка.id] || {}), ...строка }; };
  return {
    по, документы,
    products: { upsert: async (r) => патч(r), upsertMany: async (rs) => rs.forEach(патч) },
    purchases: { upsert: async (d) => { документы[d.id] = { ...(документы[d.id] || {}), ...d }; } },
  };
}

