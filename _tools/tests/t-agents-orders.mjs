// ========================================================================
//  АГЕНТ ЗАКАЗОВ.   node _tools/tests/t-agents-orders.mjs
//
//  Проверяем api/lib/agents/orders-math.js на выборке, где собрано всё,
//  на чём такой счёт обычно врёт:
//   • накладная без строки в order_fulfillment — это «оформлен», а не
//     «вне системы»;
//   • нехватка — это МИНУС по остатку, а не малый остаток: накладная
//     final склад уже списала;
//   • отправленный заказ не бывает просроченным;
//   • причину задержки берём записанную, а не придуманную.
//
//  Плюс сверка: кто попадает в учёт — решает api/lib/fulfillment.js,
//  и агент не должен считать по-своему.
// ========================================================================
const корень = new URL("../../", import.meta.url);
process.env.SUPABASE_URL = "http://db.test";
process.env.SUPABASE_SERVICE_KEY = "k";

const M = await import(new URL("api/lib/agents/orders-math.js", корень));
const F = await import(new URL("api/lib/fulfillment.js", корень));

let плохо = 0;
const ok = (имя, условие) => { if (условие) console.log("✅", имя); else { console.log("❌", имя); плохо++; } };

const СУТКИ = 86400e3;
const СЕЙЧАС = Date.parse("2026-11-23T06:00:00Z");
const назад = (д) => new Date(СЕЙЧАС - д * СУТКИ).toISOString();
const курсы = { yuan: 0.14, som: 1 / 12600 };

const ид = (n) => `0000000${n}-0000-4000-8000-000000000001`.slice(-36);

// ======================================================================
//  1. УЧЁТ — ПО ПРАВИЛАМ СКЛАДА, А НЕ ПО СВОИМ
// ======================================================================
{
  const since = назад(30);
  ok("возврат в учёт не берётся",
    F.вУчёте({ status: "final", source: "refund", created_at: назад(1) }, since, false) === false);
  ok("черновик в учёт не берётся",
    F.вУчёте({ status: "draft", created_at: назад(1) }, since, false) === false);
  ok("старая накладная без строки не берётся",
    F.вУчёте({ status: "final", created_at: назад(60), date: назад(60) }, since, false) === false);
  ok("старая накладная СО строкой берётся",
    F.вУчёте({ status: "final", created_at: назад(60), date: назад(60) }, since, true) === true);
  ok("свежая накладная берётся и без строки",
    F.вУчёте({ status: "final", created_at: назад(1), date: назад(1) }, since, false) === true);
}

// ======================================================================
//  2. ЭТАПЫ, ДНИ И СУММЫ
// ======================================================================
const товары = [
  { id: "p1", code: "LP-125", name: "Лапка сборка P50", stock_qty: 380 },
  { id: "p2", code: "AP-052", name: "Раскройная машина", stock_qty: -4 },   // ушёл в минус
  { id: "p3", code: "NJ-075", name: "Нож оверлока", stock_qty: 0 },         // ноль — это не минус
];

const продажи = [
  // оформлен, строки в order_fulfillment нет вовсе
  { id: ид(1), status: "final", created_at: назад(5), date: назад(5), currency: "usd", customer_id: "c1",
    items: [{ product_id: "p1", qty: 2, unit_price: 10, currency: "usd" }] },
  // собран, не отправлен, и собрать его нечем — товар в минусе
  { id: ид(2), status: "final", created_at: назад(3), date: назад(3), currency: "usd", customer_id: "c2",
    items: [{ product_id: "p2", qty: 1, unit_price: 300, currency: "usd" }] },
  // отправлен давно
  { id: ид(3), status: "final", created_at: назад(20), date: назад(20), currency: "usd", customer_id: "c1",
    items: [{ product_id: "p1", qty: 1, unit_price: 10, currency: "usd" }] },
  // оформлен вчера, товар на нуле — это НЕ нехватка
  { id: ид(4), status: "final", created_at: назад(1), date: назад(1), currency: "yuan", customer_id: "c3",
    items: [{ product_id: "p3", qty: 5, unit_price: 100, currency: "yuan" }] },
];
const строки = [
  { sale_id: ид(2), stage: "packed", updated_at: назад(3), packed_by: "Хусайн", ship_comment: "ждём курьера" },
  { sale_id: ид(3), stage: "shipped", updated_at: назад(18), shipped_by: "Хусайн", carrier: "BTS Express", tracking: "AB12" },
];
const доска = [{ sale_id: ид(2), urgent: true }];

const список = M.заказы({ продажи, строки, доска, товары, курсы, сейчас: СЕЙЧАС });
const по = (n) => список.find((з) => з.id === ид(n));

{
  ok("накладная без строки — это «оформлен»", по(1).этап === "placed");
  ok("этап читается у строки", по(2).этап === "packed" && по(3).этап === "shipped");
  ok("дни ожидания считаются от оформления", по(1).днейЖдёт === 5);
  ok("дни на этапе — от последнего движения", по(3).днейНаЭтапе === 18 && по(3).днейЖдёт === 20);
  ok("без строки дни на этапе равны дням ожидания", по(1).днейНаЭтапе === по(1).днейЖдёт);
  ok("сумма приведена к доллару", Math.abs(по(4).суммаUSD - 5 * 100 * 0.14) < 0.01);
  ok("срочность берётся с доски", по(2).срочно === true && по(1).срочно === false);
  ok("перевозчик и трек видны у отправленного", по(3).перевозчик === "BTS Express" && по(3).трек === "AB12");
}

// ======================================================================
//  3. НЕХВАТКА — ЭТО МИНУС, А НЕ НОЛЬ
// ======================================================================
{
  ok("товар в минусе — нечем собрать", по(2).нехватка.length === 1 && по(2).нехватка[0].код === "AP-052");
  ok("ноль на остатке нехваткой не считается", по(4).нехватка.length === 0);
  ok("положительный остаток нехваткой не считается", по(1).нехватка.length === 0);

  const н = M.нехваткаПоТоварам(список);
  ok("нехватка сведена по товару", н.length === 1 && н[0].заказов === 1);
  ok("в нехватке указаны номера заказов", н[0].заказы[0] === M.номерЗаказа(ид(2)));
}

// ======================================================================
//  4. ПРИЧИНА ЗАДЕРЖКИ — ТОЛЬКО ЗАПИСАННАЯ
// ======================================================================
{
  ok("комментарий к отправке попал в причину", /ждём курьера/.test(по(2).причина));
  ok("нехватка названа причиной", /нечем собрать/.test(по(2).причина));
  ok("без записанных причин так и написано", по(1).причина === "причина не указана");

  const безОтветственного = M.заказы({
    продажи: [продажи[0]], строки: [{ sale_id: ид(1), stage: "packed", updated_at: назад(1) }],
    доска: [], товары, курсы, сейчас: СЕЙЧАС,
  })[0];
  ok("отсутствие ответственного названо причиной", /не указан ответственный/.test(безОтветственного.причина));
}

// ======================================================================
//  5. ПРОСРОЧКА
// ======================================================================
{
  const пороги = { placed: 2, packed: 1 };
  ok("оформлен 5 дней при норме 2 — просрочен", M.просрочен(по(1), пороги) === true);
  ok("собран 3 дня при норме 1 — просрочен", M.просрочен(по(2), пороги) === true);
  ok("оформлен 1 день при норме 2 — не просрочен", M.просрочен(по(4), пороги) === false);
  ok("отправленный просроченным не бывает никогда", M.просрочен(по(3), пороги) === false);
  ok("свои пороги из настроек работают", M.просрочен(по(1), { placed: 10 }) === false);
  ok("без порогов берутся общие", M.просрочен(по(1)) === true);
}

// ======================================================================
//  6. ПРИОРИТЕТ И СВОДКА
// ======================================================================
{
  const вРаботе = список.filter((з) => з.этап !== "shipped").sort(M.поПриоритету);
  ok("срочный с нехваткой идёт первым", вРаботе[0].id === ид(2));
  ok("отправленные в работу не попадают", !вРаботе.some((з) => з.этап === "shipped"));

  const с = M.сводка(список, { placed: 2, packed: 1 });
  ok("сводка считает этапы", с.неСобрано === 2 && с.неОтправлено === 1 && с.отправлено === 1);
  ok("сводка считает просрочки", с.просрочено === 2);
  ok("сводка считает нечем собрать", с.нечемСобрать === 1);
  ok("сводка считает срочные", с.срочных === 1);
  ok("сумма в работе — только неотправленное",
    Math.abs(с.суммаВРаботеUSD - (20 + 300 + 70)) < 0.01);
  ok("самый старый в работе — оформленный пять дней назад", с.самыйСтарый.id === ид(1));
}

// ======================================================================
//  7. ПУСТОЙ СКЛАД ЗАКАЗОВ
// ======================================================================
{
  const пусто = M.сводка([], {});
  ok("на пустом списке ничего не падает",
    пусто.всего === 0 && пусто.просрочено === 0 && пусто.самыйСтарый === null);
  ok("заказы без данных дают пустой список", M.заказы({}).length === 0);
}

console.log(плохо ? `\n❌ Провалено проверок: ${плохо}` : "\n✅ Всё сошлось");
process.exit(плохо ? 1 : 0);
