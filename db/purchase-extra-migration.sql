-- ========================================================================
--  ДОПОЛНИТЕЛЬНЫЕ РАСХОДЫ ЗАКУПКИ: доставка, растаможка, комиссия.
--
--  Товар стоит не только то, что назвал поставщик. За доставку платят
--  отдельно, и эти деньги — тоже себестоимость: если их не разложить по
--  позициям, прибыль будет завышена ровно на стоимость доставки.
--
--  ЧТО ЭТА МИГРАЦИЯ ДЕЛАЕТ: добавляет ОДНУ колонку в таблицу purchases.
--  И ВСЁ. Она не трогает ни остатки, ни себестоимость, ни партии, ни
--  старые приходы: ни одной строки с данными не меняется.
--
--  У всех приходов, заведённых раньше, колонка останется пустой — а
--  пустая колонка означает «расходов нет», и такие документы считаются
--  ровно так же, как до миграции. Старые приходы не пересчитываются
--  никогда: у каждой оприходованной позиции в документе уже записано,
--  как именно она посчитана (поле «приход»), и это берётся как есть.
--
--  ЧТО ЛЕЖИТ В КОЛОНКЕ:
--    { "сумма": 500, "валюта": "yuan", "правило": "value",
--      "примечание": "доставка до Ташкента" }
--  правило — пропорционально чему делить расход между позициями:
--    value  — по стоимости позиций (обычный способ для доставки)
--    pieces — по количеству штук
--    items  — поровну между позициями
--
--  Запускать можно сколько угодно раз: всё через "if not exists".
--  Supabase → SQL Editor → Run. Своя база → psql.
-- ========================================================================

alter table if exists purchases add column if not exists extra jsonb;


-- ---------------- ПРОВЕРКА ----------------
-- 1) Колонка на месте. Должно вернуть одну строку.
select column_name, data_type
from information_schema.columns
where table_name = 'purchases' and column_name = 'extra';

-- 2) Расходов ни у одного прихода пока нет — так и должно быть. Ноль.
select count(*) as с_расходами from purchases where extra is not null;

-- 3) Приходы не изменились: сравните с числами, снятыми до миграции.
select count(*) as приходов,
       count(*) filter (where status = 'arrived') as оприходованных
from purchases;


-- ---------------- ОТКАТ ----------------
-- Удаляется только колонка, которой до миграции не было. Вместе с ней
-- пропадут вписанные расходы — но себестоимость уже оприходованных
-- приходов не изменится: она записана в партиях товара.
--
