// ========================================================================
//  СЕКРЕТ ПОДПИСИ ТОКЕНОВ — одно место на весь сервер.
//
//  Раньше в шести файлах стояло `SITE_JWT_SECRET || "dev-secret-…"`:
//  если переменная на сервере не задана, токены подписывались строкой,
//  которая лежит в открытом репозитории, — и кто угодно мог выписать себе
//  токен любого клиента или администратора.
//
//  Теперь без переменной берётся случайный ключ на время жизни процесса.
//  Подделать токен нельзя; плата — после перезапуска сервера все входят
//  заново. Громкое сообщение в журнале напоминает задать переменную.
// ========================================================================
import crypto from "crypto";

let запасной = null;
export function секретПодписи() {
  const s = process.env.SITE_JWT_SECRET;
  // прежняя публичная строка из репозитория — всё равно что пусто
  if (s && s !== "dev-secret-change-in-production") return s;
  if (!запасной) {
    запасной = crypto.randomBytes(48).toString("hex");
    console.error("[БЕЗОПАСНОСТЬ] SITE_JWT_SECRET не задан — токены подписываются случайным ключом и сбросятся при перезапуске. Задайте SITE_JWT_SECRET в .env.");
  }
  return запасной;
}
