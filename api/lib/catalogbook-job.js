// ========================================================================
//  ОЧЕРЕДЬ СБОРКИ ПЕЧАТНОГО КАТАЛОГА: одна сборка за раз.
//
//  Две сборки разом заняли бы оба ядра сервера и память под два файла по
//  100 МБ. Вторая просто получает ответ «уже собирается».
//
//  Готовые книги лежат в .cache/catalog — рядом с приложением, выкладка
//  их не трогает. Список файлов берём с диска, поэтому он переживает
//  перезапуск сервера. Ход текущей сборки держим в памяти.
// ========================================================================
import { Worker } from "worker_threads";
import { existsSync, readdirSync, statSync } from "fs";
import { join } from "path";
import { fileURLToPath } from "url";

const КОРЕНЬ = fileURLToPath(new URL("../../", import.meta.url));
export const ПАПКА_КНИГ = process.env.CACHE_DIR ? join(process.env.CACHE_DIR, "catalog") : join(КОРЕНЬ, ".cache", "catalog");

export const ЯЗЫКИ_КНИГИ = ["ru", "uz", "en"];
export const имяКниги = (язык, образец) => `general-modern-katalog-${язык}${образец ? "-obrazec" : ""}.pdf`;
const ИМЯ = /^general-modern-katalog-(ru|uz|en)(-obrazec)?\.pdf$/;
export const имяДопустимо = (имя) => ИМЯ.test(String(имя || ""));

let задача = null;
let создатьПоток = (файл, данные) => new Worker(new URL("./catalogbook-worker.js", import.meta.url), {
  workerData: данные,
  resourceLimits: { maxOldGenerationSizeMb: 2048 },
});
// для тестов: подменить поток
export function _подменитьПоток(f) { создатьПоток = f; задача = null; }

export function запустить({ язык, образец }) {
  if (!ЯЗЫКИ_КНИГИ.includes(язык)) return { ошибка: "Неизвестный язык" };
  if (задача && !задача.закончено) return { занято: true, задача };

  const имя = имяКниги(язык, !!образец);
  const файл = join(ПАПКА_КНИГ, имя);
  задача = { язык, образец: !!образец, имя, этап: "запуск", готово: 0, всего: 0, начато: Date.now(), закончено: 0, ошибка: "" };
  const текущая = задача;
  const закончить = (поля) => { if (!текущая.закончено) Object.assign(текущая, поля, { закончено: Date.now() }); };

  let поток;
  try { поток = создатьПоток(файл, { язык, образец: !!образец, файл }); }
  catch (e) { закончить({ ошибка: "Не удалось начать сборку: " + (e.message || e) }); return { задача: текущая }; }

  поток.on("message", (m) => {
    if (!m) return;
    if (m.вид === "ход") Object.assign(текущая, { этап: m.этап, готово: m.готово, всего: m.всего });
    else if (m.вид === "готово") закончить({ этап: "готово", страниц: m.страниц, всегоСтраниц: m.всегоСтраниц, байт: m.байт, товаров: m.товаров });
    else if (m.вид === "ошибка") закончить({ ошибка: m.ошибка });
  });
  поток.on("error", (e) => закончить({ ошибка: String((e && e.message) || e) }));
  поток.on("exit", (code) => закончить({ ошибка: code ? `Сборка прервалась (код ${code})` : "Сборка завершилась без результата" }));
  return { задача: текущая };
}

// Готовые книги на диске.
export function готовыеКниги() {
  if (!existsSync(ПАПКА_КНИГ)) return [];
  return readdirSync(ПАПКА_КНИГ)
    .filter(имяДопустимо)
    .map((имя) => {
      const st = statSync(join(ПАПКА_КНИГ, имя));
      const [, язык, образец] = ИМЯ.exec(имя);
      return { имя, язык, образец: !!образец, байт: st.size, собрана: st.mtimeMs };
    })
    .sort((a, b) => b.собрана - a.собрана);
}

export const текущаяЗадача = () => задача;
