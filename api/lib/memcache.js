// ========================================================================
//  КОРОТКАЯ ПАМЯТЬ СЕРВЕРА.
//
//  Склад при каждом переходе между страницами заново просит у базы все
//  товары: 940 строк, 700 КБ, полторы секунды — и так по кругу. База одна
//  и на бесплатном плане, быстрее она не станет.
//
//  Поэтому ответы списков держим в памяти сервера несколько секунд. Любая
//  запись в таблицу тут же стирает её память, так что устаревшее не
//  покажем: и склад на сайте, и склад в телефоне, и бот пишут через этот
//  же сервер.
//
//  Хранится это в одном процессе Node рядом с приложением — ни в какой
//  внешний кэш ходить не нужно.
// ========================================================================

const память = new Map();          // ключ → { до, значение }
const ПРЕДЕЛ = 200;                 // столько записей держим, дальше выбрасываем старые

export function взять(ключ) {
  const есть = память.get(ключ);
  if (!есть) return undefined;
  if (есть.до < Date.now()) { память.delete(ключ); return undefined; }
  return есть.значение;
}

export function положить(ключ, значение, секунд) {
  if (память.size >= ПРЕДЕЛ) {
    // самые старые — вон; перебирать весь список незачем, снимаем первые
    for (const k of память.keys()) { память.delete(k); if (память.size < ПРЕДЕЛ) break; }
  }
  память.set(ключ, { до: Date.now() + секунд * 1000, значение });
  return значение;
}

// Посчитать один раз и держать N секунд. Ошибки не запоминаем.
export async function помнить(ключ, секунд, сделать) {
  const есть = взять(ключ);
  if (есть !== undefined) return есть;
  const значение = await сделать();
  return положить(ключ, значение, секунд);
}

// Забыть всё, что начинается с этой приставки: после записи в таблицу.
export function забыть(приставка) {
  if (!приставка) { память.clear(); return; }
  for (const k of память.keys()) if (k.startsWith(приставка)) память.delete(k);
}

export const размерПамяти = () => память.size;
