// ========================================================================
//  СВЕДЕНИЯ О ТОВАРЕ (таблица product_fact): что можно сохранить.
//
//  Экран «Сведения» в разделе «ИИ-Агенты» присылает сюда весь набор
//  сведений одного товара. Проверяем ДО записи, браузеру не верим.
//
//  Правила:
//   • виды сведений — только известные (ВИДЫ). Неизвестный вид отбрасывается;
//   • «проверено» без источника нельзя: так устроена и сама таблица
//     (ограничение product_fact_source_required), и проверка здесь —
//     чтобы владелец получил понятную фразу, а не ошибку базы;
//   • одиночные виды (название, описание…) — по одному на товар,
//     «свойство» — до 8 штук;
//   • сведения других видов, которых экран не знает (например поля
//     карточки-картинки), при сохранении НЕ удаляются.
// ========================================================================

export const ВИДЫ = {
  название:       { подпись: "Понятное название",  один: true,  макс: 120 },
  описание:       { подпись: "Описание",            один: true,  макс: 600 },
  совместимость:  { подпись: "Подходит к",          один: true,  макс: 300 },
  свойство:       { подпись: "Свойство",            один: false, макс: 160, сколько: 8 },
  предупреждение: { подпись: "Предупреждение",      один: true,  макс: 200 },
  подзаголовок:   { подпись: "Подзаголовок карточки", один: true, макс: 80 },
  количество:     { подпись: "Количество в упаковке", один: true, макс: 20 },
  единица:        { подпись: "Единица",             один: true,  макс: 20 },
};
export const ПОРЯДОК = Object.keys(ВИДЫ);
export const УРОВНИ = ["требует проверки", "подтверждено"];

const чисто = (s, макс) => String(s ?? "").replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "").trim().slice(0, макс);

// строки: [{ key, value, source, confidence }] → { ok, строки, ошибки }
// В строках на выходе уже проставлен sort (по порядку внутри вида).
export function проверитьСведения(строки = []) {
  const ошибки = [];
  const итог = [];
  const счёт = {};
  for (const [i, с] of (Array.isArray(строки) ? строки : []).entries()) {
    const вид = String(с?.key || "");
    const о = ВИДЫ[вид];
    if (!о) continue;                                   // неизвестный вид — мимо
    const value = чисто(с?.value, о.макс);
    if (!value) continue;                               // пустая строка = удалить
    const source = чисто(с?.source, 200);
    const confidence = УРОВНИ.includes(с?.confidence) ? с.confidence : "требует проверки";
    if (confidence === "подтверждено" && !source) {
      ошибки.push(`«${о.подпись}»: чтобы отметить «проверено», укажите источник (например «упаковка», «сайт производителя», «владелец»)`);
      continue;
    }
    счёт[вид] = (счёт[вид] || 0) + 1;
    if (о.один && счёт[вид] > 1) { ошибки.push(`«${о.подпись}» может быть только одно`); continue; }
    if (о.сколько && счёт[вид] > о.сколько) { ошибки.push(`свойств не больше ${о.сколько}`); continue; }
    итог.push({ key: вид, value, source: source || null, confidence, sort: о.один ? 0 : счёт[вид], _i: i });
  }
  return ошибки.length ? { ok: false, ошибки } : { ok: true, строки: итог.map(({ _i, ...r }) => r) };
}

// Сводка по товарам для списка на экране: сколько сведений, сколько проверено.
export function сводкаСведений(строки = []) {
  const м = new Map();
  for (const с of строки || []) {
    const id = String(с.product_id);
    if (!м.has(id)) м.set(id, { product_id: id, всего: 0, проверено: 0, безИсточника: 0, название: "", описание: false });
    const з = м.get(id);
    if (!ВИДЫ[с.key]) continue;
    з.всего++;
    if (с.confidence === "подтверждено") з.проверено++;
    if (!String(с.source || "").trim()) з.безИсточника++;
    if (с.key === "название") з.название = с.value;
    if (с.key === "описание") з.описание = true;
  }
  return [...м.values()];
}
