// ========================================================================
//  Имя товара для КЛИЕНТА: вырезаем артикул (sku), если он встречается
//  в названии. Клиент не должен видеть артикул — ни отдельно, ни внутри имени.
//  Владельцу отдаётся полное имя + артикул (отдельно).
// ========================================================================
export function clientName(name, sku) {
  const n = String(name == null ? "" : name);
  const s = String(sku == null ? "" : sku).trim();
  if (!s) return n;
  // экранируем спецсимволы артикула для RegExp
  const esc = s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  // вырезаем артикул как отдельный фрагмент (границы — не буквы/цифры), регистр не важен
  let out = n.replace(new RegExp("(^|[^\\p{L}\\p{N}])" + esc + "(?=$|[^\\p{L}\\p{N}])", "giu"), "$1");
  out = out.replace(/\(\s*\)/g, " ");                       // пустые скобки от вырезанного
  out = out.replace(/\(\s+/g, "(").replace(/\s+\)/g, ")");  // пробелы у скобок
  out = out.replace(/\s{2,}/g, " ").trim();
  // убираем висячие разделители по краям (—, -, |, /, запятая), скобки НЕ трогаем
  out = out.replace(/^[\s\-–—|/,]+/, "").replace(/[\s\-–—|/,]+$/, "").trim();
  return out || n; // если после вырезания пусто — вернуть исходное имя
}
