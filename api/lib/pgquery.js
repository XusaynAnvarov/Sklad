// ========================================================================
//  ПЕРЕВОД ЗАПРОСОВ SUPABASE НА ОБЫЧНЫЙ SQL.
//
//  Весь сервер разговаривает с базой на языке PostgREST (это надстройка
//  Supabase над Postgres):
//      customers?id=eq.5&select=name,phones&order=name.asc&limit=20
//  Своя база такого языка не знает — она понимает SQL. Здесь перевод.
//
//  Переписывать полторы сотни мест в коде не нужно и опасно: вместо
//  этого переводим сам запрос, а вызовы остаются прежними. Если завтра
//  вернёмся на Supabase, достаточно переключить настройку.
//
//  Переводим ТОЛЬКО то, что действительно встречается в нашем коде
//  (я пересчитал: eq — 153 раза, in — 23, gte — 4, not.is — 3, is — 2,
//  cs — 2, lte — 1). Незнакомое условие не угадываем, а честно бросаем
//  ошибку: тихо отдать не те строки — хуже, чем упасть.
//
//  Здесь только складывание текста запроса, без обращения к базе, —
//  поэтому всё проверяется тестом _tools/tests/t-pgquery.mjs.
// ========================================================================

// Имя таблицы/колонки: только буквы, цифры и подчёркивание. Всё остальное
// — повод отказаться: имена в запрос подставляются как есть, и пропустить
// туда кавычку значит открыть дорогу чужому SQL.
const ИМЯ = /^[a-z_][a-z0-9_]*$/i;
const имя = (s) => {
  if (!ИМЯ.test(String(s || ""))) throw new Error("Недопустимое имя в запросе: " + s);
  return s;
};

// Разобрать «путь» PostgREST на таблицу и условия.
export function разобрать(путь) {
  const строка = String(путь || "");
  const [таблица, запрос = ""] = строка.split("?");
  имя(таблица);

  const условия = [];          // { колонка, оператор, значение }
  let выбрать = "*", порядок = [], предел = null, смещение = null;

  for (const кусок of запрос.split("&").filter(Boolean)) {
    const знак = кусок.indexOf("=");
    if (знак < 0) continue;
    const ключ = decodeURIComponent(кусок.slice(0, знак));
    const значение = decodeURIComponent(кусок.slice(знак + 1));

    if (ключ === "select") { выбрать = значение; continue; }
    if (ключ === "limit") { предел = Number(значение) || null; continue; }
    if (ключ === "offset") { смещение = Number(значение) || 0; continue; }
    if (ключ === "order") {
      порядок = значение.split(",").filter(Boolean).map(часть => {
        const [кол, напр = "asc"] = часть.split(".");
        return { колонка: имя(кол), вниз: /desc/i.test(напр) };
      });
      continue;
    }
    // всё прочее — условие: колонка=оператор.значение
    const точка = значение.indexOf(".");
    if (точка < 0) throw new Error("Непонятное условие: " + кусок);
    условия.push({
      колонка: имя(ключ),
      оператор: значение.slice(0, точка),
      значение: значение.slice(точка + 1),
    });
  }
  return { таблица, условия, выбрать, порядок, предел, смещение };
}

// Условия → кусок WHERE и список значений.
// Значения ВСЕГДА уходят отдельными параметрами ($1, $2 …) — так чужой
// текст не может превратиться в часть запроса.
export function где(условия, сНомера = 1) {
  const части = [];
  const значения = [];
  let n = сНомера;

  for (const { колонка, оператор, значение } of условия) {
    switch (оператор) {
      case "eq":
        части.push(`${колонка} = $${n++}`); значения.push(значение); break;
      case "neq":
        части.push(`${колонка} <> $${n++}`); значения.push(значение); break;
      case "gte":
        части.push(`${колонка} >= $${n++}`); значения.push(значение); break;
      case "lte":
        части.push(`${колонка} <= $${n++}`); значения.push(значение); break;
      case "gt":
        части.push(`${колонка} > $${n++}`); значения.push(значение); break;
      case "lt":
        части.push(`${колонка} < $${n++}`); значения.push(значение); break;
      case "is":
        if (значение === "null") { части.push(`${колонка} is null`); break; }
        if (значение === "true" || значение === "false") { части.push(`${колонка} is ${значение}`); break; }
        throw new Error("Неизвестное is." + значение);
      case "not":
        // встречается только как not.is.null — «колонка заполнена»
        if (значение === "is.null") { части.push(`${колонка} is not null`); break; }
        throw new Error("Неизвестное not." + значение);
      case "in": {
        // in.(a,b,c) — список значений
        const внутри = значение.replace(/^\(/, "").replace(/\)$/, "");
        const список = внутри.length ? внутри.split(",").map(s => s.replace(/^"|"$/g, "")) : [];
        if (!список.length) { части.push("false"); break; }   // пустой список — ничего не подходит
        части.push(`${колонка} = any($${n++}::text[])`);
        значения.push(список);
        break;
      }
      case "cs":
        // cs.["123"] — «внутри списка есть такое значение» (jsonb)
        части.push(`${колонка} @> $${n++}::jsonb`);
        значения.push(значение);
        break;
      default:
        throw new Error("Условие пока не переведено на SQL: " + оператор);
    }
  }
  return { текст: части.length ? " where " + части.join(" and ") : "", значения, следующий: n };
}

// select=*  или  select=id,name,phones
function колонки(выбрать) {
  const s = String(выбрать || "*").trim();
  if (!s || s === "*") return "*";
  return s.split(",").map(k => имя(k.trim())).join(", ");
}

// ЧТЕНИЕ: путь PostgREST → SELECT
export function чтение(путь) {
  const { таблица, условия, выбрать, порядок, предел, смещение } = разобрать(путь);
  const w = где(условия);
  let sql = `select ${колонки(выбрать)} from ${таблица}${w.текст}`;
  if (порядок.length) sql += " order by " + порядок.map(о => `${о.колонка} ${о.вниз ? "desc" : "asc"}`).join(", ");
  if (предел != null) sql += ` limit ${Number(предел)}`;
  if (смещение != null) sql += ` offset ${Number(смещение)}`;
  return { sql, значения: w.значения };
}

// ЗАПИСЬ НОВОЙ СТРОКИ (или обновление, если такая уже есть).
// Supabase звали с Prefer: resolution=merge-duplicates — то же самое
// делает "on conflict (ключ) do update".
// ключ = null — обычная вставка без «перезаписать, если уже есть».
// Так пишется журнал изменений: каждая запись новая, перезаписывать нечего.
export function вставка(таблица, строки, ключ = "id") {
  имя(таблица); if (ключ !== null) имя(ключ);
  const список = Array.isArray(строки) ? строки : [строки];
  if (!список.length) return null;

  // колонки берём из всех строк: у разных строк набор полей может отличаться
  const поля = [...new Set(список.flatMap(r => Object.keys(r || {})))].map(имя);
  if (!поля.length) throw new Error("Нечего вставлять: пустая строка");

  const значения = [];
  let n = 1;
  const куски = список.map(r => "(" + поля.map(p => {
    значения.push(готово(r[p]));
    return "$" + n++;
  }).join(", ") + ")");

  const обновить = ключ === null ? "" : поля.filter(p => p !== ключ).map(p => `${p} = excluded.${p}`).join(", ");
  const sql = `insert into ${таблица} (${поля.join(", ")}) values ${куски.join(", ")}`
    + (ключ === null ? "" : ` on conflict (${ключ}) do ${обновить ? "update set " + обновить : "nothing"}`)
    + " returning *";
  return { sql, значения };
}

// ПРАВКА: путь с условиями + что менять
export function правка(путь, данные) {
  const { таблица, условия } = разобрать(путь);
  const поля = Object.keys(данные || {}).map(имя);
  if (!поля.length) throw new Error("Нечего менять: пустая правка");

  const значения = [];
  let n = 1;
  const set = поля.map(p => { значения.push(готово(данные[p])); return `${p} = $${n++}`; }).join(", ");
  const w = где(условия, n);
  if (!w.текст) throw new Error("Правка без условия запрещена: так можно переписать всю таблицу");
  return { sql: `update ${таблица} set ${set}${w.текст} returning *`, значения: [...значения, ...w.значения] };
}

// УДАЛЕНИЕ
export function удаление(путь) {
  const { таблица, условия } = разобрать(путь);
  const w = где(условия);
  if (!w.текст) throw new Error("Удаление без условия запрещено: так можно стереть всю таблицу");
  return { sql: `delete from ${таблица}${w.текст}`, значения: w.значения };
}

// Значение для записи. Объекты и списки уходят как jsonb — в базе
// колонки partии/телефоны/позиции именно такие.
function готово(v) {
  if (v === undefined) return null;
  if (v !== null && typeof v === "object") return JSON.stringify(v);
  return v;
}
