// ========================================================================
//  СЛИЯНИЕ ЗАКАЗОВ КЛИЕНТА.
//
//  Клиент отправляет заказ и ждёт, пока владелец проставит цены. Пока ждёт —
//  заказывает ещё. Раньше вторая отправка ЗАМЕНЯЛА список товаров в том же
//  заказе, и первый заказ терял содержимое: со стороны это выглядело так,
//  будто накладная исчезла. Теперь второй заказ ДОПИСЫВАЕТСЯ в первый,
//  одинаковые товары складываются по количеству.
//
//  Один расчёт на оба входа: заказ из бота (api/order.js) и заказ с сайта
//  (api/site-order.js) — иначе они снова разойдутся.
// ========================================================================

// Столько же, сколько принимает валидация на входе: больше ста тысяч штук
// одной позиции — это опечатка, а не заказ.
export const ПОТОЛОК = 100000;

const ключ = (it) => String(it?.product_id || "");
const число = (v) => {
  const n = Math.floor(Number(v) || 0);
  return n > 0 ? Math.min(n, ПОТОЛОК) : 0;
};

// Дописать новые позиции в уже отправленный заказ.
// Существующие строки сохраняются целиком — вместе с ценой, если владелец
// успел её проставить, и с любыми другими полями, которых мы тут не знаем.
export function слить(старые, новые) {
  const итог = (Array.isArray(старые) ? старые : [])
    .filter(it => ключ(it))
    .map(it => ({ ...it }));

  const поТовару = new Map();
  итог.forEach(it => { if (!поТовару.has(ключ(it))) поТовару.set(ключ(it), it); });

  for (const н of (Array.isArray(новые) ? новые : [])) {
    const id = ключ(н);
    const qty = число(н?.qty);
    if (!id || qty <= 0) continue;
    const есть = поТовару.get(id);
    if (есть) {
      есть.qty = Math.min(ПОТОЛОК, число(есть.qty) + qty);
    } else {
      const строка = { ...н, product_id: id, qty };
      if (!(Number(строка.unit_price) > 0)) строка.unit_price = 0;
      if (!строка.currency) строка.currency = "som";
      if (строка.paid == null) строка.paid = false;
      итог.push(строка);
      поТовару.set(id, строка);
    }
  }
  return итог;
}

// Текст владельцу: что именно изменилось. Без этого приходило безликое
// «заказ изменён», и приходилось открывать склад, чтобы понять что к чему.
export function описание(старые, слитые, имена = {}) {
  const было = new Map((Array.isArray(старые) ? старые : []).map(it => [ключ(it), число(it.qty)]));
  const строки = [];
  for (const it of (Array.isArray(слитые) ? слитые : [])) {
    const id = ключ(it);
    const стало = число(it.qty), прежде = было.get(id) || 0;
    if (стало === прежде) continue;
    const имя = имена[id] || id;
    строки.push(прежде > 0
      ? `• ${имя}: ${прежде} → ${стало}`
      : `• ${имя} × ${стало} (новый)`);
  }
  return строки;
}
