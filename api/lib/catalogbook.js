// Товары → разделы, от большого к малому. Скрытые в книгу не идут.
export function собратьРазделы(товары) {
  const таблица = { ...БУКВЫ };
  const карта = new Map();
  for (const p of товары || []) {
    if (!p || p.hidden || p.status === "hidden" || p.site_status === "hidden") continue;
    const k = разделТовара(p.category);
    if (!карта.has(k)) карта.set(k, []);
    карта.get(k).push(p);
  }
  const номер = (p) => {
    const m = /^[A-Z]{2}-(\d+)$/.exec(String(p.code || ""));
    return m ? Number(m[1]) : Infinity;
  };
  return [...карта.entries()]
    .map(([ключ, список]) => {
      // буквы — по уже выданным кодам раздела, иначе по таблице
      const сКодом = список.find(p => /^[A-Z]{2}-\d+$/.test(String(p.code || "")));
      const буквы = сКодом ? сКодом.code.slice(0, 2) : буквыРаздела(ключ, таблица);
      const отсортированы = список.slice().sort((a, b) =>
        (номер(a) - номер(b)) || String(a.name || "").localeCompare(String(b.name || ""), "ru"));
      return { ключ, буквы, товары: отсортированы };
    })
    .sort((a, b) => {
      if (a.ключ === "Без категории") return 1;
      if (b.ключ === "Без категории") return -1;
      return (b.товары.length - a.товары.length) || a.ключ.localeCompare(b.ключ, "ru");
    });
}

const поЧетыре = (список) => {
  const out = [];
  for (let i = 0; i < список.length; i += СЕТКА.колонок) out.push(список.slice(i, i + СЕТКА.колонок));
  return out;
};

// Раскладка книги. Возвращает { страницы, разделы } — у каждого раздела
// номер его первой страницы (для содержания).
export function разметить(разделы) {
  const С = СЕТКА;
  const страницы = [
    { вид: "обложка" },
    { вид: "о компании" },
    { вид: "содержание" },
  ];
  const итог = разделы.map(р => ({ ...р, страница: 0 }));

  let текущая = null;          // страница сетки, куда ещё можно дописать

  const новаяСетка = () => {
    текущая = { вид: "сетка", блоки: [], занято: 0 };
    страницы.push(текущая);
    return текущая;
  };

  for (const р of итог) {
    const ряды = поЧетыре(р.товары);
    const большой = р.товары.length >= ПОРОГ_ВВОДНОЙ;

    if (большой) {
      текущая = null;
      // вводная — только на чётной (левой) странице
      if ((страницы.length + 1) % 2 === 0) {
        страницы.push({ вид: "вводная", раздел: р });
        р.страница = страницы.length;
      }
    }

    let i = 0, первый = true;
    while (i < ряды.length) {
      const отступ = текущая && текущая.блоки.length ? С.междуРазделами : 0;
      const влезетРяд = текущая && текущая.занято + отступ + С.полоса + С.послеПолосы + С.карточка <= С.высота;
      if (!влезетРяд) новаяСетка();
      const стр = текущая;
      стр.занято += (стр.блоки.length ? С.междуРазделами : 0) + С.полоса + С.послеПолосы;
      const блок = { раздел: р, продолжение: !первый, ряды: [] };
      стр.блоки.push(блок);
      if (первый && !р.страница) р.страница = страницы.length;
      первый = false;

      while (i < ряды.length && стр.занято + (блок.ряды.length ? С.зазор : 0) + С.карточка <= С.высота) {
        стр.занято += (блок.ряды.length ? С.зазор : 0) + С.карточка;
        блок.ряды.push(ряды[i++]);
      }
      if (i < ряды.length) текущая = null;     // раздел не влез — дальше с новой страницы
    }
  }

  // кратно 4 вместе с задней обложкой
  while ((страницы.length + 1) % 4 !== 0) страницы.push({ вид: "заметки" });
  страницы.push({ вид: "задняя" });
  страницы.forEach((s, i) => { s.номер = i + 1; });
  return { страницы, разделы: итог };
}

// Какие страницы взять в образец: обложка, о компании, содержание, вводная, её сетка,
// страница с несколькими малыми разделами и задняя обложка.
export function страницыОбразца(страницы) {
  const взять = new Set([1, 2, 3, страницы.length]);
  const вводная = страницы.find(s => s.вид === "вводная");
  if (вводная) { взять.add(вводная.номер); взять.add(вводная.номер + 1); }
  const смесь = страницы.find(s => s.вид === "сетка" && s.блоки.length > 1);
  if (смесь) взять.add(смесь.номер);
  for (const s of страницы) { if (взять.size >= 7) break; if (s.вид === "сетка") взять.add(s.номер); }
  return [...взять].sort((a, b) => a - b);
}

