// Снимки для обложки и вводных: без повторов (у нескольких товаров бывает
// одно фото) и сперва «студийные» — вырезанные на белом фоне (PNG и
// обработанные снимки). Остальные берём вразброс по разделу, а не подряд.
export function лучшиеСнимки(товары, сколько) {
  const видели = new Set();
  const разные = [];
  for (const p of товары || []) {
    const путь = путьСнимка(p);
    if (!путь || видели.has(путь)) continue;
    видели.add(путь);
    разные.push(p);
  }
  const студийный = (p) => /ChatGPT_Image|\.png$/i.test(путьСнимка(p));
  const первые = разные.filter(студийный).slice(0, сколько);
  const прочие = разные.filter(p => !студийный(p));
  const нужно = сколько - первые.length;
  const вразброс = [];
  for (let i = 0; i < нужно && i < прочие.length; i++) {
    вразброс.push(прочие[Math.floor((i * прочие.length) / нужно)]);
  }
  return [...первые, ...вразброс];
}

