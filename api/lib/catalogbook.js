// Логотип: золотое кольцо с разрывом слева сверху и буквы GM, как в icon.svg.
function логотип(л, cx, cy, r, { цвет = ЦВ.золото, толщина = r * 0.055, прозрачность = 1 } = {}) {
  const точка = (град) => [cx + r * Math.cos(град * Math.PI / 180), cy + r * Math.sin(град * Math.PI / 180)];
  const [x1, y1] = точка(-96), [x2, y2] = точка(238);
  л.путь(`M ${x1} ${y1} A ${r} ${r} 0 1 1 ${x2} ${y2}`, 0, 0, { borderColor: цвет, borderWidth: толщина, borderOpacity: прозрачность, borderLineCap: 1 });
  const k = (r * 0.655) / GM_ВЫСОТА;                  // высота прописной — как в значке
  const w = GM_ШИРИНА * k;
  л.путь(GM_ПУТЬ, cx - w / 2, cy + r * 0.308, { scale: k, color: цвет, opacity: прозрачность });
}

// QR-код квадратиками. size — сторона вместе с белым полем.
function qr(л, текст, x, y, size) {
  const m = qrMatrix(текст);
  const n = m.length, поле = 2;
  const шаг = size / (n + поле * 2);
  л.скруглённый(x, y, size, size, 6, { color: ЦВ.белый });
  for (let r = 0; r < n; r++) {
    for (let c = 0; c < n; c++) {
      if (!m[r][c]) continue;
      // соседние модули в строке сливаем в одну полосу — меньше объектов и нет щелей
      let len = 1;
      while (c + len < n && m[r][c + len]) len++;
      л.прямоуг(x + (поле + c) * шаг, y + (поле + r) * шаг, len * шаг + 0.05, шаг + 0.05, { color: ЦВ.тёмный });
      c += len - 1;
    }
  }
}

