// Перенос по словам в заданную ширину, не больше maxLines строк; что не
// влезло — многоточие. Слишком длинное слово режем по буквам.
export function перенести(текст, шрифт, кегль, ширина, строк = 2) {
  const ш = (t) => шрифт.widthOfTextAtSize(t, кегль);
  const слова = String(текст || "").replace(/\s+/g, " ").trim().split(" ").filter(Boolean);
  const out = [];
  let строка = "", k = 0;
  while (k < слова.length && out.length < строк) {
    const слово = слова[k];
    const проба = строка ? строка + " " + слово : слово;
    if (ш(проба) <= ширина) { строка = проба; k++; continue; }
    if (строка) { out.push(строка); строка = ""; continue; }
    // само слово шире строки — режем по буквам
    let n = слово.length;
    while (n > 1 && ш(слово.slice(0, n)) > ширина) n--;
    out.push(слово.slice(0, n));
    слова[k] = слово.slice(n);
    if (!слова[k]) k++;
  }
  if (строка) out.push(строка);                  // сюда попадаем, только если место есть
  // что-то не влезло — последняя строка с многоточием
  if (k < слова.length && out.length) {
    let last = out[out.length - 1];
    while (last.length > 1 && ш(last + "…") > ширина) last = last.slice(0, -1);
    out[out.length - 1] = last.trimEnd() + "…";
  }
  return out;
}

// Поворот, записанный телефоном в EXIF: 1 — как есть, 3/6/8 — снимок надо
// повернуть. Браузер поворачивает сам, а PDF кладёт снимок как есть.
export function ориентацияJpeg(b) {
  if (!b || b.length < 4 || b[0] !== 0xff || b[1] !== 0xd8) return 1;
  let i = 2;
  while (i + 4 <= b.length) {
    if (b[i] !== 0xff) return 1;
    const метка = b[i + 1];
    const длина = (b[i + 2] << 8) | b[i + 3];
    if (метка === 0xda || метка === 0xd9) return 1;          // дальше само изображение
    if (метка === 0xe1 && b[i + 4] === 0x45 && b[i + 5] === 0x78 && b[i + 6] === 0x69 && b[i + 7] === 0x66) {
      const t = i + 10;                                        // заголовок TIFF
      const le = b[t] === 0x49;
      const u16 = (o) => (le ? b[o] | (b[o + 1] << 8) : (b[o] << 8) | b[o + 1]);
      const u32 = (o) => (le ? (b[o] | (b[o + 1] << 8) | (b[o + 2] << 16) | (b[o + 3] << 24)) : ((b[o] << 24) | (b[o + 1] << 16) | (b[o + 2] << 8) | b[o + 3])) >>> 0;
      const ifd = t + u32(t + 4);
      if (ifd + 2 > b.length) return 1;
      const записей = u16(ifd);
      for (let k = 0; k < записей; k++) {
        const e = ifd + 2 + k * 12;
        if (e + 12 > b.length) break;
        if (u16(e) === 0x0112) return u16(e + 8) || 1;
      }
      return 1;
    }
    i += 2 + длина;
  }
  return 1;
}

// Путь снимка в хранилище из того, что лежит в товаре (ссылка или путь).
export function путьСнимка(товар) {
  const первый = (Array.isArray(товар && товар.photos) && товар.photos[0]) || (товар && товар.photo_url) || "";
  const s = String(первый);
  const i = s.indexOf("/object/public/");
  if (i >= 0) return decodeURIComponent(s.slice(i + "/object/public/".length).split("?")[0]);
  if (s.startsWith("product-photos/")) return s;
  return "";
}

