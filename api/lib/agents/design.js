// ========================================================================
//  АГЕНТ ДИЗАЙНА.
//
//  Раз в неделю собирает измеримые сигналы о том, где сайту неудобно, и
//  кладёт их владельцу с числами. Ничего не меняет и не может: ни
//  модели, ни браузера, ни прав на боевые файлы у него нет.
//
//  Где берёт данные — всё уже пишется в проекте, новых счётчиков нет:
//    • устройства визитов — client_events (журнал «Клиенты и безопасность»)
//    • вступительный ролик — api/lib/introstore.js (обезличенные счётчики)
//    • нарушения CSP       — api/csp-report.js (в памяти сервера)
//    • товары без фото     — products
//    • готовность карточек — представление product_card_ready
//
//  Сами варианты оформления делаются в сессии, в папке _demo/, и на сайт
//  попадают только после вашего одобрения — отдельной веткой, с откатом.
// ========================================================================
import { устройства, ролик, csp, каталог, сигналы } from "./design-math.js";

export async function прогон(ctx) {
  const сейчас = Date.now();
  const от = new Date(сейчас - 90 * 86400e3).toISOString();

  const [события, товары, готовность] = await Promise.all([
    ctx.читать("client_events?select=kind,channel,device&created_at=gte." + encodeURIComponent(от) + "&limit=5000").catch(() => []),
    ctx.читать("products?select=id,code,name,stock_qty,photo_url"),
    // Представление появится после db/product-card-migration.sql.
    ctx.читать("product_card_ready?ready=is.true&select=id").catch(() => null),
  ]);

  // Ролик и CSP живут в этом же процессе сервера — читаем напрямую.
  let итогРолика = {}, ролНет = null;
  try {
    const { сводка } = await import("../introstore.js");
    итогРолика = сводка(30)?.total || {};
  } catch { ролНет = "счётчики ролика не прочитались"; }

  let виденные = null, cspНет = null;
  try {
    const м = await import("../../csp-report.js");
    виденные = м._виденные;
  } catch { cspНет = "отчёты CSP не прочитались"; }

  const уст = устройства(события || []);
  const рол = ролик(итогРолика);
  const кс = csp(виденные);
  const кат = каталог(товары || [], Array.isArray(готовность) ? готовность.length : null);
  const список = сигналы({ уст, рол, кс, кат });

  const выводы = список.filter((с) => !с.мало);
  if (выводы.length) {
    const неделя = new Date(сейчас + 5 * 3600e3).toISOString().slice(0, 10);
    await ctx.уведомить({
      kind: "design_signals", level: "info",
      title: `Что стоит улучшить: ${выводы.length} ${выводы.length === 1 ? "сигнал" : "сигнала"}`,
      body: выводы.slice(0, 6).map((с) => `• ${с.что}\n  → ${с.вывод}${с.сделать ? "\n  Что сделать: " + с.сделать : ""}`).join("\n\n"),
      // Раз в неделю и только при новом наборе тем.
      dedup_key: `design:${неделя.slice(0, 7)}:${выводы.map((с) => с.тема).sort().join("|")}`,
      payload: { темы: выводы.map((с) => с.тема) },
    });
  }

  return {
    сводка: выводы.length
      ? `Сигналов: ${выводы.length}. Главное — ${выводы[0].вывод}`
      : "Заметных неудобств по данным не видно",
    детали: {
      сигналы: список,
      устройства: уст,
      ролик: рол,
      csp: { ...кс, примечание: "счётчик живёт в памяти сервера и обнуляется при перезапуске" },
      каталог: кат,
      // Чего агент не умеет — говорим прямо, а не делаем вид.
      неУмеет: [
        "смотреть сайт глазами: браузера и модели на сервере нет — варианты оформления делаются в сессии",
        "менять сайт: только предлагает, внедрение — после одобрения, отдельной веткой",
        ...(ролНет ? [ролНет] : []),
        ...(cspНет ? [cspНет] : []),
      ],
    },
  };
}

export default прогон;
