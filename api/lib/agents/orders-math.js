// ========================================================================
//  АРИФМЕТИКА ЗАКАЗОВ ДЛЯ АГЕНТА.
//
//  Только счёт: ни базы, ни сети, ни записи. Этапы здесь НЕ меняются —
//  их меняет SQL-функция fulfillment_transition, и только по нажатию
//  человека. Агент умеет лишь смотреть и считать.
//
//  Три вещи, которые легко посчитать неправильно:
//
//  1. ЭТАП БЕЗ СТРОКИ — ЭТО «ОФОРМЛЕН». Накладная, которой нет в
//     order_fulfillment, не «вне системы»: её просто ещё не трогали.
//     На доске она лежит в первой колонке, и агент считает так же.
//
//  2. НЕХВАТКА — ЭТО МИНУС, А НЕ МАЛЫЙ ОСТАТОК. Накладная со статусом
//     final уже списала товар со склада. Сравнивать её позиции с
//     остатком бессмысленно — остаток уже уменьшен. Зато если остаток
//     ушёл В МИНУС, значит списали то, чего на полке нет: собрать
//     такой заказ нечем. Это и есть сигнал.
//
//  3. ПРИЧИНУ ЗАДЕРЖКИ НЕ ВЫДУМЫВАЕМ. Берём только то, что записано:
//     комментарий к отправке, минус по остатку, отсутствие
//     ответственного. Пусто — так и пишем «причина не указана».
// ========================================================================
import { вUSD } from "./sales-math.js";

const СУТКИ = 86400e3;
const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const мс = (v) => { const t = typeof v === "number" ? v : Date.parse(v); return Number.isFinite(t) ? t : null; };

export const ЭТАПЫ = ["placed", "packed", "shipped"];
export const ЭТАП_ИМЯ = {
  placed: "оформлен, не собран",
  packed: "собран, не отправлен",
  shipped: "отправлен",
};
// Сколько дней заказу позволено простоять на этапе. Правится в
// настройках агента: config.просрочка = { placed: 2, packed: 1 }.
export const ПОРОГИ = { placed: 2, packed: 1 };

export const номерЗаказа = (id) => String(id || "").replace(/[^a-zA-Z0-9]/g, "").slice(-6).toUpperCase();

// ======================================================================
//  СОБРАТЬ КАРТИНУ
//
//  продажи — уже отфильтрованные «в учёте» накладные (это решает
//  api/lib/fulfillment.js, повторять его здесь нельзя).
// ======================================================================
export function заказы({ продажи = [], строки = [], доска = [], товары = [], курсы = {}, сейчас = Date.now() } = {}) {
  const поЗаказу = new Map((строки || []).map((с) => [String(с.sale_id), с]));
  const наДоске = new Map((доска || []).map((с) => [String(с.sale_id), с]));
  const поТовару = new Map((товары || []).map((т) => [String(т.id), т]));

  return (продажи || []).map((н) => {
    const id = String(н.id);
    const с = поЗаказу.get(id) || null;
    const д = наДоске.get(id) || null;
    const этап = ЭТАПЫ.includes(String(с?.stage)) ? String(с.stage) : "placed";

    const оформлен = мс(н.created_at) ?? мс(н.date) ?? сейчас;
    // На этапе он с последнего движения; движения не было — со дня оформления.
    const сдвинут = мс(с?.updated_at) ?? оформлен;

    const позиции = н.items || [];
    const сумма = позиции.reduce((a, п) =>
      a + вUSD(чис(п.qty) * чис(п.unit_price), п.currency || н.currency, курсы), 0);

    // Нечем собрать: товар ушёл в минус — списали то, чего нет на полке.
    const нехватка = [];
    for (const п of позиции) {
      const т = поТовару.get(String(п.product_id));
      if (!т) continue;
      const остаток = чис(т.stock_qty);
      if (остаток < 0) нехватка.push({ id: String(т.id), код: т.code || "", имя: т.name || "", остаток });
    }

    const ответственный = с?.shipped_by || с?.packed_by || "";
    const причины = [];
    if (нехватка.length) причины.push(`нечем собрать: ${нехватка.length} поз. в минусе`);
    if (с?.ship_comment) причины.push(String(с.ship_comment).slice(0, 200));
    if (этап !== "placed" && !ответственный) причины.push("не указан ответственный");

    return {
      id, номер: номерЗаказа(id),
      клиент: н.customer_id ? String(н.customer_id) : "",
      этап, этапИмя: ЭТАП_ИМЯ[этап],
      оформлен, сдвинут,
      днейЖдёт: Math.floor((сейчас - оформлен) / СУТКИ),
      днейНаЭтапе: Math.floor((сейчас - сдвинут) / СУТКИ),
      позиций: позиции.length,
      суммаUSD: Math.round(сумма * 100) / 100,
      срочно: !!д?.urgent,
      перевозчик: с?.carrier || "",
      трек: с?.tracking || "",
      ответственный,
      нехватка,
      причина: причины.length ? причины.join("; ") : "причина не указана",
    };
  });
}

// Просрочен ли заказ: стоит на этапе дольше положенного.
// Отправленные не считаются никогда — они уже уехали.
export function просрочен(з, пороги = ПОРОГИ) {
  if (!з || з.этап === "shipped") return false;
  const порог = чис(пороги?.[з.этап] ?? ПОРОГИ[з.этап]);
  return з.днейНаЭтапе > порог;
}

// Чем выше число, тем раньше заказ надо трогать.
// Срочность с доски весит больше всего: её ставит человек руками.
export function приоритет(з) {
  if (!з) return 0;
  return (з.срочно ? 1000 : 0)
    + (з.нехватка.length ? 500 : 0)
    + з.днейНаЭтапе * 10
    + Math.min(100, з.суммаUSD / 10);
}

export const поПриоритету = (а, б) => приоритет(б) - приоритет(а);

// ======================================================================
//  СВОДКА
// ======================================================================
export function сводка(список, пороги = ПОРОГИ) {
  const не = (э) => список.filter((з) => з.этап === э);
  const неСобрано = не("placed");
  const неОтправлено = не("packed");
  const просрочено = список.filter((з) => просрочен(з, пороги));
  const нечемСобрать = список.filter((з) => з.этап !== "shipped" && з.нехватка.length);
  const срочные = список.filter((з) => з.этап !== "shipped" && з.срочно);

  return {
    всего: список.length,
    неСобрано: неСобрано.length,
    неОтправлено: неОтправлено.length,
    отправлено: не("shipped").length,
    просрочено: просрочено.length,
    нечемСобрать: нечемСобрать.length,
    срочных: срочные.length,
    суммаВРаботеUSD: Math.round(
      [...неСобрано, ...неОтправлено].reduce((a, з) => a + з.суммаUSD, 0) * 100) / 100,
    самыйСтарый: список
      .filter((з) => з.этап !== "shipped")
      .reduce((м, з) => (!м || з.днейЖдёт > м.днейЖдёт ? з : м), null),
  };
}

// Какие товары не дают собрать заказы — для агента склада.
// Возвращает по товару: сколько заказов на нём стоит и насколько минус.
export function нехваткаПоТоварам(список) {
  const из = new Map();
  for (const з of список) {
    if (з.этап === "shipped") continue;
    for (const н of з.нехватка) {
      const было = из.get(н.id) || { ...н, заказов: 0, заказы: [] };
      было.заказов += 1;
      if (было.заказы.length < 20) было.заказы.push(з.номер);
      из.set(н.id, было);
    }
  }
  return [...из.values()].sort((a, b) => b.заказов - a.заказов);
}
