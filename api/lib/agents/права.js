// ========================================================================
//  ПРАВА АГЕНТОВ.
//
//  По умолчанию агент НИЧЕГО не пишет. Право на запись выдаётся
//  поимённо, таблица за таблицей, и проверяется перед каждым обращением
//  — не в голове у того, кто писал агента, а здесь, в одном месте.
//
//  Почему так, а не «агент же не станет менять остатки»: станет, если
//  в коде опечатка или если завтра кто-то допишет агенту новую задачу и
//  не вспомнит про запрет. Проверка в коде переживает забывчивость.
//
//  Остатки товаров (products) не может менять ни один агент. Запись
//  остатков в проекте идёт единственным путём — api/admin/db.js через
//  api/lib/stocklog.js, и за человеком она и остаётся.
//
//  Субагент не может получить больше прав, чем у родителя: права
//  выдаются по агенту, субагент работает с правами того же агента и
//  может их только сузить (см. сузить() ниже).
// ========================================================================

// Таблицы, которые ведёт сама система агентов. Писать в них может
// только ядро — агент туда не ходит напрямую.
export const СЛУЖЕБНЫЕ = ["agent_state", "agent_runs", "agent_subruns", "agent_notices", "agent_approvals", "agent_budget"];

// Что агент имеет право писать СВЕРХ служебных таблиц.
// Пусто — значит только чтение. Это и есть норма.
const ЗАПИСЬ = {
  warehouse: ["product_policy"],   // свои пороги закупки по товару (этап 2)
  orders:    [],                   // этапы заказов меняет только человек
  security:  [],
  telegram:  [],
  design:    [],
};

// Что агент имеет право читать. "*" — весь склад на чтение; это
// безопасно, данные и так видны администратору в складе.
const ЧТЕНИЕ = {
  warehouse: "*", orders: "*", security: "*", telegram: "*", design: "*",
};

export class ОтказДоступа extends Error {
  constructor(сообщение) { super(сообщение); this.name = "ОтказДоступа"; this.код = "нет_прав"; }
}

// Имя таблицы из пути PostgREST: "products?id=eq.5&select=*" → "products"
export const таблицаИзПути = (путь) => String(путь || "").split(/[?/]/)[0].trim();

// ------------------------------------------------------------------
//  Пропуск агента. Возвращает объект с проверками; сам по себе в базу
//  не ходит — за это отвечает core.js, который его и спрашивает.
//  Только — необязательный список: так субагент сужает права родителя.
// ------------------------------------------------------------------
export function пропуск(agentId, только = null) {
  const id = String(agentId || "");
  const разрешеноПисать = ЗАПИСЬ[id];
  if (!разрешеноПисать) throw new ОтказДоступа(`Неизвестный агент: ${id || "без имени"}`);

  let запись = разрешеноПисать;
  if (Array.isArray(только)) запись = запись.filter((t) => только.includes(t));   // сузить можно, расширить — нет

  const читатьВсё = ЧТЕНИЕ[id] === "*";

  return {
    agentId: id,
    пишет: [...запись],

    можноЧитать(путь) {
      return читатьВсё || (ЧТЕНИЕ[id] || []).includes(таблицаИзПути(путь));
    },
    можноПисать(путь) {
      return запись.includes(таблицаИзПути(путь));
    },
    проверитьЧтение(путь) {
      if (!this.можноЧитать(путь)) throw new ОтказДоступа(`Агенту «${id}» не разрешено читать «${таблицаИзПути(путь)}»`);
      return путь;
    },
    проверитьЗапись(путь) {
      const т = таблицаИзПути(путь);
      if (СЛУЖЕБНЫЕ.includes(т)) throw new ОтказДоступа(`Таблицу «${т}» ведёт ядро, агент в неё не пишет напрямую`);
      if (!this.можноПисать(путь)) throw new ОтказДоступа(`Агенту «${id}» не разрешено менять «${т}». Нужно согласование владельца.`);
      return путь;
    },
    // Права для субагента: те же или уже, никогда шире.
    сузить(список) { return пропуск(id, Array.isArray(список) ? список.filter((t) => запись.includes(t)) : []); },
  };
}

// Для раздела в складе: что агент умеет делать с данными, человеческим языком.
export function описаниеПрав(agentId) {
  const список = ЗАПИСЬ[String(agentId || "")] || [];
  return список.length
    ? `Чтение склада; запись только в ${список.join(", ")}; остальное — через ваше согласование`
    : "Только чтение склада. Любое изменение — через ваше согласование";
}
