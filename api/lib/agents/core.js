// Подключён ли агент: либо работа уже загружена, либо известно, откуда
// её взять. Карточка в разделе показывает это ДО первого прогона.
const подключён = (id) => работы.has(id) || !!РЕАЛИЗАЦИИ[id];

async function найтиРаботу(id) {
  if (работы.has(id)) return работы.get(id);
  const загрузчик = РЕАЛИЗАЦИИ[id];
  if (!загрузчик) return null;
  try {
    const мод = await загрузчик();
    const фн = мод.прогон || мод.default;
    if (typeof фн === "function") { работы.set(id, фн); return фн; }
  } catch (e) {
    console.error(`[агент ${id}] модуль не загрузился:`, e?.message || e);
  }
  return null;
}

