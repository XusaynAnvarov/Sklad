// Часы подменяются в тестах (по образцу _реализации ниже).
let часы = () => Date.now();
export const _установитьЧасы = (фн) => { часы = typeof фн === "function" ? фн : () => Date.now(); };

// Молчим, только пока не истёк срок перепроверки.
const молчим = () => естьТаблицы === false && часы() < проверитьСнова;
export const таблицыГотовы = () => !молчим();

const этоНетТаблицы = (e) => {
  const t = String(e?.message || "");
  return /agent_(state|runs|subruns|notices|approvals|budget)/.test(t) &&
         /(does not exist|schema cache|PGRST205|relation)/i.test(t);
};

async function мягко(fn, иначе = null) {
  if (молчим()) return иначе;
  try {
    const r = await fn();
    if (естьТаблицы === false) console.log("[агенты] таблицы появились — агенты работают");
    естьТаблицы = true;
    return r;
  } catch (e) {
    if (этоНетТаблицы(e)) {
      if (естьТаблицы !== false) console.warn("[агенты] db/agents-migration.sql ещё не применён — агенты молчат, перепроверю через 5 минут");
      естьТаблицы = false;
      проверитьСнова = часы() + ПЕРЕПРОВЕРКА_МС;
      return иначе;
    }
    throw e;
  }
}

