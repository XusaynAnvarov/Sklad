// ========================================================================
//  АРИФМЕТИКА АГЕНТА ДИЗАЙНА.
//
//  Агент дизайна на сервере ничего не рисует и не меняет: ни модели, ни
//  браузера, ни права трогать боевые файлы у него нет. Его работа —
//  раз в неделю собрать ИЗМЕРИМЫЕ сигналы о неудобствах и положить их
//  владельцу с числами. Сами варианты оформления делаются в сессии, в
//  папке _demo/, и попадают на сайт только после одобрения.
//
//  Правило: ВЫВОД ТОЛЬКО ПРИ ДОСТАТОЧНЫХ ДАННЫХ. Из шести визитов не
//  делается вывод «сайт смотрят с телефона». Если данных мало — так и
//  пишем, с числом, а не молчим и не выдумываем тенденцию.
// ========================================================================

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const процент = (часть, всего) => (всего > 0 ? Math.round((часть / всего) * 1000) / 10 : 0);

// Меньше стольких событий — вывода нет, есть только «мало данных».
export const МИНИМУМ = 20;

// «1 товар, 2 товара, 5 товаров» — сообщение читает человек.
export function товаров(n) {
  const к = Math.abs(n) % 100, е = к % 10;
  if (к >= 11 && к <= 14) return `${n} товаров`;
  if (е === 1) return `${n} товар`;
  if (е >= 2 && е <= 4) return `${n} товара`;
  return `${n} товаров`;
}

// ======================================================================
//  1. С ЧЕГО СМОТРЯТ
// ======================================================================
export function устройства(события = []) {
  const визиты = события.filter((с) => с.kind === "site_visit" || с.channel === "site");
  let телефон = 0, компьютер = 0, неясно = 0;
  for (const с of визиты) {
    const д = String(с.device || "").toLowerCase();
    if (д === "mobile" || д === "tablet") телефон++;
    else if (д === "desktop") компьютер++;
    else неясно++;
  }
  const известно = телефон + компьютер;
  return {
    всего: визиты.length, телефон, компьютер, неясно,
    доляТелефона: процент(телефон, известно),
    хватает: известно >= МИНИМУМ,
  };
}

// ======================================================================
//  2. ВСТУПИТЕЛЬНЫЙ РОЛИК
//
//  итог — то, что отдаёт api/lib/introstore.js сводка(): счётчики
//  событий shown / completed / skipped и сумма секунд до пропуска.
// ======================================================================
export function ролик(итог = {}) {
  const показан = чис(итог.shown);
  const досмотрен = чис(итог.completed);
  const пропущен = чис(итог.skipped);
  return {
    показан, досмотрен, пропущен,
    досмотрелиПроцент: процент(досмотрен, показан),
    пропустилиПроцент: процент(пропущен, показан),
    // На какой секунде в среднем жмут «пропустить». Две секунды — это
    // «закрыли не глядя», двадцать — «посмотрели и пошли дальше».
    пропускСекунда: пропущен > 0 ? Math.round(чис(итог.skip_sec_sum) / пропущен * 10) / 10 : null,
    сТелефона: чис(итог["shown:mobile"]),
    хватает: показан >= МИНИМУМ,
  };
}

// ======================================================================
//  3. ОТЧЁТЫ CSP
//
//  виденные — Map из api/csp-report.js: «правило ← откуда» → {count, page}.
//  Живёт в памяти сервера и обнуляется при перезапуске — это говорим
//  прямо, чтобы ноль после выкладки не читался как «всё чисто».
// ======================================================================
export function csp(виденные) {
  const список = [];
  if (виденные && typeof виденные.forEach === "function") {
    виденные.forEach((з, ключ) => список.push({ ключ: String(ключ).slice(0, 160), раз: чис(з?.count), страница: з?.page || "" }));
  }
  список.sort((a, b) => b.раз - a.раз);
  return { различных: список.length, всего: список.reduce((a, с) => a + с.раз, 0), список: список.slice(0, 15) };
}

// ======================================================================
//  4. КАТАЛОГ ГЛАЗАМИ ПОКУПАТЕЛЯ
// ======================================================================
export function каталог(товары = [], готовыхКарточек = null) {
  const вНаличии = товары.filter((т) => чис(т.stock_qty) > 0);
  const безФото = вНаличии.filter((т) => !String(т.photo_url || "").trim());
  return {
    вНаличии: вНаличии.length,
    вНаличииБезФото: безФото.length,
    безФотоКоды: безФото.slice(0, 20).map((т) => т.code || т.name || String(т.id)),
    готовыхКарточек,
  };
}

// ======================================================================
//  СИГНАЛЫ — то, что уходит владельцу.
//
//  У каждого: что измерено, сколько, где порог, какой вывод и что можно
//  сделать. Вес — чтобы самое заметное шло первым. Без вывода сигнал не
//  создаётся; при нехватке данных — сигнал «мало данных», чтобы было
//  видно, почему про это молчим.
// ======================================================================
export function сигналы({ уст, рол, кс, кат } = {}) {
  const из = [];

  if (уст) {
    if (!уст.хватает) {
      из.push({ тема: "устройства", вес: 1, мало: true,
        что: `визитов с известным устройством — ${уст.телефон + уст.компьютер}, для вывода нужно от ${МИНИМУМ}` });
    } else if (уст.доляТелефона >= 50) {
      из.push({ тема: "устройства", вес: 8,
        что: `${уст.доляТелефона}% визитов — с телефона (${уст.телефон} из ${уст.телефон + уст.компьютер})`,
        вывод: "сайт смотрят в основном с телефона",
        сделать: "проверять каждую новую страницу сначала на ширине телефона; таблицы и длинные формы — в первую очередь" });
    }
  }

  if (рол) {
    if (!рол.хватает) {
      из.push({ тема: "ролик", вес: 1, мало: true,
        что: `ролик показан ${рол.показан} раз, для вывода нужно от ${МИНИМУМ}` });
    } else if (рол.пропустилиПроцент >= 60 && (рол.пропускСекунда ?? 99) < 4) {
      из.push({ тема: "ролик", вес: 7,
        что: `${рол.пропустилиПроцент}% пропускают, в среднем на ${рол.пропускСекунда}-й секунде`,
        вывод: "ролик закрывают не глядя — он мешает, а не помогает",
        сделать: "показывать его реже (раз в неделю, а не при каждом входе) или сократить до 3–4 секунд" });
    } else if (рол.досмотрелиПроцент >= 40) {
      из.push({ тема: "ролик", вес: 2,
        что: `досматривают ${рол.досмотрелиПроцент}%`, вывод: "ролик работает — трогать не нужно" });
    }
  }

  if (кс && кс.различных > 0) {
    из.push({ тема: "csp", вес: 5,
      что: `${кс.различных} разных нарушений, всего ${кс.всего} раз; чаще всего: ${кс.список[0]?.ключ || "—"}`,
      вывод: "сайт грузит то, чего нет в списке разрешённого",
      сделать: "добавить эти адреса в api/lib/csp.js, прежде чем включать защиту вместо наблюдения" });
  }

  if (кат) {
    if (кат.вНаличииБезФото > 0) {
      из.push({ тема: "фото", вес: 9,
        что: `${товаров(кат.вНаличииБезФото)} есть на складе, но без фотографии`,
        вывод: "покупатель видит серую заглушку вместо товара, который можно купить сегодня",
        сделать: "сделать снимки этих товаров: " + кат.безФотоКоды.slice(0, 8).join(", ") + (кат.безФотоКоды.length > 8 ? "…" : "") });
    }
    if (кат.готовыхКарточек !== null && кат.вНаличии > 0) {
      const доля = процент(кат.готовыхКарточек, кат.вНаличии);
      if (доля < 10) {
        из.push({ тема: "карточки", вес: 4,
          что: `готовых к карточке: ${кат.готовыхКарточек} из ${кат.вНаличии} товаров в наличии (${доля}%)`,
          вывод: "у товаров нет фактов для карточки — названия и свойства не заведены",
          сделать: "завести хотя бы название и два свойства для самых ходовых товаров" });
      }
    }
  }

  return из.sort((a, b) => b.вес - a.вес);
}
