// ========================================================================
//  ИСПОЛНЕНИЕ ОДОБРЕННОГО.
//
//  Сюда попадает предложение ТОЛЬКО после того, как владелец нажал
//  «Одобрить» — в разделе «ИИ-Агенты» или кнопкой в Telegram. Само по
//  себе ничего отсюда не вызывается.
//
//  Что делается по каждому виду:
//    post            — публикация в канал (или в личку в тестовом режиме)
//    channel_setup   — ничего: канал создаётся руками, Bot API не умеет
//    purchase        — ничего автоматически: закупку оформляете вы на
//                      странице «Заказ поставщику», агент лишь подсказал
//    security_action — ничего автоматически: блокировки делаются руками
//
//  Последние три — нарочно «ничего». Одобрение там значит «принял к
//  сведению», а не «сделай за меня». Действие с деньгами или доступами
//  агент не совершает даже с вашего согласия: для этого в складе есть
//  свои страницы, где видно всё целиком.
// ========================================================================

export async function исполнить(заявка) {
  if (!заявка) return { ок: false, причина: "предложение не найдено" };

  switch (String(заявка.kind)) {
    case "post": {
      const { опубликовать } = await import("./telegram.js");
      const r = await опубликовать(заявка);
      return {
        ок: r.ок,
        что: r.тест ? "отправлено вам в личные сообщения (тестовый режим)" : "опубликовано в канале",
        успешно: r.успешно ?? 0, всего: r.всего ?? 0,
        ошибки: (r.послано || []).filter((x) => !x.ок).map((x) => `${x.код}: ${x.ошибка}`),
        причина: r.причина || null,
      };
    }
    case "channel_setup":
      return { ок: true, что: "заготовка принята — канал создаётся вручную по шагам из предложения" };
    case "purchase":
      return { ок: true, что: "принято к сведению — оформите закупку на странице «Заказ поставщику»" };
    case "security_action":
      return { ок: true, что: "принято к сведению — действие выполняется вручную" };
    default:
      return { ок: true, что: "принято" };
  }
}

// Подпись для владельца после исполнения: коротко и по делу.
export function итогСловами(р) {
  if (!р) return "";
  if (!р.ок) return "Не получилось: " + (р.причина || (р.ошибки || [])[0] || "причина неизвестна");
  if (р.всего) return `${р.что}: ${р.успешно} из ${р.всего}`;
  return р.что;
}
