// ========================================================================
//  ИСПОЛНЕНИЕ ОДОБРЕННОГО.
//
//  Сюда попадает предложение ТОЛЬКО после того, как владелец нажал
//  «Одобрить» — в разделе «ИИ-Агенты» или кнопкой в Telegram. Само по
//  себе ничего отсюда не вызывается.
//
//  Что делается по каждому виду:
//    post            — публикация в канал (или в личку в тестовом режиме)
//    channel_setup   — ничего: канал создаётся руками, Bot API не умеет
//    purchase        — черновик заказа поставщику (без денег и остатков):
//                      форму на странице «Заказ поставщику» он заполняет,
//                      а отправляете и сохраняете приход вы сами
//    security_action — ничего автоматически: блокировки делаются руками
//
//  Последние три — нарочно «ничего». Одобрение там значит «принял к
//  сведению», а не «сделай за меня». Действие с деньгами или доступами
//  агент не совершает даже с вашего согласия: для этого в складе есть
//  свои страницы, где видно всё целиком.
// ========================================================================

export async function исполнить(заявка) {
  if (!заявка) return { ок: false, причина: "предложение не найдено" };

  switch (String(заявка.kind)) {
    case "post": {
      const { опубликовать } = await import("./telegram.js");
      // КУДА слать — решают настройки агента на момент одобрения, а не
      // на момент, когда черновик готовили. Иначе черновик, собранный в
      // тестовом режиме, уходил бы в личку и после того, как владелец
      // тестовый режим выключил. Канал в настройках не задан — остаётся
      // то, что записано в самом черновике.
      const сейчас = await текущиеНастройкиTelegram();
      const payload = сейчас?.канал
        ? { ...(заявка.payload || {}), тест: сейчас.тест !== false, канал: сейчас.канал }
        : заявка.payload;
      const r = await опубликовать({ ...заявка, payload });
      return {
        ок: r.ок,
        что: r.тест ? "отправлено вам в личные сообщения (тестовый режим)" : "опубликовано в канале",
        успешно: r.успешно ?? 0, всего: r.всего ?? 0,
        ошибки: (r.послано || []).filter((x) => !x.ок).map((x) => `${x.код}: ${x.ошибка}`),
        причина: r.причина || null,
      };
    }
    case "channel_setup":
      return { ок: true, что: "заготовка принята — канал создаётся вручную по шагам из предложения" };
    case "purchase": {
      // Денег и остатков одобрение не трогает. Оно превращает список в
      // ЧЕРНОВИК заказа поставщику: на странице «Заказ поставщику» в блоке
      // «Черновики от агента склада» он разбит по поставщикам, одним
      // нажатием заполняет форму, а PDF/Excel/приход вы делаете сами.
      const товары = заявка.payload?.товары || [];
      const поставщиков = new Set(товары.map((т) => т.поставщик || "не определён")).size;
      return {
        ок: true, черновик: true, позиций: товары.length, поставщиков,
        что: `черновик заказа поставщику готов: ${товары.length} позиц., поставщиков: ${поставщиков}. Откройте «Заказ поставщику» → «Черновики от агента склада»`,
      };
    }
    case "security_action":
      return { ок: true, что: "принято к сведению — действие выполняется вручную" };
    default:
      return { ок: true, что: "принято" };
  }
}

async function текущиеНастройкиTelegram() {
  try {
    const { текущиеНастройки } = await import("./core.js");
    return await текущиеНастройки("telegram");
  } catch { return null; }
}

// Подпись для владельца после исполнения: коротко и по делу.
export function итогСловами(р) {
  if (!р) return "";
  if (!р.ок) return "Не получилось: " + (р.причина || (р.ошибки || [])[0] || "причина неизвестна");
  if (р.всего) return `${р.что}: ${р.успешно} из ${р.всего}`;
  return р.что;
}
