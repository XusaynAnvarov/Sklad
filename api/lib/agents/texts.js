//
//  Модели здесь нет. Пост складывается из полей карточки товара по
//  шаблону. Это осознанный выбор владельца: ключа к ИИ-модели нет, а
//  выдуманный текст о запчасти опаснее, чем отсутствие текста —
//  клиент закажет не ту деталь.
//
//  Если ключ когда-нибудь появится, менять придётся один этот файл:
//  наружу торчат только функции, а не способ получения текста.
//
//  ПРАВИЛО: ЧЕГО НЕТ В КАРТОЧКЕ, ТОГО НЕТ В ПОСТЕ. Недостающее не
//  придумывается, а перечисляется в «пропусках» — это и есть подсказка
//  владельцу, что дозаполнить.
// ========================================================================

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
export const esc = (s) => String(s ?? "")
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const ЕДИНИЦЫ = { som: "сум", usd: "$", yuan: "¥" };

// Цена в местной валюте. Показывается, только если владелец разрешил:
// в канале цена живёт своей жизнью и устаревает быстрее склада.
export function ценаСтрокой(товар, { валюта = "som" } = {}) {
  const поле = { som: "price_som", usd: "price_usd", yuan: "price_yuan" }[валюта] || "price_som";
  const v = чис(товар?.[поле]);
  if (v <= 0) return null;
  return `${числоЦены(v, валюта)} ${ЕДИНИЦЫ[валюта] || ""}`.trim();
}
// Сум — целыми: копеек в нём нет, а «3 600 000,00» читается хуже.
const числоЦены = (v, валюта) =>
  валюта === "som" ? Math.round(v).toLocaleString("ru-RU") : (Math.round(v * 100) / 100).toLocaleString("ru-RU");

export const вНаличии = (товар) => чис(товар?.stock_qty) > 0;

// ======================================================================
//  ПОСТ О ТОВАРЕ
//
//  Возвращает и текст, и список того, чего не хватило. Второе не менее
//  важно: по нему видно, какие карточки стоит дозаполнить.
// ======================================================================
// Факты карточки (таблица product_fact), которые идут в пост. Берём
// только те, у которых записан источник: без источника факт — это
// догадка, а догадка о запчасти приводит к заказу не той детали.
//   описание       — что это и для чего, одним-двумя предложениями
//   совместимость  — к каким машинам подходит
//   свойство       — пункты списка (их бывает несколько)
//   предупреждение — что проверить перед покупкой
export function фактыДляПоста(факты = []) {
  const годные = (факты || [])
    .filter((ф) => ф && String(ф.value || "").trim() && String(ф.source || "").trim() && ф.confidence !== "не найдено")
    .sort((а, б) => (Number(а.sort) || 0) - (Number(б.sort) || 0));
  const одно = (к) => годные.find((ф) => ф.key === к)?.value?.trim() || "";
  return {
    // Понятное название для покупателя: «Поворотное колесо с тормозом»
    // вместо складского «Гилдирак». В складе название не меняется.
    название: одно("название"),
    описание: одно("описание"),
    совместимость: одно("совместимость"),
    свойства: годные.filter((ф) => ф.key === "свойство").map((ф) => ф.value.trim()).slice(0, 5),
    предупреждение: одно("предупреждение"),
    источники: [...new Set(годные.map((ф) => ф.source.trim()))],
  };
}

export function постТовара(товар, { ссылка = "", показыватьЦену = false, валюта = "som", видео = null, факты = [] } = {}) {
  const пропуски = [];
  const имя = String(товар?.name || "").trim();
  if (!имя) пропуски.push("название");

  const код = String(товар?.code || "").trim();
  const бренд = String(товар?.sku || "").trim();
  const категория = String(товар?.category || "").trim();

  if (!товар?.photo_url) пропуски.push("фотография");
  if (!категория) пропуски.push("категория");

  // Заголовок — понятное название из карточки, если оно есть. Складское
  // название идёт строкой ниже: по нему товар узнают в магазине и на сайте.
  const ф = фактыДляПоста(факты);
  const заголовок = ф.название || имя;
  const строки = [];
  строки.push(`<b>${esc(заголовок || "Без названия")}</b>`);

  const складское = ф.название && имя && ф.название.toLowerCase() !== имя.toLowerCase() ? имя : "";
  const подзаголовок = [складское, категория, бренд].filter(Boolean).join(" · ");
  if (подзаголовок) строки.push(esc(подзаголовок));

  // Описание из карточки — главное, ради чего пост читают: что это
  // за деталь и куда она ставится.
  if (ф.описание) строки.push("", esc(ф.описание));
  else пропуски.push("описание");
  if (ф.свойства.length) строки.push("", ...ф.свойства.map((с) => "• " + esc(с)));
  if (ф.совместимость) строки.push("", `🧵 Подходит: ${esc(ф.совместимость)}`);
  else пропуски.push("совместимость");
  if (ф.предупреждение) строки.push(`⚠️ ${esc(ф.предупреждение)}`);

  строки.push("");

  if (код) строки.push(`Артикул: <code>${esc(код)}</code>`);
  else пропуски.push("артикул");

  if (показыватьЦену) {
    const ц = ценаСтрокой(товар, { валюта });
    if (ц) строки.push(`Цена: <b>${esc(ц)}</b>`);
    else пропуски.push("цена");
  }

  строки.push(вНаличии(товар) ? "✅ Есть в наличии" : "⏳ Под заказ");

  // Видео — только своё, из таблицы videos, и не ссылкой (ролики лежат
  // в закрытом хранилище, ссылка не открылась бы), а самим файлом рядом
  // с фото. Здесь лишь пометка; сам ролик прикладывает telegram.js.
  if (видео) строки.push("🎬 Видео работы — в этом посте");

  if (ссылка) строки.push(`\n🛒 Заказать: ${esc(ссылка)}`);

  return {
    текст: строки.join("\n").trim(),
    пропуски,
    источники: ф.источники,
    кнопки: ссылка ? [[{ text: "Заказать", url: ссылка }]] : [],
  };
}

