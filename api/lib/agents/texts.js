//
//  Модели здесь нет. Пост складывается из полей карточки товара по
//  шаблону. Это осознанный выбор владельца: ключа к ИИ-модели нет, а
//  выдуманный текст о запчасти опаснее, чем отсутствие текста —
//  клиент закажет не ту деталь.
//
//  Если ключ когда-нибудь появится, менять придётся один этот файл:
//  наружу торчат только функции, а не способ получения текста.
//
//  ПРАВИЛО: ЧЕГО НЕТ В КАРТОЧКЕ, ТОГО НЕТ В ПОСТЕ. Недостающее не
//  придумывается, а перечисляется в «пропусках» — это и есть подсказка
//  владельцу, что дозаполнить.
// ========================================================================

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
export const esc = (s) => String(s ?? "")
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

const ЕДИНИЦЫ = { som: "сум", usd: "$", yuan: "¥" };

// Цена в местной валюте. Показывается, только если владелец разрешил:
// в канале цена живёт своей жизнью и устаревает быстрее склада.
export function ценаСтрокой(товар, { валюта = "som" } = {}) {
  const поле = { som: "price_som", usd: "price_usd", yuan: "price_yuan" }[валюта] || "price_som";
  const v = чис(товар?.[поле]);
  if (v <= 0) return null;
  return `${числоЦены(v, валюта)} ${ЕДИНИЦЫ[валюта] || ""}`.trim();
}
// Сум — целыми: копеек в нём нет, а «3 600 000,00» читается хуже.
const числоЦены = (v, валюта) =>
  валюта === "som" ? Math.round(v).toLocaleString("ru-RU") : (Math.round(v * 100) / 100).toLocaleString("ru-RU");

export const вНаличии = (товар) => чис(товар?.stock_qty) > 0;

// ======================================================================
//  ПОСТ О ТОВАРЕ
//
//  Возвращает и текст, и список того, чего не хватило. Второе не менее
//  важно: по нему видно, какие карточки стоит дозаполнить.
// ======================================================================
export function постТовара(товар, { ссылка = "", показыватьЦену = false, валюта = "som", видео = null } = {}) {
  const пропуски = [];
  const имя = String(товар?.name || "").trim();
  if (!имя) пропуски.push("название");

  const код = String(товар?.code || "").trim();
  const бренд = String(товар?.sku || "").trim();
  const категория = String(товар?.category || "").trim();

  if (!товар?.photo_url) пропуски.push("фотография");
  if (!категория) пропуски.push("категория");

  const строки = [];
  строки.push(`<b>${esc(имя || "Без названия")}</b>`);

  const подзаголовок = [категория, бренд].filter(Boolean).join(" · ");
  if (подзаголовок) строки.push(esc(подзаголовок));

  строки.push("");

  if (код) строки.push(`Артикул: <code>${esc(код)}</code>`);
  else пропуски.push("артикул");

  if (показыватьЦену) {
    const ц = ценаСтрокой(товар, { валюта });
    if (ц) строки.push(`Цена: <b>${esc(ц)}</b>`);
    else пропуски.push("цена");
  }

  строки.push(вНаличии(товар) ? "✅ Есть в наличии" : "⏳ Под заказ");

  // Видео показываем только своё, из таблицы videos. Чужое не
  // перезаливаем и за своё не выдаём.
  if (видео?.ссылка) строки.push(`\n▶ Видео: ${esc(видео.ссылка)}`);

  if (ссылка) строки.push(`\n${esc(ссылка)}`);

  return {
    текст: строки.join("\n").trim(),
    пропуски,
    // Характеристик в складе нет вовсе, и это главная причина, почему
    // пост получается коротким. Говорим прямо, а не придумываем.
    примечание: "Характеристик в карточке нет — в посте их тоже нет",
    кнопки: ссылка ? [[{ text: "Заказать", url: ссылка }]] : [],
  };
}

