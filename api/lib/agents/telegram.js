// ========================================================================
//  АГЕНТ TELEGRAM.
//
//  Готовит черновики постов из склада и план на неделю. НИЧЕГО НЕ
//  ПУБЛИКУЕТ: каждый пост ложится в agent_approvals и ждёт вашего
//  нажатия — в разделе «ИИ-Агенты» или прямо в Telegram кнопками
//  ✅ Одобрить · ✏️ Изменить · ❌ Отклонить · 📅 Запланировать.
//
//  Три вещи, о которых надо знать заранее:
//
//  1. КАНАЛ НАДО СОЗДАТЬ РУКАМИ. Bot API каналы создавать не умеет —
//     это ограничение Telegram. Агент готовит название, описание,
//     закреплённое сообщение и точные шаги; пять минут работы ваши.
//  2. СЛУЖЕБНЫЙ КАНАЛ НАКЛАДНЫХ НЕ ТРОГАЕМ. Витрина — отдельный новый
//     канал, его адрес живёт в config.канал этого агента.
//  3. ТЕКСТ СОБИРАЕТСЯ ПО ШАБЛОНУ, А НЕ ПИШЕТСЯ МОДЕЛЬЮ. Чего нет в
//     карточке, того нет в посте (api/lib/agents/texts.js).
//
//  Тестовый режим (config.тест = true): одобренный пост уходит вам в
//  личные сообщения, а не в канал. Пока не убедились — пусть так.
// ========================================================================
import { постТовара, планНаНеделю, настройкаКанала, заголовокЧерновика, РУБРИКИ } from "./texts.js";
import { неделяКлюч, суткиКлюч } from "./time.js";

const СУТКИ = 86400e3;
const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };

// Сколько товаров вообще рассматриваем. Больше не нужно: в неделю
// публикуется около десятка.
const ЗАПАС = 60;

// ======================================================================
//  ПОДБОР ТОВАРОВ ПО РУБРИКАМ (чистый счёт, без базы)
// ======================================================================
export function подобрать({ товары = [], продажи = [], видео = [], сейчас = Date.now(), ужеБыли = new Set() } = {}) {
  // В канал идёт только то, что есть на складе и с чем есть что показать.
  const естьФото = (т) => !!String(т.photo_url || "").trim();
  const годен = (т) => чис(т.stock_qty) > 0 && естьФото(т) && !ужеБыли.has(String(т.id));

  const новинки = товары
    .filter((т) => годен(т) && Date.parse(т.last_arrival_at || 0) >= сейчас - 14 * СУТКИ)
    .sort((a, b) => Date.parse(b.last_arrival_at || 0) - Date.parse(a.last_arrival_at || 0));

  // Сколько раз товар продавался за квартал — это и есть «ходовое».
  const счёт = new Map();
  for (const н of продажи || []) {
    if (Date.parse(н.date || н.created_at || 0) < сейчас - 90 * СУТКИ) continue;
    for (const п of н.items || []) {
      const id = String(п.product_id || "");
      if (!id) continue;
      счёт.set(id, (счёт.get(id) || 0) + Math.max(0, чис(п.qty)));
    }
  }
  const популярные = товары
    .filter(годен)
    .map((т) => ({ т, продано: счёт.get(String(т.id)) || 0 }))
    .filter((x) => x.продано > 0)
    .sort((a, b) => b.продано - a.продано)
    .map((x) => x.т);

  // Снова в наличии: приход свежий, а продаж за квартал не было —
  // значит до прихода товара на полке не лежало.
  const вернулись = товары.filter((т) =>
    годен(т)
    && Date.parse(т.last_arrival_at || 0) >= сейчас - 30 * СУТКИ
    && !(счёт.get(String(т.id)) > 0));

  const сВидео = товары.filter((т) => годен(т) && видео.some((в) => String(в.product_id) === String(т.id)));

  // Подборка под машину: самая крупная категория среди пригодных.
  const поКатегориям = new Map();
  for (const т of товары.filter(годен)) {
    const к = String(т.category || "").trim();
    if (!к) continue;
    if (!поКатегориям.has(к)) поКатегориям.set(к, []);
    поКатегориям.get(к).push(т);
  }
  const крупнейшая = [...поКатегориям.entries()].sort((a, b) => b[1].length - a[1].length)[0];

  return {
    новинки: новинки.slice(0, ЗАПАС),
    вернулись: вернулись.slice(0, ЗАПАС),
    популярные: популярные.slice(0, ЗАПАС),
    видео: сВидео.slice(0, ЗАПАС),
    категория: крупнейшая ? крупнейшая[1].slice(0, ЗАПАС) : [],
    имяКатегории: крупнейшая ? крупнейшая[0] : "",
    ручной: [],
  };
}

// ======================================================================
//  ПРОГОН
// ======================================================================
export async function прогон(ctx) {
  const сейчас = Date.now();
  const канал = String(ctx.config?.канал || "").trim();
  const тест = ctx.config?.тест !== false;             // по умолчанию ВКЛЮЧЁН
  const показыватьЦену = ctx.config?.цены === true;    // по умолчанию выключено
  const сайт = (process.env.PUBLIC_URL || "https://generalmodern.uz").replace(/\/+$/, "");

  // ---------- канала ещё нет ----------
  if (!канал) {
    const з = настройкаКанала({ сайт: сайт.replace(/^https?:\/\//, "") });
    const заявка = await ctx.согласовать({
      kind: "channel_setup",
      title: "Создать канал-витрину — нужно пять минут вашего времени",
      idem_key: "channel_setup",                        // один раз, не каждую неделю
      payload: з,
    });
    if (заявка?.новое) await отправитьНаОдобрение({ ...заявка, payload: {
      рубрика: "создать канал-витрину", канал: "—", товары: [{ текст: з.шаги.map((ш, i) => `${i + 1}. ${ш}`).join("\n") }],
    } });
    return {
      сводка: "Канала-витрины ещё нет. Заготовка названия, описания и шагов ждёт в «Согласованиях»",
      детали: { нуженКанал: true, согласование: заявка?.id || null, заготовка: з },
    };
  }

  // ---------- канал есть: проверяем, что бот там администратор ----------
  const доступ = await проверитьКанал(канал);

  // ---------- что уже предлагали ----------
  const прошлые = await ctx.читать(
    "agent_approvals?agent_id=eq.telegram&kind=eq.post&select=payload,status,created_at&order=created_at.desc&limit=80",
  ).catch(() => []);
  const ужеБыли = new Set();
  for (const п of прошлые || []) {
    // Товар, который уже публиковали или предлагали за последний месяц,
    // второй раз без причины не берём.
    if (Date.parse(п.created_at || 0) < сейчас - 30 * СУТКИ) continue;
    for (const т of п?.payload?.товары || []) if (т.id) ужеБыли.add(String(т.id));
  }

  const [товары, продажи, видео] = await Promise.all([
    ctx.читать("products?select=id,code,name,category,sku,stock_qty,price_som,price_usd,photo_url,last_arrival_at"),
    ctx.читать("sales?select=date,created_at,status,items&status=eq.final&date=gte." + encodeURIComponent(new Date(сейчас - 90 * СУТКИ).toISOString())),
    ctx.читать("videos?select=id,title,path,product_id").catch(() => []),
  ]);

  const корзины = подобрать({ товары, продажи, видео, сейчас, ужеБыли });
  const план = планНаНеделю({
    новинки: корзины.новинки.length, вернулись: корзины.вернулись.length,
    популярные: корзины.популярные.length, видео: корзины.видео.length,
    категория: корзины.категория.length, ручной: 0,
  });

  // ---------- черновики ----------
  const неделя = неделяКлюч(сейчас);
  const черновики = [];
  for (const р of РУБРИКИ) {
    if (р.откуда === "ручной") continue;               // это пишете вы сами
    const список = (корзины[р.откуда] || []).slice(0, р.сколько);
    if (!список.length) continue;

    const посты = список.map((т) => {
      const в = видео.find((x) => String(x.product_id) === String(т.id));
      const ссылка = `${сайт}/p/${slug(т)}`;
      return {
        id: String(т.id), код: т.code || "", name: т.name || "",
        фото: т.photo_url || "",
        ...постТовара(т, {
          ссылка, показыватьЦену,
          видео: в ? { ссылка: `${сайт}${String(в.path || "").startsWith("/") ? "" : "/"}${в.path || ""}` } : null,
        }),
      };
    });

    черновики.push(await ctx.согласовать({
      kind: "post",
      title: заголовокЧерновика(список, р.имя),
      // Одна рубрика в неделю — один черновик. Повторное нажатие
      // «Запустить» не наплодит копий.
      idem_key: `post:${неделя}:${р.откуда}`,
      payload: {
        рубрика: р.имя, день: р.день, неделя,
        канал: тест ? "личные сообщения (тестовый режим)" : канал,
        тест, показыватьЦену,
        категория: р.откуда === "категория" ? корзины.имяКатегории : null,
        товары: посты.map(({ id, код, name, фото, текст, кнопки, пропуски }) =>
          ({ id, код, name, фото, текст, кнопки, пропуски })),
        // Сводно: чего не хватило по всем товарам рубрики.
        пропуски: сводкаПропусков(посты),
      },
    }));
  }

  const готовых = черновики.filter(Boolean).length;

  // Карточки с кнопками — только по новым черновикам. Повторный прогон
  // той же недели вернёт старые (idem_key), и их второй раз не шлём.
  let отправлено = 0;
  for (const ч of черновики) if (ч?.новое && await отправитьНаОдобрение(ч)) отправлено++;
  if (!доступ.ок) {
    await ctx.уведомить({
      kind: "channel_access", level: "warn",
      // Название канала — в заголовке: иначе за ним в Telegram сразу шло
      // имя агента, и читалось «в канале Агент Telegram».
      title: `Канал ${канал}: бот пока не может публиковать`,
      body: `${доступ.причина}\nПосле этого нажмите «Запустить» у агента Telegram — он проверит ещё раз. Пока не исправлено, одобренные посты в канал не уйдут (в тестовом режиме они идут вам в личку).`,
      dedup_key: `tg:access2:${канал}:${суткиКлюч(сейчас)}`,
    });
  }

  return {
    сводка: готовых
      ? `Черновиков на неделю: ${готовых}. Ждут вашего одобрения`
      : "Новых товаров для постов не нашлось",
    детали: {
      канал: тест ? "тестовый режим — в личные сообщения" : канал,
      доступБота: доступ,
      план,
      черновиков: готовых,
      карточекВTelegram: отправлено,
      запас: {
        новинки: корзины.новинки.length, вернулись: корзины.вернулись.length,
        популярные: корзины.популярные.length, видео: корзины.видео.length,
        категория: корзины.категория.length, имяКатегории: корзины.имяКатегории,
      },
      // Чего агент не умеет — говорим прямо.
      неУмеет: [
        "искать видео на YouTube и у производителей: нужен ключ YouTube Data API. Берём только свои видео из таблицы videos",
        "писать живой текст: ключа к модели нет, пост собирается по шаблону из карточки",
      ],
    },
  };
}

const slug = (т) => String(т.code || т.id).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// ======================================================================
//  КАКОЙ БОТ
//
//  В проекте два бота. Админский (TELEGRAM_BOT_TOKEN) только шлёт
//  уведомления — обработчика нажатий у него нет. Нажатия разбирает
//  /api/bot, а это бот магазина (CLIENT_BOT_TOKEN) — через него вам и
//  приходят коды входа. Поэтому и карточки на одобрение, и посты в
//  витрину идут через бота магазина: иначе нажатие ушло бы в никуда.
// ======================================================================
const ботМагазина = () => process.env.CLIENT_BOT_TOKEN || process.env.TELEGRAM_BOT_TOKEN || "";

// Кнопки одобрения. Разбираются в api/bot.js по приставке «ag:».
// Длина callback_data в Telegram — до 64 байт: «ag:later:» + uuid = 45.
export const кнопкиОдобрения = (id) => [
  [{ text: "✅ Одобрить", callback_data: `ag:ok:${id}` }, { text: "✏️ Изменить", callback_data: `ag:ed:${id}` }],
  [{ text: "❌ Отклонить", callback_data: `ag:no:${id}` }, { text: "📅 Завтра 10:00", callback_data: `ag:later:${id}` }],
];

// Карточка черновика владельцу: как будет выглядеть пост + кнопки.
// С фотографией первого товара — так же, как пост выйдет в канале.
export async function отправитьНаОдобрение(заявка, { токен = ботМагазина(), чат = process.env.ADMIN_CHAT_ID } = {}) {
  if (!токен || !чат || !заявка?.id) return false;
  const п = заявка.payload || {};
  const товары = п.товары || [];
  const первый = товары[0];
  const остальные = товары.slice(1).map((т) => т.name).filter(Boolean);
  const шапка = `📝 <b>Черновик: ${escHtml(п.рубрика || заявка.title || "пост")}</b>\n`
    + `Куда: ${escHtml(п.канал || "—")}\n`
    + `Товаров: ${товары.length}`
    + (остальные.length ? ` (ещё: ${escHtml(остальные.join(", ").slice(0, 160))})` : "")
    + (Object.keys(п.пропуски || {}).length ? `\nНе хватает в карточках: ${escHtml(Object.keys(п.пропуски).join(", "))}` : "")
    + `\n\n— первый пост —\n`;
  const текст = шапка + (первый?.текст || "");
  const р = await послатьПост(токен, {
    chat_id: String(чат), текст, фото: первый?.фото || "",
    reply_markup: { inline_keyboard: кнопкиОдобрения(заявка.id) },
  });
  return р.ok;
}
const escHtml = (s) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// ======================================================================
//  ОТПРАВКА ПОСТА С ФОТО
//
//  Снимок отдаём Telegram самим файлом, а не ссылкой: файл уже лежит в
//  кэше нашего сервера (api/lib/imgproxy.js), а по ссылке Telegram
//  ходил бы в Supabase — это лишний платный трафик, и чужой сервер
//  иногда просто не отвечает. Не нашли файл — отдаём ссылку.
//
//  Подпись к фото в Telegram — до 1024 знаков, текст — до 4096. Если
//  пост длиннее подписи, шлём фото отдельно, а текст с кнопками — сразу
//  под ним. Если фото не прошло вовсе — пост уходит текстом, а не теряется.
// ======================================================================
const ПОДПИСЬ = 1024;

export function путьВХранилище(url) {
  const м = String(url || "").match(/\/storage\/v1\/object\/public\/(product-photos\/[^?#]+)/);
  if (!м) return "";
  try { return decodeURIComponent(м[1]); } catch { return м[1]; }
}

async function файлФото(url) {
  const путь = путьВХранилище(url);
  if (!путь) return null;
  try {
    const { оригинал, типПоИмени } = await import("../imgproxy.js");
    const ф = await оригинал(путь);
    if (!ф?.байты?.length) return null;
    return { байты: ф.байты, тип: типПоИмени(путь), имя: путь.split("/").pop() || "photo.jpg" };
  } catch { return null; }
}

async function вызвать(токен, метод, тело, файл) {
  try {
    let r;
    if (файл) {
      const форма = new FormData();
      for (const [к, з] of Object.entries(тело)) {
        if (з === undefined || з === null) continue;
        форма.append(к, typeof з === "object" ? JSON.stringify(з) : String(з));
      }
      форма.append("photo", new Blob([файл.байты], { type: файл.тип }), файл.имя);
      r = await fetch(`https://api.telegram.org/bot${токен}/${метод}`, { method: "POST", body: форма });
    } else {
      r = await fetch(`https://api.telegram.org/bot${токен}/${метод}`, {
        method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(тело),
      });
    }
    return await r.json();
  } catch (e) { return { ok: false, description: "сеть" }; }
}

// Один пост: фото + текст + кнопки. Возвращает ответ Telegram.
export async function послатьПост(токен, { chat_id, текст, фото, reply_markup }) {
  const текстом = () => вызвать(токен, "sendMessage", {
    chat_id, text: текст, parse_mode: "HTML", disable_web_page_preview: true, reply_markup,
  });
  if (!фото) return текстом();

  const файл = await файлФото(фото);
  const снимок = (подпись) => вызвать(токен, "sendPhoto", {
    chat_id, ...(файл ? {} : { photo: фото }),
    ...(подпись ? { caption: текст, parse_mode: "HTML", reply_markup } : {}),
  }, файл);

  if (текст.length <= ПОДПИСЬ) {
    const р = await снимок(true);
    if (р?.ok) return р;
    return текстом();                         // фото не прошло — хотя бы текст
  }
  // Длинный пост: фото без подписи, под ним текст с кнопками.
  await снимок(false);
  return текстом();
}

function сводкаПропусков(посты) {
  const счёт = {};
  for (const п of посты) for (const пр of п.пропуски || []) счёт[пр] = (счёт[пр] || 0) + 1;
  return счёт;
}

// Бот должен быть администратором канала с правом публикации.
// Проверяем, а не предполагаем: без этого одобренный пост просто
// пропадёт, и никто не поймёт почему.
export async function проверитьКанал(канал, токен = ботМагазина()) {
  if (!токен) return { ок: false, причина: "токен бота не задан" };
  if (!канал) return { ок: false, причина: "канал не задан в настройках агента" };
  try {
    // Имя бота нужно в самом сообщении: владелец должен знать, КОГО
    // добавлять в администраторы, — ботов в проекте два.
    const me = await (await fetch(`https://api.telegram.org/bot${токен}/getMe`)).json();
    const бот = me?.result?.username ? "@" + me.result.username : "бот магазина";
    const как = `Добавьте ${бот} в канал администратором с правом «Публикация сообщений»: канал → Управление каналом → Администраторы → Добавить администратора.`;

    const r = await fetch(`https://api.telegram.org/bot${токен}/getChat?chat_id=${encodeURIComponent(канал)}`);
    const j = await r.json();
    if (!j?.ok) return { ок: false, бот, причина: `Канал ${канал} не найден. Проверьте адрес в настройках агента. ${как}` };

    // Список администраторов канала Telegram показывает только самим
    // администраторам. Отказ здесь почти всегда значит одно: бота в
    // администраторы ещё не добавили.
    const a = await (await fetch(`https://api.telegram.org/bot${токен}/getChatAdministrators?chat_id=${encodeURIComponent(канал)}`)).json();
    if (!a?.ok) return { ок: false, бот, причина: `${бот} пока не администратор канала ${канал}. ${как}`, ответTelegram: String(a?.description || "").slice(0, 160) };

    const свой = (a.result || []).find((ад) => String(ад.user?.id) === String(me?.result?.id));
    if (!свой) return { ок: false, бот, причина: `${бот} пока не администратор канала ${канал}. ${как}` };
    if (свой.can_post_messages === false) return { ок: false, бот, причина: `${бот} администратор канала, но без права публиковать. Включите ему «Публикация сообщений».` };

    // Чужие администраторы — повод присмотреться.
    const чужие = (a.result || [])
      .filter((ад) => !ад.user?.is_bot)
      .map((ад) => String(ад.user?.id));
    return { ок: true, бот, название: j.result?.title || "", администраторов: чужие.length };
  } catch {
    return { ок: false, причина: "Telegram не ответил" };
  }
}

// ======================================================================
//  ПУБЛИКАЦИЯ ОДОБРЕННОГО
//
//  Вызывается ПОСЛЕ того, как владелец нажал «Одобрить» — из ручки
//  раздела или из бота. Сама по себе не запускается никогда.
// ======================================================================
export async function опубликовать(заявка, { токен = ботМагазина(), личныйЧат = process.env.ADMIN_CHAT_ID } = {}) {
  const п = заявка?.payload || {};
  if (!токен) return { ок: false, причина: "токен бота не задан" };

  const куда = п.тест ? личныйЧат : п.канал;
  if (!куда) return { ок: false, причина: п.тест ? "не задан чат владельца" : "не задан канал" };

  const послано = [];
  for (const т of п.товары || []) {
    // Каждый товар — отдельным постом с его фото.
    const j = await послатьПост(токен, {
      chat_id: куда, текст: т.текст || "", фото: т.фото || "",
      reply_markup: т.кнопки?.length ? { inline_keyboard: т.кнопки } : undefined,
    });
    послано.push({ код: т.код, ок: !!j?.ok, ошибка: j?.ok ? null : String(j?.description || "").slice(0, 160) });
  }
  const успешно = послано.filter((x) => x.ок).length;
  return { ок: успешно > 0, послано, успешно, всего: послано.length, тест: !!п.тест };
}

