// ========================================================================
//  ВРЕМЯ АГЕНТОВ — всё по Ташкенту.
//
//  Узбекистан живёт на UTC+5 круглый год: перехода на летнее время нет.
//  Поэтому не нужен ни часовой пояс операционной системы, ни внешняя
//  библиотека — достаточно сдвига. Тот же приём уже работает в
//  server.js (вечерние итоги дня).
//
//  Приём простой: к метке времени прибавляем пять часов и дальше
//  читаем UTC-поля получившейся даты. Они и есть настенное время
//  Ташкента. Обратно — вычитаем пять часов.
//
//  Виды расписаний (хранятся в agent_state.schedule):
//    { вид:"interval", минут:60 }
//    { вид:"daily",   время:"08:30" }            или время:["09:00","18:00"]
//    { вид:"weekly",  день:1, время:"09:00" }    день: 1 пн … 7 вс
//    { вид:"monthly", число:1, время:"09:00" }   число: 1…28
//
//  Почему число ограничено 28: в феврале нет 30-го, и «каждое 30-е»
//  превратилось бы в тихий пропуск месяца. Лучше честное ограничение.
// ========================================================================

export const СДВИГ_МС = 5 * 3600e3;
const СУТКИ = 24 * 3600e3;

// Метка времени → «сдвинутая» дата, у которой UTC-поля равны ташкентским.
export const вТашкенте = (t = Date.now()) => new Date(Number(t) + СДВИГ_МС);
// И обратно.
const обратно = (сдвинутая) => сдвинутая.getTime() - СДВИГ_МС;

// "09:00" → 540 (минут от полуночи). Мусор → null.
export function разборВремени(s) {
  const m = /^(\d{1,2}):(\d{2})$/.exec(String(s ?? "").trim());
  if (!m) return null;
  const ч = Number(m[1]), мин = Number(m[2]);
  if (ч > 23 || мин > 59) return null;
  return ч * 60 + мин;
}

export const показатьВремя = (минут) =>
  String(Math.floor(минут / 60)).padStart(2, "0") + ":" + String(минут % 60).padStart(2, "0");

// Список времён суток из расписания: строка, массив строк или пусто.
function временаСуток(расписание) {
  const сырое = расписание?.время;
  const список = (Array.isArray(сырое) ? сырое : [сырое])
    .map(разборВремени)
    .filter((v) => v !== null);
  return [...new Set(список)].sort((a, b) => a - b);
}

// Полночь ташкентских суток, в которые попала метка времени.
function полночь(t) {
  const d = вТашкенте(t);
  d.setUTCHours(0, 0, 0, 0);
  return обратно(d);
}

// День недели по-человечески: 1 понедельник … 7 воскресенье.
export function деньНедели(t) {
  const d = вТашкенте(t).getUTCDay();   // 0 вс … 6 сб
  return d === 0 ? 7 : d;
}

export const числоМесяца = (t) => вТашкенте(t).getUTCDate();

// ------------------------------------------------------------------
//  Когда агенту работать в следующий раз. Строго ПОСЛЕ «от»: иначе
//  после прогона он тут же получил бы то же самое время и закрутился.
//  Непонятное расписание → null: агент не запускается сам, и карточка
//  об этом прямо пишет. Молча подставлять своё время нельзя — хозяин
//  решит, что всё настроено.
// ------------------------------------------------------------------
export function следующийЗапуск(расписание, от = Date.now()) {
  от = Number(от) || Date.now();
  const вид = String(расписание?.вид || "").toLowerCase();

  if (вид === "interval") {
    const минут = Math.min(10080, Math.max(1, Math.round(Number(расписание.минут) || 0)));
    if (!минут) return null;
    return от + минут * 60e3;
  }

  const времена = временаСуток(расписание);
  if (!времена.length) return null;

  if (вид === "daily") {
    for (let сдвиг = 0; сдвиг <= 1; сдвиг++) {
      const день = полночь(от) + сдвиг * СУТКИ;
      for (const м of времена) {
        const когда = день + м * 60e3;
        if (когда > от) return когда;
      }
    }
    return null;                                     // недостижимо, но пусть будет честно
  }

  if (вид === "weekly") {
    const нужныйДень = Math.min(7, Math.max(1, Math.round(Number(расписание.день) || 1)));
    for (let сдвиг = 0; сдвиг <= 7; сдвиг++) {
      const день = полночь(от) + сдвиг * СУТКИ;
      if (деньНедели(день) !== нужныйДень) continue;
      for (const м of времена) {
        const когда = день + м * 60e3;
        if (когда > от) return когда;
      }
    }
    return null;
  }

  if (вид === "monthly") {
    const нужноеЧисло = Math.min(28, Math.max(1, Math.round(Number(расписание.число) || 1)));
    // Хватает 62 суток вперёд: любой месяц короче, и нужное число
    // точно встретится — либо в этом месяце, либо в следующем.
    for (let сдвиг = 0; сдвиг <= 62; сдвиг++) {
      const день = полночь(от) + сдвиг * СУТКИ;
      if (числоМесяца(день) !== нужноеЧисло) continue;
      for (const м of времена) {
        const когда = день + м * 60e3;
        if (когда > от) return когда;
      }
    }
    return null;
  }

  return null;
}

// ------------------------------------------------------------------
//  Тихие часы: ночью агент работает (считает, пишет в журнал), но
//  сообщения в Telegram не шлёт — они дождутся утра. Настройка живёт
//  в config.тихо = { с:"22:00", до:"08:00" }.
//  Промежуток может переходить через полночь — это обычный случай.
// ------------------------------------------------------------------
export function тихийЧас(config, t = Date.now()) {
  const с = разборВремени(config?.тихо?.с);
  const до = разборВремени(config?.тихо?.до);
  if (с === null || до === null || с === до) return false;
  const d = вТашкенте(t);
  const сейчас = d.getUTCHours() * 60 + d.getUTCMinutes();
  return с < до ? (сейчас >= с && сейчас < до) : (сейчас >= с || сейчас < до);
}

// Человеческая подпись времени для карточки и отчёта: «22 ноября, 14:35».
const МЕСЯЦЫ = ["января","февраля","марта","апреля","мая","июня","июля","августа","сентября","октября","ноября","декабря"];
export function человеку(t) {
  if (!t) return "—";
  const ms = typeof t === "number" ? t : Date.parse(t);
  if (!Number.isFinite(ms)) return "—";
  const d = вТашкенте(ms);
  return `${d.getUTCDate()} ${МЕСЯЦЫ[d.getUTCMonth()]}, ` +
    `${String(d.getUTCHours()).padStart(2, "0")}:${String(d.getUTCMinutes()).padStart(2, "0")}`;
}

// Ключи для потолков расходов и для защиты от повторов: ташкентские сутки и месяц.
export const суткиКлюч = (t = Date.now()) => вТашкенте(t).toISOString().slice(0, 10);
export const месяцКлюч = (t = Date.now()) => вТашкенте(t).toISOString().slice(0, 7);
// Номер недели нужен уведомлениям: «кончился товар» пишется раз в неделю, а не каждый прогон.
export function неделяКлюч(t = Date.now()) {
  const d = вТашкенте(t);
  d.setUTCDate(d.getUTCDate() + 4 - (d.getUTCDay() || 7));      // четверг этой недели (ISO)
  const началоГода = Date.UTC(d.getUTCFullYear(), 0, 1);
  const номер = Math.ceil(((d.getTime() - началоГода) / СУТКИ + 1) / 7);
  return `${d.getUTCFullYear()}-W${String(номер).padStart(2, "0")}`;
}
