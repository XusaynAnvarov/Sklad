// ========================================================================
//  ЧИСТЫЙ ТЕКСТ — через это проходит ВСЁ, что агент записывает в журнал
//  или отправляет в Telegram.
//
//  Повод простой: агент безопасности читает настройки сервера, агент
//  Telegram — ответы Bot API, и любой из них может случайно затащить в
//  отчёт токен или ключ. Отчёт потом лежит в базе и уходит в сообщение.
//  Поэтому не «постараемся не писать секреты», а «секрет физически не
//  проходит наружу».
//
//  Работает двумя способами сразу:
//   1. По образцу — то, что выглядит как токен, ключ или пароль.
//   2. По значению — настоящие значения переменных окружения этого
//      сервера. Самый надёжный способ: даже если ключ попал в текст
//      кусками чужого формата, точное совпадение всё равно поймается.
//
//  Проверяется тестом _tools/tests/t-agents-core.mjs.
// ========================================================================

export const ЗАМЕНА = "[скрыто]";

// Переменные окружения, значения которых нельзя показывать никогда.
const СЕКРЕТНЫЕ_ПЕРЕМЕННЫЕ = [
  "SUPABASE_SERVICE_KEY", "SUPABASE_ANON_KEY", "SUPABASE_KEY",
  "SITE_JWT_SECRET", "JWT_SECRET", "ADMIN_JWT_SECRET",
  "TELEGRAM_WEBHOOK_SECRET", "CLIENT_BOT_TOKEN", "ADMIN_BOT_TOKEN", "BOT_TOKEN",
  "ADMIN_PASSWORD", "PGPASSWORD", "DATABASE_URL", "PG_URL",
  "OPENAI_API_KEY", "YOUTUBE_API_KEY", "CF_API_TOKEN", "INDEXNOW_KEY",
];

const ОБРАЗЦЫ = [
  // токен Telegram-бота: 1234567890:AA…
  /\b\d{6,12}:[A-Za-z0-9_-]{25,}/g,
  // JWT (три части через точку)
  /\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g,
  // ключи вида sk-…, pk-…, ghp_…, xoxb-…
  /\b(?:sk|pk|rk)-[A-Za-z0-9_-]{16,}/g,
  /\bgh[pousr]_[A-Za-z0-9]{20,}/g,
  /\bxox[baprs]-[A-Za-z0-9-]{10,}/g,
  // длинная шестнадцатеричная строка — почти всегда ключ или хэш секрета
  /\b[0-9a-fA-F]{32,}\b/g,
  // строка подключения с паролем
  /\b(postgres(?:ql)?|mysql|mongodb(?:\+srv)?):\/\/[^\s"']+/gi,
];

// «token: abc», "secret"="abc", пароль = abc — забираем именно значение.
const ПОЛЯ = /\b(token|secret|password|passwd|pwd|apikey|api_key|access_key|service_key|auth|bearer|пароль|ключ|токен)\b(["']?\s*[:=]\s*["']?)([^\s"',;}{]{4,})/gi;

export function безопасныйТекст(вход) {
  if (вход === null || вход === undefined) return вход;
  let s = String(вход);
  if (!s) return s;

  // 1. Настоящие значения из окружения — точным совпадением.
  for (const имя of СЕКРЕТНЫЕ_ПЕРЕМЕННЫЕ) {
    const v = process.env[имя];
    if (typeof v === "string" && v.length >= 8 && s.includes(v)) s = s.split(v).join(ЗАМЕНА);
  }
  // 2. По образцу.
  for (const re of ОБРАЗЦЫ) s = s.replace(re, ЗАМЕНА);
  s = s.replace(ПОЛЯ, (_, поле, разделитель) => `${поле}${разделитель}${ЗАМЕНА}`);

  return s;
}

// То же самое, но для объекта целиком: ключи оставляем, значения чистим.
// Глубина ограничена — отчёт агента не должен уметь зациклить сервер.
export function безопасныйОбъект(значение, глубина = 0) {
  if (глубина > 8) return "[глубоко]";
  if (значение === null || значение === undefined) return значение;
  if (typeof значение === "string") return безопасныйТекст(значение);
  if (typeof значение === "number" || typeof значение === "boolean") return значение;
  if (Array.isArray(значение)) return значение.slice(0, 500).map((v) => безопасныйОбъект(v, глубина + 1));
  if (typeof значение === "object") {
    const из = {};
    for (const [k, v] of Object.entries(значение).slice(0, 200)) {
      // Поле с «говорящим» именем вычищаем целиком, не разбирая значение.
      из[k] = /token|secret|password|пароль|ключ|токен|apikey|api_key/i.test(k) ? ЗАМЕНА : безопасныйОбъект(v, глубина + 1);
    }
    return из;
  }
  return String(значение);
}
