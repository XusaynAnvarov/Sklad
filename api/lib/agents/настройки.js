// ========================================================================
//  НАСТРОЙКИ АГЕНТОВ: что можно менять и в каких пределах.
//
//  Форма в разделе «ИИ-Агенты» присылает настройки сюда, и здесь они
//  проверяются ДО записи. Браузеру не верим: в базу попадает только то,
//  что прошло проверку, а неизвестные поля просто отбрасываются.
//
//  Три правила, ради которых этот файл существует:
//
//  1. ВИТРИНА — НЕ КАНАЛ НАКЛАДНЫХ. Адрес канала, куда агент Telegram
//     публикует товары, не может совпадать со служебным каналом
//     накладных (settings.telegram_channel). Перепутать их — значит
//     вывалить рекламу туда, где лежат документы клиентов.
//  2. ПАПКА КОПИЙ — ТОЛЬКО АБСОЛЮТНЫЙ ПУТЬ БЕЗ «..». Агент безопасности
//     читает список файлов в этой папке. Путь вида «../../etc» дал бы
//     ему читать что угодно на сервере.
//  3. ЧАСТИЧНОЕ ОБНОВЛЕНИЕ НЕ СТИРАЕТ ОСТАЛЬНОЕ. Поменяли тихие часы —
//     адрес канала остался на месте. Пустое поле значит «убрать
//     настройку», а не «оставить как было» — так форма и устроена.
// ========================================================================
import { разборВремени } from "./time.js";

// Что вообще понимает каждый агент. Остальное отбрасывается.
export const КЛЮЧИ = {
  общие: ["тихо"],
  warehouse: [],
  orders: ["просрочка"],
  security: ["копии"],
  telegram: ["канал", "тест", "цены"],
  design: [],
};

// Потолок расходов (config.потолок) форма не показывает — платных
// сервисов нет. Но если он уже задан, правка формы его не стирает.
const СОХРАНЯТЬ_ВСЕГДА = ["потолок"];

const КАНАЛ = /^(@[A-Za-z][A-Za-z0-9_]{4,31}|-100\d{6,14})$/;
const ПУТЬ = /^\/[\w\-./ Ѐ-ӿ]{1,199}$/;

export function проверитьНастройки(id, новые = {}, { было = {}, каналНакладных = "" } = {}) {
  const разрешено = [...(КЛЮЧИ.общие || []), ...(КЛЮЧИ[id] || [])];
  if (!(id in КЛЮЧИ) || id === "общие") return { ok: false, ошибки: ["неизвестный агент"] };

  const ошибки = [];
  // Начинаем с прежнего: правка одного поля не трогает остальные.
  const итог = {};
  for (const к of [...разрешено, ...СОХРАНЯТЬ_ВСЕГДА]) if (было && к in было) итог[к] = было[к];

  for (const [ключ, значение] of Object.entries(новые || {})) {
    if (!разрешено.includes(ключ)) continue;            // чужое молча отбрасываем

    switch (ключ) {
      case "тихо": {
        const с = String(значение?.с ?? "").trim(), до = String(значение?.до ?? "").trim();
        if (!с && !до) { delete итог.тихо; break; }
        if (разборВремени(с) === null || разборВремени(до) === null) { ошибки.push("тихие часы: время пишется как 22:00"); break; }
        if (с === до) { ошибки.push("тихие часы: начало и конец совпадают"); break; }
        итог.тихо = { с, до };
        break;
      }
      case "просрочка": {
        const п = {};
        for (const этап of ["placed", "packed"]) {
          const сырое = значение?.[этап];
          if (сырое === "" || сырое === null || сырое === undefined) continue;
          const n = Number(сырое);
          if (!Number.isInteger(n) || n < 0 || n > 30) { ошибки.push("нормы просрочки: целое число дней от 0 до 30"); continue; }
          п[этап] = n;
        }
        if (Object.keys(п).length) итог.просрочка = п; else delete итог.просрочка;
        break;
      }
      case "копии": {
        const путь = String(значение ?? "").trim();
        if (!путь) { delete итог.копии; break; }
        if (!ПУТЬ.test(путь) || путь.split("/").includes("..")) {
          ошибки.push("папка копий: полный путь от корня, например /var/backups/sklad, без «..»");
          break;
        }
        итог.копии = путь.replace(/\/+$/, "") || "/";
        break;
      }
      case "канал": {
        const к = String(значение ?? "").trim();
        if (!к) { delete итог.канал; break; }
        if (!КАНАЛ.test(к)) { ошибки.push("канал: адрес вида @generalmodern или номер вида -1001234567890"); break; }
        if (каналНакладных && к === String(каналНакладных).trim()) {
          ошибки.push("канал: это служебный канал накладных — для витрины нужен отдельный новый канал");
          break;
        }
        итог.канал = к;
        break;
      }
      case "тест":
      case "цены":
        итог[ключ] = значение === true || значение === "true" || значение === "on";
        break;
    }
  }

  return ошибки.length ? { ok: false, ошибки } : { ok: true, config: итог };
}
