// 1. Сертификат домена. tls встроен в Node — новых зависимостей нет.
export async function проверитьСертификат(адрес, { таймаут = 8000 } = {}) {
  let host;
  try { host = new URL(адрес).hostname; } catch { return { проверен: false, причина: "адрес сайта не задан (PUBLIC_URL)" }; }
  if (!host || /^(localhost|127\.|0\.0\.0\.0)/.test(host)) return { проверен: false, причина: "локальный адрес, сертификата нет" };

  return new Promise((готово) => {
    let закрыт = false;
    const финал = (из) => { if (!закрыт) { закрыт = true; готово(из); } };
    const таймер = setTimeout(() => { финал({ проверен: false, причина: "сервер не ответил за 8 секунд" }); }, таймаут);
    try {
      // rejectUnauthorized:false стоит здесь СОЗНАТЕЛЬНО, и это не дыра.
      // Мы не передаём по этому соединению ни байта: открыли, прочли
      // сертификат, закрыли. Проверять подлинность нечего и незачем —
      // предмет проверки и есть сам сертификат. С проверкой включённой
      // соединение рвалось бы до того, как мы его прочтём, и агент
      // молчал бы ровно в том случае, ради которого он написан:
      // когда сертификат уже просрочен.
      // Для любой передачи данных так делать нельзя.
      const сокет = tls.connect({ host, port: 443, servername: host, rejectUnauthorized: false }, () => {
        const c = сокет.getPeerCertificate();
        сокет.end();
        clearTimeout(таймер);
        if (!c || !c.valid_to) return финал({ проверен: false, причина: "сертификат не прочитался" });
        const до = Date.parse(c.valid_to);
        финал({
          проверен: true,
          до: new Date(до).toISOString().slice(0, 10),
          осталосьДней: Math.floor((до - Date.now()) / СУТКИ),
          кем: String(c.issuer?.O || c.issuer?.CN || "").slice(0, 80),
          домен: host,
        });
      });
      сокет.on("error", (e) => { clearTimeout(таймер); финал({ проверен: false, причина: "не удалось соединиться: " + (e?.code || e?.message || "ошибка") }); });
    } catch (e) {
      clearTimeout(таймер);
      финал({ проверен: false, причина: String(e?.message || e) });
    }
  });
}

// 2. Доступы и ключи. Наружу — только выводы.
export function проверитьДоступы(env = process.env, естьФайлПароля = false) {
  const находки = [];
  const ключи = ["SITE_JWT_SECRET", "TELEGRAM_WEBHOOK_SECRET", "SUPABASE_SERVICE_KEY"].map(оСекрете);

  for (const к of ключи) {
    if (!к.задан) {
      находки.push(находка({
        тип: "нет ключа", уровень: к.имя === "TELEGRAM_WEBHOOK_SECRET" ? 80 : 95,
        компонент: к.имя,
        суть: "переменная не задана",
        последствия: к.имя === "SITE_JWT_SECRET"
          ? "пропуска в склад подписывать нечем — вход сломан или подделывается"
          : к.имя === "TELEGRAM_WEBHOOK_SECRET"
            ? "вебхук бота принимает запросы от кого угодно"
            : "сервер не достучится до базы",
        решение: `задать ${к.имя} в .env на сервере и перезапустить pm2`,
      }));
    } else if (к.слабый) {
      находки.push(находка({
        тип: "слабый ключ", уровень: 70, компонент: к.имя,
        суть: `значение короткое (${к.длина} симв.) или похоже на временное`,
        последствия: "подпись и защита вебхука подбираются перебором",
        решение: "заменить на случайную строку от 32 символов",
      }));
    }
  }

  // Двухфакторная проверка при входе в склад.
  const двеФазы = String(env.ADMIN_2FA || "").toLowerCase() !== "off"
    && !!env.CLIENT_BOT_TOKEN && !!env.ADMIN_CHAT_ID;
  if (!двеФазы) {
    const выключена = String(env.ADMIN_2FA || "").toLowerCase() === "off";
    находки.push(находка({
      тип: "вход без кода", уровень: 85, компонент: "вход в склад",
      суть: выключена ? "ADMIN_2FA=off — код при входе отключён" : "нет бота или чата для отправки кода",
      последствия: "знающий пароль войдёт в склад без подтверждения",
      решение: выключена ? "убрать ADMIN_2FA=off из .env" : "задать CLIENT_BOT_TOKEN и ADMIN_CHAT_ID",
    }));
  }

  // Пароль в окружении, когда он уже перенесён в файл.
  if (естьФайлПароля && env.ADMIN_PASSWORD) {
    находки.push(находка({
      тип: "лишний пароль в окружении", уровень: 60, компонент: "ADMIN_PASSWORD",
      суть: "пароль задан и в .env, и в data/admin-creds.json",
      последствия: "смена пароля в складе не действует — вход остаётся по старому из .env",
      решение: "убрать ADMIN_PASSWORD из .env, оставить только файл",
    }));
  }

  return { находки, ключи: ключи.map(({ имя, задан, длина }) => ({ имя, задан, длина })), двеФазы };
}

// 3. Вебхук бота: тот ли адрес, есть ли секрет, нет ли завала.
export async function проверитьВебхук(токен, публичныйАдрес) {
  if (!токен) return { проверен: false, причина: "токен бота не задан" };
  let ответ;
  try {
    const r = await fetch(`https://api.telegram.org/bot${токен}/getWebhookInfo`);
    ответ = await r.json();
  } catch (e) {
    return { проверен: false, причина: "Telegram не ответил" };
  }
  if (!ответ?.ok) return { проверен: false, причина: "Telegram вернул отказ" };
  const и = ответ.result || {};
  const находки = [];

  if (!и.url) {
    находки.push(находка({
      тип: "вебхук не установлен", уровень: 75, компонент: "Telegram-бот",
      суть: "адрес вебхука пуст",
      последствия: "бот не получает сообщения — заказы и коды входа не доходят",
      решение: "переустановить вебхук на " + (публичныйАдрес || "адрес сайта") + "/api/bot",
    }));
  } else if (публичныйАдрес && !String(и.url).startsWith(публичныйАдрес)) {
    находки.push(находка({
      тип: "чужой адрес вебхука", уровень: 95, компонент: "Telegram-бот",
      суть: "вебхук указывает не на ваш сайт",
      последствия: "сообщения бота уходят на чужой сервер",
      решение: "немедленно переустановить вебхук на свой адрес и сменить токен бота",
    }));
  }
  if (и.url && !и.has_custom_certificate && и.allowed_updates === undefined && !и.pending_update_count) {
    // ничего тревожного — просто тихий вебхук
  }
  if (чис(и.pending_update_count) > 50) {
    находки.push(находка({
      тип: "завал обновлений", уровень: 60, компонент: "Telegram-бот",
      суть: `не разобрано ${и.pending_update_count} сообщений`,
      последствия: "бот отвечает с задержкой или не отвечает вовсе",
      решение: "проверить, что сервер отвечает на /api/bot без ошибок",
    }));
  }
  if (и.last_error_message) {
    находки.push(находка({
      тип: "ошибка вебхука", уровень: 65, компонент: "Telegram-бот",
      суть: String(и.last_error_message).slice(0, 160),
      последствия: "часть сообщений теряется",
      решение: "посмотреть журнал pm2 за время ошибки",
    }));
  }

  return {
    проверен: true, находки,
    // Сам адрес не показываем целиком: в нём бывает токен.
    адресСвой: публичныйАдрес ? String(и.url || "").startsWith(публичныйАдрес) : null,
    ждёт: чис(и.pending_update_count),
    последняяОшибка: и.last_error_message ? String(и.last_error_message).slice(0, 160) : null,
  };
}

// 4. Подозрительная активность — из того, что и так пишется.
export function разобратьСобытия(события, { сейчас = Date.now(), окноДней = 7 } = {}) {
  const от = сейчас - окноДней * СУТКИ;
  const свежие = (события || []).filter((с) => Date.parse(с.created_at || 0) >= от);

  const находки = [];
  const рисковые = свежие.filter((с) => чис(с.risk) >= 70);
  const неудачи = свежие.filter((с) => с.kind === "login_fail");

  // Подбор пароля: много неудач с одного адреса.
  const поАдресу = new Map();
  for (const с of неудачи) {
    const к = String(с.ip_hash || с.device_hash || "неизвестно");
    поАдресу.set(к, (поАдресу.get(к) || 0) + 1);
  }
  for (const [адрес, сколько] of поАдресу) {
    if (сколько < ПОДБОР) continue;
    находки.push(находка({
      тип: "подбор пароля", уровень: 85, компонент: "вход в склад",
      // ip_hash — это уже хэш, не адрес: в отчёте он безвреден.
      суть: `${сколько} неудачных входов с одного устройства (${адрес.slice(0, 12)}…)`,
      последствия: "пароль подбирают перебором",
      решение: "сменить пароль администратора и проверить журнал входов",
    }));
  }

  if (рисковые.length) {
    находки.push(находка({
      тип: "рискованные события", уровень: 75, компонент: "журнал входов",
      суть: `${рисковые.length} событий с оценкой риска 70 и выше`,
      последствия: "возможен вход с чужого устройства или из незнакомого места",
      решение: "открыть «Клиенты и безопасность» и просмотреть эти события",
    }));
  }

  const подмена = свежие.filter((с) => (с.flags || {}).impersonation || с.kind === "impersonation");
  if (подмена.length) {
    находки.push(находка({
      тип: "вход под клиентом", уровень: 70, компонент: "кабинет клиента",
      суть: `${подмена.length} входов администратора под чужой учётной записью`,
      последствия: "если это были не вы — у кого-то есть доступ администратора",
      решение: "сверить время входов со своими действиями",
    }));
  }

  return {
    находки,
    всего: свежие.length,
    неудачныхВходов: неудачи.length,
    рискованных: рисковые.length,
    // Подтверждённое и просто подозрительное разделяем: это разные вещи.
    подтверждено: находки.filter((н) => н.тип === "подбор пароля").length,
    подозрительно: находки.length - находки.filter((н) => н.тип === "подбор пароля").length,
  };
}

// 5. Резервные копии. Путь задаётся в настройках агента; без него
//    агент честно говорит, что проверить нечего, а не молчит.
export async function проверитьКопии(путь) {
  if (!путь) {
    return { проверен: false, причина: "папка копий не задана в настройках агента (config.копии)" };
  }
  try {
    const { readdir, stat } = await import("fs/promises");
    const имена = await readdir(путь);
    let свежая = null, размер = 0, штук = 0;
    for (const и of имена) {
      try {
        const s = await stat(путь + "/" + и);
        if (!s.isFile()) continue;
        штук++;
        if (!свежая || s.mtimeMs > свежая) { свежая = s.mtimeMs; размер = s.size; }
      } catch { /* пропускаем нечитаемое */ }
    }
    if (!штук) return { проверен: true, пусто: true, находки: [находка({
      тип: "нет копий", уровень: 90, компонент: "резервные копии",
      суть: "в папке копий нет ни одного файла",
      последствия: "при потере базы восстанавливать будет нечего",
      решение: "проверить, что скрипт копирования работает",
    })] };

    const возрастЧасов = Math.floor((Date.now() - свежая) / 3600e3);
    const находки = [];
    if (возрастЧасов > 48) {
      находки.push(находка({
        тип: "копии устарели", уровень: 85, компонент: "резервные копии",
        суть: `свежей копии ${возрастЧасов} часов`,
        последствия: "потеряются данные за всё время с последней копии",
        решение: "проверить расписание копирования на сервере",
      }));
    }
    return { проверен: true, штук, возрастЧасов, размерМБ: Math.round(размер / 1048576 * 10) / 10, находки };
  } catch (e) {
    return { проверен: false, причина: "папка копий не читается" };
  }
}

