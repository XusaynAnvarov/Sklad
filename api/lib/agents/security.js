import tls from "tls";
import { суткиКлюч } from "./time.js";

const СУТКИ = 86400e3;
const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };

// Сколько дней до истечения сертификата считать поводом для тревоги.
const СЕРТ_ТРЕВОГА = 14;
// Сколько неудачных входов с одного адреса за сутки — это уже подбор.
const ПОДБОР = 5;

// ======================================================================
//  ВСПОМОГАТЕЛЬНОЕ: как описать секрет, не показывая его
// ======================================================================
function оСекрете(имя) {
  const v = process.env[имя];
  if (!v) return { имя, задан: false, длина: 0, слабый: true };
  const s = String(v);
  // «Слабый» — короткий или очевидно временный. Самого значения мы
  // никуда не передаём, только вывод о нём.
  const слабый = s.length < 24 || /^(test|demo|secret|password|changeme|123)/i.test(s);
  return { имя, задан: true, длина: s.length, слабый };
}

const находка = ({ тип, уровень, компонент, суть, последствия, решение }) => ({
  тип, уровень, компонент, суть, последствия, решение,
  когда: new Date().toISOString(),
});

