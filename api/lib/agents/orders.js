// ========================================================================
//  АГЕНТ ЗАКАЗОВ.
//
//  Утром и вечером смотрит, что не собрано, что собрано и не отправлено,
//  что стоит дольше положенного и что собрать нечем.
//
//  ЭТАПЫ АГЕНТ НЕ МЕНЯЕТ. Прав на order_fulfillment у него нет
//  (api/lib/agents/права.js), а сами переходы и так идут только через
//  SQL-функцию fulfillment_transition с журналом и защитой от пропуска
//  этапа. Агент читает и считает.
//
//  Кто в учёте — решает api/lib/fulfillment.js (вУчёте). Повторять эту
//  логику здесь нельзя: разойдётся с доской, и агент начнёт считать не
//  те заказы, что видит владелец.
//
//  Связь со складом: товары, ушедшие в минус, мешают собрать заказы.
//  Агент кладёт уведомление kind:"shortage" — его читает агент склада
//  и поднимает такие товары в закупке.
// ========================================================================
import { вУчёте } from "../fulfillment.js";
import { курсыИзНастроек } from "./sales-math.js";
import { заказы, сводка, просрочен, поПриоритету, нехваткаПоТоварам, ПОРОГИ, ЭТАП_ИМЯ } from "./orders-math.js";
import { суткиКлюч } from "./time.js";

const СУТКИ = 86400e3;
// Накладные читаем за 180 дней: всё, что старше и не отправлено, —
// это уже не оперативная задача, а разбор завалов.
const ОКНО_ДНЕЙ = 180;

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };

export async function прогон(ctx) {
  const сейчас = Date.now();
  const от = new Date(сейчас - ОКНО_ДНЕЙ * СУТКИ).toISOString();
  const пороги = { ...ПОРОГИ, ...(ctx.config?.просрочка || {}) };

  const [продажи, строки, доска, конфиг, товары, настройки, клиенты] = await Promise.all([
    ctx.читать("sales?select=id,date,created_at,status,source,currency,customer_id,items&date=gte." + encodeURIComponent(от)),
    ctx.читать("order_fulfillment?select=*").catch(() => []),
    ctx.читать("order_board?select=sale_id,urgent").catch(() => []),
    ctx.читать("fulfillment_config?id=eq.1&select=since").catch(() => []),
    ctx.читать("products?select=id,code,name,stock_qty"),
    ctx.читать("settings?select=rate_yuan_usd,rate_som_usd"),
    ctx.читать("customers?select=id,name").catch(() => []),
  ]);

  // Миграции сборки может не быть — тогда считать нечего, и об этом
  // надо сказать прямо, а не показывать нули.
  if (!Array.isArray(строки)) {
    return { статус: "skipped", сводка: "Сборка и отправка ещё не включены: не применён db/order-fulfillment-migration.sql" };
  }

  const since = конфиг?.[0]?.since || null;
  const есть = new Set((строки || []).map((с) => String(с.sale_id)));
  const вРаботе = (продажи || []).filter((н) => вУчёте(н, since, есть.has(String(н.id))));

  const курсы = курсыИзНастроек((настройки || [])[0] || {});
  const имена = new Map((клиенты || []).map((к) => [String(к.id), к.name || ""]));

  const список = заказы({ продажи: вРаботе, строки, доска, товары, курсы, сейчас })
    .map((з) => ({ ...з, клиентИмя: имена.get(з.клиент) || "—", просрочен: просрочен(з, пороги) }));

  const итог = сводка(список, пороги);
  const вРаботеСписок = список.filter((з) => з.этап !== "shipped").sort(поПриоритету);
  const нехватки = нехваткаПоТоварам(список);

  await уведомления(ctx, { список, итог, вРаботеСписок, нехватки, пороги, сейчас });

  const сводкаТекст = вРаботеСписок.length
    ? `В работе ${вРаботеСписок.length}: не собрано ${итог.неСобрано}, не отправлено ${итог.неОтправлено}`
      + (итог.просрочено ? `, просрочено ${итог.просрочено}` : "")
      + (итог.нечемСобрать ? `, нечем собрать ${итог.нечемСобрать}` : "")
    : "Все заказы отправлены — в работе ничего нет";

  return {
    сводка: сводкаТекст,
    детали: {
      ...итог,
      пороги,
      учётС: since,
      самыйСтарый: итог.самыйСтарый
        ? { номер: итог.самыйСтарый.номер, днейЖдёт: итог.самыйСтарый.днейЖдёт, этап: итог.самыйСтарый.этапИмя }
        : null,
      // Полный список того, что в работе: он же ложится в отчёт раздела.
      вРаботе: вРаботеСписок.slice(0, 100).map(коротко),
      нехватки: нехватки.slice(0, 30),
    },
  };
}

// Что показываем в отчёте по каждому заказу. Ровно то, что просил
// владелец, и ничего сверх: выдуманных полей тут нет.
const коротко = (з) => ({
  номер: з.номер, клиент: з.клиентИмя, этап: з.этапИмя,
  оформлен: new Date(з.оформлен).toISOString().slice(0, 10),
  днейЖдёт: з.днейЖдёт, днейНаЭтапе: з.днейНаЭтапе,
  позиций: з.позиций, суммаUSD: з.суммаUSD,
  срочно: з.срочно, просрочен: з.просрочен,
  перевозчик: з.перевозчик, ответственный: з.ответственный || "—",
  причина: з.причина,
});

// ======================================================================
//  УВЕДОМЛЕНИЯ
//
//  Утром — что не отправлено. Вечером — что за день не сдвинулось.
//  Ключи суточные: один и тот же список дважды в день не нужен.
// ======================================================================
async function уведомления(ctx, { итог, вРаботеСписок, нехватки, пороги, сейчас }) {
  const день = суткиКлюч(сейчас);
  // Час по Ташкенту: до полудня — утренний отчёт, после — вечерний.
  const час = new Date(сейчас + 5 * 3600e3).getUTCHours();
  const вечер = час >= 15;

  if (вРаботеСписок.length) {
    const топ = вРаботеСписок.slice(0, 12);
    await ctx.уведомить({
      kind: вечер ? "orders_evening" : "orders_morning",
      level: итог.просрочено ? "warn" : "info",
      title: вечер
        ? `Вечер: в работе ${вРаботеСписок.length} заказов`
        : `Утро: не отправлено ${вРаботеСписок.length} заказов`,
      body: топ.map((з) =>
        `${з.номер} · ${з.клиентИмя} · ${з.этапИмя} · ${з.днейНаЭтапе} дн.`
        + (з.срочно ? " · СРОЧНО" : "")
        + (з.нехватка.length ? " · нечем собрать" : "")).join("\n"),
      dedup_key: `ord:${вечер ? "pm" : "am"}:${день}`,
      payload: { всего: вРаботеСписок.length, просрочено: итог.просрочено },
    });
  }

  const просроченные = вРаботеСписок.filter((з) => з.просрочен);
  if (просроченные.length) {
    await ctx.уведомить({
      kind: "orders_overdue", level: "danger",
      title: `Просрочено ${просроченные.length} заказов`,
      body: просроченные.slice(0, 12).map((з) =>
        `${з.номер} · ${з.клиентИмя} · ${з.этапИмя} ${з.днейНаЭтапе} дн. при норме ${пороги[з.этап]}`
        + ` · ${з.причина}`).join("\n"),
      dedup_key: `ord:overdue:${день}`,
    });
  }

  // Шина между агентами: это уведомление читает агент склада.
  if (нехватки.length) {
    await ctx.уведомить({
      kind: "shortage", level: "warn",
      title: `${нехватки.length} товаров не дают собрать заказы`,
      body: нехватки.slice(0, 12).map((н) =>
        `${н.код || н.имя} — остаток ${н.остаток}, держит заказов: ${н.заказов} (${н.заказы.join(", ")})`).join("\n"),
      dedup_key: `ord:shortage:${день}`,
      // Агент склада берёт отсюда список товаров и поднимает их в закупке.
      payload: { товары: нехватки.map((н) => ({ id: н.id, код: н.код, остаток: н.остаток, заказов: н.заказов })) },
    });
  }
}

export default прогон;
