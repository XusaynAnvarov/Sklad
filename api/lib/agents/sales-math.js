// ========================================================================
//  АРИФМЕТИКА ПРОДАЖ ДЛЯ АГЕНТА СКЛАДА.
//
//  Здесь только счёт: ни базы, ни сети, ни записи. Поэтому всё можно
//  проверить тестом на выдуманной выборке — что и делает
//  _tools/tests/t-agents-warehouse.mjs.
//
//  Три правила, которые легко нарушить и трудно заметить:
//
//  1. ОФОРМЛЕННЫЙ ЗАКАЗ — НЕ ПРОДАЖА. Пока заказ не выдан, склад по нему
//     не списан. Список невыданных статусов взят из js/debt.js — там он
//     уже выверен, и расходиться с ним нельзя.
//  2. ВОЗВРАТ ВЫЧИТАЕТСЯ САМ. У возвратных накладных количество
//     отрицательное (проверено на базе: -4 и -1). Поэтому обычная сумма
//     по позициям уже учитывает возвраты, и вычитать их отдельно —
//     значит вычесть дважды.
//  3. ЧЕГО НЕ ХВАТАЕТ, ТОГО НЕ СЧИТАЕМ. Сезонный коэффициент и сравнение
//     с прошлым годом требуют года истории. Сейчас её полгода. Эти
//     функции возвращают null и причину, а не правдоподобное число.
// ========================================================================

const СУТКИ = 86400e3;
const СДВИГ = 5 * 3600e3;                       // Ташкент, UTC+5

// Невыданные статусы — один в один с js/debt.js. Если там список
// поменяется, он должен поменяться и здесь; за этим следит тест.
export const НЕ_ВЫДАНО = ["order", "pending_confirm", "confirmed", "draft", "canceled"];
export const выдана = (накладная) => !НЕ_ВЫДАНО.includes(String(накладная?.status || ""));

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const мс = (v) => { const t = typeof v === "number" ? v : Date.parse(v); return Number.isFinite(t) ? t : null; };

// ======================================================================
//  ПЕРИОДЫ. Границы считаются по ташкентскому календарю: «месяц» для
//  владельца начинается в полночь в Ташкенте, а не в Лондоне.
// ======================================================================
const тшк = (t) => new Date(t + СДВИГ);
const изТшк = (d) => d.getTime() - СДВИГ;

function полночь(t) { const d = тшк(t); d.setUTCHours(0, 0, 0, 0); return изТшк(d); }

export const СЕЗОНЫ = [
  { имя: "зима", месяцы: [11, 0, 1] },
  { имя: "весна", месяцы: [2, 3, 4] },
  { имя: "лето", месяцы: [5, 6, 7] },
  { имя: "осень", месяцы: [8, 9, 10] },
];
export const сезонМесяца = (м) => СЕЗОНЫ.find((с) => с.месяцы.includes(м)).имя;

// вид: день | неделя | месяц | квартал | сезон | год | свой
export function диапазон(вид, { когда = Date.now(), от, до } = {}) {
  const t = мс(когда) ?? Date.now();
  const d = тшк(t);
  const год = d.getUTCFullYear(), месяц = d.getUTCMonth();

  switch (String(вид)) {
    case "день": {
      const н = полночь(t);
      return { от: н, до: н + СУТКИ, имя: "день" };
    }
    case "неделя": {
      // Неделя начинается с понедельника: так считает весь склад.
      const день = (d.getUTCDay() + 6) % 7;
      const н = полночь(t) - день * СУТКИ;
      return { от: н, до: н + 7 * СУТКИ, имя: "неделя" };
    }
    case "месяц":
      return { от: изТшк(new Date(Date.UTC(год, месяц, 1))), до: изТшк(new Date(Date.UTC(год, месяц + 1, 1))), имя: "месяц" };
    case "квартал": {
      const к = Math.floor(месяц / 3) * 3;
      return { от: изТшк(new Date(Date.UTC(год, к, 1))), до: изТшк(new Date(Date.UTC(год, к + 3, 1))), имя: "квартал" };
    }
    case "сезон": {
      const с = СЕЗОНЫ.find((x) => x.месяцы.includes(месяц));
      // Зима начинается в декабре прошлого года — это единственный сезон,
      // который перескакивает через новый год.
      const начало = с.имя === "зима" ? (месяц === 11 ? год : год - 1) : год;
      const первый = с.месяцы[0];
      return {
        от: изТшк(new Date(Date.UTC(начало, первый, 1))),
        до: изТшк(new Date(Date.UTC(начало, первый + 3, 1))),
        имя: "сезон · " + с.имя,
      };
    }
    case "год":
      return { от: изТшк(new Date(Date.UTC(год, 0, 1))), до: изТшк(new Date(Date.UTC(год + 1, 0, 1))), имя: "год" };
    case "свой": {
      const a = мс(от), b = мс(до);
      if (a === null || b === null || b <= a) return null;
      return { от: a, до: b, имя: "свой период" };
    }
    default:
      return null;
  }
}

// Тот же период годом раньше — для сравнения.
export function годНазад({ от, до }) {
  const сдвиг = (t) => { const d = тшк(t); return изТшк(new Date(Date.UTC(d.getUTCFullYear() - 1, d.getUTCMonth(), d.getUTCDate(), d.getUTCHours(), d.getUTCMinutes()))); };
  return { от: сдвиг(от), до: сдвиг(до), имя: "тот же период годом раньше" };
}

// ======================================================================
//  ДЕНЬГИ. Валюты сводим к доллару: иначе «самый прибыльный» нельзя
//  сравнить между сумовой и юаневой продажей.
//  курсы: { yuan: сколько USD за юань, som: сколько USD за сум }
// ======================================================================
export function вUSD(сумма, валюта, курсы = {}) {
  const v = чис(сумма);
  switch (String(валюта || "").toLowerCase()) {
    case "usd": return v;
    case "yuan": return v * чис(курсы.yuan);
    case "som": return v * чис(курсы.som);
    default: return 0;
  }
}

// Курсы из строки settings склада → «сколько долларов в одной единице».
//
// Склад хранит курс как «сколько $ в одном юане / суме» (js/fx.js:
// rate_yuan_usd ≈ 0.152, rate_som_usd ≈ 0.0000826). Раньше здесь курс
// ПЕРЕВОРАЧИВАЛИ, будто там «юаней/сумов за доллар», — и агенты завышали
// суммы в сумах в ~150 млн раз (заказ на $385 млрд), в юанях — в ~43 раза.
// Доллар никогда не дешевле юаня или сума, поэтому число > 1 — это
// «единиц за доллар» (старый формат), его переворачиваем; < 1 берём как есть.
export function курсыИзНастроек(s = {}) {
  const вДоллары = (v) => { const x = чис(v); return x <= 0 ? 0 : x > 1 ? 1 / x : x; };
  return { yuan: вДоллары(s.rate_yuan_usd), som: вДоллары(s.rate_som_usd) };
}

// ======================================================================
//  ПРОДАЖИ ПО ТОВАРАМ ЗА ПЕРИОД
// ======================================================================
export function поТоварам(продажи, { от, до, курсы = {} } = {}) {
  const итог = new Map();
  for (const н of продажи || []) {
    if (!выдана(н)) continue;                      // заказ — ещё не продажа
    const t = мс(н.date) ?? мс(н.created_at);
    if (t === null) continue;
    if (от != null && t < от) continue;
    if (до != null && t >= до) continue;

    for (const п of н.items || []) {
      const id = String(п.product_id || "");
      if (!id) continue;
      const кол = чис(п.qty);                      // у возврата он отрицательный
      const валюта = п.currency || н.currency;
      const выручка = вUSD(кол * чис(п.unit_price), валюта, курсы);
      // Себестоимость пишется в позицию при проведении накладной.
      const себест = чис(п.cogs_usd);

      const з = итог.get(id) || { кол: 0, выручкаUSD: 0, себестUSD: 0, документов: 0, возвратов: 0, последняя: null };
      з.кол += кол;
      з.выручкаUSD += выручка;
      з.себестUSD += себест;
      з.документов += 1;
      if (кол < 0) з.возвратов += 1;
      if (з.последняя === null || t > з.последняя) з.последняя = t;
      итог.set(id, з);
    }
  }
  for (const з of итог.values()) з.прибыльUSD = з.выручкаUSD - з.себестUSD;
  return итог;
}

// Сколько штук в день продаётся, за последние N суток.
export function скорость(продажи, дней, { до = Date.now(), курсы = {} } = {}) {
  const окно = Math.max(1, Math.round(дней));
  const карта = поТоварам(продажи, { от: до - окно * СУТКИ, до, курсы });
  const из = new Map();
  for (const [id, з] of карта) из.set(id, Math.max(0, з.кол) / окно);
  return из;
}

// Сколько дней истории вообще есть. Без этого нельзя честно говорить
// ни о сезоне, ни о прошлом годе.
export function глубинаИстории(продажи) {
  let мин = null, макс = null;
  for (const н of продажи || []) {
    if (!выдана(н)) continue;
    const t = мс(н.date) ?? мс(н.created_at);
    if (t === null) continue;
    if (мин === null || t < мин) мин = t;
    if (макс === null || t > макс) макс = t;
  }
  if (мин === null) return { дней: 0, от: null, до: null };
  return { дней: Math.round((макс - мин) / СУТКИ), от: мин, до: макс };
}

// Сравнение с тем же периодом прошлого года — ТОЛЬКО если история
// достаточна. Иначе возвращаем причину, а не выдуманный процент.
export function сравнитьСПрошлымГодом(продажи, период, { курсы = {} } = {}) {
  const г = глубинаИстории(продажи);
  const нужно = период.до - годНазад(период).от;   // от начала прошлого периода до конца этого
  if (г.от === null || г.от > годНазад(период).от) {
    return {
      хватает: false,
      причина: `истории ${г.дней} дн., для сравнения с прошлым годом нужно от ${Math.round(нужно / СУТКИ)} дн.`,
    };
  }
  const сейчас = поТоварам(продажи, { ...период, курсы });
  const раньше = поТоварам(продажи, { ...годНазад(период), курсы });
  const сумма = (м) => [...м.values()].reduce((a, з) => a + з.выручкаUSD, 0);
  const было = сумма(раньше), стало = сумма(сейчас);
  return {
    хватает: true, было, стало,
    ростПроцент: было > 0 ? Math.round((стало - было) / было * 1000) / 10 : null,
  };
}

// Сезонный коэффициент. Тот же разговор: нужен хотя бы год.
export function сезонныйКоэффициент(продажи, когда = Date.now()) {
  const г = глубинаИстории(продажи);
  if (г.дней < 400) {
    return { коэффициент: 1, известен: false, причина: `истории ${г.дней} дн., для сезонности нужно от 400 дн.` };
  }
  const этотСезон = диапазон("сезон", { когда });
  const вСезон = поТоварам(продажи, этотСезон);
  const всего = поТоварам(продажи, { от: г.от, до: г.до });
  const штукВСезон = [...вСезон.values()].reduce((a, з) => a + Math.max(0, з.кол), 0);
  const штукВсего = [...всего.values()].reduce((a, з) => a + Math.max(0, з.кол), 0);
  const долиДней = (этотСезон.до - этотСезон.от) / (г.до - г.от);
  const ожидалось = штукВсего * долиДней;
  return {
    коэффициент: ожидалось > 0 ? Math.round(штукВСезон / ожидалось * 100) / 100 : 1,
    известен: true,
  };
}

// ======================================================================
//  ПРОГНОЗ ЗАКУПКИ ПО ОДНОМУ ТОВАРУ
//
//  Считаем так, как считал бы кладовщик:
//    запас в днях   = (что лежит − что обещано клиентам) ÷ продажи в день
//    точка заказа   = продажи в день × (срок поставки + страховой запас)
//    заказать       = точка заказа + запас на срок − (лежит + в пути)
//
//  Чего не хватает для счёта — перечисляем поимённо. Это и есть ответ
//  на вопрос «почему агент ничего не советует по этому товару».
// ======================================================================
export function прогноз({
  остаток = 0, зарезервировано = 0, вПути = 0,
  скорость7 = 0, скорость30 = 0, скорость90 = 0,
  срокДней = null, страховкаДней = 7, сезонныйК = 1, минЗапасДней = null,
} = {}) {
  const нет = [];
  // Берём самую осторожную из трёх скоростей — наибольшую. Товар,
  // который в последнюю неделю пошёл втрое быстрее, кончится раньше,
  // чем обещает среднее за квартал.
  const вДень = Math.max(чис(скорость7), чис(скорость30), чис(скорость90)) * (чис(сезонныйК) || 1);
  const свободно = чис(остаток) - чис(зарезервировано);

  if (вДень <= 0) нет.push("нет продаж за 90 дней");
  if (срокДней === null) нет.push("неизвестен срок поставки");

  const хватитДней = вДень > 0 ? Math.floor(свободно / вДень) : null;
  const срок = срокДней === null ? null : Math.max(0, Math.round(срокДней));
  // Страховой запас в днях: свой у товара (product_policy.min_days) или
  // общий по умолчанию.
  const запасДней = Math.max(0, Math.round(чис(минЗапасДней === null ? страховкаДней : минЗапасДней)));

  const точкаЗаказа = (вДень > 0 && срок !== null) ? Math.ceil(вДень * (срок + запасДней)) : null;
  // Заказать столько, чтобы хватило на срок поставки плюс запас.
  const надоИметь = точкаЗаказа === null ? null : Math.ceil(вДень * (срок + запасДней * 2));
  const рекомендовано = надоИметь === null ? null
    : Math.max(0, Math.ceil(надоИметь - свободно - чис(вПути)));

  return { вДень: Math.round(вДень * 1000) / 1000, свободно, хватитДней, точкаЗаказа, рекомендовано, нет };
}

// ======================================================================
//  СВЕТОФОР ОСТАТКОВ
//    🔴 нет вовсе        🟠 кончится раньше, чем приедет новое
//    🟡 подошёл к точке заказа   🟢 хватает   ⚪ не продаётся
// ======================================================================
export function светофор({ остаток = 0, свободно = null, хватитДней = null, срокДней = null, точкаЗаказа = null, вДень = 0 }) {
  const есть = свободно === null ? чис(остаток) : чис(свободно);
  if (чис(вДень) <= 0) return есть <= 0 ? { цвет: "🔴", код: "нет", текст: "нет на складе" }
                                        : { цвет: "⚪", код: "стоит", текст: "нет движения" };
  if (есть <= 0) return { цвет: "🔴", код: "нет", текст: "кончился" };
  if (срокДней !== null && хватитДней !== null && хватитДней < срокДней)
    return { цвет: "🟠", код: "срочно", текст: `кончится через ${хватитДней} дн., а везти ${срокДней} дн.` };
  if (точкаЗаказа !== null && есть <= точкаЗаказа)
    return { цвет: "🟡", код: "пора", текст: "подошёл к точке заказа" };
  return { цвет: "🟢", код: "хватает", текст: хватитДней === null ? "хватает" : `хватит на ${хватитДней} дн.` };
}

// ======================================================================
//  КЛАССЫ ТОВАРОВ
// ======================================================================
export function классы(продажи, { сейчас = Date.now(), курсы = {} } = {}) {
  const за = (дней) => поТоварам(продажи, { от: сейчас - дней * СУТКИ, до: сейчас, курсы });
  const за30 = за(30), за90 = за(90), за180 = за(180);
  const предыдущие30 = поТоварам(продажи, { от: сейчас - 60 * СУТКИ, до: сейчас - 30 * СУТКИ, курсы });

  const все = new Set([...за180.keys()]);
  const из = {
    постоянные: [], частые: [], мёртвые: [], прибыльные: [], просевшие: [], новые: [],
  };

  for (const id of все) {
    const м30 = за30.get(id), м90 = за90.get(id), м180 = за180.get(id);
    const кол90 = Math.max(0, м90?.кол || 0);
    const док90 = м90?.документов || 0;

    // Постоянный — продавался не одним разом, а равномерно: минимум
    // три разных документа за квартал.
    if (док90 >= 3) из.постоянные.push({ id, документов: док90, кол: кол90 });
    if (док90 >= 6) из.частые.push({ id, документов: док90 });

    // Мёртвый — за полгода ни одной выдачи.
    if (!м180 || м180.кол <= 0) из.мёртвые.push({ id });

    if ((м90?.прибыльUSD || 0) > 0) из.прибыльные.push({ id, прибыльUSD: м90.прибыльUSD });

    // Просел — продавался раньше и почти перестал.
    const было = Math.max(0, предыдущие30.get(id)?.кол || 0);
    const стало = Math.max(0, м30?.кол || 0);
    if (было >= 3 && стало < было / 2) из.просевшие.push({ id, было, стало });

    // Новый спрос — за прошлый месяц не было, в этом пошёл.
    if (было === 0 && стало > 0) из.новые.push({ id, стало });
  }

  из.постоянные.sort((a, b) => b.кол - a.кол);
  из.частые.sort((a, b) => b.документов - a.документов);
  из.прибыльные.sort((a, b) => b.прибыльUSD - a.прибыльUSD);
  из.просевшие.sort((a, b) => (b.было - b.стало) - (a.было - a.стало));
  return из;
}

// ======================================================================
//  СРОК ПОСТАВКИ ПО ИСТОРИИ ПРИХОДОВ
//
//  В проекте нет ни справочника поставщиков, ни поля «срок поставки» —
//  и заводить их руками не нужно: срок уже записан в самих приходах.
//  Дата документа — когда заказали, «приход.когда» — когда оприходовали.
//  Разница и есть срок. По базе: Кампир 43 и 32 дня, Гел калиш 39,
//  местные магазины — ноль.
// ======================================================================
export function срокиПоставщиков(приходы) {
  const по = new Map();
  for (const п of приходы || []) {
    if (String(п.status) !== "arrived") continue;
    const заказано = мс(п.date);
    if (заказано === null) continue;
    const имя = String(п.supplier || "").trim() || "без поставщика";
    for (const поз of п.items || []) {
      const пришло = мс(поз?.приход?.когда);
      if (пришло === null) continue;
      const дней = Math.round((пришло - заказано) / СУТКИ);
      if (дней < 0 || дней > 365) continue;        // мусор в датах не считаем
      const з = по.get(имя) || { сроки: [], товары: new Set() };
      з.сроки.push(дней);
      if (поз.product_id) з.товары.add(String(поз.product_id));
      по.set(имя, з);
    }
  }
  const из = new Map();
  for (const [имя, з] of по) {
    const сорт = [...з.сроки].sort((a, b) => a - b);
    // Медиана, а не среднее: одна застрявшая поставка не должна
    // раздувать срок для всех остальных.
    const медиана = сорт[Math.floor(сорт.length / 2)];
    из.set(имя, { дней: медиана, наблюдений: сорт.length, товаров: з.товары.size, надёжно: сорт.length >= 3 });
  }
  return из;
}

// Кто в последний раз привозил этот товар.
export function поставщикиТоваров(приходы) {
  const из = new Map();
  for (const п of приходы || []) {
    const t = мс(п.date);
    if (t === null) continue;
    const имя = String(п.supplier || "").trim();
    if (!имя) continue;
    for (const поз of п.items || []) {
      const id = String(поз.product_id || "");
      if (!id) continue;
      const было = из.get(id);
      if (!было || t > было.когда) из.set(id, { поставщик: имя, когда: t });
    }
  }
  return из;
}

// Сколько штук уже заказано и ещё не приехало.
export function вПути(приходы) {
  const из = new Map();
  for (const п of приходы || []) {
    if (!["in_transit", "ordered"].includes(String(п.status))) continue;
    for (const поз of п.items || []) {
      const id = String(поз.product_id || "");
      if (!id) continue;
      из.set(id, (из.get(id) || 0) + Math.max(0, чис(поз.qty)));
    }
  }
  return из;
}

// Сколько штук обещано клиентам: заказы, которые ещё не выданы.
export function зарезервировано(продажи) {
  const из = new Map();
  for (const н of продажи || []) {
    if (выдана(н)) continue;                       // выданное уже списано со склада
    if (String(н.status) === "canceled" || String(н.status) === "draft") continue;
    for (const п of н.items || []) {
      const id = String(п.product_id || "");
      if (!id) continue;
      из.set(id, (из.get(id) || 0) + Math.max(0, чис(п.qty)));
    }
  }
  return из;
}
