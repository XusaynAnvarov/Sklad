// ========================================================================
//  АГЕНТ СКЛАДА.
//
//  Раз в сутки смотрит, что продаётся, что кончается и что лежит зря,
//  и готовит предложение о закупке. Закупку он НЕ СОЗДАЁТ: кладёт её в
//  agent_approvals и ждёт нажатия. Остатки товаров менять он не может —
//  права на products ему не выданы (api/lib/agents/права.js).
//
//  Весь счёт — в api/lib/agents/sales-math.js, здесь только чтение базы
//  и складывание отчёта. Так арифметику можно проверить тестом без базы.
//
//  Что агент отказывается делать и почему:
//   • Не сравнивает с прошлым годом: истории шесть месяцев (с 22 мая
//     2026). Пишет об этом прямо, а не показывает ноль.
//   • Не применяет сезонный коэффициент: для него нужен год. Берёт 1.
//   • Не советует заказывать товар, у которого нет продаж за 90 дней
//     или неизвестен срок поставки, — перечисляет, чего не хватает.
// ========================================================================
import {
  диапазон, поТоварам, скорость, глубинаИстории, сравнитьСПрошлымГодом,
  сезонныйКоэффициент, прогноз, светофор, классы,
  срокиПоставщиков, поставщикиТоваров, вПути, зарезервировано, курсыИзНастроек,
} from "./sales-math.js";
import { суткиКлюч, неделяКлюч } from "./time.js";

const СУТКИ = 86400e3;
// Продажи читаем за 400 дней: 90 для скорости, 180 для классов, запас
// сверху — чтобы было видно, что истории пока не хватает на год.
const ОКНО_ДНЕЙ = 400;

const чис = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
const имя = (т) => (т?.code ? т.code + " · " : "") + (т?.name || "без названия");

// ======================================================================
//  ПРОГОН
// ======================================================================
export async function прогон(ctx) {
  const сейчас = Date.now();
  const от = new Date(сейчас - ОКНО_ДНЕЙ * СУТКИ).toISOString();

  // Непрочитанные сигналы от агента заказов: какие товары не дают
  // собрать заказы. Это и есть шина между агентами — отдельной очереди
  // задач в проекте нет и не нужно.
  const сигналы = await ctx.читать(
    "agent_notices?kind=eq.shortage&seen_at=is.null&select=payload,created_at&order=created_at.desc&limit=5",
  ).catch(() => []);
  const держатЗаказы = new Map();
  for (const с of сигналы || []) {
    for (const т of с?.payload?.товары || []) {
      const id = String(т.id || "");
      if (id) держатЗаказы.set(id, Math.max(держатЗаказы.get(id) || 0, чис(т.заказов)));
    }
  }

  const [товары, продажи, приходы, настройки, пороги] = await Promise.all([
    ctx.читать("products?select=id,code,name,category,stock_qty,price_usd,cost_usd,unit,last_arrival_at,photo_url"),
    ctx.читать("sales?select=id,date,created_at,status,source,currency,items&date=gte." + encodeURIComponent(от)),
    ctx.читать("purchases?select=id,date,status,supplier,items"),
    ctx.читать("settings?select=rate_yuan_usd,rate_som_usd"),
    ctx.читать("product_policy?select=*").catch(() => []),   // миграции может не быть
  ]);

  const курсы = курсыИзНастроек((настройки || [])[0] || {});
  const политика = new Map((пороги || []).map((п) => [String(п.product_id), п]));
  const история = глубинаИстории(продажи);

  // ---------------- общая картина ----------------
  const за30 = поТоварам(продажи, { от: сейчас - 30 * СУТКИ, до: сейчас, курсы });
  const ск7 = скорость(продажи, 7, { до: сейчас, курсы });
  const ск30 = скорость(продажи, 30, { до: сейчас, курсы });
  const ск90 = скорость(продажи, 90, { до: сейчас, курсы });
  const резерв = зарезервировано(продажи);
  const путь = вПути(приходы);
  const сроки = срокиПоставщиков(приходы);
  const ктоВозит = поставщикиТоваров(приходы);
  const сезон = сезонныйКоэффициент(продажи, сейчас);

  // ---------------- по каждому товару ----------------
  const строки = [];
  for (const т of товары || []) {
    const id = String(т.id);
    const п = политика.get(id) || {};
    if (п.never_order) continue;

    const поставщик = (п.supplier || ктоВозит.get(id)?.поставщик || "").trim();
    const срокИзИстории = поставщик ? сроки.get(поставщик) : null;
    const срокДней = п.lead_days != null ? чис(п.lead_days)
      : (срокИзИстории ? срокИзИстории.дней : null);

    const пр = прогноз({
      остаток: чис(т.stock_qty),
      зарезервировано: резерв.get(id) || 0,
      вПути: путь.get(id) || 0,
      скорость7: ск7.get(id) || 0,
      скорость30: ск30.get(id) || 0,
      скорость90: ск90.get(id) || 0,
      срокДней,
      минЗапасДней: п.min_days != null ? чис(п.min_days) : null,
      сезонныйК: сезон.коэффициент,
    });
    const св = светофор({ ...пр, остаток: чис(т.stock_qty), срокДней });

    строки.push({
      id, код: т.code || "", имя: т.name || "", категория: т.category || "",
      остаток: чис(т.stock_qty), свободно: пр.свободно,
      резерв: резерв.get(id) || 0, вПути: путь.get(id) || 0,
      вДень: пр.вДень, хватитДней: пр.хватитДней,
      точкаЗаказа: пр.точкаЗаказа, рекомендовано: пр.рекомендовано,
      поставщик, срокДней,
      срокОткуда: п.lead_days != null ? "настройка"
        : срокИзИстории ? (срокИзИстории.надёжно ? "история" : `история (${срокИзИстории.наблюдений} пост.)`)
        : "неизвестен",
      ценаUSD: чис(т.price_usd), себестUSD: чис(т.cost_usd),
      цвет: св.цвет, состояние: св.код, пояснение: св.текст,
      нет: пр.нет,
      продаж30: Math.max(0, за30.get(id)?.кол || 0),
      // Сколько заказов стоит из-за этого товара (сигнал от агента заказов).
      держитЗаказов: держатЗаказы.get(id) || 0,
      // Когда кончится при нынешнем темпе. null — темпа нет, считать нечем.
      кончится: пр.хватитДней === null ? null
        : new Date(сейчас + пр.хватитДней * СУТКИ).toISOString().slice(0, 10),
      приоритет: держатЗаказы.get(id) ? "Срочно" : (ПРИОРИТЕТ[св.код] || "—"),
      причина: причина(св, пр, { вПути: путь.get(id) || 0, держитЗаказов: держатЗаказы.get(id) || 0 }),
    });
  }

  // ---------------- что попадёт в закупку ----------------
  // Товар, из-за которого стоят заказы, попадает в закупку независимо
  // от светофора: клиент уже ждёт, и обычное «хватает» тут не довод.
  const кЗакупке = строки
    .filter((с) => (с.рекомендовано > 0 && ["нет", "срочно", "пора"].includes(с.состояние)) || с.держитЗаказов > 0)
    .sort((a, b) => порядок(a) - порядок(b));

  const сводкаЦветов = строки.reduce((a, с) => { a[с.цвет] = (a[с.цвет] || 0) + 1; return a; }, {});
  const кл = классы(продажи, { сейчас, курсы });

  // ---------------- уведомления ----------------
  await уведомления(ctx, строки, сейчас);

  // ---------------- предложение о закупке ----------------
  let предложение = null;
  if (кЗакупке.length) {
    const сумма = кЗакупке.reduce((a, с) => a + с.рекомендовано * с.себестUSD, 0);
    предложение = await ctx.согласовать({
      kind: "purchase",
      title: `Закупка: ${кЗакупке.length} позиц. на ≈ ${Math.round(сумма)} $`,
      // Ключ недельный: за неделю список успевает поменяться, а внутри
      // недели второе такое же предложение владельцу не нужно.
      idem_key: `purchase:${неделяКлюч(сейчас)}`,
      payload: {
        позиций: кЗакупке.length,
        сумма_usd: Math.round(сумма * 100) / 100,
        поставщики: [...new Set(кЗакупке.map((с) => с.поставщик).filter(Boolean))],
        товары: кЗакупке.slice(0, 60).map((с) => ({
          код: с.код, имя: с.имя, остаток: с.остаток, вПути: с.вПути,
          продажВДень: с.вДень, хватитДней: с.хватитДней,
          заказать: с.рекомендовано, поставщик: с.поставщик || "не определён",
          срокДней: с.срокДней, срокОткуда: с.срокОткуда, светофор: с.цвет,
        })),
      },
    });
  }

  // ---------------- итог прогона ----------------
  const сводка = кЗакупке.length
    ? `К закупке ${кЗакупке.length} позиц.; ${сводкаЦветов["🔴"] || 0} кончилось, ${сводкаЦветов["🟠"] || 0} кончится раньше поставки`
    : `Закупать нечего. ${сводкаЦветов["🔴"] || 0} кончилось, ${сводкаЦветов["🟢"] || 0} в запасе`;

  const срокиСписком = [...сроки].map(([п, з]) => ({ поставщик: п, дней: з.дней, поставок: з.наблюдений, надёжно: з.надёжно }));

  return {
    сводка,
    детали: {
      товаров: строки.length,
      светофор: сводкаЦветов,
      историяДней: история.дней,
      сезон: сезон.известен ? { коэффициент: сезон.коэффициент } : { неизвестен: сезон.причина },
      прошлыйГод: сравнитьСПрошлымГодом(продажи, диапазон("месяц", { когда: сейчас }), { курсы }),
      сроки: срокиСписком,
      кЗакупке: кЗакупке.slice(0, 60),
      классы: {
        постоянных: кл.постоянные.length, частых: кл.частые.length,
        мёртвых: кл.мёртвые.length, просевших: кл.просевшие.length, новых: кл.новые.length,
      },
      согласование: предложение?.id || null,
      // Чего не хватило для счёта — поимённо, по числу товаров.
      пробелы: пробелы(строки),
      // Готовые листы для выгрузки в Excel: браузеру остаётся только
      // разложить их по страницам книги.
      листы: листы(строки, { сезон, история, сроки: срокиСписком, цвета: сводкаЦветов, кл }),
    },
  };
}

export const ПРИОРИТЕТ = { нет: "Срочно", срочно: "Высокий", пора: "Средний", хватает: "Низкий", стоит: "Не заказывать" };

// Почему товар попал в список — человеческим языком, чтобы в Excel
// было видно основание, а не только цифру.
export function причина(св, пр, { вПути = 0, держитЗаказов = 0 } = {}) {
  if (держитЗаказов > 0) return `Из-за него стоит заказов: ${держитЗаказов}`;
  if (пр.нет.length) return "Нечем считать: " + пр.нет.join("; ");

  // Товар кончился, но партия уже едет — заказывать нечего, и это надо
  // сказать прямо. Без этой строки получалась бы строка «срочно» с
  // нулём в колонке «Заказать», и владелец ломал бы голову.
  const едет = вПути > 0 && пр.рекомендовано === 0;

  switch (св.код) {
    case "нет":
      return едет
        ? `Кончился, но в пути ${вПути} шт — заказывать не нужно`
        : `Кончился, продавался ${пр.вДень.toFixed(2)} шт/день`;
    case "срочно":
      return едет
        ? `Хватит на ${пр.хватитДней} дн., но в пути ${вПути} шт`
        : `Хватит на ${пр.хватитДней} дн., а везти дольше`;
    case "пора": return едет ? `Дошёл до точки заказа, в пути ${вПути} шт` : "Остаток опустился до точки заказа";
    case "стоит": return "Нет продаж за 90 дней — деньги стоят на полке";
    default: return `Хватит на ${пр.хватитДней} дн.`;
  }
}

// Шесть листов будущего Excel. Собираются здесь, а не в браузере:
// браузер не должен повторять логику агента, иначе числа в отчёте и в
// файле однажды разойдутся.
export function листы(строки, { сезон, история, сроки, цвета, кл }) {
  const по = (к) => строки.filter((с) => с.состояние === к);
  const срочные = [...по("нет").filter((с) => с.вДень > 0), ...по("срочно")]
    .sort((a, b) => b.вДень - a.вДень);
  const скоро = [...по("пора"), ...строки.filter((с) => с.состояние === "хватает" && с.хватитДней !== null && с.хватитДней <= 30)]
    .sort((a, b) => (a.хватитДней ?? 1e9) - (b.хватитДней ?? 1e9));
  const постоянные = строки.filter((с) => с.продаж30 > 0).sort((a, b) => b.продаж30 - a.продаж30).slice(0, 200);
  const медленные = строки.filter((с) => с.состояние === "стоит" && с.остаток > 0)
    .sort((a, b) => b.остаток * b.себестUSD - a.остаток * a.себестUSD);

  return {
    срочная: срочные,
    скоро,
    // Сезонной закупки не будет, пока нет года истории. Лист остаётся
    // на месте и объясняет, почему он пуст, — это честнее, чем убрать
    // его и сделать вид, что сезонность учтена.
    сезонная: сезон.известен ? строки.filter((с) => с.рекомендовано > 0) : [],
    сезоннаяПричина: сезон.известен ? null : сезон.причина,
    постоянные,
    медленные,
    аналитика: {
      товаров: строки.length,
      светофор: цвета,
      историяДней: история.дней,
      историяОт: история.от ? new Date(история.от).toISOString().slice(0, 10) : null,
      классы: {
        постоянных: кл.постоянные.length, частых: кл.частые.length,
        мёртвых: кл.мёртвые.length, просевших: кл.просевшие.length, новых: кл.новые.length,
      },
      сроки,
      деньгиНаПолке: Math.round(медленные.reduce((a, с) => a + с.остаток * с.себестUSD, 0)),
      пробелы: пробелы(строки),
    },
  };
}

// Сначала то, что уже кончилось, потом что кончится раньше поставки,
// внутри — дороже простой.
function порядок(с) {
  // Товар, который держит чужие заказы, идёт первым: там уже ждёт клиент.
  if (с.держитЗаказов > 0) return -1e9 - с.держитЗаказов;
  const вес = { нет: 0, срочно: 1, пора: 2 }[с.состояние] ?? 9;
  return вес * 1e6 - с.вДень * 1000;
}

function пробелы(строки) {
  const счёт = {};
  for (const с of строки) for (const п of с.нет) счёт[п] = (счёт[п] || 0) + 1;
  return счёт;
}

// ======================================================================
//  УВЕДОМЛЕНИЯ
//
//  Ключ защиты от повторов — недельный: «лапка P50 кончилась» на этой
//  неделе пишется один раз, а не каждое утро.
// ======================================================================
async function уведомления(ctx, строки, сейчас) {
  const нед = неделяКлюч(сейчас);
  const кончились = строки.filter((с) => с.состояние === "нет" && с.вДень > 0);
  const срочные = строки.filter((с) => с.состояние === "срочно");
  const стоят = строки.filter((с) => с.состояние === "стоит" && с.остаток > 0);

  if (кончились.length) {
    const топ = [...кончились].sort((a, b) => b.вДень - a.вДень).slice(0, 10);
    await ctx.уведомить({
      kind: "out_of_stock", level: "danger",
      title: `Кончилось ${кончились.length} ходовых товаров`,
      body: топ.map((с) => `${имя(с)} — продавался ${с.вДень.toFixed(2)} шт/день`).join("\n"),
      dedup_key: `wh:out:${нед}`,
      payload: { товаров: кончились.length, топ: топ.map((с) => с.код || с.имя) },
    });
  }

  if (срочные.length) {
    await ctx.уведомить({
      kind: "run_out_soon", level: "warn",
      title: `${срочные.length} товаров кончатся раньше, чем приедет новое`,
      body: срочные.slice(0, 10).map((с) => `${имя(с)} — хватит на ${с.хватитДней} дн., везти ${с.срокДней} дн.`).join("\n"),
      dedup_key: `wh:soon:${нед}`,
    });
  }

  // Про лежачий товар — раз в месяц: за неделю он никуда не денется,
  // а каждое утро напоминать о нём незачем.
  if (стоят.length >= 10) {
    await ctx.уведомить({
      kind: "dead_stock", level: "info",
      title: `${стоят.length} товаров лежат без движения`,
      body: "За последние 90 дней ни одной выдачи. Деньги стоят на полке.",
      dedup_key: `wh:dead:${суткиКлюч(сейчас).slice(0, 7)}`,
    });
  }
}

export default прогон;
